// Module: math_divider_srt_radix2_csa
// Purpose: SRT radix-2 integer divider with carry-save remainder and
//          estimate-based quotient-digit selection
//
// Selection-table correctness argument:
//   The true partial remainder t lies in [-D,D].  The estimate is the top
//   6 bits of t aligned to the divisor MSB position p, i.e. t/2^(p-5).
//   The estimate grid is 1/32.  Because the remainder is kept carry-save,
//   the estimate of the sum S+C can be off by the carry-save uncertainty
//   (at most 1/32) plus the grid quantization (1/32), for a total error
//   u_tot = 1/16 in units of 2^p.  With eps = 1/128, any threshold T+ placed
//   in the window [u_tot+eps, d_lo/2 - u_tot - eps] guarantees that the
//   estimate-based decision matches the exact t >= D/2 boundary for every
//   d_norm in the bucket [d_lo, d_lo+1/4).  The four bucket thresholds below
//   are the midpoint of that window and were generated by the golden model.
//
// Documentation: docs/markdown/rtl-math/overview.md
// Subsystem: math
//
// Author: sean galloway
// Created: 2026-10-11

`timescale 1ns / 1ps

`include "reset_defs.svh"

module math_divider_srt_radix2_csa #(
    parameter int DATA_WIDTH = 32
) (
    input  logic                    i_clk,
    input  logic                    i_rst_n,
    input  logic                    i_valid,
    output logic                    ow_busy,
    output logic                    ow_done,
    output logic                    ow_dbz,
    input  logic [DATA_WIDTH-1:0]   i_dividend,
    input  logic [DATA_WIDTH-1:0]   i_divisor,
    output logic [DATA_WIDTH-1:0]   ow_quotient,
    output logic [DATA_WIDTH-1:0]   ow_remainder
);

    localparam int REXT    = DATA_WIDTH + 6;
    localparam int COUNT_W = (DATA_WIDTH <= 1) ? 1 : $clog2(DATA_WIDTH);
    localparam logic signed [DATA_WIDTH+1:0] C_ONE = {{(DATA_WIDTH+1){1'b0}}, 1'b1};
    localparam int PW      = (DATA_WIDTH <= 1) ? 1 : $clog2(DATA_WIDTH);

    localparam logic [REXT-1:0] MASK = {REXT{1'b1}};

    // Selection thresholds from the golden model (bucket -> T+, est in 1/32 units).
    localparam logic signed [9:0] SRT2CSA_TAB [0:3] = '{
        10'sd8,  // bucket 0: d_norm in [1.00, 1.25)
        10'sd10, // bucket 1: d_norm in [1.25, 1.50)
        10'sd12, // bucket 2: d_norm in [1.50, 1.75)
        10'sd14  // bucket 3: d_norm in [1.75, 2.00)
    };

    localparam logic [1:0] S_IDLE = 2'd0,
                           S_RUN  = 2'd1,
                           S_DONE = 2'd2;

    logic [1:0] r_state;
    logic       r_busy;
    logic       r_done;
    logic       r_dbz;

    logic [DATA_WIDTH-1:0]        r_d;
    logic [PW-1:0]                r_p;
    logic [REXT-1:0]              r_S;
    logic [REXT-1:0]              r_C;
    logic signed [DATA_WIDTH+1:0] r_Q;
    logic signed [DATA_WIDTH+1:0] r_QM;
    logic [DATA_WIDTH-1:0]        r_x_shift;
    logic [COUNT_W-1:0]           r_count;

    logic [REXT-1:0]              w_a_t, w_b_t, w_c_t;
    logic [REXT-1:0]              w_Sx, w_Cx;
    logic signed [REXT-1:0]       w_t_true;
    logic signed [9:0]            w_est;
    logic [1:0]                   w_bucket;
    logic signed [1:0]            w_q;
    logic [REXT-1:0]              w_term;
    logic [REXT-1:0]              w_a_r, w_b_r, w_c_r;
    logic [REXT-1:0]              w_Sy, w_Cy;
    logic signed [DATA_WIDTH+1:0] w_Q_next;
    logic signed [DATA_WIDTH+1:0] w_QM_next;
    logic signed [REXT-1:0]       w_final_R;
    logic signed [DATA_WIDTH-1:0] w_rem_out;

    assign ow_busy     = r_busy;
    assign ow_done     = r_done;
    assign ow_dbz      = r_dbz;
    assign ow_quotient = (w_final_R < 0) ? r_QM[DATA_WIDTH-1:0] : r_Q[DATA_WIDTH-1:0];
    assign ow_remainder= w_rem_out;

    function automatic [PW-1:0] msb_pos(input [DATA_WIDTH-1:0] d);
        msb_pos = '0;
        for (int i = 0; i < DATA_WIDTH; i++) begin
            if (d[i]) msb_pos = i[PW-1:0];
        end
    endfunction

    always_comb begin
        // t = 2(S+C) + x_i, formed as a 3:2 carry-save compression.
        w_a_t = (r_S << 1) & MASK;
        w_b_t = (r_C << 1) & MASK;
        w_c_t = {{(REXT-1){1'b0}}, r_x_shift[DATA_WIDTH-1]};
        w_Sx  = w_a_t ^ w_b_t ^ w_c_t;
        w_Cx  = (((w_a_t & w_b_t) | (w_a_t & w_c_t) | (w_b_t & w_c_t)) << 1) & MASK;

        // Signed estimate of t in units of 2^p/32.
        w_t_true = signed'(w_Sx) + signed'(w_Cx);
        // 10-bit signed: est range is +/-256 (|t| <= ~2D, grid 2^p/32).
        if (r_p < 5) w_est = 10'(w_t_true <<< (5 - r_p));
        else         w_est = 10'(w_t_true >>> (r_p - 5));

        // Bucket from the top two bits of the normalized divisor.
        w_bucket = 2'(((32'(r_d) << 2) >> r_p) - 4);

        // Digit selection from the estimate and the per-bucket threshold.
        if (w_est >= SRT2CSA_TAB[w_bucket])      w_q = 2'sd1;
        else if (w_est <= -SRT2CSA_TAB[w_bucket]) w_q = -2'sd1;
        else                                     w_q = 2'sd0;

        // R = t - q*D via carry-save addition of Sx, Cx, and (-q*D).
        case (w_q)
            2'sd1:   w_term = (~{{(REXT-DATA_WIDTH){1'b0}}, r_d} + 1'b1) & MASK;
            -2'sd1:  w_term = {{(REXT-DATA_WIDTH){1'b0}}, r_d};
            default: w_term = {REXT{1'b0}};
        endcase
        w_a_r = w_Sx;
        w_b_r = w_Cx;
        w_c_r = w_term;
        w_Sy  = w_a_r ^ w_b_r ^ w_c_r;
        w_Cy  = (((w_a_r & w_b_r) | (w_a_r & w_c_r) | (w_b_r & w_c_r)) << 1) & MASK;

        // On-the-fly radix-2 Q/QM conversion.
        case (w_q)
            2'sd1: begin
                w_Q_next  = (r_Q <<< 1) + C_ONE;
                w_QM_next = (r_Q <<< 1);
            end
            2'sd0: begin
                w_Q_next  = (r_Q <<< 1);
                w_QM_next = (r_QM <<< 1) + C_ONE;
            end
            default: begin
                w_Q_next  = (r_QM <<< 1) + C_ONE;
                w_QM_next = (r_QM <<< 1);
            end
        endcase

        // Final true remainder from one carry-propagate add (off the critical path).
        w_final_R = signed'(r_S) + signed'(r_C);
        w_rem_out = (w_final_R < 0) ? DATA_WIDTH'(w_final_R + signed'({1'b0, r_d}))
                                    : w_final_R[DATA_WIDTH-1:0];
    end

    `ALWAYS_FF_RST(i_clk, i_rst_n,
        if (`RST_ASSERTED(i_rst_n)) begin
            r_state    <= S_IDLE;
            r_busy     <= 1'b0;
            r_done     <= 1'b0;
            r_dbz      <= 1'b0;
            r_d        <= {DATA_WIDTH{1'b0}};
            r_p        <= {PW{1'b0}};
            r_S        <= {REXT{1'b0}};
            r_C        <= {REXT{1'b0}};
            r_Q        <= '0;
            r_QM       <= -1;
            r_x_shift  <= {DATA_WIDTH{1'b0}};
            r_count    <= {COUNT_W{1'b0}};
        end else begin
            r_done <= 1'b0;
            case (r_state)
                S_IDLE: begin
                    if (i_valid) begin
                        if (i_divisor == {DATA_WIDTH{1'b0}}) begin
                            r_dbz      <= 1'b1;
                            r_done     <= 1'b1;
                            r_busy     <= 1'b0;
                            r_Q        <= '0;
                            r_QM       <= -1;
                            r_S        <= {REXT{1'b0}};
                            r_C        <= {REXT{1'b0}};
                            r_state    <= S_DONE;
                        end else begin
                            r_dbz      <= 1'b0;
                            r_busy     <= 1'b1;
                            r_d        <= i_divisor;
                            r_p        <= msb_pos(i_divisor);
                            r_S        <= {REXT{1'b0}};
                            r_C        <= {REXT{1'b0}};
                            r_Q        <= '0;
                            r_QM       <= -1;
                            r_x_shift  <= i_dividend;
                            r_count    <= COUNT_W'(DATA_WIDTH - 1);
                            r_state    <= S_RUN;
                        end
                    end
                end

                S_RUN: begin
                    r_S       <= w_Sy;
                    r_C       <= w_Cy;
                    r_Q       <= w_Q_next;
                    r_QM      <= w_QM_next;
                    r_x_shift <= {r_x_shift[DATA_WIDTH-2:0], 1'b0};
                    if (r_count == {COUNT_W{1'b0}}) begin
                        r_busy  <= 1'b0;
                        r_done  <= 1'b1;
                        r_state <= S_DONE;
                    end else begin
                        r_count <= r_count - 1'b1;
                    end
                end

                S_DONE: begin
                    r_state <= S_IDLE;
                end

                default: begin
                    r_state <= S_IDLE;
                end
            endcase
        end
    )

endmodule : math_divider_srt_radix2_csa
