"""Generate the lockstep pair wrapper for one pick core (memory-controllers MC-028).

The wrapper instantiates the core as it is now and its pre-MC-028 copy
(<core>_pre028) with the same parameters and the same inputs, sliced from one
free bus, and returns one mismatch bit per output. The plain-Verilog harness
beside it makes the bus free per cycle and asserts no mismatch.

    gen_pair.py <core> <rtl.sv> <out.sv> [--strobe-gated name=strobe_expr ...]

--strobe-gated compares an output only while the given expression (in gold's
outputs, g_<port>) holds, for outputs whose idle value is not part of the
contract (the row lane's bank / row bus between fires).
"""
import argparse
import re
import sys
from pathlib import Path


def header(text: str, core: str) -> str:
    i = text.index("\nmodule " + core)
    j = re.search(r"\n\s*\);\s*\n", text[i:]).end() + i
    return re.sub(r"//[^\n]*", "", text[i:j])


def write_harness(core: str, n_out: int, path: str, names: str) -> None:
    """The plain-Verilog top read by yosys: free bus, reset, the assertions."""
    h = f"""// SPDX-License-Identifier: MIT
// GENERATED by formal/mc_common/mc_row_lane/gen_pair.py -- do not edit.
//
// memory-controllers MC-028 step A: {core} with the row lane in mc_row_lane
// against {core}_pre028, every output every cycle after reset (the strobe-
// gated buses only while gold fires on them). The inputs are one free bus,
// new each cycle, so equivalence holds for whatever the environment presents,
// stronger than the system can produce. Parameters are set on {core}_pair
// (chparam in the .sby).
//
// mism bit map:
{names}
`timescale 1ns / 1ps
module formal_{core}_equiv (
    input clk,
    input rst_n
);
    (* anyseq *) reg [8191:0] free;
    wire [{n_out}-1:0] mism;
    wire       fits;
    wire [3:0] cov;
    {core}_pair u_pair (.aclk(clk), .aresetn(rst_n), .free_i(free),
                        .mism_o(mism), .in_fits_o(fits), .cov_o(cov));

    reg [7:0] f_past_valid = 0;
    always @(posedge clk) f_past_valid <= f_past_valid + (f_past_valid < 8'hFF);
    initial assume (!rst_n);
    always @(posedge clk) if (f_past_valid >= 2) assume (rst_n);

    always @(posedge clk) begin
        a_fits: assert (fits);
        if (rst_n) a_equiv: assert (mism == 0);
    end
    // not vacuous: the lane fires both classes, the main lane issues
    always @(posedge clk) if (rst_n) begin
        c_lane_act: cover (cov[0]);
        c_lane_pre: cover (cov[1]);
        c_cmd:      cover (cov[2]);
    end
endmodule
"""
    Path(path).write_text(h)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("core")
    ap.add_argument("rtl")
    ap.add_argument("out")
    ap.add_argument("--strobe-gated", action="append", default=[])
    a = ap.parse_args()

    hdr = header(Path(a.rtl).read_text(), a.core)
    params = [l.strip().rstrip(",") for l in hdr.split("\n")
              if re.match(r"\s*parameter\b", l)]
    ports = []
    for l in hdr.split("\n"):
        m = re.match(r"\s*(input|output)\s+(.*?)\s*(\w+)\s*,?\s*$", l)
        if m:
            ports.append((m.group(1), m.group(2), m.group(3)))
    if not ports or not params:
        print(f"gen_pair: no ports / params parsed from {a.rtl}", file=sys.stderr)
        return 1
    gated = dict(g.split("=", 1) for g in a.strobe_gated)
    pnames = [re.match(r"parameter\s+(?:\w+\s+)?(\w+)", p).group(1) for p in params]
    ins = [(t, n) for d, t, n in ports if d == "input" and n not in ("aclk", "aresetn")]
    outs = [(t, n) for d, t, n in ports if d == "output"]
    unknown = set(gated) - {n for _, n in outs}
    if unknown:
        print(f"gen_pair: --strobe-gated names no output: {sorted(unknown)}", file=sys.stderr)
        return 1

    o = []
    o.append("// SPDX-License-Identifier: MIT")
    o.append(f"// GENERATED by formal/mc_common/mc_row_lane/gen_pair.py from {a.core}.sv -- do not edit;")
    o.append("// rerun `make pair` here after a port change.")
    o.append("//")
    o.append(f"// Lockstep pair for memory-controllers MC-028: {a.core} (now) against")
    o.append(f"// {a.core}_pre028 (its copy before the row lane moved into mc_row_lane),")
    o.append("// same parameters, same inputs from one free bus, one mismatch bit per output.")
    o.append("`timescale 1ns / 1ps")
    o.append(f"module {a.core}_pair")
    o.append("    import mc_common_pkg::*;")
    o.append("#(")
    o.append(",\n".join("    " + p for p in params) + ",")
    o.append("    parameter int FREE_W = 8192")
    o.append(") (")
    o.append("    input  logic              aclk,")
    o.append("    input  logic              aresetn,")
    o.append("    input  logic [FREE_W-1:0] free_i,")
    o.append(f"    output logic [{len(outs)}-1:0]    mism_o,")
    o.append("    output logic              in_fits_o,")
    o.append("    output logic [3:0]        cov_o")
    o.append(");")
    o.append("    typedef struct packed {")
    for t, n in ins:
        o.append(f"        {t} {n};")
    o.append("    } in_t;")
    o.append("    localparam int IN_W = $bits(in_t);")
    o.append("    in_t w_in;")
    o.append("    assign w_in      = in_t'(free_i[IN_W-1:0]);")
    o.append("    assign in_fits_o = (IN_W <= FREE_W);")
    for t, n in outs:
        o.append(f"    {t} n_{n}, g_{n};")
    pmap = ", ".join(f".{p}({p})" for p in pnames)

    def inst(mod: str, pre: str, name: str) -> None:
        o.append(f"    {mod} #({pmap}) {name} (")
        conns = [".aclk(aclk)", ".aresetn(aresetn)"]
        conns += [f".{n}(w_in.{n})" for _, n in ins]
        conns += [f".{n}({pre}{n})" for _, n in outs]
        o.append(",\n".join("        " + c for c in conns))
        o.append("    );")

    inst(a.core, "n_", "u_new")
    inst(a.core + "_pre028", "g_", "u_gold")
    for k, (t, n) in enumerate(outs):
        cmp = f"(n_{n} != g_{n})"
        if n in gated:
            cmp = f"(({gated[n]}) && {cmp})"
        o.append(f"    assign mism_o[{k}] = {cmp};   // {n}")
    have = {n for _, n in outs}
    cov = [f"g_{x}" for x in ("row2_act_o", "row2_pre_o") if x in have]
    cov += ["g_cmd_valid_o" if "cmd_valid_o" in have else "1'b0"]
    while len(cov) < 4:
        cov.append("1'b0")
    o.append(f"    assign cov_o = {{{', '.join(reversed(cov[:4]))}}};")
    o.append(f"endmodule : {a.core}_pair")
    Path(a.out).write_text("\n".join(o) + "\n")
    names = "\n".join(f"//   mism[{k}] {n}" for k, (_, n) in enumerate(outs))
    Path(a.out.replace(".sv", "_map.txt")).write_text(names + "\n")
    write_harness(a.core, len(outs), a.out.replace("_pair.sv", "_equiv.sv"), names)
    print(f"gen_pair: {a.out}: {len(ins)} inputs, {len(outs)} outputs, {len(gated)} strobe-gated")
    return 0


if __name__ == "__main__":
    sys.exit(main())
