"""Derive the 16-channel STREAM register map and top from the 8-channel ones.

The 8-channel sources are hand-written: rtl/macro/stream_regs.rdl (with
stream_mon_regs.rdl) and rtl/top/stream_top_ch8.sv. The 16-channel versions
differ only where a channel count shows, so they are DERIVED, never edited
(the RAPIDS counterpart is rapids/bin/gen_rapids_regs_16ch.py):

    CH8..CH15_CTRL_{LOW,HIGH}        0x040-0x07C (free in the 8-ch map)
    KICK_ENABLE                      KICK0..KICK15 (stays at 0x128)
    per-channel bit fields           [7:0] -> [15:0] (enable, reset, idle,
                                     scheduler error, read/write complete)
    CH_STATE                         [8] @ 0x150 -> [16] @ 0x180 (16 entries
                                     would overrun SCHED_ERROR at 0x170)
    VERSION.NUM_CHANNELS             8 -> 16
    OBS_CTRL                         CH_SEL [2:0] -> [3:0], CAT_SEL [4:3] -> [5:4]
    PERF_CH_SEL.CH_SEL               [2:0] -> [3:0]
    {RD,WR}MON_PERF_CH_OVERFLOW_HI   new, MON +0x1F8 / +0x1FC: channels 8..15

Also written:
  rtl/top/generated/regsel_{8,16}ch/stream_regsel*.svh  -- the regblock module,
      hwif types, field width and per-channel-by-name glue stream_top_ch8.sv
      includes (the filelist picks the variant by +incdir)
  rtl/top/stream_top_ch16.sv  -- stream_top_ch8.sv renamed, NUM_CHANNELS 16,
      AXI_USER_WIDTH 4

    python3 bin/gen_stream_regs_16ch.py           # (re)write
    python3 bin/gen_stream_regs_16ch.py --check   # exit 1 if anything is stale

Every rewrite asserts it matched exactly as often as expected, so a change to
an 8-channel source this script does not understand fails here instead of
producing a quietly wrong 16-channel version. After a rewrite regenerate the
16-channel regblock with bin/peakrdl_generate.py.
"""

import argparse
import re
import sys
from pathlib import Path

STREAM = Path(__file__).resolve().parent.parent
RTL = STREAM / 'rtl'
SRC = RTL / 'macro'
OUT_RDL = SRC / 'generated_16ch'
OUT_SEL = RTL / 'top' / 'generated'

STAMP = ("// Generated by: projects/components/dma-ip/stream/bin/gen_stream_regs_16ch.py -- DO NOT EDIT\n"
         "// Source: the 8-channel version (edit that, then rerun the script).\n")

CH_FIELDS = ('CH_EN', 'CH_RST', 'CH_IDLE', 'DESC_IDLE', 'SCHED_IDLE', 'SCHED_ERR',
             'RD_COMPLETE', 'WR_COMPLETE')


def sub(text, old, new, count=1):
    n = text.count(old)
    if n != count:
        sys.exit(f"gen_stream_regs_16ch: expected {count} x {old!r}, found {n}")
    return text.replace(old, new)


def resub(text, pattern, repl, count=1):
    out, n = re.subn(pattern, repl, text)
    if n != count:
        sys.exit(f"gen_stream_regs_16ch: expected {count} x /{pattern}/, found {n}")
    return out


def regs_16ch(src):
    t = sub(src, '`include "stream_mon_regs.rdl"', '`include "stream_mon_regs_16ch.rdl"')
    t = sub(t, 'addrmap stream_regs {', 'addrmap stream_regs_16ch {')
    t = sub(t, 'stream_mon_regs MON @ 0x1000;', 'stream_mon_regs_16ch MON @ 0x1000;')

    lo7 = re.search(r'^.*CH7_CTRL_LOW  @ 0x038;\n', t, re.M)
    hi7 = re.search(r'^.*CH7_CTRL_HIGH @ 0x03C;\n', t, re.M)
    if not (lo7 and hi7):
        sys.exit("gen_stream_regs_16ch: CH7_CTRL_LOW/HIGH not found")
    extra = ''
    for ch in range(8, 16):
        extra += (lo7.group(0).replace('Ch7', f'Ch{ch}').replace('CH7_CTRL_LOW  ', f'CH{ch}_CTRL_LOW ')
                  .replace('0x038', f'0x{ch * 8:03X}'))
        extra += (hi7.group(0).replace('Ch7', f'Ch{ch}').replace('CH7_', f'CH{ch}_')
                  .replace('0x03C', f'0x{ch * 8 + 4:03X}'))
    t = t[:hi7.end()] + extra + t[hi7.end():]

    k7 = '          field { sw=w; hw=r; singlepulse; } KICK7[7:7]=0;\n'
    t = sub(t, k7, k7 + ''.join(f'          field {{ sw=w; hw=r; singlepulse; }} KICK{c}[{c}:{c}]=0;\n'
                                for c in range(8, 16)))
    t = sub(t, '          field { sw=r; hw=na; } RSVD[31:8]=0; } KICK_ENABLE @ 0x128;',
             '          field { sw=r; hw=na; } RSVD[31:16]=0; } KICK_ENABLE @ 0x128;')

    for f in CH_FIELDS:
        t = resub(t, rf"\}} {f}\[7:0\]( = 8'h00)?;",
                  lambda m, f=f: f"}} {f}[15:0]" + (" = 16'h0000" if m.group(1) else '') + ';')
    t = resub(t, r'(bits) \[7:0\] - ', r'\1 [15:0] - ', count=len(CH_FIELDS))
    t = resub(t, r"(\} (?:CH_EN|CH_RST|CH_IDLE|DESC_IDLE|SCHED_IDLE|SCHED_ERR|RD_COMPLETE|WR_COMPLETE)"
                 r"\[15:0\](?: = 16'h0000)?;\n\n        field \{\n            desc = \"Reserved\";\n"
                 r"            sw = r;\n            hw = na;\n        \}) RSVD\[31:8\] = 24'h0;",
              r"\1 RSVD[31:16] = 16'h0;", count=len(CH_FIELDS))

    t = sub(t, '} CH_STATE[8] @ 0x150 += 0x4;', '} CH_STATE[16] @ 0x180 += 0x4;')
    t = sub(t, "} NUM_CHANNELS[23:16] = 8'h08;", "} NUM_CHANNELS[23:16] = 8'h10;")
    # OBS_CTRL: CH_SEL widens, CAT_SEL moves up one bit
    t = sub(t, "} CH_SEL[2:0] = 3'b0;", "} CH_SEL[3:0] = 4'b0;")
    t = sub(t, "} CAT_SEL[4:3] = 2'b0;", "} CAT_SEL[5:4] = 2'b0;")
    t = sub(t, "} RSVD[31:5] = 27'h0;\n\n    } OBS_CTRL @ 0x2C0;", "} RSVD[31:6] = 26'h0;\n\n    } OBS_CTRL @ 0x2C0;")
    # PERF_CH_SEL
    t = sub(t, "} CH_SEL[2:0] = 3'h0;", "} CH_SEL[3:0] = 4'h0;")
    t = sub(t, "} RSVD[31:3] = 29'h0;\n\n    } PERF_CH_SEL", "} RSVD[31:4] = 28'h0;\n\n    } PERF_CH_SEL")
    return STAMP + t


def mon_16ch(src):
    t = sub(src, 'regfile stream_mon_regs {', 'regfile stream_mon_regs_16ch {')
    hi = '''
    reg {{
        name = "{name} Per-Channel Overflow Stickies, channels 8-15";
        desc = "Channels 8..15 of {low} (4 bits/channel, channel 8 in the low nibble).";

        field {{
            desc = "Per-channel overflow mask, channels 8..15";
            sw = r;
            hw = w;
        }} VAL[31:0];

    }} {low}_HI @ {addr};
'''
    add = (hi.format(name='Read Datapath', low='RDMON_PERF_CH_OVERFLOW', addr='0x1F8')
           + hi.format(name='Write Datapath', low='WRMON_PERF_CH_OVERFLOW', addr='0x1FC'))
    t = sub(t, '    } WRMON_PERF_CH_OVERFLOW @ 0x1F4;\n', '    } WRMON_PERF_CH_OVERFLOW @ 0x1F4;\n' + add)
    return STAMP + t


def regsel(nch):
    mod, pkg = ('stream_regs', 'stream_regs_pkg') if nch == 8 else ('stream_regs_16ch', 'stream_regs_16ch_pkg')
    hdr = STAMP.replace('// Source: the 8-channel version', f'// {nch}-channel variant; source: the 8-channel version')
    defs = (hdr + f'''// Selected by +incdir (rtl/filelists/top/stream_top_ch{nch}.f).
`ifndef STREAM_REGSEL_SVH
`define STREAM_REGSEL_SVH
`define STREAM_REGS_NCH   {nch}
`define STREAM_REGS_MOD   {mod}
`define STREAM_REGS_IN_T  {pkg}::{mod}__in_t
`define STREAM_REGS_OUT_T {pkg}::{mod}__out_t
`endif
''')
    kick = hdr + '// Body of the kick always_comb in stream_top_ch8: registers that exist per channel by name.\n'
    for c in range(nch):
        kick += (f'        w_staged_addr[{c}] = {{hwif_out.CH{c}_CTRL_HIGH.DESC_ADDR_HIGH.value, '
                 f'hwif_out.CH{c}_CTRL_LOW.DESC_ADDR_LOW.value}};\n')
    for c in range(nch):
        kick += f'        w_kick_pulse[{c}] = hwif_out.KICK_ENABLE.KICK{c}.value;\n'
    status = hdr + '// Inside the hwif_in always_comb of stream_top_ch8: per-variant status fields.\n'
    if nch == 16:
        status += ("        hwif_in.MON.RDMON_PERF_CH_OVERFLOW_HI.VAL.next = 32'(64'(rdmon_ch_overflow) >> 32);\n"
                   "        hwif_in.MON.WRMON_PERF_CH_OVERFLOW_HI.VAL.next = 32'(64'(wrmon_ch_overflow) >> 32);\n")
    d = OUT_SEL / f'regsel_{nch}ch'
    return {d / 'stream_regsel.svh': defs, d / 'stream_regsel_kick.svh': kick,
            d / 'stream_regsel_status.svh': status}


def top_16ch(src):
    t = sub(src, 'module stream_top_ch8 #(', 'module stream_top_ch16 #(')
    t = sub(t, 'endmodule : stream_top_ch8', 'endmodule : stream_top_ch16')
    t = resub(t, r'(\n    parameter int NUM_CHANNELS = )8,', r'\g<1>16,')
    t = resub(t, r'(\n    parameter int AXI_USER_WIDTH = )3,', r'\g<1>4,')
    t = re.sub(r'^// Module: stream_top_ch8', '// Module: stream_top_ch16', t, count=1, flags=re.M)
    return STAMP + '// 16-channel STREAM: NUM_CHANNELS = 16 and the 16-channel register map\n' \
        '// (compile with rtl/filelists/top/stream_top_ch16.f, which selects it).\n' + t


def outputs():
    rd = lambda p: p.read_text()
    out = {
        OUT_RDL / 'stream_regs_16ch.rdl': regs_16ch(rd(SRC / 'stream_regs.rdl')),
        OUT_RDL / 'stream_mon_regs_16ch.rdl': mon_16ch(rd(SRC / 'stream_mon_regs.rdl')),
        RTL / 'top' / 'stream_top_ch16.sv': top_16ch(rd(RTL / 'top' / 'stream_top_ch8.sv')),
    }
    out.update(regsel(8))
    out.update(regsel(16))
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--check', action='store_true', help='exit 1 if any output is stale')
    args = ap.parse_args()
    stale = 0
    for path, text in outputs().items():
        rel = path.relative_to(STREAM)
        cur = path.read_text() if path.exists() else None
        if args.check:
            if cur != text:
                print(f"STALE {rel}")
                stale += 1
        elif cur != text:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
            print(f"wrote {rel}")
        else:
            print(f"unchanged {rel}")
    if args.check:
        print("all 16-channel STREAM outputs current" if not stale else f"{stale} stale")
    return 1 if stale else 0


if __name__ == '__main__':
    sys.exit(main())
