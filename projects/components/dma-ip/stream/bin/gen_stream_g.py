"""Generate the stream-g tree (stream TASK-020) from the product STREAM.

stream-g is STREAM with its schedulers sequenced by one gatling per core
(fub_g/scheduler_g + the rapids-g sequencer block rapids_seq_g, reused as is).
Above the schedulers the RTL is the product's, so it is DERIVED here rather
than copied by hand, as rapids/bin/gen_rapids_g.py derives rapids-g:

    rtl/macro_g/generated/scheduler_group_array_g.sv  <- macro/scheduler_group_array.sv
    rtl/macro_g/generated/stream_core_g.sv            <- macro/stream_core.sv
    rtl/top_g/generated/stream_g_top_ch8.sv           <- top/stream_top_ch8.sv
    rtl/top_g/generated/stream_g_top_ch16.sv          <- top/stream_top_ch16.sv (itself derived
                                                         from the 8-channel top by gen_stream_regs_16ch.py)

Every edit is a module rename or an anchored insertion that must match the
expected number of times; a product change that moves an anchor fails the run
instead of producing a wrong file. The array takes the hand-written sequencer
block rtl/macro_g/scheduler_group_array_g_seq.svh; the tops take
rtl/top_g/stream_g_top_reg_arb.svh (the register mailbox arbiter) and
rtl/top_g/stream_g_top_fw.svh (the firmware load).

    python3 bin/gen_stream_g.py           # (re)write the generated -g RTL
    python3 bin/gen_stream_g.py --check   # exit 1 if any of it is stale

Never hand-edit a generated file: change the product, the .svh or this
script, and rerun. The firmware is rapids-g's (rapids/bin/gen_rapids_g_fw.py):
the scheduler_g window is the same, so one image serves both.
"""
import argparse
import sys
from pathlib import Path

RTL = Path(__file__).resolve().parent.parent / 'rtl'
STAMP = "// Generated by: projects/components/dma-ip/stream/bin/gen_stream_g.py -- DO NOT EDIT"

# --- the array ---------------------------------------------------------------
SCHED_PORT_ANCHOR = """                .cfg_rd_prefetch_enable (cfg_rd_prefetch_enable),
                .scheduler_idle         (scheduler_idle[ch]),
"""
SEQ_PORTS = """                .cfg_rd_prefetch_enable (cfg_rd_prefetch_enable),
                .seq_wr_en              (g_seq_wr_en[ch]),
                .seq_wr_addr            (g_seq_wr_addr),
                .seq_wr_data            (g_seq_wr_data),
                .seq_rd_addr            (g_seq_rd_addr),
                .seq_rd_data            (g_seq_rd_data[ch]),
                .seq_attn               (g_seq_attn[ch]),
                .seq_fault              (g_seq_fault[ch]),
                .seq_alg_max            (g_seq_alg_max),
                .scheduler_idle         (scheduler_idle[ch]),
"""
SEQ_LOOP_ANCHOR = "        for (genvar ch = 0; ch < NUM_CHANNELS; ch++) begin : gen_schedulers\n"
GEN_ANCHOR = "    generate\n    if (SHARED_ENGINES == 0) begin : g_per_channel\n"
FATAL_G = """    // stream-g: the schedulers are scheduler_g, which exist only in the
    // shared-engine structure; one gatling serves 4, 8 or 16 of them.
    initial begin
        if (SHARED_ENGINES == 0)
            $fatal(1, "scheduler_group_array_g: stream-g needs SHARED_ENGINES = 1");
        if ((NUM_CHANNELS != 4) && (NUM_CHANNELS != 8) && (NUM_CHANNELS != 16))
            $fatal(1, "scheduler_group_array_g: NUM_CHANNELS must be 4, 8 or 16, got %0d", NUM_CHANNELS);
    end

"""

# The register-mailbox master the gatling drives (rapids_seq_g -> the top's
# rapids_g_reg_arb), passed up through every level.
REG_SIGS = (('output', '', 'cmd_valid'), ('input ', '', 'cmd_ready'), ('output', '', 'cmd_pwrite'),
            ('output', '[11:0]', 'cmd_paddr'), ('output', '[31:0]', 'cmd_pwdata'),
            ('input ', '', 'rsp_valid'), ('output', '', 'rsp_ready'),
            ('input ', '[31:0]', 'rsp_prdata'), ('input ', '', 'rsp_pslverr'))
RST_CAM_PORT = ("    input  logic                        rst_n,\n"
                "    input  logic                        cam_clear,  // sync clear of monitor trans CAMs\n")
# The gatling's restart (rapids_seq_g), one input from the top down
RESTART_PORT = f"    input  logic {'':<26} seq_restart,\n"
RESTART_CONN = "        .seq_restart            (seq_restart),\n"
CAM_PORT = "    input  logic                                    cam_clear,\n"
CAM_PORT_G = (CAM_PORT + "    // stream-g: one cycle restarts the gatling's harts (rapids_seq_g); pulse it\n"
              "    // only while every channel is idle, tie it to 0 otherwise\n"
              "    input  logic                                    seq_restart,\n")


def reg_ports(prefix, why=None):
    lines = [f"    // stream-g: {why}"] if why else []
    lines += [f"    {d} logic {w:<26} {prefix}seq_reg_{n}," for d, w, n in REG_SIGS]
    return "\n".join(lines) + "\n"


def reg_conns(port_prefix, net_prefix):
    return "".join(f"        .{port_prefix}seq_reg_{n:<12} ({net_prefix}seq_reg_{n}),\n" for _, _, n in REG_SIGS)


# The firmware-load bus (stream TASK-020, as rapids TASK-038): the FW_*
# registers -> the gatling (rapids_seq_g fw_*), passed down through every
# level. Inputs below the top; fw_rd_data comes back up for FW_RDATA.
FW_SIGS = (('input ', '', 'hold'), ('input ', '', 'wr_en'), ('input ', '[15:0]', 'addr'),
           ('input ', '[31:0]', 'wr_data'), ('input ', '[7:0]', 'alg_max'),
           ('output', '[31:0]', 'rd_data'))
FW_PARAM = ("\n    // stream-g: 1 = the gatling instruction memory is writable through the\n"
            "    // FW_* registers (stream TASK-020); 0 = a ROM holding the generated image\n"
            "    parameter int FW_WRITABLE = 0,")
FW_PCONN = "        .FW_WRITABLE            (FW_WRITABLE),\n"


def fw_ports(prefix, why=None):
    lines = [f"    // stream-g: {why}"] if why else []
    lines += [f"    {d} logic {w:<26} {prefix}fw_{n}," for d, w, n in FW_SIGS]
    return "\n".join(lines) + "\n"


def fw_conns(port_prefix, net_prefix):
    return "".join(f"        .{port_prefix}fw_{n:<17} ({net_prefix}fw_{n}),\n" for _, _, n in FW_SIGS)


# --- the tops ----------------------------------------------------------------
# The FW_* read-back fields the product top ties to 0 (the register block
# decodes them either way); the -g top drives them from the firmware glue.
FW_HWIF_PRODUCT = """        // Firmware-load registers (stream TASK-020): a stream-g build drives
        // these from its gatling; here they read as "no firmware".
        hwif_in.FW_CTRL.WRITABLE.next  = 1'b0;
        hwif_in.FW_CTRL.STREAM_G.next  = 1'b0;
        hwif_in.FW_RDATA.DATA.next     = 32'h0;
        hwif_in.FW_ADDR.ADDR.we        = 1'b0;
        hwif_in.FW_ADDR.ADDR.next      = 16'h0;
"""
FW_HWIF_G = """        // stream-g firmware load: FW_WRITABLE, the word at FW_ADDR, the advance
        hwif_in.FW_CTRL.WRITABLE.next  = (FW_WRITABLE != 0);
        hwif_in.FW_CTRL.STREAM_G.next  = 1'b1;
        hwif_in.FW_RDATA.DATA.next     = w_fw_rd_data;
        hwif_in.FW_ADDR.ADDR.we        = w_fw_adv;
        hwif_in.FW_ADDR.ADDR.next      = hwif_out.FW_ADDR.ADDR.value + 16'd1;
"""
FW_GLUE_ANCHOR = "    always_comb begin\n        hwif_in.GLOBAL_STATUS.SYSTEM_IDLE.next = hwif_system_idle;\n"
FW_TOP_CONNS = "".join(
    f"        .fw_{n:<17} ({v}),\n"
    for n, v in (('hold', "hwif_out.FW_CTRL.HOLD.value"), ('wr_en', "w_fw_wr"),
                 ('addr', "hwif_out.FW_ADDR.ADDR.value"), ('wr_data', "hwif_out.FW_DATA.DATA.value"),
                 ('alg_max', "hwif_out.FW_CTRL.ALG_MAX.value"), ('rd_data', "w_fw_rd_data")))
# Both APB slaves (CDC and pass-through branches) hand their cmd/rsp to the
# arbiter under the host_* names
APB4_RENAME = [(f"                .{p:<23}(apb_{p}),", f"                .{p:<23}(host_{p}),", 2)
               for p in ('cmd_valid', 'cmd_ready', 'cmd_pwrite', 'cmd_paddr', 'cmd_pwdata', 'cmd_pstrb',
                         'rsp_valid', 'rsp_ready', 'rsp_prdata')]
APB4_RENAME.append(("                .rsp_pslverr            (apb_rsp_pslverr)\n",
                    "                .rsp_pslverr            (host_rsp_pslverr)\n", 2))
# The arbiter include DECLARES the host_* nets the two APB slave instances
# connect to, so it must land BEFORE their generate block, not after it. With
# the include after them Verilator resolved the names anyway, but Vivado made
# implicit 1-bit nets at the instances and declared the real ones separately:
# the host register path was dead in silicon ("Net host_cmd_valid ... does not
# have driver"), found on the Genesys 2 (stream TASK-020 phase 6).
REG_ARB_ANCHOR = "    generate\n        if (CDC_ENABLE != 0) begin : g_apb4_slave_cdc\n"


def top_job(nch):
    stem = f"stream_top_ch{nch}"
    return (f"top_g/generated/stream_g_top_ch{nch}.sv", f"top/{stem}.sv", [
        (f"module {stem} #(", f"module stream_g_top_ch{nch} #("),
        (f"endmodule : {stem}\n", f"endmodule : stream_g_top_ch{nch}\n"),
        (f"    parameter int NUM_CHANNELS = {nch},\n",
         f"    parameter int NUM_CHANNELS = {nch},\n" + FW_PARAM.lstrip("\n") + "\n"),
        (CAM_PORT, CAM_PORT_G),
        ("            stream_core #(\n", "            stream_core_g #(\n" + "        " + FW_PCONN, 2),
        ("            ) u_stream_core (\n", "            ) u_stream_core (\n" + RESTART_CONN
         + reg_conns('', 'w_') + FW_TOP_CONNS, 2),
        (REG_ARB_ANCHOR, '`include "stream_g_top_reg_arb.svh"\n\n' + REG_ARB_ANCHOR),
        (FW_GLUE_ANCHOR, '`include "stream_g_top_fw.svh"\n\n' + FW_GLUE_ANCHOR),
        (FW_HWIF_PRODUCT, FW_HWIF_G),
    ] + APB4_RENAME, f"the {nch}-channel top")


# (generated file, source, [(old, new[, count])], what it is)
JOBS = (
    ('macro_g/generated/scheduler_group_array_g.sv', 'macro/scheduler_group_array.sv', [
        ("module scheduler_group_array #(", "module scheduler_group_array_g #(" + FW_PARAM),
        ("endmodule : scheduler_group_array\n", "endmodule : scheduler_group_array_g\n"),
        (GEN_ANCHOR, FATAL_G + GEN_ANCHOR),
        (SEQ_LOOP_ANCHOR, '`include "scheduler_group_array_g_seq.svh"\n\n' + SEQ_LOOP_ANCHOR),
        ("            scheduler #(\n", "            scheduler_g #(\n"),
        (SCHED_PORT_ANCHOR, SEQ_PORTS),
        (RST_CAM_PORT, RST_CAM_PORT + RESTART_PORT
         + reg_ports('', "the register mailbox (rapids_seq_g -> the top's rapids_g_reg_arb)")
         + fw_ports('', "the firmware load (FW_* registers -> rapids_seq_g)")),
    ], "the scheduler array, its schedulers sequenced by one gatling"),
    ('macro_g/generated/stream_core_g.sv', 'macro/stream_core.sv', [
        ("module stream_core #(", "module stream_core_g #(" + FW_PARAM),
        ("endmodule : stream_core\n", "endmodule : stream_core_g\n"),
        ("    scheduler_group_array #(\n", "    scheduler_group_array_g #(\n" + FW_PCONN),
        (RST_CAM_PORT, RST_CAM_PORT + RESTART_PORT + reg_ports('', "the register mailbox")
         + fw_ports('', "the firmware load")),
        ("    ) u_scheduler_group_array (\n", "    ) u_scheduler_group_array (\n" + RESTART_CONN
         + reg_conns('', '') + fw_conns('', '')),
    ], "the core"),
    top_job(8),
    top_job(16),
)


def derive(src_rel, edits, what):
    text = (RTL / src_rel).read_text()
    for edit in edits:
        old, new = edit[0], edit[1]
        want = edit[2] if len(edit) > 2 else 1
        n = text.count(old)
        if n != want:
            sys.exit(f"gen_stream_g: {src_rel}: anchor found {n} times (want {want}):\n{old}")
        text = text.replace(old, new)
    head = (f"{STAMP}\n"
            f"// stream-g {what}: derived from rtl/{src_rel} (stream TASK-020).\n"
            f"// The product module, renamed; see the generator for every edit.\n")
    return head + text


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--check', action='store_true', help='exit 1 if a generated file is stale')
    args = ap.parse_args()
    stale = 0
    for dst, src, edits, what in JOBS:
        path, text = RTL / dst, derive(src, edits, what)
        old = path.read_text() if path.exists() else None
        if args.check:
            if old != text:
                print(f"STALE: {path.relative_to(RTL.parent)}")
                stale += 1
        elif old != text:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
            print(f"wrote {path.relative_to(RTL.parent)}")
        else:
            print(f"unchanged {path.relative_to(RTL.parent)}")
    if args.check:
        print("all stream-g RTL current" if not stale else f"{stale} stale file(s): rerun gen_stream_g.py")
    return 1 if stale else 0


if __name__ == '__main__':
    sys.exit(main())
