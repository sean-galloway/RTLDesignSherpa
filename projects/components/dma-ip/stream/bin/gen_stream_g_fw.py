"""Build stream-g's scheduler firmware into its SystemVerilog include.

STREAM owns its image (rtl/fw_g/sched_g.S, forked from rapids-g's on
2026-10-24); the assembler, linker and renderer are rapids' gen_rapids_g_fw.py,
imported, so the two images are built the same way and differ only in source.

    python3 bin/gen_stream_g_fw.py            # rtl/macro_g/generated/fw/sched_g_fw.svh
    python3 bin/gen_stream_g_fw.py --check    # exit 1 if it is stale
RISCV_TOOLCHAIN names the toolchain bin directory (rapids' default otherwise).
"""
import argparse
import os
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
AREA = HERE.parent
REPO = AREA.parents[3]
sys.path.insert(0, str(REPO / 'projects/components/dma-ip/rapids/bin'))
import gen_rapids_g_fw as rg  # noqa: E402

SRC = AREA / 'rtl/fw_g/sched_g.S'
OUT = AREA / 'rtl/macro_g/generated/fw/sched_g_fw.svh'
STAMP = "// Generated by: projects/components/dma-ip/stream/bin/gen_stream_g_fw.py -- DO NOT EDIT"


def render() -> str:
    tools = Path(os.environ.get('RISCV_TOOLCHAIN', rg.TOOLCHAIN_DEFAULT))
    if not (tools / 'riscv-none-elf-as').exists():
        sys.exit(f"no riscv-none-elf-as in {tools} (set RISCV_TOOLCHAIN)")
    words = rg.build_words(SRC, tools, need_ptab=True)
    text = rg.render(words, rg.alg_max(SRC), src=SRC)
    lines = text.splitlines()
    lines[0] = STAMP
    lines[1] = f"// Source: projects/components/dma-ip/stream/rtl/fw_g/{SRC.name}"
    lines[2] = "// rapids_seq_g's instruction ROM image for stream-g (stream TASK-020)."
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--check', action='store_true', help='exit 1 if the include is stale')
    a = ap.parse_args()
    text = render()
    rel = OUT.relative_to(AREA)
    if a.check:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"STALE: {rel} -- run bin/gen_stream_g_fw.py")
            return 1
        print(f"ok: {rel} is current")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print(f"wrote {rel} ({text.count(chr(10)) - 8} words)")
    return 0


if __name__ == '__main__':
    sys.exit(main())
