"""Generate the rapids-g tree (rapids TASK-034) from the byte-tree RAPIDS.

rapids-g is RAPIDS with its schedulers sequenced by one gatling per half
(fub_g/scheduler_g + macro_g/rapids_seq_g). Above the schedulers the RTL is
the product's, so it is DERIVED here rather than copied by hand:

    rtl/macro_g/generated/scheduler_group_array_g.sv  <- macro/scheduler_group_array.sv
    rtl/macro_g/generated/rapids_src_g.sv              <- macro/rapids_src.sv
    rtl/macro_g/generated/rapids_snk_g.sv              <- macro/rapids_snk.sv
    rtl/macro_g/generated/rapids_core_g.sv             <- macro/rapids_core.sv
    rtl/top_g/generated/rapids_g_top_base.sv           <- top/rapids_top_base.sv
    rtl/top_g/generated/rapids_g_top.sv                <- the AXIS thin top of the -g base
    rtl/top_g/generated/rapids_g_cxs_top.sv            <- the CXS thin top of the -g base
    rtl/top_g/generated/rapids_g_16ch_top.sv           <- the AXIS thin top, NUM_CHANNELS = 16 (rapids TASK-036)
    rtl/top_g/generated/rapids_g_16ch_cxs_top.sv       <- the CXS thin top, NUM_CHANNELS = 16

Every edit is a module rename or an anchored insertion that must match
exactly once; a product change that moves an anchor fails the run instead of
producing a wrong file. The array takes the hand-written sequencer block
rtl/macro_g/scheduler_group_array_g_seq.svh. The thin tops come from
gen_plane_tops.gen(), the same derivation as the product tops.

    python3 bin/gen_rapids_g.py           # (re)write the generated -g RTL
    python3 bin/gen_rapids_g.py --check   # exit 1 if any of it is stale

Never hand-edit a generated file: change the product, the .svh or this
script, and rerun. The firmware is a separate generator, gen_rapids_g_fw.py.
"""

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import gen_plane_tops  # noqa: E402

RTL = Path(__file__).resolve().parent.parent / 'rtl'
STAMP = "// Generated by: projects/components/dma-ip/rapids/bin/gen_rapids_g.py -- DO NOT EDIT"

# The scheduler instance's port list continues after this anchor in the
# shared-engine branch; the seq_* hookup goes in front of scheduler_idle.
SCHED_PORT_ANCHOR = """                .tile_dest_legal         (tile_dest_legal),
                .scheduler_idle          (scheduler_idle[ch]),
                .scheduler_state         (scheduler_state[ch]),
                .sched_error             (sched_error[ch]),
"""
SEQ_PORTS = """                .tile_dest_legal         (tile_dest_legal),
                .seq_wr_en               (g_seq_wr_en[ch]),
                .seq_wr_addr             (g_seq_wr_addr),
                .seq_wr_data             (g_seq_wr_data),
                .seq_rd_addr             (g_seq_rd_addr),
                .seq_rd_data             (g_seq_rd_data[ch]),
                .seq_attn                (g_seq_attn[ch]),
                .seq_fault               (g_seq_fault[ch]),
                .seq_alg_max             (g_seq_alg_max),
                .scheduler_idle          (scheduler_idle[ch]),
                .scheduler_state         (scheduler_state[ch]),
                .sched_error             (sched_error[ch]),
"""
SEQ_LOOP_ANCHOR = "        for (genvar ch = 0; ch < NUM_CHANNELS; ch++) begin : gen_schedulers\n"
FATAL_ANCHOR = "        if ((TILE_HDR != 0) && (SHARED_ENGINES == 0))\n"
FATAL_G = """        // rapids-g: the schedulers are scheduler_g, which exist only in the
        // shared-engine structure; one gatling serves 4, 8 or 16 of them.
        if (SHARED_ENGINES == 0)
            $fatal(1, "scheduler_group_array_g: rapids-g needs SHARED_ENGINES = 1");
        if ((NUM_CHANNELS != 4) && (NUM_CHANNELS != 8) && (NUM_CHANNELS != 16))
            $fatal(1, "scheduler_group_array_g: NUM_CHANNELS must be 4, 8 or 16, got %0d", NUM_CHANNELS);
"""

# The register-mailbox master each half's gatling drives (rapids_seq_g ->
# rapids_g_reg_arb in the top base), passed up through every level.
REG_SIGS = (('output', '', 'cmd_valid'), ('input ', '', 'cmd_ready'), ('output', '', 'cmd_pwrite'),
            ('output', '[11:0]', 'cmd_paddr'), ('output', '[31:0]', 'cmd_pwdata'),
            ('input ', '', 'rsp_valid'), ('output', '', 'rsp_ready'),
            ('input ', '[31:0]', 'rsp_prdata'), ('input ', '', 'rsp_pslverr'))
RST_PORT = "    input  logic                        rst_n,\n"
# The gatlings' restart (rapids_seq_g), one input from the top to both halves
RESTART_PORT = f"    input  logic {'':<26} seq_restart,\n"
RESTART_CONN = "        .seq_restart            (seq_restart),\n"
CAM_PORT = "    input  logic                                    cam_clear,\n"
CAM_PORT_G = (CAM_PORT + "    // rapids-g: one cycle restarts both gatlings' harts (rapids_seq_g); pulse it\n"
              "    // only while every channel is idle, tie it to 0 otherwise\n"
              "    input  logic                                    seq_restart,\n")


def reg_ports(prefix, why=None):
    lines = [f"    // rapids-g: {why}"] if why else []
    lines += [f"    {d} logic {w:<26} {prefix}seq_reg_{n}," for d, w, n in REG_SIGS]
    return "\n".join(lines) + "\n"


def reg_conns(port_prefix, net_prefix):
    return "".join(f"        .{port_prefix}seq_reg_{n:<12} ({net_prefix}seq_reg_{n}),\n" for _, _, n in REG_SIGS)


APB4_RENAME = [(f"        .{p:<15}(apb_{p}),", f"        .{p:<15}(host_{p}),")
               for p in ('cmd_valid', 'cmd_ready', 'cmd_pwrite', 'cmd_paddr', 'cmd_pwdata',
                         'rsp_valid', 'rsp_ready', 'rsp_prdata')]
APB4_RENAME.append(("        .rsp_pslverr    (apb_rsp_pslverr)\n", "        .rsp_pslverr    (host_rsp_pslverr)\n"))
REG_ARB_ANCHOR = """    //=========================================================================
    // APB -> register chain (single sink)
"""

# (generated file, source, [(old, new)], what it is)
JOBS = (
    ('macro_g/generated/scheduler_group_array_g.sv', 'macro/scheduler_group_array.sv', [
        ("module scheduler_group_array #(", "module scheduler_group_array_g #("),
        ("endmodule : scheduler_group_array\n", "endmodule : scheduler_group_array_g\n"),
        (FATAL_ANCHOR, FATAL_G + FATAL_ANCHOR),
        (SEQ_LOOP_ANCHOR, '`include "scheduler_group_array_g_seq.svh"\n\n' + SEQ_LOOP_ANCHOR),
        ("            scheduler #(\n", "            scheduler_g #(\n"),
        (SCHED_PORT_ANCHOR, SEQ_PORTS),
        (RST_PORT, RST_PORT + RESTART_PORT
         + reg_ports('', "this half's register mailbox (rapids_seq_g -> rapids_g_reg_arb)")),
    ], "the scheduler array, its schedulers sequenced by one gatling"),
    ('macro_g/generated/rapids_src_g.sv', 'macro/rapids_src.sv', [
        ("module rapids_src #(", "module rapids_src_g #("),
        ("endmodule : rapids_src\n", "endmodule : rapids_src_g\n"),
        ("    scheduler_group_array #(\n", "    scheduler_group_array_g #(\n"),
        (RST_PORT, RST_PORT + RESTART_PORT + reg_ports('', "this half's register mailbox")),
        ("    ) u_scheduler_group_array (\n", "    ) u_scheduler_group_array (\n" + RESTART_CONN + reg_conns('', '')),
    ], "the SOURCE half"),
    ('macro_g/generated/rapids_snk_g.sv', 'macro/rapids_snk.sv', [
        ("module rapids_snk #(", "module rapids_snk_g #("),
        ("endmodule : rapids_snk\n", "endmodule : rapids_snk_g\n"),
        ("    scheduler_group_array #(\n", "    scheduler_group_array_g #(\n"),
        (RST_PORT, RST_PORT + RESTART_PORT + reg_ports('', "this half's register mailbox")),
        ("    ) u_scheduler_group_array (\n", "    ) u_scheduler_group_array (\n" + RESTART_CONN + reg_conns('', '')),
    ], "the SINK half"),
    ('macro_g/generated/rapids_core_g.sv', 'macro/rapids_core.sv', [
        ("module rapids_core #(", "module rapids_core_g #("),
        ("endmodule : rapids_core\n", "endmodule : rapids_core_g\n"),
        ("    rapids_src #(\n", "    rapids_src_g #(\n"),
        ("    rapids_snk #(\n", "    rapids_snk_g #(\n"),
        (RST_PORT, RST_PORT + RESTART_PORT
         + reg_ports('src_', "the halves' register mailboxes") + reg_ports('snk_')),
        ("    ) u_src (\n", "    ) u_src (\n" + RESTART_CONN + reg_conns('', 'src_')),
        ("    ) u_snk (\n", "    ) u_snk (\n" + RESTART_CONN + reg_conns('', 'snk_')),
    ], "the core: both halves"),
    ('top_g/generated/rapids_g_top_base.sv', 'top/rapids_top_base.sv', [
        ("module rapids_top_base #(", "module rapids_g_top_base #("),
        ("endmodule : rapids_top_base\n", "endmodule : rapids_g_top_base\n"),
        ("    rapids_core #(\n", "    rapids_core_g #(\n"),
        (CAM_PORT, CAM_PORT_G),
        ("    ) u_core (\n", "    ) u_core (\n" + RESTART_CONN
         + reg_conns('src_', 'w_src_') + reg_conns('snk_', 'w_snk_')),
        (REG_ARB_ANCHOR, '`include "rapids_g_top_reg_arb.svh"\n\n' + REG_ARB_ANCHOR),
    ] + APB4_RENAME, "the top base"),
)


def derive(src_rel, edits, what):
    text = (RTL / src_rel).read_text()
    for old, new in edits:
        n = text.count(old)
        if n != 1:
            sys.exit(f"gen_rapids_g: {src_rel}: anchor found {n} times (want 1):\n{old}")
        text = text.replace(old, new)
    head = (f"{STAMP}\n"
            f"// rapids-g {what}: derived from rtl/{src_rel} (rapids TASK-034).\n"
            f"// The product module, renamed; see the generator for every edit.\n")
    return head + text


def derived_jobs():
    return [(RTL / dst, derive(src, edits, what)) for dst, src, edits, what in JOBS]


def top_jobs():
    """The thin tops: the product derivation, applied to the -g base on disk."""
    out = []
    for nch, stem in ((None, None), (16, 'rapids_g_16ch_top')):
        for kind in ('axis', 'cxs'):
            path, text = gen_plane_tops.gen('top_g/generated', 'rapids_g_top', kind, nch=nch, stem=stem)
            text = text.replace(gen_plane_tops.STAMP,
                                STAMP + "\n// (the thin-top derivation of bin/gen_plane_tops.py, on rapids_g_top_base)")
            # the variant note names the product's filelist directory
            text = text.replace('rtl/filelists/top/', 'rtl/filelists/top_g/')
            out.append((path, text))
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--check', action='store_true', help='exit 1 if a generated file is stale')
    args = ap.parse_args()
    stale = 0
    # The tops read the generated base, so the derived files go first.
    for phase in (derived_jobs, top_jobs):
        for path, text in phase():
            old = path.read_text() if path.exists() else None
            if args.check:
                if old != text:
                    print(f"STALE: {path.relative_to(RTL.parent)}")
                    stale += 1
            elif old != text:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text)
                print(f"wrote {path.relative_to(RTL.parent)}")
            else:
                print(f"unchanged {path.relative_to(RTL.parent)}")
    if args.check:
        print("all rapids-g RTL current" if not stale else f"{stale} stale file(s): rerun gen_rapids_g.py")
    return 1 if stale else 0


if __name__ == '__main__':
    sys.exit(main())
