"""Generate the RAPIDS thin tops: <top>_base + one TX and one RX network plane.

    rtl/top/rapids_top.sv              rapids_top_base       + AXIS planes
    rtl/top/rapids_cxs_top.sv          rapids_top_base       + CXS planes
    rtl/top_beats/rapids_beats_top.sv      rapids_beats_top_base + AXIS planes
    rtl/top_beats/rapids_beats_cxs_top.sv  rapids_beats_top_base + CXS planes

and, for the byte tree, one pair per register-map size (the base is the same
module; the filelist picks the register map, rtl/filelists/top/):

    rtl/top/rapids_8ch_top.sv / rapids_8ch_cxs_top.sv     NUM_CHANNELS = 8,  8-channel map
    rtl/top/rapids_16ch_top.sv / rapids_16ch_cxs_top.sv   NUM_CHANNELS = 16, 16-channel map

The base is the hand-written RTL. Each thin top is DERIVED from it: the base's
parameter and port text is copied verbatim, the plane-facing streams and the
plane interface become internal wires, and the network pins of the chosen
plane are added. A plane is swapped by its module name and its outer pins, so
both tops of a tree are the same file but for those.

    python3 bin/gen_plane_tops.py           # (re)write the four tops
    python3 bin/gen_plane_tops.py --check   # exit 1 if any top is stale

Never hand-edit a generated top: change the base or this script and rerun.
"""

import argparse
import re
import sys
from pathlib import Path

RTL = Path(__file__).resolve().parent.parent / 'rtl'
STAMP = "// Generated by: projects/components/dma-ip/rapids/bin/gen_plane_tops.py -- DO NOT EDIT"

TREES = (('top', 'rapids_top'), ('top_beats', 'rapids_beats_top'))
# Channel-count variants of the byte tree: (channels, top name stem)
CH_VARIANTS = ((8, 'rapids_8ch_top'), (16, 'rapids_16ch_top'))
NC_PARAM = re.compile(r"(    parameter int NUM_CHANNELS +=) 8,")

# The parameters the planes own (they sat in the original top, here they come back)
PLANE_PARAMS = """    // AXIS data-path monitor-lites (rapids TASK-015): sink ingress in the SNK
    // half (agent 0x09, configured by SNK.MON.WRMON_*), source egress in the SRC
    // half (agent 0x0A, configured by SRC.MON.RDMON_*). Both gated by
    // USE_AXI_MONITORS. ACLK_MHZ scales their microsecond timeout tick.
    parameter int SNK_AXIS_MON_AGENT_ID = 9,
    parameter int SRC_AXIS_MON_AGENT_ID = 10,
    parameter int ACLK_MHZ             = 100,
"""
BASE_PARAM_NOTE = re.compile(r"    // The network-plane monitors \(agent ids, ACLK_MHZ\) are parameters of the\n"
                             r"    // thin tops, which own the planes \(rtl/plane\)\.\n")

CXS_PARAMS = """    // CXS link (rtl/plane/rapids_plane_cxs_*): Issue D, credits, idle timeout.
    // One link per direction; CXSSRCID carries the channel. One credit is one
    // flit (IHI 0079D 2.1). 32 covers the ~3-cycle grant->flit->free round
    // trip with ~29 cycles to spare (link pipelining or a CDC) at full rate.
    // Above the spec's 63 the link is built CXS_CREDIT_BEYOND_SPEC (both ends
    // of the link must agree). The receive FIFO is the pool.
    parameter int CXS_MAX_CREDIT       = 32,
    parameter int CXS_RX_FIFO_DEPTH    = CXS_MAX_CREDIT,
    parameter bit CXS_CREDIT_BEYOND_SPEC = (CXS_MAX_CREDIT > 63),
    parameter logic [7:0] CXS_IDLE_CYCLES = 8'd32,
"""

PLANE_BLOCK = re.compile(r"\n    //-+\n    // Network plane interface, (SRC|SNK) half[^\n]*\n    //-+\n(    (input|output) [^\n]*\n)+")
AXIS_BLOCK = {
    'snk': re.compile(r"    //-+\n    // Sink Path - plane-facing AXIS[^\n]*\n    //-+\n(    (input|output) [^\n]*s_axis_t\w+,?\n){8}"),
    'src': re.compile(r"    //-+\n    // Source Path - plane-facing AXIS[^\n]*\n    //-+\n(    (input|output) [^\n]*m_axis_t\w+,?\n){8}"),
}
PORT = re.compile(r"^\s*(input|output)\s+.*?\b(\w+)\s*,?\s*(//.*)?$")
PARAM = re.compile(r"^\s*parameter\s+.*?\b(\w+)\s*=")


def split_header(text, module):
    m = re.search(rf"\nmodule {module}\s*\n?\s*(import [^\n]*\n)?#\(\n", text)
    assert m, f"no module header for {module}"
    p0 = m.end()
    p1 = text.index("\n) (\n", p0)
    q0 = p1 + len("\n) (\n")
    q1 = text.index("\n);\n", q0)
    return text[p0:p1], text[q0:q1], (m.group(1) or '')


def names(block, rx):
    return [rx.match(l).group(2 if rx is PORT else 1) for l in block.split('\n') if rx.match(l)]


def cxs_ports():
    rx = []
    for h, p, io in (('snk', 's_cxs', ('input ', 'output')), ('src', 'm_cxs', ('output', 'input '))):
        word = 'Sink Path - CXS Receiver (external link -> SRAM)' if h == 'snk' else \
               'Source Path - CXS Transmitter (SRAM -> external link)'
        rows = [(io[0], '', 'valid'), (io[0], '[DW-1:0]', 'data'), (io[0], '[CXS_CNTL_PW-1:0]', 'cntl'),
                (io[0], '[CXS_IW-1:0]', 'srcid'), (io[0], '[CXS_DESTW-1:0]', 'tgtid'),
                (io[0], '[CXS_UW-1:0]', 'user'), (io[1], '', 'crdgnt'), (io[0], '', 'crdrtn'),
                (io[0], '', 'activereq'), (io[1], '', 'activeack'), (io[1], '', 'deacthint')]
        lines = [f"    //{'-' * 73}", f"    // {word}", f"    //   tid -> CXSSRCID, tdest -> CXSTGTID, {{tuser, tstrb}} -> CXSUSER",
                 f"    //{'-' * 73}"]
        lines += [f"    {a} logic {w:<40} {p}_{n}," for a, w, n in rows]
        lines += [f"    output logic {'[1:0]':<40} {h}_cxs_link_state,",
                  f"    output logic {'':<40} {h}_cxs_protocol_error,"]
        if h == 'snk':
            lines.append(f"    output logic {'':<40} snk_cxs_unsupported,")
        rx.append("\n".join(lines) + "\n")
    return rx


CXS_LOCALS = """    // CXS port widths (match rtl/plane/rapids_plane_cxs_*; do not override)
    parameter int CXS_IW               = (AXIS_ID_WIDTH   > 0) ? AXIS_ID_WIDTH   : 1,
    parameter int CXS_DESTW            = (AXIS_DEST_WIDTH > 0) ? AXIS_DEST_WIDTH : 1,
    parameter int CXS_UW               = (DATA_WIDTH / 8) + ((((DATA_WIDTH / 8) + AXIS_USER_WIDTH) <= 128) ? AXIS_USER_WIDTH : 0),
    parameter int CXS_CNTL_PW          = cxs_pkg::port_w(cxs_pkg::cntl_width(2, DATA_WIDTH, 16)),
"""


def plane_inst(kind, d, h):
    tx = d == 'tx'
    mod = f"rapids_plane_{kind}_{d}"
    agent = 'SRC_AXIS_MON_AGENT_ID' if h == 'src' else 'SNK_AXIS_MON_AGENT_ID'
    params = [("USE_MONITOR", "(USE_AXI_MONITORS == 1)"),
              ("MON_UNIT_ID", "1"),          # rapids_core's MON_UNIT_ID (the top does not override it)
              ("MON_AGENT_ID", agent), ("ACLK_MHZ", "ACLK_MHZ"), ("DATA_WIDTH", "DATA_WIDTH"),
              ("AXIS_ID_WIDTH", "AXIS_ID_WIDTH"), ("AXIS_DEST_WIDTH", "AXIS_DEST_WIDTH"),
              ("AXIS_USER_WIDTH", "AXIS_USER_WIDTH")]
    if kind == 'cxs':
        params.append(("CXS_MAX_CREDIT", "CXS_MAX_CREDIT"))
        params.append(("CXS_CREDIT_BEYOND_SPEC", "CXS_CREDIT_BEYOND_SPEC"))
        params.append(("CXS_STREAM_SRCID_BITS", "CIW"))   # channels interleave; CXSSRCID = channel
        params.append(("CXS_IDLE_CYCLES", "CXS_IDLE_CYCLES") if tx else ("RX_FIFO_DEPTH", "CXS_RX_FIFO_DEPTH"))
    w = f"w_{h}_axis_"
    conn = [("clk", "aclk"), ("rst_n", "aresetn")]
    conn += [(f"fub_axis_t{f}", f"{w}t{f}") for f in ('data', 'strb', 'last', 'id', 'dest', 'user', 'valid', 'ready')]
    for f in ('enable', 'err_enable', 'compl_enable', 'perf_enable', 'timeout_enable',
              'timeout_cycles', 'latency_thresh', 'pkt_mask'):
        conn.append((f"cfg_mon_{f}", f"w_{h}_plane_cfg_mon_{f}"))
    for f in ('busy', 'packet_count', 'error_count', 'dropped_count'):
        conn.append((f"sts_mon_{f}", ""))           # no CSR today (rapids TASK-015)
    for f in ('valid', 'ready', 'packet', 'timestamp'):
        conn.append((f"monbus_{f}", f"w_{h}_plane_mon_{f}"))
    if kind == 'axis':
        ext = 'm_axis' if tx else 's_axis'
        conn += [(f"{ext}_t{f}", f"{ext}_t{f}") for f in ('data', 'strb', 'last', 'id', 'dest', 'user', 'valid', 'ready')]
    else:
        ext = 'm_cxs' if tx else 's_cxs'
        conn += [(f"{ext}_{f}", f"{ext}_{f}") for f in ('valid', 'data', 'cntl', 'srcid', 'tgtid', 'user', 'crdgnt',
                                                        'crdrtn', 'activereq', 'activeack', 'deacthint')]
        conn += [("sts_cxs_link_state", f"{h}_cxs_link_state"), ("sts_cxs_protocol_error", f"{h}_cxs_protocol_error")]
        if not tx:
            conn.append(("sts_cxs_unsupported", "snk_cxs_unsupported"))
    live = [c for c in conn if c[1]]
    empty = [c for c in conn if not c[1]]
    body = ",\n".join(f"        .{a:<24}({b})" for a, b in live)
    body += ",\n        /* verilator lint_off PINCONNECTEMPTY */\n"
    body += ",\n".join(f"        .{a:<24}()" for a, _ in empty)
    body += "\n        /* verilator lint_on PINCONNECTEMPTY */"
    p = ",\n".join(f"        .{a:<18}({b})" for a, b in params)
    return f"    {mod} #(\n{p}\n    ) u_{h}_plane (\n{body}\n    );\n"


def gen(tree, top, kind, nch=None, stem=None):
    base_mod = f"{top}_base"
    base_text = (RTL / tree / f"{base_mod}.sv").read_text()
    pblock, ports, imp = split_header(base_text, base_mod)
    base_params = names(pblock, PARAM)
    base_ports = names(ports, PORT)

    name = stem if stem else top
    out_mod = name if kind == 'axis' else name.replace('_top', '_cxs_top')
    # parameters: the base's, verbatim, with the plane parameters back in place
    assert BASE_PARAM_NOTE.search(pblock), "base parameter note missing"
    params = BASE_PARAM_NOTE.sub(lambda m: PLANE_PARAMS, pblock)
    if nch is not None:
        params, n = NC_PARAM.subn(lambda m: f"{m.group(1)} {nch},", params)
        assert n == 1, "NUM_CHANNELS parameter not found in the base"
    variant = ("" if nch is None else
               f"\n// {nch}-channel variant: NUM_CHANNELS = {nch} and the {nch}-channel register map\n"
               f"// (compile with rtl/filelists/top/{out_mod}.f, which selects it).")
    if kind == 'cxs':
        # appended after the base's last parameter (which carries no comma)
        params = params.rstrip('\n') + ",\n" + CXS_PARAMS + CXS_LOCALS.rstrip(',\n')
    # ports: drop the plane interface; AXIS keeps the streams as external pins
    pl = PLANE_BLOCK.sub('', ports)
    if kind == 'axis':
        pl = pl.replace("// Sink Path - plane-facing AXIS (the RX plane -> SRAM); tid = channel",
                        "// Sink Path - AXIS Slave Interface (External network -> SRAM); tid = channel")
        pl = pl.replace("// Source Path - plane-facing AXIS (SRAM -> the TX plane); tid = channel",
                        "// Source Path - AXIS Master Interface (SRAM -> External network); tid = channel")
    else:
        rx_blk, tx_blk = cxs_ports()
        pl, n1 = AXIS_BLOCK['snk'].subn(lambda m: rx_blk, pl)
        pl, n2 = AXIS_BLOCK['src'].subn(lambda m: tx_blk, pl)
        assert n1 == n2 == 1, "AXIS blocks not found in base ports"
    pl = pl.rstrip()
    if pl.endswith(','):
        pl = pl[:-1]

    # base instance: every parameter and port by name
    stream = {f"{p}_t{f}": f"w_{h}_axis_t{f}" for h, p in (('snk', 's_axis'), ('src', 'm_axis'))
              for f in ('data', 'strb', 'last', 'id', 'dest', 'user', 'valid', 'ready')}
    bconn = []
    for n in base_ports:
        if n in stream:
            bconn.append((n, stream[n]))
        elif re.match(r"(src|snk)_plane_", n):
            bconn.append((n, 'w_' + n))
        else:
            bconn.append((n, n))
    inst_p = ",\n".join(f"        .{n:<24}({n})" for n in base_params)
    inst_c = ",\n".join(f"        .{a:<32}({b})" for a, b in bconn)

    wires = ["    // Plane-facing AXIS streams and the plane interface (rtl/plane)"]
    for h in ('snk', 'src'):
        wires += [f"    logic [DW-1:0]              w_{h}_axis_tdata;",
                  f"    logic [SW-1:0]              w_{h}_axis_tstrb;",
                  f"    logic                       w_{h}_axis_tlast;",
                  f"    logic [AXIS_ID_WIDTH-1:0]   w_{h}_axis_tid;",
                  f"    logic [AXIS_DEST_WIDTH-1:0] w_{h}_axis_tdest;",
                  f"    logic [AXIS_USER_WIDTH-1:0] w_{h}_axis_tuser;",
                  f"    logic                       w_{h}_axis_tvalid;",
                  f"    logic                       w_{h}_axis_tready;",
                  f"    logic                       w_{h}_plane_cfg_mon_enable, w_{h}_plane_cfg_mon_err_enable,",
                  f"                                w_{h}_plane_cfg_mon_compl_enable, w_{h}_plane_cfg_mon_perf_enable,",
                  f"                                w_{h}_plane_cfg_mon_timeout_enable;",
                  f"    logic [31:0]                w_{h}_plane_cfg_mon_timeout_cycles, w_{h}_plane_cfg_mon_latency_thresh;",
                  f"    logic [15:0]                w_{h}_plane_cfg_mon_pkt_mask;",
                  f"    logic                       w_{h}_plane_mon_valid, w_{h}_plane_mon_ready;",
                  f"    monitor_common_pkg::monitor_packet_t   w_{h}_plane_mon_packet;",
                  f"    monitor_common_pkg::monbus_timestamp_t w_{h}_plane_mon_timestamp;"]
    what = 'AXI-Stream' if kind == 'axis' else 'CXS (Arm IHI 0079 Issue D)'
    text = f"""// SPDX-License-Identifier: MIT
// SPDX-FileCopyrightText: 2026 sean galloway
//
// RTL Design Sherpa - Industry-Standard RTL Design and Verification
// https://github.com/sean-galloway/RTLDesignSherpa
//
{STAMP}
//
// Module: {out_mod}
// Purpose: RAPIDS with {what} network planes: {base_mod} + rapids_plane_{kind}_rx (sink
//          ingress) + rapids_plane_{kind}_tx (source egress)
//
// Documentation: projects/components/dma-ip/rapids/docs/rapids_planes.md
// Subsystem: rapids
//
// The thin top that picks this tree's network planes. Everything but the
// planes is {base_mod}; its parameter and port text is copied here verbatim by
// the generator. The sibling top of this tree differs only in the plane module
// names and the network pins.{variant}

`timescale 1ns / 1ps

module {out_mod}
{imp}#(
{params}
) (
{pl}
);

{chr(10).join(wires)}

    {base_mod} #(
{inst_p}
    ) u_base (
{inst_c}
    );

    // Sink ingress plane: network -> w_snk_axis_* -> SINK half
{plane_inst(kind, 'rx', 'snk')}
    // Source egress plane: SOURCE half -> w_src_axis_* -> network
{plane_inst(kind, 'tx', 'src')}
endmodule : {out_mod}
"""
    return RTL / tree / f"{out_mod}.sv", text


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--check', action='store_true', help='exit 1 if a generated top differs from the base')
    args = ap.parse_args()
    stale = 0
    jobs = [(tree, top, kind, None, None) for tree, top in TREES for kind in ('axis', 'cxs')]
    jobs += [('top', 'rapids_top', kind, nch, stem) for nch, stem in CH_VARIANTS for kind in ('axis', 'cxs')]
    for tree, top, kind, nch, stem in jobs:
        if True:
            path, text = gen(tree, top, kind, nch, stem)
            old = path.read_text() if path.exists() else None
            if args.check:
                if old != text:
                    print(f"STALE: {path.relative_to(RTL.parent)}")
                    stale += 1
            elif old != text:
                path.write_text(text)
                print(f"wrote {path.relative_to(RTL.parent)}")
            else:
                print(f"unchanged {path.relative_to(RTL.parent)}")
    if args.check:
        print("all generated tops current" if not stale else f"{stale} stale top(s): rerun gen_plane_tops.py")
    return 1 if stale else 0


if __name__ == '__main__':
    sys.exit(main())
