"""Build the rapids-g scheduler firmware into a SystemVerilog include.

    rtl/fw_g/sched_g.S  ->  rtl/macro_g/generated/fw/sched_g_fw.svh

The include defines FW_WORDS and FW_IMAGE[FW_WORDS] for rapids_seq_g's
instruction ROM, so the image needs no file path at simulation or synthesis
time. The flow is the house RISC-V one (kestrel's fuzz_gen.build_stream):
riscv-none-elf-as -> ld (text at 0) -> objcopy -O binary; the words are
little-endian, as gatling fetches them.

    python3 bin/gen_rapids_g_fw.py           # (re)write the include
    python3 bin/gen_rapids_g_fw.py --check   # exit 1 if it is stale

RISCV_TOOLCHAIN names the toolchain bin directory (default: the xpack install
kestrel uses). Never hand-edit the include: change the .S and rerun.
"""

import argparse
import os
import subprocess
import sys
import tempfile
from pathlib import Path

RTL = Path(__file__).resolve().parent.parent / 'rtl'
SRC = RTL / 'fw_g' / 'sched_g.S'
OUT = RTL / 'macro_g' / 'generated' / 'fw' / 'sched_g_fw.svh'
TOOLCHAIN_DEFAULT = '/mnt/data/tools/xpack-riscv-none-elf-gcc/bin'
STAMP = "// Generated by: projects/components/dma-ip/rapids/bin/gen_rapids_g_fw.py -- DO NOT EDIT"


def build_words(src: Path, tools: Path) -> list:
    """Assemble and link src at address 0; return its little-endian words."""
    with tempfile.TemporaryDirectory() as tmp:
        tmp = Path(tmp)
        obj, elf, binf = tmp / 'fw.o', tmp / 'fw.elf', tmp / 'fw.bin'

        def run(cmd):
            res = subprocess.run([str(c) for c in cmd], capture_output=True, text=True)
            if res.returncode != 0:
                sys.exit(f"{cmd[0].name}: failed\n{res.stderr}")

        run([tools / 'riscv-none-elf-as', '-march=rv32i', '-mabi=ilp32', src, '-o', obj])
        run([tools / 'riscv-none-elf-ld', '-Ttext=0', '-e', '_start', obj, '-o', elf])
        run([tools / 'riscv-none-elf-objcopy', '-O', 'binary', '-j', '.text', elf, binf])
        data = binf.read_bytes()
    if len(data) % 4:
        sys.exit(f"{src.name}: image is {len(data)} bytes, not a whole number of words")
    return [int.from_bytes(data[i:i + 4], 'little') for i in range(0, len(data), 4)]


def render(words: list) -> str:
    lines = [STAMP,
             f"// Source: projects/components/dma-ip/rapids/rtl/fw_g/{SRC.name}",
             "// rapids_seq_g's instruction ROM image (rapids TASK-034).",
             "",
             f"localparam int FW_WORDS = {len(words)};",
             "localparam logic [31:0] FW_IMAGE [FW_WORDS] = '{"]
    for i, w in enumerate(words):
        sep = ',' if i + 1 < len(words) else ''
        lines.append(f"    32'h{w:08x}{sep}  // 0x{4 * i:04x}")
    lines.append("};")
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--check', action='store_true', help='exit 1 if the include is stale')
    args = ap.parse_args()
    tools = Path(os.environ.get('RISCV_TOOLCHAIN', TOOLCHAIN_DEFAULT))
    if not (tools / 'riscv-none-elf-as').exists():
        sys.exit(f"no riscv-none-elf-as in {tools} (set RISCV_TOOLCHAIN)")
    words = build_words(SRC, tools)
    text = render(words)
    if args.check:
        current = OUT.read_text() if OUT.exists() else ''
        if current != text:
            print(f"STALE: {OUT.relative_to(RTL.parent)} (rerun bin/gen_rapids_g_fw.py)")
            return 1
        print(f"ok: {OUT.relative_to(RTL.parent)} is current")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(RTL.parent)} ({len(words)} words)")
    return 0


if __name__ == '__main__':
    sys.exit(main())
