"""Derive the 16-channel RAPIDS register map from the 8-channel one.

The 8-channel RDL (rtl/macro_beats/rapids_{engine,mon}_regs.rdl,
rapids_regs.rdl, rapids_regmap.rdl) is the hand-written source. The
16-channel map differs only where a channel count shows, so it is DERIVED,
never hand-edited:

    CH8..CH15_DESC_ADDR_{LOW,HIGH}   0x040-0x07C (the 8-ch map ends at 0x03C)
    KICK_ENABLE                      KICK0..KICK15, moved 0x040 -> 0x080
    per-channel bit fields           [7:0] -> [15:0] (enable, reset, idle,
                                     scheduler error, read/write complete)
    CH_STATE                         [8] @ 0x150 -> [16] @ 0x180 (16 entries
                                     would overrun SCHED_ERROR at 0x170)
    CH_SCRATCH                       [8] -> [16] @ 0x300 (16 x 4 bytes ends at 0x340, below PERF_CH_SEL)
    VERSION.NUM_CHANNELS             8 -> 16
    PERF_CH_SEL.CH_SEL               [2:0] -> [3:0]
    TILE_DESC_DROPPED                DROP0..DROP7 -> DROP0..DROP15
    {RD,WR}MON_PERF_CH_OVERFLOW_HI   new, MON +0x1F8 / +0x1FC: channels 8..15
                                     (4 bits per channel no longer fit 32)

It also writes the per-variant include the byte-tree base reads
(rtl/top/generated/regsel_{8,16}ch/rapids_regsel*.svh): the regblock's
module and hwif types, the field width, and the glue for the registers that
exist per channel by NAME (the kick bits and staged addresses).

    python3 bin/gen_rapids_regs_16ch.py           # (re)write
    python3 bin/gen_rapids_regs_16ch.py --check   # exit 1 if anything is stale

Every rewrite asserts it matched exactly as often as expected, so a change
to the 8-channel source that this script does not understand fails here
instead of producing a quietly wrong 16-channel map. After a rewrite,
regenerate the 16-channel regblock with bin/peakrdl_generate.py (see the
handbook's generated-rtl rules).
"""

import argparse
import re
import sys
from pathlib import Path

RAPIDS = Path(__file__).resolve().parent.parent
RTL = RAPIDS / 'rtl'
SRC_DIR = RTL / 'macro_beats'
OUT_RDL = SRC_DIR / 'generated_16ch'
OUT_SEL = RTL / 'top' / 'generated'

STAMP = ("// Generated by: projects/components/dma-ip/rapids/bin/gen_rapids_regs_16ch.py -- DO NOT EDIT\n"
         "// Source: the 8-channel map in rtl/macro_beats (edit that, then rerun the script).\n")

CH_FIELDS = ('CH_EN', 'CH_RST', 'CH_IDLE', 'DESC_IDLE', 'SCHED_IDLE', 'SCHED_ERR',
             'RD_COMPLETE', 'WR_COMPLETE')


def sub(text: str, old: str, new: str, count: int = 1) -> str:
    n = text.count(old)
    if n != count:
        sys.exit(f"gen_rapids_regs_16ch: expected {count} x {old!r}, found {n}")
    return text.replace(old, new)


def resub(text: str, pattern: str, repl, count: int = 1) -> str:
    out, n = re.subn(pattern, repl, text)
    if n != count:
        sys.exit(f"gen_rapids_regs_16ch: expected {count} x /{pattern}/, found {n}")
    return out


def engine_16ch(src: str) -> str:
    t = sub(src, '`include "rapids_mon_regs.rdl"', '`include "rapids_mon_regs_16ch.rdl"')
    t = sub(t, 'regfile rapids_engine_regs {', 'regfile rapids_engine_regs_16ch {')
    t = sub(t, 'rapids_mon_regs MON @ 0x800;', 'rapids_mon_regs_16ch MON @ 0x800;')

    # Staged descriptor addresses: CH8..CH15 after CH7, same geometry
    ch7 = re.search(r'^.*CH7_DESC_ADDR_HIGH @ 0x03C;\n', t, re.M)
    if not ch7:
        sys.exit("gen_rapids_regs_16ch: CH7_DESC_ADDR_HIGH @ 0x03C not found")
    lo7 = re.search(r'^.*CH7_DESC_ADDR_LOW  @ 0x038;\n', t, re.M).group(0)
    hi7 = ch7.group(0)
    extra = ''
    for ch in range(8, 16):
        lo = lo7.replace('Ch7', f'Ch{ch}').replace('CH7_', f'CH{ch}_').replace('0x038', f'0x{ch * 8:03X}')
        hi = hi7.replace('Ch7', f'Ch{ch}').replace('CH7_', f'CH{ch}_').replace('0x03C', f'0x{ch * 8 + 4:03X}')
        extra += lo.replace('CH%d_DESC_ADDR_LOW ' % ch, 'CH%d_DESC_ADDR_LOW' % ch) if ch >= 10 else lo
        extra += hi
    t = t[:ch7.end()] + extra + t[ch7.end():]

    # Kick bits and the register's new home
    k7 = '        field { sw=w; hw=r; singlepulse; } KICK7[7:7]=0;\n'
    t = sub(t, k7, k7 + ''.join(f'        field {{ sw=w; hw=r; singlepulse; }} KICK{c}[{c}:{c}]=0;\n'
                                for c in range(8, 16)))
    t = sub(t, '        } RSVD[31:8] = 24\'h0;\n\n    } KICK_ENABLE @ 0x040;',
             '        } RSVD[31:16] = 16\'h0;\n\n    } KICK_ENABLE @ 0x080;')

    # Per-channel bit fields: the field, its description and its reserved neighbour
    for f in CH_FIELDS:
        t = resub(t, rf'\}} {f}\[7:0\]( = 8\'h00)?;',
                  lambda m: f"}} {f}[15:0]" + (" = 16'h0000" if m.group(1) else '') + ';')
    t = resub(t, r'(bits) \[7:0\] - ', r'\1 [15:0] - ', count=len(CH_FIELDS))
    t = resub(t, r"(\} (?:CH_EN|CH_RST|CH_IDLE|DESC_IDLE|SCHED_IDLE|SCHED_ERR|RD_COMPLETE|WR_COMPLETE)"
                 r"\[15:0\](?: = 16'h0000)?;\n\n        field \{\n            desc = \"Reserved\";\n"
                 r"            sw = r;\n            hw = na;\n        \}) RSVD\[31:8\] = 24'h0;",
              r"\1 RSVD[31:16] = 16'h0;", count=len(CH_FIELDS))

    t = sub(t, '} CH_STATE[8] @ 0x150 += 0x4;', '} CH_STATE[16] @ 0x180 += 0x4;')
    t = sub(t, '} CH_SCRATCH[8] @ 0x300 += 0x4;', '} CH_SCRATCH[16] @ 0x300 += 0x4;')
    t = sub(t, "} NUM_CHANNELS[23:16] = 8'h08;", "} NUM_CHANNELS[23:16] = 8'h10;")
    t = sub(t, "} CH_SEL[2:0] = 3'h0;", "} CH_SEL[3:0] = 4'h0;")

    # Cell-descriptor drop bits: one W1C field per channel
    d7 = re.search(r"\n        field \{\n            desc = \"Channel 7: [^\n]*\n[^\n]*\n        \} DROP7\[7:7\] = 1'b0;\n", t)
    if not d7:
        sys.exit("gen_rapids_regs_16ch: DROP7 field not found")
    blk = d7.group(0)
    more = ''.join(blk.replace('Channel 7:', f'Channel {c}:').replace('DROP7[7:7]', f'DROP{c}[{c}:{c}]')
                   for c in range(8, 16))
    t = t[:d7.end()] + more + t[d7.end():]
    t = sub(t, "        } RSVD[31:8] = 24'h0;\n\n    } TILE_DESC_DROPPED @ 0x2D4;",
             "        } RSVD[31:16] = 16'h0;\n\n    } TILE_DESC_DROPPED @ 0x2D4;")
    t = sub(t, "} RSVD[31:3] = 29'h0;\n\n    } PERF_CH_SEL", "} RSVD[31:4] = 28'h0;\n\n    } PERF_CH_SEL")
    return STAMP + t


def mon_16ch(src: str) -> str:
    t = sub(src, 'regfile rapids_mon_regs {', 'regfile rapids_mon_regs_16ch {')
    hi = '''
    reg {{
        name = "{name} Per-Channel Overflow Stickies, channels 8-15";
        desc = "Channels 8..15 of {low} (4 bits/channel, channel 8 in the low nibble).";

        field {{
            desc = "Per-channel overflow mask, channels 8..15";
            sw = r;
            hw = w;
        }} VAL[31:0];

    }} {reg}_HI @ {addr};
'''
    add = (hi.format(name='Read Datapath', low='RDMON_PERF_CH_OVERFLOW', reg='RDMON_PERF_CH_OVERFLOW',
                     addr='0x1F8')
           + hi.format(name='Write Datapath', low='WRMON_PERF_CH_OVERFLOW', reg='WRMON_PERF_CH_OVERFLOW',
                       addr='0x1FC'))
    t = sub(t, '    } WRMON_PERF_CH_OVERFLOW @ 0x1F4;\n', '    } WRMON_PERF_CH_OVERFLOW @ 0x1F4;\n' + add)
    return STAMP + t


def regs_16ch(src: str) -> str:
    t = sub(src, '`include "rapids_engine_regs.rdl"', '`include "rapids_engine_regs_16ch.rdl"')
    t = sub(t, 'addrmap rapids_regs {', 'addrmap rapids_regs_16ch {')
    t = sub(t, '    rapids_engine_regs SRC @ 0x0000;\n    rapids_engine_regs SNK @ 0x1000;',
             '    rapids_engine_regs_16ch SRC @ 0x0000;\n    rapids_engine_regs_16ch SNK @ 0x1000;')
    return STAMP + t


def regmap_16ch(src: str) -> str:
    t = sub(src, '`include "rapids_engine_regs.rdl"', '`include "rapids_engine_regs_16ch.rdl"')
    t = sub(t, 'addrmap rapids {', 'addrmap rapids_16ch {')
    t = sub(t, '    rapids_engine_regs regs @ 0x0;', '    rapids_engine_regs_16ch regs @ 0x0;')
    return STAMP + t


def regsel(nch: int) -> dict:
    """The per-variant include set for rtl/top/rapids_top_base.sv."""
    if nch == 8:
        mod, pkg = 'rapids_regs', 'rapids_regs_pkg'
    else:
        mod, pkg = 'rapids_regs_16ch', 'rapids_regs_16ch_pkg'
    hdr = STAMP.replace('// Source: the 8-channel map', f'// {nch}-channel variant; source: the 8-channel map')
    defs = (hdr + f'''// Selected by +incdir (rtl/filelists/top/rapids_top_base{"" if nch == 8 else "_16ch"}.f).
`ifndef RAPIDS_REGSEL_SVH
`define RAPIDS_REGSEL_SVH
`define RAPIDS_REGS_NCH   {nch}
`define RAPIDS_REGS_MOD   {mod}
`define RAPIDS_REGS_IN_T  {pkg}::{mod}__in_t
`define RAPIDS_REGS_OUT_T {pkg}::{mod}__out_t
`endif
''')
    kick = hdr + '// Body of the kick always_comb in rapids_top_base: the registers that exist per channel by name.\n'
    for half in ('src', 'snk'):
        for c in range(nch):
            kick += (f'        w_kick_{half}_pulse[{c}] = hwif_out.{half.upper()}.KICK_ENABLE.KICK{c}.value;\n')
    for half in ('src', 'snk'):
        for c in range(nch):
            H = half.upper()
            kick += (f'        w_staged_{half}_addr[{c}] = {{hwif_out.{H}.CH{c}_DESC_ADDR_HIGH.DESC_ADDR_HIGH.value,\n'
                     f'                        hwif_out.{H}.CH{c}_DESC_ADDR_LOW.DESC_ADDR_LOW.value}};\n')
    status = hdr + '// Inside the hwif_in always_comb of rapids_top_base: per-variant status fields.\n'
    for c in range(nch):
        status += f'        hwif_in.SRC.TILE_DESC_DROPPED.DROP{c}.next = w_tile_dropped_reg[{c}];\n'
    if nch == 16:
        status += ('        hwif_in.SRC.MON.RDMON_PERF_CH_OVERFLOW_HI.VAL.next = '
                   '32\'(64\'(w_rd_ch_overflow) >> 32);\n'
                   '        hwif_in.SNK.MON.WRMON_PERF_CH_OVERFLOW_HI.VAL.next = '
                   '32\'(64\'(w_wr_ch_overflow) >> 32);\n')
    d = OUT_SEL / f'regsel_{nch}ch'
    return {d / 'rapids_regsel.svh': defs, d / 'rapids_regsel_kick.svh': kick,
            d / 'rapids_regsel_status.svh': status}


def outputs() -> dict:
    rd = lambda n: (SRC_DIR / n).read_text()
    out = {
        OUT_RDL / 'rapids_engine_regs_16ch.rdl': engine_16ch(rd('rapids_engine_regs.rdl')),
        OUT_RDL / 'rapids_mon_regs_16ch.rdl': mon_16ch(rd('rapids_mon_regs.rdl')),
        OUT_RDL / 'rapids_regs_16ch.rdl': regs_16ch(rd('rapids_regs.rdl')),
        OUT_RDL / 'rapids_regmap_16ch.rdl': regmap_16ch(rd('rapids_regmap.rdl')),
    }
    out.update(regsel(8))
    out.update(regsel(16))
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--check', action='store_true', help='exit 1 if any output is stale')
    args = ap.parse_args()
    stale = 0
    for path, text in outputs().items():
        rel = path.relative_to(RAPIDS)
        cur = path.read_text() if path.exists() else None
        if args.check:
            if cur != text:
                print(f"STALE {rel}")
                stale += 1
        elif cur != text:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
            print(f"wrote {rel}")
        else:
            print(f"unchanged {rel}")
    if args.check:
        print("all 16-channel register outputs current" if not stale else f"{stale} stale")
    return 1 if stale else 0


if __name__ == '__main__':
    sys.exit(main())
