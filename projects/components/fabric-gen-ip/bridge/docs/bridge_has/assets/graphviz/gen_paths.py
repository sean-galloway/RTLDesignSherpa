# ---- element key v3 (vault/handbook/authoring/block-diagrams.md) ---------
# Each node takes its class's shape and fill; return-data edges are green.
# The key row is generated at render time (bin/render_block_diagram.py).
V3_ATTRS = {
    "interface": 'style="rounded,filled", fillcolor="#E2EFDA"',
    "bar": 'style="rounded,filled,bold", fillcolor="#E2EFDA"',
    "logic": 'style="filled", fillcolor="white"',
    "registered": 'peripheries=2, style="filled", fillcolor="#D6E4F0"',
    "fsm": 'peripheries=2, style="filled,diagonals", fillcolor="#FCE4D6"',
    "storage": 'shape=cylinder, style="filled", fillcolor="#E8DFF5"',
    "pick": 'style="filled", fillcolor="#FFF2CC"',
    "note": 'shape=note',
}


def style_v3(text, classes, returns):
    """Append class attrs to each `    nid [...]` line; colour return edges."""
    import re
    out = []
    for line in text.split("\n"):
        m = re.match(r"^\s+(\w+)\s+\[", line)
        e = re.match(r"^\s+(\w+)\s*->\s*(\w+)\s*\[", line)
        if e and (e.group(1), e.group(2)) in returns:
            line = line.replace("[", '[color="#1A7A1A", ', 1)
        elif m and not e and m.group(1) in classes and line.rstrip().endswith("];"):
            line = line.rstrip()[:-2] + ", " + V3_ATTRS[classes[m.group(1)]] + "];"
        out.append(line)
    return "\n".join(out)

CLASSES = dict(pw="interface", pc="interface", pr="interface", others="interface",
               mW="storage", mC="logic", mR="storage", wdest="logic", arb="pick",
               rmux="logic", wown="logic", trk="registered", sW="storage",
               sC="storage", sR="storage", bar="bar")
RETURNS = {("pr", "mR"), ("mR", "rmux"), ("rmux", "trk"), ("trk", "sR"), ("sR", "bar")}


def build(d):
    e = d["e"]
    w = "mW" in d
    o = [HEAD.format(name=d["name"], title=d["title"])]
    for nid, lab, g in d["ports"]:
        o.append(f'    {nid} [label="{lab}", fillcolor="white", group={g}];')
    pids = [p[0] for p in d["ports"]]
    o.append("    { rank=same; " + "; ".join(pids) + "; }")
    o.append("    " + " -> ".join(pids) + " [style=invis];")
    m = (["mW"] if w else []) + ["others", "mC", "mR"]
    if w:
        o.append(f'    mW [label="{d["mW"]}", group=L];')
    o.append(f'    others [label="{d["others"]}", fillcolor="white"];')
    o.append(f'    mC [label="{d["mC"]}", group=C];')
    o.append(f'    mR [label="{d["mR"]}", group=R];')
    o.append("    { rank=same; " + "; ".join(m) + "; }")
    o.append("    " + " -> ".join(m) + " [style=invis];")
    x = (["wdest"] if w else []) + ["arb", "rmux"]
    if w:
        o.append(f'    wdest [label="{d["wdest"]}", group=L];')
    o.append(f'    arb [label="{d["arb"]}", shape=invtrapezium, width=6.4, height=0.7, group=C];')
    o.append(f'    rmux [label="{d["rmux"]}", group=R];')
    o.append("    { rank=same; " + "; ".join(x) + "; }")
    o.append("    " + " -> ".join(x) + " [style=invis];")
    y = (["wown"] if w else []) + ["pc3", "trk"]
    if w:
        o.append(f'    wown [label="{d["wown"]}", group=L];')
    o.append('    pc3 [shape=point, width=0.01, label="", group=C];')
    o.append(f'    trk [label="{d["trk"]}", group=R];')
    o.append("    { rank=same; " + "; ".join(y) + "; }")
    if w:
        o.append("    wown -> pc3 [style=invis];")
    z = (["sW"] if w else []) + ["sC", "sR"]
    if w:
        o.append(f'    sW [label="{d["sW"]}", group=L];')
    o.append(f'    sC [label="{d["sC"]}", group=C];')
    o.append(f'    sR [label="{d["sR"]}", group=R];')
    o.append("    { rank=same; " + "; ".join(z) + "; }")
    o.append("    " + " -> ".join(z) + " [style=invis];")
    o.append(f'    bar [label="{d["bar"]}", fillcolor="white", width={11 if w else 10.5}, group=C];')
    if w:
        o += [f'    pw -> mW [label="{e["p_w"]}"];',
              f'    mW -> wdest [label="{e["m_w"]}"];',
              f'    wdest -> wown [label="{e["wd"]}"];',
              f'    wown -> sW [label="{e["wo"]}"];',
              f'    sW -> bar [xlabel="{e["s_w"]}"];']
    o += [f'    pc -> mC [label="{e["p_c"]}"];',
          f'    mC -> arb [label="{e["m_c"]}"];',
          f'    others -> arb [label="{e["o_c"]}"];',
          '    arb -> pc3 [dir=none, penwidth=1.8];',
          f'    pc3 -> sC [xlabel="{e["a_c"]}", penwidth=1.8];',
          f'    sC -> bar [label="{e["s_c"]}", penwidth=1.8];',
          f'    pr -> mR [dir=back, label="{e["p_r"]}"];',
          f'    mR -> rmux [dir=back, label="{e["m_r"]}"];',
          f'    rmux -> trk [dir=back, label="{e["r_r"]}"];',
          f'    trk -> sR [dir=back, label="{e["t_r"]}"];',
          f'    sR -> bar [dir=back, xlabel="{e["s_r"]}"];',
          f'    pc3 -> trk [style=dashed, xlabel="{e["acc"]}"];',
          "}"]
    open(d["name"] + ".dot", "w").write(style_v3("\n".join(o), CLASSES, RETURNS) + "\n")


for spec in (WRITE, READ):
    build(spec)
