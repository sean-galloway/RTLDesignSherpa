def node(n, lab, g, white=False):
    f = ', fillcolor="white"' if white else ''
    return f'    {n} [label="{lab}", group={g}{f}];'


def build(d):
    o = [HEAD.format(name=d["name"], title=d["title"])]
    if d.get("p"):
        (pl, pc, pr), (bl, bc, br), e = d["p"], d["b"], d["e"]
        o += [node("pl", pl, "L", True), node("pc", pc, "C", True), node("pr", pr, "R", True),
              "    { rank=same; pl; pc; pr; }", "    pl -> pc -> pr [style=invis];",
              node("bl", bl, "L"), node("bc", bc, "C"), node("br", br, "R"),
              "    { rank=same; bl; bc; br; }", "    bl -> bc -> br [style=invis];",
              f'    bar [label="{d["bar"]}", fillcolor="white", width=7.5];',
              f'    pl -> bl [xlabel="{e[0]}"];',
              f'    pc -> bc [xlabel="{e[1]}"];',
              f'    pr -> br [dir=back, xlabel="{e[2]}"];',
              f'    bl -> bar [xlabel="{e[3]}"];',
              f'    bc -> bar [xlabel="{e[4]}", penwidth=1.8];',
              f'    br -> bar [dir=back, xlabel="{e[5]}"];']
    else:
        (pc, pr), (bc, br), e = d["p2"], d["b2"], d["e2"]
        o += [node("pc", pc, "C", True), node("pr", pr, "R", True),
              "    { rank=same; pc; pr; }", "    pc -> pr [style=invis];",
              node("bc", bc, "C"), node("br", br, "R"),
              "    { rank=same; bc; br; }", "    bc -> br [style=invis];",
              f'    bar [label="{d["bar"]}", fillcolor="white", width=6.5];',
              f'    pc -> bc [xlabel="{e[0]}"];',
              f'    pr -> br [dir=back, xlabel="{e[1]}"];',
              f'    bc -> bar [xlabel="{e[2]}", penwidth=1.8];',
              f'    br -> bar [dir=back, xlabel="{e[3]}"];']
    o.append("}")
    open(d["name"] + ".dot", "w").write("\n".join(o) + "\n")


for d in EX:
    build(d)
