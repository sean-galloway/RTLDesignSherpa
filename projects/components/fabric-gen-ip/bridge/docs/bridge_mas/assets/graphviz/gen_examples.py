"""Generate the four worked-example conversion figures of MAS chapter 5 from
one three-lane layout (data left, request center, response right), so they
read alike (vault/handbook/authoring/block-diagrams.md: a family of
near-identical diagrams comes from one script). Edit this file, not the .dot.

Sources: projects/components/utility-ip/converters/rtl/
axi4_dwidth_converter_{wr,rd}.sv, axi4_to_apb4_shim.sv, axi4_to_apb4_convert.sv."""

