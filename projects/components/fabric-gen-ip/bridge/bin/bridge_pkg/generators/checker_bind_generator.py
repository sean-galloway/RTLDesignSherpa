"""Opt-in protocol checkers for a generated bridge (GitHub #119 L3).

Emits `<bridge>_checkers.sv`: one `bind` per external AXI4/AXI5 port,
attaching `formal/bridge/axi4_protocol_checker` (handshake and payload
stability, VALID low after reset, legal burst type and size) to that port on
its own clock. On a master port it checks what the requester drives; on a
slave port it checks what the bridge drives. Nothing here is in the RTL or
in the synthesis filelist: `<bridge>_checkers.f` is the bridge filelist plus
the checker and the bind file, for simulation and formal only.

Ports of other protocols (APB, AXI4-Lite, AXI3, WB4) have no checker yet.
"""
from typing import List, Tuple

CHECKED_PROTOCOLS = ('axi4', 'axi5')
CHECKER_SRC = "$REPO_ROOT/formal/bridge/axi4_protocol_checker.sv"

_WR = {'awid': 'ID', 'awaddr': 'ADDR', 'awlen': 8, 'awsize': 3, 'awburst': 2,
       'awvalid': 1, 'awready': 1, 'wdata': 'DATA', 'wstrb': 'STRB', 'wlast': 1,
       'wvalid': 1, 'wready': 1, 'bid': 'ID', 'bresp': 2, 'bvalid': 1, 'bready': 1}
_RD = {'arid': 'ID', 'araddr': 'ADDR', 'arlen': 8, 'arsize': 3, 'arburst': 2,
       'arvalid': 1, 'arready': 1, 'rid': 'ID', 'rdata': 'DATA', 'rresp': 2,
       'rlast': 1, 'rvalid': 1, 'rready': 1}


def _prefix(p: str) -> str:
    return p if (not p or p.endswith('_')) else p + '_'


def checked_ports(masters, slaves) -> List[Tuple[str, object]]:
    """(role, port) for every port that gets a checker."""
    out = []
    for m in masters:
        if getattr(m, 'protocol', 'axi4') in CHECKED_PROTOCOLS and getattr(m, 'id_width', 0):
            out.append(('master', m))
    for s in slaves:
        if (getattr(s, 'protocol', 'axi4') in CHECKED_PROTOCOLS
                and not getattr(s, 'internal', False) and getattr(s, 'id_width', 0)):
            out.append(('slave', s))
    return out


def _bind_lines(bridge: str, role: str, port) -> List[str]:
    pfx = _prefix(port.prefix)
    ch = getattr(port, 'channels', 'rw')
    clk, rst = (f"{port.port_name}_aclk", f"{port.port_name}_aresetn") \
        if getattr(port, 'cdc', False) else ("aclk", "aresetn")
    widths = {'ID': port.id_width, 'ADDR': port.addr_width,
              'DATA': port.data_width, 'STRB': port.data_width // 8}
    conns = [f".aclk({clk})", f".aresetn({rst})"]
    for present, sigs in ((ch in ('rw', 'wr'), _WR), (ch in ('rw', 'rd'), _RD)):
        for sig, w in sigs.items():
            if present:
                conns.append(f".{sig}({pfx}{sig})")
            else:
                n = widths[w] if isinstance(w, str) else w
                conns.append(f".{sig}({n}'b0)")
    lines = [f"// {role} port {port.port_name} ({port.protocol}, {ch}) on {clk}",
             f"bind {bridge} axi4_protocol_checker #(",
             f"    .ID_WIDTH({port.id_width}),",
             f"    .ADDR_WIDTH({port.addr_width}),",
             f"    .DATA_WIDTH({port.data_width})",
             f") u_chk_{port.port_name} ("]
    lines += [f"    {c}{',' if i < len(conns) - 1 else ''}" for i, c in enumerate(conns)]
    lines += [");", ""]
    return lines


def generate_checker_binds(bridge: str, masters, slaves) -> str:
    ports = checked_ports(masters, slaves)
    lines = [
        f"// {bridge}_checkers.sv -- opt-in AXI protocol checkers (GitHub #119 L3).",
        "// Generated by: CheckerBindGenerator. Simulation and formal only: never",
        "// in a synthesis filelist. Uses <bridge>_checkers.f.",
        "",
    ]
    if not ports:
        lines.append("// No AXI4/AXI5 ports with IDs on this bridge: nothing to bind.")
    for role, port in ports:
        lines += _bind_lines(bridge, role, port)
    return "\n".join(lines) + "\n"


def generate_checker_filelist(bridge: str, bridge_filelist: str, bind_file: str) -> str:
    return "\n".join([
        f"# {bridge} plus its protocol checkers (simulation / formal only, GitHub #119 L3)",
        f"-f {bridge_filelist}",
        CHECKER_SRC,
        bind_file,
        "",
    ])
