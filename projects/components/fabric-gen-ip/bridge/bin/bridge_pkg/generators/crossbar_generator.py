"""
Crossbar Generator

Generates crossbar module that routes width-adapted signals from adapters to slaves.

The crossbar:
1. Takes multiple width-specific inputs from each adapter
2. Takes address decode one-hot signals (slave_select_aw/ar)
3. Selects correct width path based on target slave's width
4. Routes selected signals to slave outputs

Author: RTL Design Sherpa
Date: 2025-11-04
"""

from typing import List, Dict, Set
from dataclasses import dataclass

from bridge_pkg.generators.adapter_generator import MasterConfig, SlaveInfo
from bridge_pkg.width_utils import get_connected_slave_widths, get_masters_connecting_to_slave
from bridge_pkg.signal_naming import SignalNaming, Direction, AXI4Channel, AXI4_SLAVE_SIGNALS, AXI4_MASTER_SIGNALS
from bridge_pkg import cdc_lanes


class CrossbarGenerator:
    """
    Generates crossbar module for intelligent width-based routing.

    For each slave, routes signals from the correctly-sized path of each
    master that can target that slave.

    Example:
        Master A (64b) connects to Slave 0 (64b) and Slave 1 (128b)
        - Master A adapter outputs: 64b path, 128b path
        - Slave 0 gets: Master A 64b path (direct)
        - Slave 1 gets: Master A 128b path (converted)
    """

    def __init__(self, bridge_name: str, masters: List[MasterConfig], slaves: List[SlaveInfo],
                 pipeline: bool = False, arbitration: str = 'rr', qos_aging_shift: int = 4):
        """
        Initialize crossbar generator.

        Args:
            bridge_name: Name of bridge (e.g., "bridge_4x4_rw")
            masters: List of master configurations
            slaves: List of slave configurations
        """
        self.bridge_name = bridge_name
        self.masters = masters
        self.slaves = slaves
        # bridge TASK-006 (was BRIDGE-017): registered crossbar. When set, every slave-side request
        # channel (AW/W/AR, carrying the bridge id) and response channel (B/R,
        # carrying the bridge id and the route-open flag) passes through a
        # 2-deep gaxi_skid_buffer inside the xbar. The routing and mux logic
        # below is unchanged; it drives/reads the `xs_<slave>_axi_*` nets and
        # _generate_pipeline_stages() joins them to the ports. Both the
        # request cone (decode -> arbiter -> N-way mux) and the response
        # OR-merge end at a register, at full throughput, +1 cycle each way.
        self.pipeline = bool(pipeline)
        # bridge TASK-006 (was BRIDGE-017): per-slave arbitration policy. 'rr' is the round-robin
        # the fabric has always had. 'qos' picks the requester with the
        # highest EFFECTIVE priority -- AxQOS plus an age term that grows
        # while a request waits (one level every 2**qos_aging_shift cycles,
        # saturating at 15) -- so a low-QoS master is delayed, never starved;
        # ties fall back to round-robin. Same lock-until-handshake.
        if arbitration not in ('rr', 'qos'):
            raise ValueError(f"arbitration must be 'rr' or 'qos', got {arbitration!r}")
        self.arbitration = arbitration
        self.qos_aging_shift = int(qos_aging_shift)

        # AXI5 native sideband (A5-2 slice 2). Union drives which struct
        # fields exist (response-direction fields must be driven for
        # EVERY master); per-slave feats drive which discrete slave-side
        # sideband signals exist.
        from bridge_pkg.sideband import sideband_union, port_features
        self.sb_union = sideband_union(self.masters, self.slaves)
        # bridge TASK-007 (was BRIDGE-018): the width-independent aw/ar/b structs size their
        # data-scaled sideband (MTE tags) for the widest port in the bridge;
        # the crossbar fits those fields to each slave port's own width.
        self.bridge_max_dw = max([m.data_width for m in self.masters]
                                 + [sl.data_width for sl in self.slaves])
        self._sb_port_features = port_features

    def generate(self) -> str:
        """Generate complete crossbar module."""
        lines = []

        # Header
        lines.extend(self._generate_header())

        # Module declaration
        lines.extend(self._generate_module_declaration())

        # Crossbar routing logic
        lines.extend(self._generate_routing_logic())

        # Module end
        lines.append(f"endmodule : {self.bridge_name}_xbar")
        lines.append("")

        return "\n".join(lines)

    def _generate_header(self) -> List[str]:
        """Generate file header."""
        return [
            f"// Crossbar: {self.bridge_name}_xbar",
            "// Generated by: CrossbarGenerator",
            "// ",
            "// Routes width-adapted signals from adapters to slaves.",
            "// Selects correct width path based on address decode.",
            "",
            "`timescale 1ns / 1ps",
            "",
            '`include "reset_defs.svh"',   # ALWAYS_FF_RST / RST_ASSERTED
            "",
            ""
        ]

    def _generate_module_declaration(self) -> List[str]:
        """Generate module declaration with all ports."""
        lines = []

        # NUM_SLAVES goes in the PARAMETER PORT LIST, not the module body.
        #
        # It is used by the port declarations immediately below
        # ([NUM_SLAVES-1:0] on the slave-select vectors), and a body localparam
        # is elaborated AFTER the port list. Verilator accepts the back
        # reference; iverilog and other strict front ends reject it, and
        # bin/check_sv_decl_order.py flags it on every generated xbar.
        #
        # A parameter port list is elaborated in order, so the ports can use it.
        # The default is the generated slave count, so existing instantiations
        # that pass no parameters are unaffected.
        lines.append(f"module {self.bridge_name}_xbar")
        lines.append(f"    import {self.bridge_name}_pkg::*;")
        lines.append("#(")
        lines.append(f"    parameter int NUM_SLAVES = {len(self.slaves)}")
        lines.append(") (")
        lines.append("    input  logic aclk,")
        lines.append("    input  logic aresetn,")
        lines.append("")

        # Adapter inputs (multiple width paths per master)
        for master_idx, master in enumerate(self.masters):
            is_last_master = (master_idx == len(self.masters) - 1)
            has_slaves = (len(self.slaves) > 0)
            lines.append(f"    // {master.name} adapter outputs (multiple width paths)")
            lines.extend(self._generate_adapter_input_ports(master, is_last_master, has_slaves))

            # Add comma if not last master or if slaves follow
            if not is_last_master or has_slaves:
                lines.append("")

        # Slave outputs
        for slave_idx, slave in enumerate(self.slaves):
            lines.append(f"    // Slave {slave_idx}: {slave.name}")
            lines.extend(self._generate_slave_output_ports(slave))

            # Add comma if not last slave
            if slave_idx < len(self.slaves) - 1:
                lines.append("")

        lines.append(");")
        lines.append("")

        return lines

    def _generate_adapter_input_ports(self, master: MasterConfig, is_last_master: bool, has_slaves: bool) -> List[str]:
        """
        Generate input ports from adapter for one master.

        Args:
            master: Master configuration
            is_last_master: True if this is the last master in the list
            has_slaves: True if there are slave ports following

        Includes:
        - Address decode one-hot signals
        - Width-specific channel signals (one set per unique slave width)
        """
        lines = []

        # Get unique slave widths this master connects to
        slave_widths = self._get_connected_slave_widths(master)

        # Address decode signals (for request routing)
        if master.channels in ["wr", "rw"]:
            lines.append(f"    input  logic [NUM_SLAVES-1:0] {master.name}_slave_select_aw,")
            lines.append(f"    input  logic [BRIDGE_ID_WIDTH-1:0] {master.name}_bridge_id_aw,")
        if master.channels in ["rd", "rw"]:
            lines.append(f"    input  logic [NUM_SLAVES-1:0] {master.name}_slave_select_ar,")
            lines.append(f"    input  logic [BRIDGE_ID_WIDTH-1:0] {master.name}_bridge_id_ar,")

        # Width-specific signals for each unique width
        for width_idx, width in enumerate(slave_widths):
            suffix = f"{width}b"
            is_last_width = (width_idx == len(slave_widths) - 1)
            # This port needs comma unless it's the VERY last port in the entire module
            needs_comma = not (is_last_master and is_last_width and not has_slaves)

            lines.append(f"    // {width}b path")

            # Write channels
            if master.channels in ["wr", "rw"]:
                lines.append(f"    input  axi4_aw_t     {master.name}_{suffix}_aw,")
                lines.append(f"    input  logic         {master.name}_{suffix}_awvalid,")
                lines.append(f"    output logic         {master.name}_{suffix}_awready,")
                lines.append(f"    input  axi4_w_{suffix}_t  {master.name}_{suffix}_w,")
                lines.append(f"    input  logic         {master.name}_{suffix}_wvalid,")
                lines.append(f"    output logic         {master.name}_{suffix}_wready,")
                lines.append(f"    output axi4_b_t      {master.name}_{suffix}_b,")
                lines.append(f"    output logic         {master.name}_{suffix}_bvalid,")
                # Determine if comma needed
                if master.channels == "wr" and is_last_width:
                    # This is last signal for write-only master
                    if needs_comma:
                        lines.append(f"    input  logic         {master.name}_{suffix}_bready,")
                    else:
                        lines.append(f"    input  logic         {master.name}_{suffix}_bready")
                else:
                    lines.append(f"    input  logic         {master.name}_{suffix}_bready,")

            # Read channels
            if master.channels in ["rd", "rw"]:
                lines.append(f"    input  axi4_ar_t     {master.name}_{suffix}_ar,")
                lines.append(f"    input  logic         {master.name}_{suffix}_arvalid,")
                lines.append(f"    output logic         {master.name}_{suffix}_arready,")
                lines.append(f"    output axi4_r_{suffix}_t  {master.name}_{suffix}_r,")
                lines.append(f"    output logic         {master.name}_{suffix}_rvalid,")
                # Determine if comma needed (rready is always last for rd/rw channels)
                if is_last_width:
                    # This is last signal for this master
                    if needs_comma:
                        lines.append(f"    input  logic         {master.name}_{suffix}_rready,")
                    else:
                        lines.append(f"    input  logic         {master.name}_{suffix}_rready")
                else:
                    lines.append(f"    input  logic         {master.name}_{suffix}_rready,")

        return lines

    def _determine_bridge_channels(self) -> List[AXI4Channel]:
        """
        Determine which AXI4 channels the bridge needs based on masters.

        Returns list of channels needed:
        - If ANY master has wr/rw: include AW, W, B
        - If ANY master has rd/rw: include AR, R
        """
        has_write = any(m.channels in ["wr", "rw"] for m in self.masters)
        has_read = any(m.channels in ["rd", "rw"] for m in self.masters)

        channels = []
        if has_write:
            channels.extend([AXI4Channel.AW, AXI4Channel.W, AXI4Channel.B])
        if has_read:
            channels.extend([AXI4Channel.AR, AXI4Channel.R])

        return channels

    def _determine_slave_channels(self, slave: SlaveInfo) -> List[AXI4Channel]:
        """
        Determine which AXI4 channels THIS SPECIFIC SLAVE needs based on
        the masters that connect to it.

        Args:
            slave: Slave to determine channels for

        Returns:
            List of channels needed for this slave:
            - If ANY connecting master has wr/rw: include AW, W, B
            - If ANY connecting master has rd/rw: include AR, R
        """
        # Get masters that connect to this slave
        connecting_masters = self._get_masters_connecting_to_slave(slave)

        if not connecting_masters:
            # No masters connect - shouldn't happen, but return empty for safety
            return []

        # Check if any connecting master needs write channels
        has_write = any(m.channels in ["wr", "rw"] for m in connecting_masters)
        # Check if any connecting master needs read channels
        has_read = any(m.channels in ["rd", "rw"] for m in connecting_masters)

        channels = []
        if has_write:
            channels.extend([AXI4Channel.AW, AXI4Channel.W, AXI4Channel.B])
        if has_read:
            channels.extend([AXI4Channel.AR, AXI4Channel.R])

        return channels

    def _sb_fields(self, channel, feats, dw=None):
        from bridge_pkg.sideband import channel_fields
        return channel_fields(feats, channel, dw)

    def _sb_struct_to_port(self, channel, width, struct_expr, slave_dw):
        """A channel-struct sideband field as a slave-port-width expression
        (bridge TASK-007, was BRIDGE-018). Struct fields are sized by struct_dw (per path for
        w/r -- the path width IS the slave's -- and bridge-wide max for
        aw/ar/b); port signals by the slave's own data width."""
        from bridge_pkg.sideband import field_width, fit_expr, struct_dw
        sw = field_width(width, struct_dw(channel, slave_dw, self.bridge_max_dw))
        pw = field_width(width, slave_dw)
        return fit_expr(struct_expr, sw, pw)

    def _sb_port_to_struct(self, channel, width, port_expr, slave_dw):
        """The reverse fit: a slave-port response field into the master's
        channel struct."""
        from bridge_pkg.sideband import field_width, fit_expr, struct_dw
        sw = field_width(width, struct_dw(channel, slave_dw, self.bridge_max_dw))
        pw = field_width(width, slave_dw)
        return fit_expr(port_expr, pw, sw)

    def _sb_slave_feats(self, slave):
        """Sideband features this slave exposes discrete xbar signals
        for (its own features, restricted to the bridge union)."""
        return self._sb_port_features(slave) & self.sb_union

    def _generate_slave_output_ports(self, slave: SlaveInfo) -> List[str]:
        """
        Generate output ports to slave using SignalNaming convention.

        IMPORTANT:
        - Crossbar acts as MASTER to the slave, so port directions are from master perspective
        - Uses SignalNaming convention: <port_name>_axi_<channel><signal> (no direction prefix)
        - Only generates channels needed by THIS SPECIFIC SLAVE based on connecting masters
        """
        lines = []

        # Use SignalNaming convention: <port_name>_axi_<channel><signal>
        prefix = f"{slave.name}_axi_"

        # Determine correct interface width (for APB slaves, use connecting master's width)
        data_width, addr_width = self._determine_slave_interface_width(slave)

        # AXI4 *id width is master pass-through, not a fixed crossbar constant
        # (Bug B in TASK-011 — was hardcoded to 4). Floor at 1 to avoid the
        # invalid `[-1:0]` SV range when id_width=0 (Bug A).
        # bridge TASK-005 (was BRIDGE-016): slave-side IDs are {master index, master id}.
        from bridge_pkg.width_utils import xbar_id_width
        master_id_width = xbar_id_width(self.masters)

        # Width parameters for signal info queries
        width_values = {
            'ID_WIDTH': master_id_width,
            'ADDR_WIDTH': addr_width,
            'DATA_WIDTH': data_width,
            'STRB_WIDTH': data_width // 8,
            'USER_WIDTH': 1
        }

        # Get channels needed by THIS SLAVE (based on connecting masters' channel types)
        channels = self._determine_slave_channels(slave)
        has_write = any(c in [AXI4Channel.AW, AXI4Channel.W, AXI4Channel.B] for c in channels)
        has_read = any(c in [AXI4Channel.AR, AXI4Channel.R] for c in channels)

        # Add bridge_id signals (from slave adapter, for response routing)
        if has_write:
            lines.append(f"    output logic [BRIDGE_ID_WIDTH-1:0] {slave.name}_axi_bridge_id_aw,")
            lines.append(f"    input  logic [BRIDGE_ID_WIDTH-1:0] {slave.name}_axi_bid_bridge_id,")
            lines.append(f"    input  logic                       {slave.name}_axi_bid_valid,")
        if has_read:
            if has_write:
                lines.append("")
            lines.append(f"    output logic [BRIDGE_ID_WIDTH-1:0] {slave.name}_axi_bridge_id_ar,")
            lines.append(f"    input  logic [BRIDGE_ID_WIDTH-1:0] {slave.name}_axi_rid_bridge_id,")
            lines.append(f"    input  logic                       {slave.name}_axi_rid_valid,")
        lines.append("")
        if self._is_lane(slave):
            lines.extend(self._lane_ports(slave, has_write, has_read, master_id_width, addr_width))

        # AXI5 native sideband (A5-2 slice 2): discrete signals only for
        # slaves that enable the feature. Request-direction = outputs,
        # response-direction = inputs. Always followed by the base
        # channel signals, so trailing commas are safe.
        sb_feats = self._sb_slave_feats(slave)
        if sb_feats:
            sb_lines = []
            req_chs = (['aw', 'w'] if has_write else []) + (['ar'] if has_read else [])
            rsp_chs = (['b'] if has_write else []) + (['r'] if has_read else [])
            for ch in req_chs:
                for _f, w, feat, base in self._sb_fields(ch, sb_feats, slave.data_width):
                    rng = "        " if w == 1 else f"[{w-1}:0]  "
                    sb_lines.append(f"    output logic {rng}{slave.name}_axi_{base},")
            for ch in rsp_chs:
                for _f, w, feat, base in self._sb_fields(ch, sb_feats, slave.data_width):
                    rng = "        " if w == 1 else f"[{w-1}:0]  "
                    sb_lines.append(f"    input  logic {rng}{slave.name}_axi_{base},")
            if sb_lines:
                lines.append("    // AXI5 native sideband (A5-2 slice 2)")
                lines.extend(sb_lines)
                lines.append("")

        # Get signal info from SignalNaming (crossbar is master to slave)
        signal_db = AXI4_MASTER_SIGNALS  # Crossbar acts as MASTER to slaves (outputs request, inputs response)

        # Generate declarations for each channel
        first_channel = True

        # Pre-calculate which is the last signal for comma handling
        is_last_slave = (slave == self.slaves[-1])
        last_channel = channels[-1] if channels else None

        for channel_idx, channel in enumerate(channels):
            if not first_channel:
                lines.append("")
            first_channel = False

            if channel not in signal_db:
                continue

            channel_signals = list(signal_db[channel])
            for sig_idx, sig_info in enumerate(channel_signals):
                # Build signal name using prefix + channel + signal
                sig_name = f"{prefix}{channel.value}{sig_info.name}"
                # Get complete signal declaration
                declaration = sig_info.get_declaration(sig_name, width_values)

                # Check if this is the VERY last signal in the module port list
                is_last_channel = (channel == last_channel)
                is_last_signal_in_channel = (sig_idx == len(channel_signals) - 1)
                is_very_last_signal = (is_last_slave and is_last_channel and is_last_signal_in_channel)

                if is_very_last_signal:
                    lines.append(f"    {declaration}")  # No comma
                else:
                    lines.append(f"    {declaration},")

        return lines

    def _generate_routing_logic(self) -> List[str]:
        """
        Generate crossbar routing logic.

        For each slave:
        1. Determine the slave's data width
        2. For each master that connects to this slave:
           - Select the width path matching slave's width
           - Route based on address decode one-hot
        """
        lines = []

        lines.append("    // ================================================================")
        lines.append("    // Crossbar Routing")
        lines.append("    // ================================================================")
        # NUM_SLAVES is now a parameter in the port list (see _generate_module_declaration):
        # declaring it again here would shadow it, and declaring it ONLY here is
        # what made the port list reference a not-yet-elaborated name.
        lines.append("")

        # W-follow wires are declared up front: the slave routing blocks
        # consume them, but they are assigned by the per-path W destination
        # FIFOs that are emitted after the slave blocks (they reference the
        # per-slave addr-decode wires those blocks declare).
        lines.extend(self._generate_w_follow_decls())

        # Per-master request slots of every arbitrated slave: the write
        # ordering gate of one slave reads the slots of the others, which
        # are emitted later.
        lines.extend(self._generate_slot_decls())

        # Likewise the registered crossbar's xs_* nets: the slave routing
        # blocks drive them, the stages that consume them come last.
        if self.pipeline:
            lines.extend(self._generate_pipeline_decls())

        # Response arbiters (per master width path, B and R): the slave
        # routing blocks gate each slave's BREADY/RREADY with their grants,
        # and the response muxes select by them.
        lines.extend(self._generate_response_arbiters())

        # Route to each slave
        for slave_idx, slave in enumerate(self.slaves):
            lines.extend(self._generate_slave_routing(slave_idx, slave))
            lines.append("")

        # Per-(master, width-path) W destination FIFOs
        lines.extend(self._generate_w_dest_fifos())

        # Generate response MUXes (OR together responses from all slaves)
        lines.extend(self._generate_response_muxes())

        if self.pipeline:
            lines.extend(self._generate_pipeline_stages())

        return lines

    def _sp(self, slave: SlaveInfo) -> str:
        """Prefix of the nets the routing/mux logic drives for `slave`: the
        port itself, or the pre-stage nets when the crossbar is pipelined."""
        return f"xs_{slave.name}_axi_" if self.pipeline else f"{slave.name}_axi_"

    def _wr_paths(self):
        """Yield (master, suffix, connected wr-slaves of that width, in
        slave-index order) for every write-capable (master, width path)."""
        for master in self.masters:
            if master.channels not in ("wr", "rw"):
                continue
            for width in self._get_connected_slave_widths(master):
                slaves = [self.slaves[i] for i in sorted(master.slave_connections)
                          if self.slaves[i].data_width == width]
                if slaves:
                    yield master, f"{width}b", slaves

    @staticmethod
    def _wdest_depth(m) -> int:
        """W destination FIFO depth: max_outstanding, a power of two >= 2."""
        return max(2, 1 << (int(getattr(m, 'max_outstanding', 16)) - 1).bit_length())

    def _wlive(self, m, suffix: str, slave) -> str:
        """Live W-destination entries of m's `suffix` path bound for lane slave `slave`."""
        return f"{m.name}_{suffix}_wlive_{slave.name}"

    def _generate_w_follow_decls(self) -> List[str]:
        """Declare the W-follow wires assigned by _generate_w_dest_fifos
        and the slave routing blocks."""
        lines = ["    // W-follow declarations (assigned below)"]
        for m, suffix, slaves in self._wr_paths():
            lines.append(f"    logic {m.name}_{suffix}_wdest_full;")
            db = self._wdest_depth(m).bit_length() - 1
            for s in slaves:
                if self._is_lane(s):
                    lines.append(f"    logic [{db}:0] {self._wlive(m, suffix, s)};")
            for s in slaves:
                lines.append(f"    logic {m.name}_{suffix}_w_to_{s.name};")
                lines.append(f"    logic {m.name}_{suffix}_w_sel_{s.name};")
        lines.append("")
        return lines

    def _generate_w_dest_fifos(self) -> List[str]:
        """One FIFO per write-capable (master, width path): each accepted AW
        pushes WHICH slave the burst targets; the head steers that path's W
        beats. This preserves the master's own AW order ACROSS slaves --
        the old per-(master,slave) occupancy FIFOs asserted w_to for every
        slave with an outstanding burst simultaneously, interleaving one
        master's W streams into two slaves at once."""
        lines = []
        lines.append("    // ================================================================")
        lines.append("    // W destination FIFOs (per master width-path)")
        lines.append("    // ================================================================")
        for m, suffix, slaves in self._wr_paths():
            base = f"{m.name}_{suffix}_wdest"
            n = len(slaves)
            j = max(1, (n - 1).bit_length())
            # An entry lives from this path's AW handshake to its WLAST, both
            # here. The master adapter's max_outstanding counts the MASTER's
            # bursts, but a width converter on this path may issue several
            # AWs for one of them (a > 256-beat split; one AW per beat for
            # FIXED / WRAP wider than the path, bridge BUG-018), so that
            # bound does not hold here. The FIFO is sized to max_outstanding
            # and is FULL-CHECKED: a full FIFO holds the path's AW off
            # (_aw_gate). Without the check the 17th entry overwrote a live
            # one and that path's W beats went to the wrong slave.
            ddepth = self._wdest_depth(m)
            db = ddepth.bit_length() - 1
            lines.append(f"    // {m.name} {suffix} path -> {', '.join(s.name for s in slaves)}"
                         f" ({ddepth} deep: max_outstanding)")
            lines.append(f"    logic [{j-1}:0] {base}_mem [{ddepth}];")
            lines.append(f"    logic [{db}:0] {base}_wptr, {base}_rptr;")
            enc = f"{j}'d0"
            for code, s in reversed(list(enumerate(slaves))):
                if code == 0:
                    continue
                enc = f"{m.name}_{suffix}_aw_to_{s.name} ? {j}'d{code} : {enc}"
            lines.append(f"    wire [{j-1}:0] {base}_enc = {enc};")
            lines.append(f"    wire {base}_push = {m.name}_{suffix}_awvalid && {m.name}_{suffix}_awready;")
            lines.append(f"    wire {base}_pop  = {m.name}_{suffix}_wvalid && {m.name}_{suffix}_wready && {m.name}_{suffix}_w.last;")
            lines.append(f"    `ALWAYS_FF_RST(aclk, aresetn,")
            lines.append(f"        if (`RST_ASSERTED(aresetn)) begin")
            lines.append(f"            {base}_wptr <= '0;")
            lines.append(f"            {base}_rptr <= '0;")
            lines.append(f"        end else begin")
            lines.append(f"            if ({base}_push) begin")
            lines.append(f"                {base}_mem[{base}_wptr[{db-1}:0]] <= {base}_enc;")
            lines.append(f"                {base}_wptr <= {base}_wptr + 1'b1;")
            lines.append(f"            end")
            lines.append(f"            if ({base}_pop) begin")
            lines.append(f"                {base}_rptr <= {base}_rptr + 1'b1;")
            lines.append(f"            end")
            lines.append(f"        end")
            lines.append(f"    )")
            lines.append(f"    wire {base}_valid = ({base}_wptr != {base}_rptr);")
            lines.append(f"    assign {base}_full = ({base}_wptr[{db}] != {base}_rptr[{db}]) && "
                         f"({base}_wptr[{db-1}:0] == {base}_rptr[{db-1}:0]);")
            lines.append(f"    wire [{j-1}:0] {base}_head = {base}_mem[{base}_rptr[{db-1}:0]];")
            for code, s in enumerate(slaves):
                lines.append(f"    assign {m.name}_{suffix}_w_to_{s.name} = {base}_valid && ({base}_head == {j}'d{code});")
            # Live entries bound for each CDC (lane) slave: from the AW
            # handshake to the burst's WLAST into the lane. While any is
            # live, this master's AWs to OTHER slaves wait (_aw_gate): a lane
            # slave orders W by its own pick on its own clock, which need not
            # follow this master's issue order, so an AW of this master
            # granted elsewhere meanwhile could close a crossed-W cycle
            # (bridge BUG-024). Once its W is in the lane, the master's W
            # stream no longer waits on the lane slave's order.
            for code, s in enumerate(slaves):
                if not self._is_lane(s):
                    continue
                c = self._wlive(m, suffix, s)
                inc = f"({base}_push && ({base}_enc == {j}'d{code}))"
                dec = f"({base}_pop && ({base}_head == {j}'d{code}))"
                lines.append(f"    `ALWAYS_FF_RST(aclk, aresetn,")
                lines.append(f"        if (`RST_ASSERTED(aresetn)) {c} <= '0;")
                lines.append(f"        else {c} <= {c} + {db+1}'({inc}) - {db+1}'({dec});")
                lines.append(f"    )")
            lines.append("")
        return lines

    # ------------------------------------------------------------------
    # Arbitration at the slave pins (bridge W3)
    # ------------------------------------------------------------------
    # A slave that two or more masters reach is arbitrated where it is
    # served: each master's AW / AR request waits in its own registered
    # slot here, and the round-robin (or QoS) pick is made among the slots,
    # straight onto the slave-side nets. There is no address queue past the
    # pick -- the slave adapter's AW/AR stage and the registered crossbar's
    # AW/AR stage are cut for these slaves (see arbitrated_slave()).
    #
    # The arbiter used to pick from the raw requests and feed a 2-deep
    # stage (sometimes two) behind it. While the slave held off, those
    # stages filled with requests already granted, so a master with few
    # transactions in flight queued behind the others' and its share
    # followed its outstanding count: 8 vs 2 in flight against a slave that
    # takes 2 at a time gave the 2-deep master 34%, not 50%.
    #
    # Writes need one more rule. AXI4 W has no ID, so each slave's W beats
    # follow its AW pick order, and a master's W stream follows its own AW
    # order. If a master could leave AWs waiting at two slaves at once, the
    # two picks could land in opposite orders for two masters and each slave
    # would wait on the other's W -- a deadlock. So a master's AW enters a
    # slot only while none of its other slots holds one: its AWs are picked
    # in the order it issued them. The master adapter's own rule (a new AW
    # to another slave waits until every earlier W burst has left the
    # adapter) gives the same order wherever W cannot be held between the
    # adapter's tracker and here; this hold makes it true at the pick
    # itself, whatever a width converter buffers. Removing it alone does not
    # fail the perf suite's wr_order case on 2x2_rw or 4x4_rw (measured).

    def _connecting_masters(self, slave: SlaveInfo) -> List[MasterConfig]:
        idx = self.slaves.index(slave)
        return [m for m in self.masters if idx in m.slave_connections]

    def _is_arbitrated(self, slave: SlaveInfo) -> bool:
        return len(self._connecting_masters(slave)) >= 2

    def _uses_slots(self, slave: SlaveInfo, ch: str) -> bool:
        """Arbitrate this slave's AW/AR at its pins from request slots: an
        arbitrated AXI4/AXI5 slave whose channel had a register to replace
        (its adapter stage, or the registered crossbar's). A slave cut to a
        wire (latency = "cut_none") had no queue behind its arbiter and keeps
        its zero-cycle path. An APB/AXI4-Lite/WB4 shim takes slots too (bridge
        W14): picked from the masters' live requests, one master's request
        gating ran through the grant into another master's accept -- the
        worst path of bridge_mix_e. The shim holds one request of its own, so
        the slot costs it one cycle of address latency and nothing else.
        Must agree with slave_adapter_generator's `arbitrated` stage cut
        (AXI slaves only; a shim has no stage to cut)."""
        if not self._is_arbitrated(slave):
            return False
        if self._is_lane(slave):
            return False   # arbitrated on its own clock (bridge W9)
        if slave.protocol in ('apb', 'apb5', 'axil', 'axil5', 'wb4'):
            return True
        if slave.protocol not in ('axi3', 'axi4', 'axi5'):
            return False
        depth = int((getattr(slave, 'skid_depths', None) or {}).get(ch, 2))
        return depth > 0 or self.pipeline

    def _slot(self, m: MasterConfig, suffix: str, ch: str, slave: SlaveInfo) -> str:
        return f"{m.name}_{suffix}_{ch}_slot_{slave.name}"

    def _slots(self, ch: str):
        """Yield (master, suffix, slave) for every request slot of channel
        ch ('aw' or 'ar') in the bridge, slave-index order."""
        want = ("wr", "rw") if ch == "aw" else ("rd", "rw")
        for slave in self.slaves:
            if not self._uses_slots(slave, ch):
                continue
            suffix = f"{slave.data_width}b"
            for m in self._connecting_masters(slave):
                if m.channels in want:
                    yield m, suffix, slave

    def _generate_slot_decls(self) -> List[str]:
        lines = []
        for ch, typ in (("aw", "axi4_aw_t"), ("ar", "axi4_ar_t")):
            for m, suffix, slave in self._slots(ch):
                q = self._slot(m, suffix, ch, slave)
                lines.append(f"    {typ} {q};")
                lines.append(f"    logic {q}_valid, {q}_ready, {q}_in_valid, {q}_in_ready;")
        if not lines:
            return []   # no slots: these bridges are unchanged
        holds = []
        for m, suffix, slaves in self._wr_paths():
            for sl in slaves:
                others = self._aw_other_slots(m, sl)
                if others:
                    h = self._aw_hold(m, suffix, sl)
                    holds.append(f"    wire {h} = " + " || ".join(f"{q}_valid" for q in others) + ";")
        out = ["    // Request slots of the arbitrated slaves (assigned below)"] + lines
        if holds:
            out += ["    // Write ordering: a master's AW waits while another of its slots",
                    "    // holds an AW (see _generate_request_slots)"] + holds
        return out + [""]

    def _aw_other_slots(self, m: MasterConfig, slave: SlaveInfo) -> List[str]:
        """m's write slots at every slave other than `slave`, any width path."""
        return [self._slot(om, osfx, "aw", osl) for om, osfx, osl in self._slots("aw")
                if om is m and osl is not slave]

    def _aw_hold(self, m: MasterConfig, suffix: str, slave: SlaveInfo) -> str:
        return f"{m.name}_{suffix}_aw_hold_{slave.name}"

    def _aw_gate(self, m: MasterConfig, suffix: str, slave: SlaveInfo) -> str:
        """' && !(hold || lane_live || wdest_full)' for an AW from m toward
        `slave`: the write-ordering hold when m has another slot, a live
        burst of m into a lane slave other than `slave` (bridge BUG-024), and
        always the path's W destination FIFO being full
        (_generate_w_dest_fifos). Applies to EVERY path an AW takes -- a slot, a
        grant-on-entry arbiter, a single-master slave -- because an AW
        accepted elsewhere while an earlier one still waits in a slot can
        close the same ordering cycle."""
        terms = [f"{m.name}_{suffix}_wdest_full"]
        terms[:0] = [f"(|{self._wlive(om, osfx, ls)})" for om, osfx, ls in self._lane_live(m, slave)]
        if self._aw_other_slots(m, slave):
            terms.insert(0, self._aw_hold(m, suffix, slave))
        return " && !" + (terms[0] if len(terms) == 1 else "(" + " || ".join(terms) + ")")

    def _lane_live(self, m: MasterConfig, slave: SlaveInfo):
        """(master, path, lane slave) for every lane slave other than `slave`
        that one of m's write paths reaches: its live-W counter holds m's AWs
        toward `slave` (bridge BUG-024)."""
        return [(om, osfx, ls) for om, osfx, sls in self._wr_paths() if om is m
                for ls in sls if self._is_lane(ls) and ls is not slave]

    def _generate_request_slots(self, slave: SlaveInfo, suffix: str, ch: str,
                                masters: List[MasterConfig]) -> List[str]:
        """One 2-deep registered slot per master for this slave's AW or AR
        (full rate: the skid's ready is registered and it reads and writes in
        one cycle). Its output side is drained by the pin-side arbiter."""
        lines = [f"    // {ch.upper()} request slots for {slave.name}: arbitration at the slave pins"]
        typ = "axi4_aw_t" if ch == "aw" else "axi4_ar_t"
        for m in masters:
            q = self._slot(m, suffix, ch, slave)
            gate = self._aw_gate(m, suffix, slave) if ch == "aw" else ""
            lines.append(f"    assign {q}_in_valid = {m.name}_{suffix}_{ch}_to_{slave.name} && "
                         f"{m.name}_{suffix}_{ch}valid{gate};")
            lines.append(f"    gaxi_skid_buffer #(.DEPTH(2), .DATA_WIDTH($bits({typ}))) u_{q} (")
            lines.append(f"        .axi_aclk(aclk), .axi_aresetn(aresetn),")
            lines.append(f"        .wr_valid({q}_in_valid), .wr_ready({q}_in_ready), .wr_data({m.name}_{suffix}_{ch}),")
            lines.append(f"        .rd_valid({q}_valid), .rd_ready({q}_ready), .rd_data({q}),")
            lines.append(f"        /* verilator lint_off PINCONNECTEMPTY */")
            lines.append(f"        .count(), .rd_count()")
            lines.append(f"        /* verilator lint_on PINCONNECTEMPTY */")
            lines.append(f"    );")
        lines.append("")
        return lines

    def _ax_ready_term(self, m: MasterConfig, suffix: str, ch: str, slave: SlaveInfo) -> str:
        """The master-side AWREADY/ARREADY contribution of one slave."""
        if self._is_lane(slave):
            i = self._lane_index(m, slave)
            gate = self._aw_gate(m, suffix, slave) if ch == "aw" else ""
            return (f"(({m.name}_{suffix}_{ch}_to_{slave.name}{gate}) ? "
                    f"{slave.name}_axi_lane_{ch}ready[{i}] : '0)")
        if self._uses_slots(slave, ch):
            q = self._slot(m, suffix, ch, slave)
            gate = self._aw_gate(m, suffix, slave) if ch == "aw" else ""
            return (f"(({m.name}_{suffix}_{ch}_to_{slave.name}{gate}) ? {q}_in_ready : '0)")
        # Grant-on-entry (and single-master) slaves: the grant already
        # carries the write hold (it is in the request / the alias).
        return f"({m.name}_{suffix}_{ch}_gnt_{slave.name} ? {self._sp(slave)}{ch}ready : '0)"

    def _generate_slave_routing(self, slave_idx: int, slave: SlaveInfo) -> List[str]:
        """
        Generate routing logic for one slave.

        Selects correct width path from each master based on:
        - Whether master connects to this slave
        - Slave's data width
        - Address decode one-hot signal
        """
        lines = []
        slave_width = slave.data_width
        slave_suffix = f"{slave_width}b"

        lines.append(f"    // ================================================================")
        lines.append(f"    // Slave {slave_idx}: {slave.name} ({slave_width}b)")
        lines.append(f"    // ================================================================")

        # Find masters that connect to this slave
        connecting_masters = []
        for master in self.masters:
            if slave_idx in master.slave_connections:
                connecting_masters.append(master)

        if len(connecting_masters) == 0:
            lines.append(f"    // No masters connect to {slave.name}")
            # Use SignalNaming convention for signal names
            prefix = self._sp(slave)
            # Only assign signals for channels that THIS SLAVE needs
            slave_channels = self._determine_slave_channels(slave)
            if AXI4Channel.AW in slave_channels:
                lines.append(f"    assign {prefix}awvalid = 1'b0;")
            if AXI4Channel.W in slave_channels:
                lines.append(f"    assign {prefix}wvalid = 1'b0;")
            if AXI4Channel.AR in slave_channels:
                lines.append(f"    assign {prefix}arvalid = 1'b0;")
            return lines

        # For single master case (simplified routing)
        if len(connecting_masters) == 1:
            master = connecting_masters[0]
            lines.extend(self._generate_single_master_routing(slave_idx, slave, master))
        else:
            # Multi-master: OR-merge each master's contribution to the
            # slave-side request signals, gated by that master's own
            # `slave_select_aw/ar[slave_idx]`. This is correct as long as
            # only one master at a time is targeting this slave (which is
            # what the basic_connectivity test exercises). Simultaneous
            # contention would need a real arbiter; that's a separate
            # follow-up. Response-side routing already uses the
            # slave_adapter's bid_bridge_id/rid_bridge_id tracking
            # to pick the right destination master.
            if self._is_lane(slave):
                lines.extend(self._generate_lane_routing(slave, connecting_masters))
            else:
                lines.extend(self._generate_multi_master_routing(slave_idx, slave, connecting_masters))

        return lines

    # ------------------------------------------------------------------
    # Lanes into a multi-master slave on its own clock (bridge W9)
    # ------------------------------------------------------------------
    # Arbitration belongs in the slave's clock domain. For a cdc slave the
    # crossbar does not pick: each master's AW / W / AR leaves on a lane of
    # its own, and the slave adapter's bridge_cdc_slave_arb crosses the
    # lanes and arbitrates on s_aclk. (Picked here, the granted requests
    # queued in the one crossing behind the pick and a master's share
    # followed its outstanding count.) W needs no owner here: each lane
    # carries only its master's W, in that master's AW order (its W
    # destination FIFO), and the slave side follows its own AW pick. That
    # pick need not follow the masters' issue order, though, so a master
    # with a lane burst whose W is not yet in the lane holds its AWs to
    # every other slave (_lane_live; bridge BUG-024, a crossed-W deadlock
    # between a lane slave and a slot slave).

    def _is_lane(self, slave: SlaveInfo) -> bool:
        return cdc_lanes.is_lane_slave(slave, self.slaves.index(slave), self.masters)

    def _lane_masters(self, slave: SlaveInfo) -> List[MasterConfig]:
        return cdc_lanes.lane_masters(self.slaves.index(slave), self.masters)

    def _lane_index(self, m: MasterConfig, slave: SlaveInfo) -> int:
        return self._lane_masters(slave).index(m)

    def _lane_ports(self, slave: SlaveInfo, has_write: bool, has_read: bool,
                    id_w: int, addr_w: int) -> List[str]:
        n = len(self._lane_masters(slave))
        axw = cdc_lanes.ax_width(id_w, addr_w)
        ww = cdc_lanes.w_width(slave.data_width)
        p = f"{slave.name}_axi_lane_"
        lines = [f"    // Per-master lanes: {slave.name} arbitrates on its own clock (bridge W9)"]
        if has_write:
            lines += [f"    output logic [{n-1}:0] {p}awvalid,",
                      f"    input  logic [{n-1}:0] {p}awready,",
                      f"    output logic [{n * axw - 1}:0] {p}aw,",
                      f"    output logic [{n-1}:0] {p}wvalid,",
                      f"    input  logic [{n-1}:0] {p}wready,",
                      f"    output logic [{n * ww - 1}:0] {p}w,"]
        if has_read:
            lines += [f"    output logic [{n-1}:0] {p}arvalid,",
                      f"    input  logic [{n-1}:0] {p}arready,",
                      f"    output logic [{n * axw - 1}:0] {p}ar,"]
        return lines + [""]

    def _generate_lane_routing(self, slave: SlaveInfo, masters: List[MasterConfig]) -> List[str]:
        """Drive the per-master lanes of a multi-master cdc slave. The
        ordinary request nets are tied off; B and R come back on the
        ordinary ports and route by the ID's master bits as for any slave."""
        lines = []
        suffix = f"{slave.data_width}b"
        prefix = self._sp(slave)
        s = slave.name
        p = f"{s}_axi_lane_"
        from bridge_pkg.width_utils import xbar_id_width
        axw = cdc_lanes.ax_width(xbar_id_width(self.masters), self._determine_slave_interface_width(slave)[1])
        ww = cdc_lanes.w_width(slave.data_width)
        channels = self._determine_slave_channels(slave)
        has_write = AXI4Channel.AW in channels
        has_read = AXI4Channel.AR in channels
        lines.append(f"    // {s}: {len(masters)} masters on per-master lanes, arbitrated on "
                     f"{s}'s own clock in its slave adapter (bridge W9)")
        for m in masters:
            if has_write and m.channels in ("wr", "rw"):
                lines.append(f"    wire {m.name}_{suffix}_aw_to_{s} = "
                             f"{self._addr_decode_expr(m.name, suffix, 'aw', slave)};")
            if has_read and m.channels in ("rd", "rw"):
                lines.append(f"    wire {m.name}_{suffix}_ar_to_{s} = "
                             f"{self._addr_decode_expr(m.name, suffix, 'ar', slave)};")
        ax = ", ".join(f"{{src}}.{f}" for f in cdc_lanes.AX_FIELDS)
        wf = ", ".join(f"{{src}}.{f}" for f in cdc_lanes.W_FIELDS)
        for i, m in enumerate(masters):
            if has_write:
                if m.channels in ("wr", "rw"):
                    src = f"{m.name}_{suffix}_aw"
                    gate = self._aw_gate(m, suffix, slave)
                    lines.append(f"    assign {p}awvalid[{i}] = {m.name}_{suffix}_aw_to_{s}{gate} && "
                                 f"{m.name}_{suffix}_awvalid;")
                    lines.append(f"    assign {p}aw[{i}*{axw} +: {axw}] = {{{ax.format(src=src)}}};")
                    lines.append(f"    assign {m.name}_{suffix}_w_sel_{s} = {m.name}_{suffix}_w_to_{s};")
                    lines.append(f"    assign {p}wvalid[{i}] = {m.name}_{suffix}_w_to_{s} && "
                                 f"{m.name}_{suffix}_wvalid;")
                    lines.append(f"    assign {p}w[{i}*{ww} +: {ww}] = "
                                 f"{{{wf.format(src=m.name + '_' + suffix + '_w')}}};")
                else:
                    lines.append(f"    assign {p}awvalid[{i}] = 1'b0;")
                    lines.append(f"    assign {p}aw[{i}*{axw} +: {axw}] = '0;")
                    lines.append(f"    assign {p}wvalid[{i}] = 1'b0;")
                    lines.append(f"    assign {p}w[{i}*{ww} +: {ww}] = '0;")
            if has_read:
                if m.channels in ("rd", "rw"):
                    src = f"{m.name}_{suffix}_ar"
                    lines.append(f"    assign {p}arvalid[{i}] = {m.name}_{suffix}_ar_to_{s} && "
                                 f"{m.name}_{suffix}_arvalid;")
                    lines.append(f"    assign {p}ar[{i}*{axw} +: {axw}] = {{{ax.format(src=src)}}};")
                else:
                    lines.append(f"    assign {p}arvalid[{i}] = 1'b0;")
                    lines.append(f"    assign {p}ar[{i}*{axw} +: {axw}] = '0;")
        # The ordinary request nets carry nothing for this slave.
        req = []
        if has_write:
            req += ['awid', 'awaddr', 'awlen', 'awsize', 'awburst', 'awlock', 'awcache',
                    'awprot', 'awqos', 'awregion', 'awuser', 'awvalid',
                    'wdata', 'wstrb', 'wlast', 'wuser', 'wvalid', 'bridge_id_aw']
        if has_read:
            req += ['arid', 'araddr', 'arlen', 'arsize', 'arburst', 'arlock', 'arcache',
                    'arprot', 'arqos', 'arregion', 'aruser', 'arvalid', 'bridge_id_ar']
        for sig in req:
            lines.append(f"    assign {prefix}{sig} = '0;")
        wr_masters = [m for m in masters if m.channels in ("wr", "rw")]
        rd_masters = [m for m in masters if m.channels in ("rd", "rw")]
        if has_write:
            terms = [f"({self._rgnt(m, suffix, 'b', slave)} ? {m.name}_{suffix}_bready : '0)"
                     for m in wr_masters]
            lines.append(f"    assign {prefix}bready = " + " |\n        ".join(terms) + ";")
        if has_read:
            terms = [f"({self._rgnt(m, suffix, 'r', slave)} ? {m.name}_{suffix}_rready : '0)"
                     for m in rd_masters]
            lines.append(f"    assign {prefix}rready = " + " |\n        ".join(terms) + ";")
        lines.append("")
        return lines

    def _generate_arbiter(self, slave: SlaveInfo, suffix: str, prefix: str,
                          channel: str, masters: List[MasterConfig]) -> List[str]:
        """Per-slave request arbiter for one address channel (aw/ar), at the
        slave pins: round-robin pick among the masters' request slots
        (_generate_request_slots), grant LOCKED until the
        slave-side handshake completes (switching the mux mid-stall would
        change the request payload under an asserted valid -- an AXI
        violation, and exactly the OR-merge corruption this replaces).

        Emits, per master m: `{m}_{suffix}_{channel}_gnt_{slave}` -- high
        when m owns the slave's address channel this cycle. Field muxes
        and the ready return are gated by it."""
        lines = []
        n = len(masters)
        k = max(1, (n - 1).bit_length())
        s = slave.name
        arb = f"{s}_{channel}_arb"
        ready = f"{prefix}{channel}ready"

        qos = (self.arbitration == 'qos')
        policy = "QoS + aging, round-robin ties" if qos else "round-robin"
        lines.append(f"    // ---- {channel.upper()} arbiter for {s}: {policy}, lock until handshake ----")
        slots = self._uses_slots(slave, channel)
        if slots:
            req_bits = ", ".join(f"{self._slot(m, suffix, channel, slave)}_valid"
                                 for m in reversed(masters))
        else:
            req_bits = ", ".join(
                f"{m.name}_{suffix}_{channel}_to_{s} && {m.name}_{suffix}_{channel}valid"
                + (self._aw_gate(m, suffix, slave) if channel == "aw" else "")
                for m in reversed(masters))
        lines.append(f"    logic [{n-1}:0] {arb}_req;")
        lines.append(f"    assign {arb}_req = {{{req_bits}}};")
        lines.append(f"    logic [{k-1}:0] {arb}_lock, {arb}_rr;")
        lines.append(f"    logic {arb}_locked;")
        # The vector the round-robin pick walks: every requester under 'rr',
        # only the requesters at the highest effective priority under 'qos'.
        pick_vec = f"{arb}_req"
        if qos:
            sh = self.qos_aging_shift
            lines.append(f"    // QoS with aging (bridge TASK-006, was BRIDGE-017): effective priority = AxQOS + age,")
            lines.append(f"    // age climbing one level every 2**{sh} cycles a request waits, saturating")
            lines.append(f"    // at 15, cleared on grant. The highest effective priority wins; equals")
            lines.append(f"    // share round-robin. A QoS-0 requester behind a QoS-15 one is served")
            lines.append(f"    // after at most 15 * 2**{sh} cycles of waiting, never starved.")
            for i, m in enumerate(masters):
                lines.append(f"    logic [7:0] {arb}_age_{i};")
                lines.append(f"    wire  [7:0] {arb}_boost_{i} = {arb}_age_{i} >> {sh};")
                src = self._slot(m, suffix, channel, slave) if slots else f"{m.name}_{suffix}_{channel}"
                lines.append(f"    wire  [4:0] {arb}_sum_{i} = 5'({src}.qos) + "
                             f"(({arb}_boost_{i} > 8'd15) ? 5'd15 : 5'({arb}_boost_{i}[3:0]));")
                lines.append(f"    wire  [3:0] {arb}_eff_{i} = {arb}_sum_{i}[4] ? 4'hF : {arb}_sum_{i}[3:0];")
                lines.append(f"    wire  [3:0] {arb}_cand_{i} = {arb}_req[{i}] ? {arb}_eff_{i} : 4'h0;")
            best = f"{arb}_cand_0"
            for i in range(1, n):
                best = f"(({arb}_cand_{i} > {best}) ? {arb}_cand_{i} : {best})"
            lines.append(f"    wire  [3:0] {arb}_best = {best};")
            elig_bits = ", ".join(f"({arb}_req[{i}] && ({arb}_eff_{i} == {arb}_best))"
                                  for i in reversed(range(n)))
            lines.append(f"    wire  [{n-1}:0] {arb}_elig = {{{elig_bits}}};")
            pick_vec = f"{arb}_elig"
        # Round-robin pick, unrolled at generation time (n is small).
        pick_cases = []
        for r in range(n):
            order = [(r + o) % n for o in range(n)]
            expr = f"{k}'d{order[-1]}"
            for idx in reversed(order[:-1]):
                expr = f"{pick_vec}[{idx}] ? {k}'d{idx} : {expr}"
            pick_cases.append(expr)
        if n == 1:
            lines.append(f"    wire [{k-1}:0] {arb}_pick = {k}'d0;")
        else:
            expr = pick_cases[-1]
            for r in range(n - 2, -1, -1):
                expr = f"({arb}_rr == {k}'d{r}) ? ({pick_cases[r]}) : \n        {expr}"
            lines.append(f"    wire [{k-1}:0] {arb}_pick = {expr};")
        lines.append(f"    wire {arb}_gnt_valid = {arb}_locked || (|{arb}_req);")
        lines.append(f"    wire [{k-1}:0] {arb}_gnt = {arb}_locked ? {arb}_lock : {arb}_pick;")
        lines.append(f"    `ALWAYS_FF_RST(aclk, aresetn,")
        lines.append(f"        if (`RST_ASSERTED(aresetn)) begin")
        lines.append(f"            {arb}_lock   <= '0;")
        lines.append(f"            {arb}_rr     <= '0;")
        lines.append(f"            {arb}_locked <= 1'b0;")
        if qos:
            for i in range(n):
                lines.append(f"            {arb}_age_{i} <= 8'd0;")
        lines.append(f"        end else begin")
        lines.append(f"            if ({prefix}{channel}valid && {ready}) begin")
        lines.append(f"                {arb}_locked <= 1'b0;")
        lines.append(f"                {arb}_rr <= ({arb}_gnt == {k}'d{n-1}) ? {k}'d0 : {arb}_gnt + 1'b1;")
        lines.append(f"            end else if ({prefix}{channel}valid) begin")
        lines.append(f"                {arb}_lock   <= {arb}_gnt;")
        lines.append(f"                {arb}_locked <= 1'b1;")
        lines.append(f"            end")
        if qos:
            for i in range(n):
                lines.append(f"            if ({arb}_gnt_valid && ({arb}_gnt == {k}'d{i}))")
                lines.append(f"                {arb}_age_{i} <= 8'd0;")
                lines.append(f"            else if ({arb}_req[{i}] && ({arb}_age_{i} != 8'hFF))")
                lines.append(f"                {arb}_age_{i} <= {arb}_age_{i} + 8'd1;")
        lines.append(f"        end")
        lines.append(f"    )")
        for i, m in enumerate(masters):
            lines.append(f"    wire {m.name}_{suffix}_{channel}_gnt_{s} = "
                         f"{arb}_gnt_valid && ({arb}_gnt == {k}'d{i}) && {arb}_req[{i}];")
        if slots:
            for m in masters:
                q = self._slot(m, suffix, channel, slave)
                lines.append(f"    assign {q}_ready = {m.name}_{suffix}_{channel}_gnt_{s} && {ready};")
        lines.append("")
        return lines

    def _generate_multi_master_routing(self, slave_idx: int, slave: SlaveInfo,
                                        masters: List[MasterConfig]) -> List[str]:
        """Arbitrated mux of each master's request contribution onto the
        slave-side request signals. The mux keeps the OR-merge SHAPE, but
        every term is gated by an arbiter grant, so exactly one master's
        payload reaches the slave per cycle (the ungated OR let two
        concurrent requests merge field-by-field: addr = A|B). Responses
        route back by the slave's bid_*/rid_* tracking, unchanged."""
        lines = []
        suffix = f"{slave.data_width}b"
        prefix = self._sp(slave)

        wr_masters = [m for m in masters if m.channels in ("wr", "rw")]
        rd_masters = [m for m in masters if m.channels in ("rd", "rw")]

        lines.append(f"    // Multi-master ({len(masters)} masters) → {slave.name}")
        for m in masters:
            lines.append(f"    //   - {m.name} ({m.channels})")
        lines.append("")

        # Per-master address-decode signals. Defined once up-front and
        # reused by the arbiters and muxes below.
        for m in masters:
            if m.channels in ("wr", "rw"):
                aw_dec = self._addr_decode_expr(m.name, suffix, "aw", slave)
                lines.append(f"    wire {m.name}_{suffix}_aw_to_{slave.name} = {aw_dec};")
            if m.channels in ("rd", "rw"):
                ar_dec = self._addr_decode_expr(m.name, suffix, "ar", slave)
                lines.append(f"    wire {m.name}_{suffix}_ar_to_{slave.name} = {ar_dec};")
        lines.append("")

        def _gnt_merge(struct_field: str | None, master_sig_template: str,
                       master_subset: List[MasterConfig],
                       gate_template: str) -> str:
            """OR-shaped mux where each term is gated by a one-hot grant
            (arbiter gnt wires for AW/AR, w_sel for W) -- at most one term
            is ever non-zero."""
            parts = []
            for m in master_subset:
                base = master_sig_template.format(m=m.name, suffix=suffix)
                lhs = f"{base}{struct_field}" if struct_field else base
                gate = gate_template.format(m=m.name, suffix=suffix)
                parts.append(f"({gate} ? {lhs} : '0)")
            return " |\n        ".join(parts) if parts else "'0"

        if wr_masters:
            aw_slots = self._uses_slots(slave, "aw")
            if aw_slots:
                lines.extend(self._generate_request_slots(slave, suffix, "aw", wr_masters))
            lines.extend(self._generate_arbiter(slave, suffix, prefix, "aw", wr_masters))

            aw_gate = f"{{m}}_{{suffix}}_aw_gnt_{slave.name}"
            lines.append("    // AW channel (arbitrated mux across writing masters)")
            # qos/region/user are ordinary AXI4 signals: the struct has
            # carried them all along and the master adapters populate them,
            # but they were never muxed out to the slave. That left every
            # generated slave port's awqos/awregion/awuser UNDRIVEN -- 130,
            # 130 and 193 lint warnings across the 35 variants -- so a
            # master's QoS never reached its slave and the outputs floated
            # rather than tying to zero.
            aw_pairs = [("awid", ".id"), ("awaddr", ".addr"), ("awlen", ".len"),
                        ("awsize", ".size"), ("awburst", ".burst"),
                        ("awlock", ".lock"), ("awcache", ".cache"),
                        ("awprot", ".prot"), ("awqos", ".qos"),
                        ("awregion", ".region"), ("awuser", ".user")]
            aw_pairs += [(base, f".{field}") for field, _w, _f, base
                         in self._sb_fields('aw', self._sb_slave_feats(slave))]
            for sig, fld in aw_pairs:
                expr = _gnt_merge(fld, "{m}_{suffix}_aw" + ("_slot_" + slave.name if aw_slots else ""),
                                  wr_masters, aw_gate)
                lines.append(f"    assign {prefix}{sig} = {expr};")
            gnt_or = " || ".join(f"{m.name}_{suffix}_aw_gnt_{slave.name}" for m in wr_masters)
            lines.append(f"    assign {prefix}awvalid = {gnt_or};")
            lines.append("")

            # W owner FIFO: W beats at this slave must follow the order its
            # AWs were ACCEPTED (i.e. grant order), not whichever master
            # happens to have data ready. Push the granted master index at
            # each slave-side AW handshake; the head owns the W channel
            # until its WLAST.
            n = len(wr_masters)
            k = max(1, (n - 1).bit_length())
            own = f"{slave.name}_wowner"
            # Depth bound: an entry lives from the AW pick here to its WLAST
            # here, and WLAST precedes the B that frees the slave tracker, so
            # live entries <= the slave's max_outstanding plus what sits
            # between the pick and the tracker -- nothing: an arbitrated
            # slave has no AW stage past the pick, even in a registered
            # crossbar (it was + 2 while one existed). No full check, so the
            # FIFO covers that bound. A fixed 16 could overflow on any slave
            # deeper than 16 (bridge GitHub #119 L5).
            omo = int(getattr(slave, 'max_outstanding', 16))
            odepth = 1 << (omo - 1).bit_length()
            ob = odepth.bit_length() - 1
            lines.append(f"    // W owner FIFO: slave-side AW pick order owns the W channel")
            lines.append(f"    // ({odepth} deep: max_outstanding {omo})")
            lines.append(f"    logic [{k-1}:0] {own}_mem [{odepth}];")
            lines.append(f"    logic [{ob}:0] {own}_wptr, {own}_rptr;")
            # The owner bypass sends W ahead of its AW handshake; an AXI slave
            # adapter takes that, an APB/AXI4-Lite/WB4 shim does not (it
            # deadlocked bridge_2x2_wb4's concurrent test, bridge W14).
            shim = slave.protocol in ('apb', 'apb5', 'axil', 'axil5', 'wb4')
            if not aw_slots or shim:
                lines.append(f"    `ALWAYS_FF_RST(aclk, aresetn,")
                lines.append(f"        if (`RST_ASSERTED(aresetn)) begin")
                lines.append(f"            {own}_wptr <= '0;")
                lines.append(f"            {own}_rptr <= '0;")
                lines.append(f"        end else begin")
                lines.append(f"            if ({prefix}awvalid && {prefix}awready) begin")
                lines.append(f"                {own}_mem[{own}_wptr[{ob-1}:0]] <= {slave.name}_aw_arb_gnt;")
                lines.append(f"                {own}_wptr <= {own}_wptr + 1'b1;")
                lines.append(f"            end")
                lines.append(f"            if ({prefix}wvalid && {prefix}wready && {prefix}wlast) begin")
                lines.append(f"                {own}_rptr <= {own}_rptr + 1'b1;")
                lines.append(f"            end")
                lines.append(f"        end")
                lines.append(f"    )")
                lines.append(f"    wire {own}_valid = ({own}_wptr != {own}_rptr);")
                lines.append(f"    wire [{k-1}:0] {own}_head = {own}_mem[{own}_rptr[{ob-1}:0]];")
                for i, m in enumerate(wr_masters):
                    lines.append(f"    assign {m.name}_{suffix}_w_sel_{slave.name} = "
                                 f"{own}_valid && ({own}_head == {k}'d{i}) && {m.name}_{suffix}_w_to_{slave.name};")
            else:
                # Owner bypass: the pick is made at the pins, a cycle after the
                # AW entered its slot, so the FIFO alone would hand W its owner
                # a cycle later than the grant-on-entry arbiter did -- one
                # more cycle of write round trip (8 single-beat writes in
                # flight ran at 8/9). With the FIFO empty, the AW the arbiter
                # is presenting owns W now: the grant depends on registered
                # state only (slot valids, round-robin pointer, lock), never
                # on a ready, and W ahead of its AW is legal AXI. If that
                # burst's WLAST goes before the AW handshake, `ahead` marks
                # it so the handshake does not push an owner it no longer
                # needs; the grant is locked to that master meanwhile.
                lines.append(f"    logic {own}_ahead;")
                lines.append(f"    wire {own}_valid = ({own}_wptr != {own}_rptr);")
                lines.append(f"    wire {own}_byp = !{own}_valid && !{own}_ahead && {prefix}awvalid;")
                lines.append(f"    wire {own}_aw_hs = {prefix}awvalid && {prefix}awready;")
                lines.append(f"    wire {own}_w_end = {prefix}wvalid && {prefix}wready && {prefix}wlast;")
                lines.append(f"    `ALWAYS_FF_RST(aclk, aresetn,")
                lines.append(f"        if (`RST_ASSERTED(aresetn)) begin")
                lines.append(f"            {own}_wptr  <= '0;")
                lines.append(f"            {own}_rptr  <= '0;")
                lines.append(f"            {own}_ahead <= 1'b0;")
                lines.append(f"        end else begin")
                lines.append(f"            if ({own}_aw_hs && {own}_ahead) begin")
                lines.append(f"                {own}_ahead <= 1'b0;   // its W already went")
                lines.append(f"            end else if ({own}_aw_hs && !({own}_byp && {own}_w_end)) begin")
                lines.append(f"                {own}_mem[{own}_wptr[{ob-1}:0]] <= {slave.name}_aw_arb_gnt;")
                lines.append(f"                {own}_wptr <= {own}_wptr + 1'b1;")
                lines.append(f"            end else if (!{own}_aw_hs && {own}_byp && {own}_w_end) begin")
                lines.append(f"                {own}_ahead <= 1'b1;")
                lines.append(f"            end")
                lines.append(f"            if ({own}_valid && {own}_w_end) begin")
                lines.append(f"                {own}_rptr <= {own}_rptr + 1'b1;")
                lines.append(f"            end")
                lines.append(f"        end")
                lines.append(f"    )")
                lines.append(f"    wire [{k-1}:0] {own}_head = {own}_valid ? {own}_mem[{own}_rptr[{ob-1}:0]]")
                lines.append(f"                                       : {slave.name}_aw_arb_gnt;")
                for i, m in enumerate(wr_masters):
                    lines.append(f"    assign {m.name}_{suffix}_w_sel_{slave.name} = "
                                 f"({own}_valid || {own}_byp) && ({own}_head == {k}'d{i}) && "
                                 f"{m.name}_{suffix}_w_to_{slave.name};")
            lines.append("")

            w_gate = f"({{m}}_{{suffix}}_w_sel_{slave.name} && {{m}}_{{suffix}}_wvalid)"
            lines.append("    // W channel (owner-gated mux across writing masters)")
            w_pairs = [("wdata", ".data"), ("wstrb", ".strb"), ("wlast", ".last"),
                       ("wuser", ".user")]
            w_pairs += [(base, f".{field}") for field, _w, _f, base
                        in self._sb_fields('w', self._sb_slave_feats(slave))]
            for sig, fld in w_pairs:
                expr = _gnt_merge(fld, "{m}_{suffix}_w", wr_masters, w_gate)
                lines.append(f"    assign {prefix}{sig} = {expr};")
            wv_or = " || ".join(
                f"({m.name}_{suffix}_w_sel_{slave.name} && {m.name}_{suffix}_wvalid)"
                for m in wr_masters)
            lines.append(f"    assign {prefix}wvalid = {wv_or};")
            lines.append("")

            # bready: route back to whichever master owns this response
            # (per bid_bridge_id from the slave_adapter). bid_valid keeps
            # the path open across the whole B handshake.
            lines.append("    // Bready (slave -> the master whose response arbiter granted it)")
            bready_terms = []
            for m in wr_masters:
                bready_terms.append(
                    f"({self._rgnt(m, suffix, 'b', slave)} ? {m.name}_{suffix}_bready : '0)"
                )
            lines.append(f"    assign {prefix}bready = " + " |\n        ".join(bready_terms) + ";")
            lines.append("")

            # bridge_id_aw: which master originated this AW — the granted one.
            lines.append("    // Bridge ID (writes) — the granted master's id")
            bid_terms = []
            for m in wr_masters:
                bid_terms.append(
                    f"({m.name}_{suffix}_aw_gnt_{slave.name} ? {m.name}_bridge_id_aw : '0)"
                )
            lines.append(f"    assign {prefix}bridge_id_aw = " + " |\n        ".join(bid_terms) + ";")
            lines.append("")

        # Read side: same arbitration story, no W-follow machinery.
        if rd_masters:
            ar_slots = self._uses_slots(slave, "ar")
            if ar_slots:
                lines.extend(self._generate_request_slots(slave, suffix, "ar", rd_masters))
            lines.extend(self._generate_arbiter(slave, suffix, prefix, "ar", rd_masters))

            ar_gate = f"{{m}}_{{suffix}}_ar_gnt_{slave.name}"
            lines.append("    // AR channel (arbitrated mux across reading masters)")
            ar_pairs = [("arid", ".id"), ("araddr", ".addr"), ("arlen", ".len"),
                        ("arsize", ".size"), ("arburst", ".burst"),
                        ("arlock", ".lock"), ("arcache", ".cache"),
                        ("arprot", ".prot"), ("arqos", ".qos"),
                        ("arregion", ".region"), ("aruser", ".user")]
            ar_pairs += [(base, f".{field}") for field, _w, _f, base
                         in self._sb_fields('ar', self._sb_slave_feats(slave))]
            for sig, fld in ar_pairs:
                expr = _gnt_merge(fld, "{m}_{suffix}_ar" + ("_slot_" + slave.name if ar_slots else ""),
                                  rd_masters, ar_gate)
                lines.append(f"    assign {prefix}{sig} = {expr};")
            gnt_or = " || ".join(f"{m.name}_{suffix}_ar_gnt_{slave.name}" for m in rd_masters)
            lines.append(f"    assign {prefix}arvalid = {gnt_or};")
            lines.append("")

            lines.append("    // Rready (slave -> the master whose response arbiter granted it)")
            rready_terms = []
            for m in rd_masters:
                rready_terms.append(
                    f"({self._rgnt(m, suffix, 'r', slave)} ? {m.name}_{suffix}_rready : '0)"
                )
            lines.append(f"    assign {prefix}rready = " + " |\n        ".join(rready_terms) + ";")
            lines.append("")

            lines.append("    // Bridge ID (reads) — the granted master's id")
            rid_terms = []
            for m in rd_masters:
                rid_terms.append(
                    f"({m.name}_{suffix}_ar_gnt_{slave.name} ? {m.name}_bridge_id_ar : '0)"
                )
            lines.append(f"    assign {prefix}bridge_id_ar = " + " |\n        ".join(rid_terms) + ";")
            lines.append("")

        return lines

    def _generate_single_master_routing(self, slave_idx: int, slave: SlaveInfo,
                                       master: MasterConfig) -> List[str]:
        """
        Generate routing for slave with single master.

        Directly connects master's width-matched path to slave.
        For APB slaves, uses LCD width instead of slave native width.
        """
        lines = []

        # Determine adapter output width for this slave connection
        # For ALL slaves (both APB and AXI4), use the slave's native data width
        # The master adapter handles width conversion to produce correctly-sized paths
        adapter_width = slave.data_width

        suffix = f"{adapter_width}b"

        lines.append(f"    // Single master: {master.name} → {slave.name}")
        lines.append(f"    // Master width: {master.data_width}b, Slave width: {slave.data_width}b")
        lines.append(f"    // Using {suffix} path from adapter (APB LCD width)" if slave.protocol in ('apb', 'apb5') else f"    // Using {suffix} path from adapter")
        lines.append("")

        # Write channels
        if master.channels in ["wr", "rw"]:
            lines.extend(self._generate_write_channel_routing(slave_idx, slave, master, suffix))

        # Read channels
        if master.channels in ["rd", "rw"]:
            lines.extend(self._generate_read_channel_routing(slave_idx, slave, master, suffix))

        return lines

    def _addr_decode_expr(self, master_name: str, suffix: str, channel: str,
                          slave: SlaveInfo) -> str:
        """Return an expression evaluating to 1 when
        `<master_name>_<suffix>_<channel>.addr` falls in `slave`'s range.
        Used in place of `<master>_slave_select_<channel>[slave_idx]` to
        gate AR/AW signals: the address bus on the converter/passthrough
        m_axi side is held stable across the entire handshake, while the
        master adapter's `slave_select_*` reverts the moment fub_axi
        `*addr` reverts -- which happens as soon as the wrapper pops the
        skid, before the converter has finished pushing to the xbar.
        """
        # SUBTRACTIVE slave: it claims what nobody else claimed, so its term
        # is the NEGATION of every positively-decoded slave this master can
        # reach -- not its address range. Its range is the full span, which
        # would reduce to a tautological 1'b1 here and route EVERY
        # transaction to both the real slave and the catch-all at once. The
        # muxes OR their payloads, so the master would read back
        # addr = real | catchall. That is the corruption, not a hang, and it
        # is worse.
        if getattr(slave, 'internal', False):
            m = next((mm for mm in self.masters if mm.name == master_name), None)
            reachable = set(getattr(m, 'slave_connections', []) or []) if m else set()
            others = [sl for i, sl in enumerate(self.slaves)
                      if not getattr(sl, 'internal', False) and i in reachable]
            if not others:
                return "1'b1"   # nothing else to claim; everything is unmapped
            # Inline each range comparison rather than referencing the sibling
            # `<master>_<suffix>_<channel>_to_<slave>` wires. Those are emitted
            # per channel, so a slave with no read path from this master has no
            # `ar_to_` wire at all and naming it is a compile error
            # ("Can't find definition of variable"). Recomputing the comparison
            # is a few gates the synthesiser CSEs away, and it cannot dangle.
            terms = " || ".join(
                f"({self._addr_decode_expr(master_name, suffix, channel, sl)})"
                for sl in others)
            return f"!({terms})"

        addr_sig = f"{master_name}_{suffix}_{channel}.addr"
        base = slave.base_addr
        end = slave.base_addr + slave.addr_range - 1
        # The decode compares the FABRIC address -- the channel struct's addr,
        # sized to the widest port (bridge_module_generator's package
        # addr_width) -- so its literals and its full-span shortcut take that
        # width, not the slave's. A slave narrower than the fabric (an APB
        # slave windowed to its offset) used to get its base sized to its own
        # addr_width: 20'h30000000 does not elaborate, and with a 20-bit
        # max_addr the end-of-space shortcut dropped the upper bound, so the
        # slave would have claimed every address from its base up.
        aw = max(p.addr_width for p in list(self.masters) + list(self.slaves))
        hex_digits = (aw + 3) // 4
        max_addr = (1 << aw) - 1
        # Verilator warns when comparisons are tautological for an
        # unsigned bus. Drop the always-true halves to keep the RTL
        # lint-clean. If the slave covers the full address space, the
        # decode is just a constant 1.
        base_zero = (base == 0)
        end_max = (end >= max_addr)
        if base_zero and end_max:
            return "1'b1"
        if base_zero:
            return f"({addr_sig} <= {aw}'h{end:0{hex_digits}x})"
        if end_max:
            return f"({addr_sig} >= {aw}'h{base:0{hex_digits}x})"
        return (f"(({addr_sig} >= {aw}'h{base:0{hex_digits}x}) && "
                f"({addr_sig} <= {aw}'h{end:0{hex_digits}x}))")

    def _generate_write_channel_routing(self, slave_idx: int, slave: SlaveInfo,
                                        master: MasterConfig, suffix: str) -> List[str]:
        """Generate AW, W, B channel routing.

        AW gating uses address re-decode on `<master>_<suffix>_aw.addr`
        (the converter/passthrough's m_axi side) -- see _addr_decode_expr
        for rationale. W follows AW via a small per-(master,slave) FIFO
        that captures which slave the AW went to at AW handshake and
        gates W beats until the WLAST handshake pops the FIFO.
        """
        lines = []
        # Use SignalNaming convention for slave signals
        prefix = self._sp(slave)
        master_idx = self.masters.index(master)
        addr_dec = self._addr_decode_expr(master.name, suffix, "aw", slave)
        sig_select = f"{master.name}_{suffix}_aw_to_{slave.name}"
        w_sig = f"{master.name}_{suffix}_w_to_{slave.name}"

        # AW channel (master → slave) - address-decode gating
        lines.append("    // AW channel (gated by address re-decode -- see _addr_decode_expr)")
        lines.append(f"    wire {sig_select} = {addr_dec};")
        # Grant alias: single master needs no arbiter; the response muxes
        # gate on _gnt_ uniformly for single- and multi-master slaves.
        lines.append(f"    wire {master.name}_{suffix}_aw_gnt_{slave.name} = "
                     f"{sig_select}{self._aw_gate(master, suffix, slave)};")
        lines.append(f"    assign {prefix}awid     = {sig_select} ? {master.name}_{suffix}_aw.id : '0;")
        lines.append(f"    assign {prefix}awaddr   = {sig_select} ? {master.name}_{suffix}_aw.addr : '0;")
        lines.append(f"    assign {prefix}awlen    = {sig_select} ? {master.name}_{suffix}_aw.len : '0;")
        lines.append(f"    assign {prefix}awsize   = {sig_select} ? {master.name}_{suffix}_aw.size : '0;")
        lines.append(f"    assign {prefix}awburst  = {sig_select} ? {master.name}_{suffix}_aw.burst : '0;")
        lines.append(f"    assign {prefix}awlock   = {sig_select} ? {master.name}_{suffix}_aw.lock : '0;")
        lines.append(f"    assign {prefix}awcache  = {sig_select} ? {master.name}_{suffix}_aw.cache : '0;")
        lines.append(f"    assign {prefix}awprot   = {sig_select} ? {master.name}_{suffix}_aw.prot : '0;")
        # qos/region/user: ordinary AXI4 signals the struct has always
        # carried. Omitted here as well as in the arbitrated path, so
        # single-master bridges left them undriven too.
        lines.append(f"    assign {prefix}awqos    = {sig_select} ? {master.name}_{suffix}_aw.qos : '0;")
        lines.append(f"    assign {prefix}awregion = {sig_select} ? {master.name}_{suffix}_aw.region : '0;")
        lines.append(f"    assign {prefix}awuser   = {sig_select} ? {master.name}_{suffix}_aw.user : '0;")
        for field, w, _feat, base in self._sb_fields('aw', self._sb_slave_feats(slave)):
            src = self._sb_struct_to_port('aw', w, f"{master.name}_{suffix}_aw.{field}", slave.data_width)
            lines.append(f"    assign {prefix}{base}  = {sig_select} ? {src} : '0;  // AXI5 sideband")
        if self._aw_gate(master, suffix, slave):
            lines.append(f"    assign {prefix}awvalid  = {master.name}_{suffix}_aw_gnt_{slave.name} && "
                         f"{master.name}_{suffix}_awvalid;")
        else:
            lines.append(f"    assign {prefix}awvalid  = {sig_select} && {master.name}_{suffix}_awvalid;")
        lines.append("")

        # W follows the AW via the per-path W destination FIFO (emitted in
        # _generate_w_dest_fifos, which assigns {w_sig}). Single master →
        # no owner arbitration; w_sel is just w_to.
        lines.append(f"    assign {master.name}_{suffix}_w_sel_{slave.name} = {w_sig};")
        lines.append("")

        # W channel (master → slave)
        lines.append("    // W channel (gated by the W destination FIFO head)")
        lines.append(f"    assign {prefix}wdata  = {w_sig} ? {master.name}_{suffix}_w.data : '0;")
        lines.append(f"    assign {prefix}wstrb  = {w_sig} ? {master.name}_{suffix}_w.strb : '0;")
        lines.append(f"    assign {prefix}wlast  = {w_sig} ? {master.name}_{suffix}_w.last : '0;")
        lines.append(f"    assign {prefix}wuser  = {w_sig} ? {master.name}_{suffix}_w.user : '0;")
        for field, w, _feat, base in self._sb_fields('w', self._sb_slave_feats(slave)):
            src = self._sb_struct_to_port('w', w, f"{master.name}_{suffix}_w.{field}", slave.data_width)
            lines.append(f"    assign {prefix}{base} = {w_sig} ? {src} : '0;  // AXI5 sideband")
        lines.append(f"    assign {prefix}wvalid = {w_sig} && {master.name}_{suffix}_wvalid;")
        lines.append("")

        # bready (master → slave). Use the slave's bid_valid/bid_bridge_id
        # tracking instead of slave_select_aw, because slave_select_aw is
        # combinational from fub_axi_awaddr and goes back to 0 once the AW
        # has been issued — leaving bready stuck at 0 while the slave is
        # still trying to drive bvalid for the response. Earlier versions
        # had this exact bug.
        lines.append("    // Bready (master → slave) — gated on bid_valid so the path stays")
        lines.append("    // open through the entire B handshake, not just the AW phase.")
        lines.append(f"    assign {prefix}bready = {self._rgnt(master, suffix, 'b', slave)} ? {master.name}_{suffix}_bready : '0;")
        lines.append("")

        # Bridge ID routing (master → slave) - passes master index for response routing
        lines.append("    // Bridge ID (master → slave)")
        lines.append(f"    assign {prefix}bridge_id_aw = {sig_select} ? {master.name}_bridge_id_aw : '0;")
        lines.append("")

        return lines

    def _generate_read_channel_routing(self, slave_idx: int, slave: SlaveInfo,
                                       master: MasterConfig, suffix: str) -> List[str]:
        """Generate AR, R channel routing.

        AR gating uses address re-decode on `<master>_<suffix>_ar.addr`
        (the converter/passthrough's m_axi side). See _addr_decode_expr.
        """
        lines = []
        # Use SignalNaming convention for slave signals
        prefix = self._sp(slave)
        master_idx = self.masters.index(master)
        addr_dec = self._addr_decode_expr(master.name, suffix, "ar", slave)
        sig_select = f"{master.name}_{suffix}_ar_to_{slave.name}"

        # AR channel (master → slave) - address-decode gating
        lines.append("    // AR channel (gated by address re-decode -- see _addr_decode_expr)")
        lines.append(f"    wire {sig_select} = {addr_dec};")
        # Grant alias: see _generate_write_channel_routing.
        lines.append(f"    wire {master.name}_{suffix}_ar_gnt_{slave.name} = {sig_select};")
        lines.append(f"    assign {prefix}arid     = {sig_select} ? {master.name}_{suffix}_ar.id : '0;")
        lines.append(f"    assign {prefix}araddr   = {sig_select} ? {master.name}_{suffix}_ar.addr : '0;")
        lines.append(f"    assign {prefix}arlen    = {sig_select} ? {master.name}_{suffix}_ar.len : '0;")
        lines.append(f"    assign {prefix}arsize   = {sig_select} ? {master.name}_{suffix}_ar.size : '0;")
        lines.append(f"    assign {prefix}arburst  = {sig_select} ? {master.name}_{suffix}_ar.burst : '0;")
        lines.append(f"    assign {prefix}arlock   = {sig_select} ? {master.name}_{suffix}_ar.lock : '0;")
        lines.append(f"    assign {prefix}arcache  = {sig_select} ? {master.name}_{suffix}_ar.cache : '0;")
        lines.append(f"    assign {prefix}arprot   = {sig_select} ? {master.name}_{suffix}_ar.prot : '0;")
        lines.append(f"    assign {prefix}arqos    = {sig_select} ? {master.name}_{suffix}_ar.qos : '0;")
        lines.append(f"    assign {prefix}arregion = {sig_select} ? {master.name}_{suffix}_ar.region : '0;")
        lines.append(f"    assign {prefix}aruser   = {sig_select} ? {master.name}_{suffix}_ar.user : '0;")
        for field, w, _feat, base in self._sb_fields('ar', self._sb_slave_feats(slave)):
            src = self._sb_struct_to_port('ar', w, f"{master.name}_{suffix}_ar.{field}", slave.data_width)
            lines.append(f"    assign {prefix}{base}  = {sig_select} ? {src} : '0;  // AXI5 sideband")
        lines.append(f"    assign {prefix}arvalid  = {sig_select} && {master.name}_{suffix}_arvalid;")
        lines.append("")

        # rready (master → slave). Same fix as bready: gate on rid_valid /
        # rid_bridge_id (which the slave_adapter holds combinationally
        # across the response phase) instead of slave_select_ar (which
        # is combinational from fub_axi_araddr and goes back to 0 once
        # the AR has been issued — so the slave never gets rready and
        # the R handshake stalls).
        lines.append("    // Rready (master → slave) — gated on rid_valid so the path stays")
        lines.append("    // open through the entire R handshake, not just the AR phase.")
        lines.append(f"    assign {prefix}rready = {self._rgnt(master, suffix, 'r', slave)} ? {master.name}_{suffix}_rready : '0;")
        lines.append("")

        # Bridge ID routing (master → slave) - passes master index for response routing
        lines.append("    // Bridge ID (master → slave)")
        lines.append(f"    assign {prefix}bridge_id_ar = {sig_select} ? {master.name}_bridge_id_ar : '0;")
        lines.append("")

        return lines

    def _path_slaves(self, master: MasterConfig, width: int):
        """Slaves `master` connects to on its `width` path, as (index, slave)."""
        return [(si, self.slaves[si]) for si in master.slave_connections
                if self.slaves[si].data_width == width]

    def _rgnt(self, master: MasterConfig, suffix: str, ch: str, slave: SlaveInfo) -> str:
        """Name of the response grant: `slave` owns `master`'s `ch` (b|r) path."""
        return f"{master.name}_{suffix}_{ch}_rgnt_{slave.name}"

    def _generate_response_arbiters(self) -> List[str]:
        """Per master width path and response channel, pick ONE slave.

        A master may have transactions in flight at several slaves of one
        width path at once (the one-outstanding-target rule is gone), so two
        of them can hold a response for it in the same cycle. The muxes used
        to OR every slave whose tracker head belonged to the master, which
        was only correct while at most one could. This round-robin picks
        one requesting slave; only it sees the master's ready.

        Grant locking: a granted response held off by the master keeps its
        grant (its payload must not change under an asserted valid); B and R
        alike re-arbitrate on every beat taken. R used to hold through RLAST
        so bursts never interleaved toward a master, but a slave may itself
        interleave R beats across IDs (AXI4), and two such slaves could then
        each wait on the other's held master path -- a deadlock. The width
        converters now convert per ID, so beat-level interleaving toward a
        master is legal and handled (bridge R interleave, 2026-10-18).

        A path with a single slave keeps the plain ownership gate (no
        arbiter, no extra state), so its timing and latency are unchanged.
        """
        lines = ["    // ================================================================",
                 "    // Response arbiters (one slave per master path per channel)",
                 "    // ================================================================",
                 ""]
        for master in self.masters:
            mi = self.masters.index(master)
            for width in self._get_connected_slave_widths(master):
                suffix = f"{width}b"
                conn = self._path_slaves(master, width)
                for ch, on in (("b", master.channels in ("wr", "rw")),
                               ("r", master.channels in ("rd", "rw"))):
                    if not on or not conn:
                        continue
                    lines.extend(self._generate_response_arbiter(master, mi, suffix, ch, conn))
        return lines

    def _generate_response_arbiter(self, master, mi, suffix, ch, conn) -> List[str]:
        lines = []
        n = len(conn)
        own = [f"(({self._sp(sl)}{ch}id_bridge_id == {mi}) && {self._sp(sl)}{ch}id_valid)"
               for _si, sl in conn]
        if n == 1:
            sl = conn[0][1]
            lines.append(f"    wire {self._rgnt(master, suffix, ch, sl)} = {own[0]};")
            lines.append("")
            return lines
        k = max(1, (n - 1).bit_length())
        arb = f"{master.name}_{suffix}_{ch}_rarb"
        ready = f"{master.name}_{suffix}_{ch}ready"
        lines.append(f"    // ---- {ch.upper()} response arbiter, master {master.name} {suffix}: "
                     f"round-robin per beat, lock until taken ----")
        req_bits = ", ".join(f"{own[i]} && {self._sp(conn[i][1])}{ch}valid" for i in reversed(range(n)))
        lines.append(f"    logic [{n-1}:0] {arb}_req;")
        lines.append(f"    assign {arb}_req = {{{req_bits}}};")
        lines.append(f"    logic [{k-1}:0] {arb}_lock, {arb}_rr;")
        lines.append(f"    logic {arb}_locked;")
        pick_cases = []
        for r in range(n):
            order = [(r + o) % n for o in range(n)]
            expr = f"{k}'d{order[-1]}"
            for idx in reversed(order[:-1]):
                expr = f"{arb}_req[{idx}] ? {k}'d{idx} : {expr}"
            pick_cases.append(expr)
        expr = pick_cases[-1]
        for r in range(n - 2, -1, -1):
            expr = f"({arb}_rr == {k}'d{r}) ? ({pick_cases[r]}) : \n        {expr}"
        lines.append(f"    wire [{k-1}:0] {arb}_pick = {expr};")
        lines.append(f"    wire [{k-1}:0] {arb}_gnt = {arb}_locked ? {arb}_lock : {arb}_pick;")
        lines.append(f"    wire {arb}_gnt_valid = {arb}_locked || (|{arb}_req);")
        for i, (_si, sl) in enumerate(conn):
            lines.append(f"    wire {self._rgnt(master, suffix, ch, sl)} = "
                         f"{arb}_gnt_valid && ({arb}_gnt == {k}'d{i});")
        vld = " || ".join(f"({self._rgnt(master, suffix, ch, sl)} && {arb}_req[{i}])"
                          for i, (_si, sl) in enumerate(conn))
        lines.append(f"    wire {arb}_vld = {vld};")
        lines.append(f"    `ALWAYS_FF_RST(aclk, aresetn,")
        lines.append(f"        if (`RST_ASSERTED(aresetn)) begin")
        lines.append(f"            {arb}_lock   <= '0;")
        lines.append(f"            {arb}_rr     <= '0;")
        lines.append(f"            {arb}_locked <= 1'b0;")
        lines.append(f"        end else if ({arb}_vld && {ready}) begin")
        lines.append(f"            {arb}_locked <= 1'b0;")
        lines.append(f"            {arb}_rr <= ({arb}_gnt == {k}'d{n-1}) ? {k}'d0 : {arb}_gnt + 1'b1;")
        lines.append(f"        end else if ({arb}_vld) begin")
        lines.append(f"            {arb}_lock   <= {arb}_gnt;       // offered, not taken: hold")
        lines.append(f"            {arb}_locked <= 1'b1;")
        lines.append(f"        end")
        lines.append(f"    )")
        lines.append("")
        return lines

    def _generate_response_muxes(self) -> List[str]:
        """
        Generate the response muxes: each master path takes its B/R from
        the slave its response arbiter granted (_generate_response_arbiters).

        For each master and width combination, generate OR-based muxing of:
        - Write responses: awready, wready, b.* (uses slave_select_aw)
        - Read responses: arready, r.* (uses slave_select_ar)

        This avoids multiple driver errors from individual slave routing.
        """
        lines = []

        lines.append("    // ================================================================")
        lines.append("    // Response MUXes (OR together all slave responses)")
        lines.append("    // ================================================================")
        lines.append("")

        # Generate response muxes for each master
        for master in self.masters:
            # Get unique widths this master connects to
            widths = self._get_connected_slave_widths(master)

            # Generate muxes for each width path
            for width in widths:
                suffix = f"{width}b"

                lines.append(f"    // Master: {master.name}, Width path: {suffix}")

                # Write channel responses (if master has write channels)
                if master.channels in ["wr", "rw"]:
                    lines.extend(self._generate_write_response_mux(master, width, suffix))

                # Read channel responses (if master has read channels)
                if master.channels in ["rd", "rw"]:
                    lines.extend(self._generate_read_response_mux(master, width, suffix))

                lines.append("")

        return lines

    def _generate_write_response_mux(self, master: MasterConfig, width: int,
                                     suffix: str) -> List[str]:
        """Generate write response MUX (awready, wready, b.*) using slave prefixes."""
        lines = []

        # Helper to get slave signal prefix using SignalNaming convention
        def get_slave_prefix(slave: SlaveInfo) -> str:
            return self._sp(slave)

        # Find slaves at this width that master connects to
        connected_slaves = []
        for slave_idx in master.slave_connections:
            if self.slaves[slave_idx].data_width == width:
                connected_slaves.append((slave_idx, self.slaves[slave_idx]))

        if not connected_slaves:
            return lines

        # Get master index for bridge_id matching
        master_idx = self.masters.index(master)

        # Generate awready MUX: an arbitrated slave's term is its request
        # slot accepting (gated by the write ordering rule); a single-master
        # slave's is the address decode (the gnt alias) and the slave's ready.
        lines.append(f"    assign {master.name}_{suffix}_awready = ")
        mux_terms = []
        for slave_idx, slave in connected_slaves:
            prefix = get_slave_prefix(slave)
            mux_terms.append(f"        {self._ax_ready_term(master, suffix, 'aw', slave)}")
        lines.append(" |\n".join(mux_terms) + ";")
        lines.append("")

        # Generate wready MUX -- W beats follow the destination FIFO head,
        # gated by the slave's W-owner (w_sel) so only the owning master
        # sees wready.
        lines.append(f"    assign {master.name}_{suffix}_wready = ")
        mux_terms = []
        for slave_idx, slave in connected_slaves:
            prefix = get_slave_prefix(slave)
            wready = (f"{slave.name}_axi_lane_wready[{self._lane_index(master, slave)}]"
                      if self._is_lane(slave) else f"{prefix}wready")
            mux_terms.append(f"        ({master.name}_{suffix}_w_sel_{slave.name} ? {wready} : '0)")
        lines.append(" |\n".join(mux_terms) + ";")
        lines.append("")

        # Generate B channel MUXes (bid, bresp, bvalid) - uses bridge_id for response routing
        lines.append(f"    assign {master.name}_{suffix}_b.id = ")
        mux_terms = []
        for slave_idx, slave in connected_slaves:
            prefix = get_slave_prefix(slave)
            mux_terms.append(f"        ({self._rgnt(master, suffix, 'b', slave)} ? {prefix}bid : '0)")
        lines.append(" |\n".join(mux_terms) + ";")
        lines.append("")

        lines.append(f"    assign {master.name}_{suffix}_b.resp = ")
        mux_terms = []
        for slave_idx, slave in connected_slaves:
            prefix = get_slave_prefix(slave)
            mux_terms.append(f"        ({self._rgnt(master, suffix, 'b', slave)} ? {prefix}bresp : '0)")
        lines.append(" |\n".join(mux_terms) + ";")
        lines.append("")

        # buser: the response struct has always carried it and the master
        # adapter reads it, but it was never driven -- the return half of the
        # same gap that left awuser/aruser undriven on the request side.
        lines.append(f"    assign {master.name}_{suffix}_b.user = ")
        mux_terms = []
        for slave_idx, slave in connected_slaves:
            prefix = get_slave_prefix(slave)
            mux_terms.append(f"        ({self._rgnt(master, suffix, 'b', slave)} ? {prefix}buser : '0)")
        lines.append(" |\n".join(mux_terms) + ";")
        lines.append("")

        lines.append(f"    assign {master.name}_{suffix}_bvalid = ")
        mux_terms = []
        for slave_idx, slave in connected_slaves:
            prefix = get_slave_prefix(slave)
            mux_terms.append(f"        ({self._rgnt(master, suffix, 'b', slave)} ? {prefix}bvalid : '0)")
        lines.append(" |\n".join(mux_terms) + ";")
        lines.append("")

        # AXI5 sideband: union fields exist in the struct for every
        # master, so they must always be driven; only slaves that expose
        # the feature contribute (others fall to the '0 default).
        for field, w, feat, base in self._sb_fields('b', self.sb_union):
            lines.append(f"    assign {master.name}_{suffix}_b.{field} = ")
            mux_terms = []
            for slave_idx, slave in connected_slaves:
                if feat not in self._sb_slave_feats(slave):
                    continue
                prefix = get_slave_prefix(slave)
                src = self._sb_port_to_struct('b', w, f"{prefix}{base}", slave.data_width)
                mux_terms.append(f"        ({self._rgnt(master, suffix, 'b', slave)} ? {src} : '0)")
            lines.append((" |\n".join(mux_terms) if mux_terms else "        '0") + ";")
            lines.append("")

        return lines

    def _generate_read_response_mux(self, master: MasterConfig, width: int,
                                    suffix: str) -> List[str]:
        """Generate read response MUX (arready, r.*) using slave prefixes."""
        lines = []

        # Helper to get slave signal prefix using SignalNaming convention
        def get_slave_prefix(slave: SlaveInfo) -> str:
            return self._sp(slave)

        # Find slaves at this width that master connects to
        connected_slaves = []
        for slave_idx in master.slave_connections:
            if self.slaves[slave_idx].data_width == width:
                connected_slaves.append((slave_idx, self.slaves[slave_idx]))

        if not connected_slaves:
            return lines

        # Get master index for bridge_id matching
        master_idx = self.masters.index(master)

        # Generate arready MUX: the arbitrated slave's request slot, or the
        # single-master slave's decode and ready (see the awready MUX).
        lines.append(f"    assign {master.name}_{suffix}_arready = ")
        mux_terms = []
        for slave_idx, slave in connected_slaves:
            prefix = get_slave_prefix(slave)
            mux_terms.append(f"        {self._ax_ready_term(master, suffix, 'ar', slave)}")
        lines.append(" |\n".join(mux_terms) + ";")
        lines.append("")

        # Generate R channel MUXes (rid, rdata, rresp, rlast, rvalid) - uses bridge_id for response routing
        lines.append(f"    assign {master.name}_{suffix}_r.id = ")
        mux_terms = []
        for slave_idx, slave in connected_slaves:
            prefix = get_slave_prefix(slave)
            mux_terms.append(f"        ({self._rgnt(master, suffix, 'r', slave)} ? {prefix}rid : '0)")
        lines.append(" |\n".join(mux_terms) + ";")
        lines.append("")

        lines.append(f"    assign {master.name}_{suffix}_r.data = ")
        mux_terms = []
        for slave_idx, slave in connected_slaves:
            prefix = get_slave_prefix(slave)
            # Explicitly size the default value to match the slave's data width
            mux_terms.append(f"        ({self._rgnt(master, suffix, 'r', slave)} ? {prefix}rdata : {width}'b0)")
        lines.append(" |\n".join(mux_terms) + ";")
        lines.append("")

        lines.append(f"    assign {master.name}_{suffix}_r.resp = ")
        mux_terms = []
        for slave_idx, slave in connected_slaves:
            prefix = get_slave_prefix(slave)
            mux_terms.append(f"        ({self._rgnt(master, suffix, 'r', slave)} ? {prefix}rresp : '0)")
        lines.append(" |\n".join(mux_terms) + ";")
        lines.append("")

        lines.append(f"    assign {master.name}_{suffix}_r.last = ")
        mux_terms = []
        for slave_idx, slave in connected_slaves:
            prefix = get_slave_prefix(slave)
            mux_terms.append(f"        ({self._rgnt(master, suffix, 'r', slave)} ? {prefix}rlast : '0)")
        lines.append(" |\n".join(mux_terms) + ";")
        lines.append("")

        lines.append(f"    assign {master.name}_{suffix}_r.user = ")
        mux_terms = []
        for slave_idx, slave in connected_slaves:
            prefix = get_slave_prefix(slave)
            mux_terms.append(f"        ({self._rgnt(master, suffix, 'r', slave)} ? {prefix}ruser : '0)")
        lines.append(" |\n".join(mux_terms) + ";")
        lines.append("")

        lines.append(f"    assign {master.name}_{suffix}_rvalid = ")
        mux_terms = []
        for slave_idx, slave in connected_slaves:
            prefix = get_slave_prefix(slave)
            mux_terms.append(f"        ({self._rgnt(master, suffix, 'r', slave)} ? {prefix}rvalid : '0)")
        lines.append(" |\n".join(mux_terms) + ";")
        lines.append("")

        # AXI5 sideband (see write-response mux comment).
        for field, w, feat, base in self._sb_fields('r', self.sb_union):
            lines.append(f"    assign {master.name}_{suffix}_r.{field} = ")
            mux_terms = []
            for slave_idx, slave in connected_slaves:
                if feat not in self._sb_slave_feats(slave):
                    continue
                prefix = get_slave_prefix(slave)
                src = self._sb_port_to_struct('r', w, f"{prefix}{base}", slave.data_width)
                mux_terms.append(f"        ({self._rgnt(master, suffix, 'r', slave)} ? {src} : '0)")
            lines.append((" |\n".join(mux_terms) if mux_terms else "        '0") + ";")
            lines.append("")

        return lines

