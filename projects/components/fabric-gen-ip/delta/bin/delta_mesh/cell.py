        self.comment("output; an idle input routes its presented head flit")
        self.comment("(route_req from the table). Drop/config heads and")
        self.comment("draining bodies request nothing -- they consume without a")
        self.comment("grant -- so a head beat is never consumed early and a")
        self.comment("malformed flit never reaches an output.")
        self.comment("==========================================================================")
        self.instruction("")
        self.instruction("logic [NUM_PORTS-1:0] request_matrix [NUM_PORTS];  // [output][input]")
