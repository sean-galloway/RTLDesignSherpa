    def generate_localparams(self):
        self.comment("==========================================================================")
        self.comment("Local parameters")
        self.comment("==========================================================================")
        self.instruction("localparam int NUM_PORTS = 9;")
        self.instruction("localparam int PORT_W    = $clog2(NUM_PORTS);")
        self.instruction("")
        self.comment("Mesh port ids (pinned; Task 6c: P_DIA at 6, P_DIA2")
        self.comment("at 7, P_LOCAL moved to 8)")
        for name, value in PORT_IDS:
            self.instruction(f"localparam int {name} = {value};")
        self.instruction("")
        self.comment("Input buffer configuration (plan-pinned DEPTH=4)")
        self.instruction("localparam int FIFO_DEPTH = 4;")
        self.instruction("localparam int FLIT_W     = DATA_WIDTH + USER_WIDTH + 1;")
        self.instruction("localparam int VC_W       = (NUM_VC > 1) ? $clog2(NUM_VC) : 1;")
        self.comment("FIFO memory style from the FIFO_IMPL knob: 'reg' -> AUTO")
        self.comment("(register array, mux read); 'sram' -> BRAM (registered read)")
        self.instruction('localparam fifo_mem_t P_FIFO_MEM_STYLE =')
        self.instruction('    (FIFO_IMPL == "sram") ? FIFO_BRAM : FIFO_AUTO;')
        self.instruction("")
        self.comment("Head-flit header field offsets in TUSER, LSB-first")
        self.comment("(single source of truth: bin/delta_mesh/header.py)")
        for field, (lo, width) in self.hdr_offsets.items():
            if field.startswith(("dst_", "src_")):
                self.instruction(f"localparam int HDR_{field.upper()}_LO = {lo};")
        vc_lo, vc_w = self.hdr_offsets['vc']
        self.instruction(f"localparam int HDR_VC_LO = {vc_lo};")
        self.instruction(f"localparam int HDR_VC_W  = {vc_w};")
        qos_lo, qos_w = self.hdr_offsets['qos']
        self.instruction(f"localparam int HDR_QOS_LO = {qos_lo};")
        self.instruction(f"localparam int HDR_QOS_W  = {qos_w};")
        sr_lo, _sr_w = self.hdr_offsets['sr_ptr']
        self.instruction(f"localparam int HDR_SR_PTR_LO = {sr_lo};")
        mb_lo, mb_w = self.hdr_offsets['misroute_budget']
        self.instruction(f"localparam int HDR_MRB_LO = {mb_lo};")
        self.instruction(f"localparam int HDR_MRB_W  = {mb_w};")
        mcast_lo, _mcast_w = self.hdr_offsets['mcast']
        self.instruction(f"localparam int HDR_MCAST_LO = {mcast_lo};")
        pid_lo, _pid_w = self.hdr_offsets['packet_id']
        self.instruction(f"localparam int HDR_PID_LO = {pid_lo};")
        self.instruction("")
