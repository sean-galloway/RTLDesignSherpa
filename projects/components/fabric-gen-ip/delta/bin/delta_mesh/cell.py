    def generate_multicast(self):
        self.comment("==========================================================================")
        self.comment("Multicast flood - VC0-only single-beat BFS-tree replication")
        self.comment("(Task 8)")
        self.comment("==========================================================================")
        self.comment("A multicast head (mcast=1, vc=0, single beat) replicates on")
        self.comment("a dimension-ordered spanning tree rooted at the header src")
        self.comment("coordinate.  The tree is X-first, then Y, then Z: at each")
        self.comment("cell the parent port is the one the DOR route from this")
        self.comment("cell back to src would first take; children are the reverse")
        self.comment("edges.  P_DIA/P_DIA2 are never multicast links.  Multi-beat")
        self.comment("mcast heads, non-VC0 mcasts, and mcast packets arriving on")
        self.comment("a non-parent port are dropped.  Response-shaped unicast")
        self.comment("packets (dst == src, injected away from src) are also")
        self.comment("dropped.  The multicast path bypasses the arbiter: the")
        self.comment("head is latched into a holding register and fires to all")
        self.comment("children + local in one cycle once every target output is")
        self.comment("idle and has VC0 credit.")
        self.comment("==========================================================================")
        self.instruction("")
        self.instruction("logic [COORD_W-1:0] mcast_src_x [NUM_PORTS];")
        self.instruction("logic [COORD_W-1:0] mcast_src_y [NUM_PORTS];")
        self.instruction("logic [COORD_W-1:0] mcast_src_z [NUM_PORTS];")
        self.instruction("logic               mcast_is_vc0 [NUM_PORTS];")
        self.instruction("logic               mcast_single [NUM_PORTS];")
        self.instruction("logic               mcast_parent_port [NUM_PORTS];")
        self.instruction("logic [NUM_PORTS-1:0] mcast_child_mask [NUM_PORTS];")
        self.instruction("logic                 mcast_ok_req [NUM_PORTS];")
        self.instruction("logic                 mcast_bad_req [NUM_PORTS];")
        self.instruction("logic                 resp_drop_req [NUM_PORTS];")
        self.instruction("")
        self.comment("Per-input multicast classification and spanning-tree")
        self.comment("parent/child computation.")
        self.instruction("always_comb begin")
        self.instruction("    for (int p = 0; p < NUM_PORTS; p++) begin")
        self.instruction("        mcast_src_x[p] = pres_tuser[p][HDR_SRC_X_LO +: COORD_W];")
        self.instruction("        mcast_src_y[p] = pres_tuser[p][HDR_SRC_Y_LO +: COORD_W];")
        self.instruction("        mcast_src_z[p] = pres_tuser[p][HDR_SRC_Z_LO +: COORD_W];")
        self.instruction("        mcast_is_vc0[p] = (sel_vc[p] == '0);")
        self.instruction("        mcast_single[p] = pres_last[p];")
        self.comment("        Parent port: the incoming direction matches the")
        self.comment("        DOR first-hop from this cell back to the multicast")
        self.comment("        source.  P_DIA/P_DIA2 are never on the tree.")
        self.instruction("        mcast_parent_port[p] = 1'b0;")
        self.instruction("        case (p)")
        self.instruction("            P_X_NEG: mcast_parent_port[p] =")
        self.instruction("                (int'(POS_X) > int'(mcast_src_x[p]));")
        self.instruction("            P_X_POS: mcast_parent_port[p] =")
        self.instruction("                (int'(POS_X) < int'(mcast_src_x[p]));")
        self.instruction("            P_Y_NEG: mcast_parent_port[p] =")
        self.instruction("                (int'(POS_X) == int'(mcast_src_x[p])) &&")
        self.instruction("                (int'(POS_Y) > int'(mcast_src_y[p]));")
        self.instruction("            P_Y_POS: mcast_parent_port[p] =")
        self.instruction("                (int'(POS_X) == int'(mcast_src_x[p])) &&")
        self.instruction("                (int'(POS_Y) < int'(mcast_src_y[p]));")
        self.instruction("            P_Z_NEG: mcast_parent_port[p] =")
        self.instruction("                (int'(POS_X) == int'(mcast_src_x[p])) &&")
        self.instruction("                (int'(POS_Y) == int'(mcast_src_y[p])) &&")
        self.instruction("                (int'(POS_Z) > int'(mcast_src_z[p]));")
        self.instruction("            P_Z_POS: mcast_parent_port[p] =")
        self.instruction("                (int'(POS_X) == int'(mcast_src_x[p])) &&")
        self.instruction("                (int'(POS_Y) == int'(mcast_src_y[p])) &&")
        self.instruction("                (int'(POS_Z) < int'(mcast_src_z[p]));")
        self.instruction("            P_LOCAL: mcast_parent_port[p] =")
        self.instruction("                (int'(POS_X) == int'(mcast_src_x[p])) &&")
        self.instruction("                (int'(POS_Y) == int'(mcast_src_y[p])) &&")
        self.instruction("                (int'(POS_Z) == int'(mcast_src_z[p]));")
        self.instruction("            default: mcast_parent_port[p] = 1'b0;")
        self.instruction("        endcase")
        self.comment("        Child mask: all downstream neighbors on the DOR")
        self.comment("        spanning tree, plus the local host.  Boundary")
        self.comment("        checks suppress out-of-grid directions.")
        self.instruction("        mcast_child_mask[p] = '0;")
        self.instruction("        if (int'(POS_X) < int'(mcast_src_x[p])) begin")
        self.instruction("            mcast_child_mask[p][P_X_NEG] = (POS_X > 0);")
        self.instruction("        end else if (int'(POS_X) > int'(mcast_src_x[p])) begin")
        self.instruction("            mcast_child_mask[p][P_X_POS] = (POS_X < GRID_X-1);")
        self.instruction("        end else begin")
        self.instruction("            if (POS_X > 0)")
        self.instruction("                mcast_child_mask[p][P_X_NEG] = 1'b1;")
        self.instruction("            if (POS_X < GRID_X-1)")
        self.instruction("                mcast_child_mask[p][P_X_POS] = 1'b1;")
        self.instruction("            if (int'(POS_Y) < int'(mcast_src_y[p])) begin")
        self.instruction("                mcast_child_mask[p][P_Y_NEG] = (POS_Y > 0);")
        self.instruction("            end else if (int'(POS_Y) > int'(mcast_src_y[p])) begin")
        self.instruction("                mcast_child_mask[p][P_Y_POS] = (POS_Y < GRID_Y-1);")
        self.instruction("            end else begin")
        self.instruction("                if (POS_Y > 0)")
        self.instruction("                    mcast_child_mask[p][P_Y_NEG] = 1'b1;")
        self.instruction("                if (POS_Y < GRID_Y-1)")
        self.instruction("                    mcast_child_mask[p][P_Y_POS] = 1'b1;")
        self.instruction("                if (int'(POS_Z) < int'(mcast_src_z[p])) begin")
        self.instruction("                    mcast_child_mask[p][P_Z_NEG] = (POS_Z > 0);")
        self.instruction("                end else if (int'(POS_Z) > int'(mcast_src_z[p])) begin")
        self.instruction("                    mcast_child_mask[p][P_Z_POS] = (POS_Z < GRID_Z-1);")
        self.instruction("                end else begin")
        self.instruction("                    if (POS_Z > 0)")
        self.instruction("                        mcast_child_mask[p][P_Z_NEG] = 1'b1;")
        self.instruction("                    if (POS_Z < GRID_Z-1)")
        self.instruction("                        mcast_child_mask[p][P_Z_POS] = 1'b1;")
        self.instruction("                end")
        self.instruction("            end")
        self.instruction("        end")
        self.instruction("        mcast_child_mask[p][P_LOCAL] = 1'b1;")
        self.comment("        Valid single-beat VC0 multicast on the parent port.")
        self.instruction("        mcast_ok_req[p] = pres_valid[p] && !lock_active[p] &&")
        self.instruction("                          !drop_active[p] && head_mcast[p] &&")
        self.instruction("                          !pres_tuser[p][HDR_SR_PTR_LO] &&")
        self.instruction("                          mcast_is_vc0[p] && mcast_single[p] &&")
        self.instruction("                          mcast_parent_port[p];")
        self.comment("        Malformed multicast: wrong VC, multi-beat, control")
        self.comment("        class, or non-parent arrival (duplicate/loop")
        self.comment("        prevention).")
        self.instruction("        mcast_bad_req[p] = pres_valid[p] && !lock_active[p] &&")
        self.instruction("                           !drop_active[p] && head_mcast[p] &&")
        self.instruction("                           !pres_tuser[p][HDR_SR_PTR_LO] &&")
        self.instruction("                           (!mcast_is_vc0[p] || !mcast_single[p] ||")
        self.instruction("                            !mcast_parent_port[p]);")
        self.comment("        Response-shaped data unicast: dst == src, injected")
        self.comment("        away from the source coordinate.")
        self.instruction("        resp_drop_req[p] = pres_valid[p] && !lock_active[p] &&")
        self.instruction("                           !drop_active[p] && !head_mcast[p] &&")
        self.instruction("                           !pres_tuser[p][HDR_SR_PTR_LO] &&")
        self.instruction("                           (r_mode != 4'd6) &&")
        self.instruction("                           (int'(head_dst_x[p]) == int'(mcast_src_x[p])) &&")
        self.instruction("                           (int'(head_dst_y[p]) == int'(mcast_src_y[p])) &&")
        self.instruction("                           (int'(head_dst_z[p]) == int'(mcast_src_z[p])) &&")
        self.instruction("                           ((int'(POS_X) != int'(mcast_src_x[p])) ||")
        self.instruction("                            (int'(POS_Y) != int'(mcast_src_y[p])) ||")
        self.instruction("                            (int'(POS_Z) != int'(mcast_src_z[p])));")
        self.instruction("    end")
        self.instruction("end")
        self.instruction("")
        self.comment("Multicast holding register and one-cycle fan-out fire.")
        self.instruction("logic                 mcast_hold_valid;")
        self.instruction("logic [DATA_WIDTH-1:0] mcast_hold_tdata;")
        self.instruction("logic [USER_WIDTH-1:0] mcast_hold_tuser;")
        self.instruction("logic                 mcast_hold_last;")
        self.instruction("logic [NUM_PORTS-1:0] mcast_hold_child_mask;")
        self.instruction("logic [PORT_W-1:0]    mcast_hold_in_port;")
        self.instruction("logic                 mcast_latch;")
        self.instruction("logic                 mcast_fire_next;")
        self.instruction("logic                 mcast_fire;")
        self.instruction("logic                 mcast_consume;")
        self.instruction("")
        self.comment("Pick one valid multicast head per cycle (lowest port")
        self.comment("wins) only when the hold register is empty.  A held")
        self.comment("packet that is waiting for an output port leaves its")
        self.comment("head-of-line position in the input FIFO, so it cannot")
        self.comment("be overwritten by a newly arriving multicast.")
        self.instruction("always_comb begin")
        self.instruction("    mcast_latch = 1'b0;")
        self.instruction("    mcast_hold_in_port = PORT_W'(P_LOCAL);")
        self.instruction("    if (!mcast_hold_valid) begin")
        self.instruction("        for (int p = NUM_PORTS-1; p >= 0; p--) begin")
        self.instruction("            if (mcast_ok_req[p]) begin")
        self.instruction("                mcast_latch = 1'b1;")
        self.instruction("                mcast_hold_in_port = PORT_W'(p);")
        self.instruction("            end")
        self.instruction("        end")
        self.instruction("    end")
        self.instruction("    mcast_consume = mcast_latch;")
        self.instruction("end")
        self.instruction("")
        self.comment("Fire when the hold register is valid and every target")
        self.comment("output is idle, has VC0 credit, and is AXI-ready (the")
        self.comment("local output must also be free of a pending config")
        self.comment("response).")
        self.instruction("always_comb begin")
        self.instruction("    mcast_fire_next = mcast_hold_valid &&")
        self.instruction("                      (mcast_hold_child_mask != '0);")
        self.instruction("    for (int q = 0; q < NUM_PORTS; q++) begin")
        self.instruction("        if (mcast_hold_child_mask[q]) begin")
        self.instruction("            mcast_fire_next = mcast_fire_next && !packet_active[q] &&")
        self.instruction("                              s_credit[q][0] &&")
        self.instruction("                              m_axis_tready[q] &&")
        self.instruction("                              ((q != P_LOCAL) || !cfg_resp_present);")
        self.instruction("        end")
        self.instruction("    end")
        self.instruction("end")
        self.instruction("")
        self.instruction("`ALWAYS_FF_RST(aclk, aresetn,")
        self.instruction("    if (!aresetn) begin")
        self.instruction("        mcast_hold_valid <= 1'b0;")
        self.instruction("        mcast_fire       <= 1'b0;")
        self.instruction("        mcast_hold_tdata <= '0;")
        self.instruction("        mcast_hold_tuser <= '0;")
        self.instruction("        mcast_hold_last  <= 1'b0;")
        self.instruction("        mcast_hold_child_mask <= '0;")
        self.instruction("    end else begin")
        self.instruction("        mcast_fire <= mcast_fire_next;")
        self.instruction("        if (mcast_latch) begin")
        self.instruction("            mcast_hold_valid <= 1'b1;")
        self.instruction("            mcast_hold_tdata <= pres_tdata[mcast_hold_in_port];")
        self.instruction("            mcast_hold_tuser <= pres_tuser[mcast_hold_in_port];")
        self.instruction("            mcast_hold_last  <= pres_last[mcast_hold_in_port];")
        self.instruction("            mcast_hold_child_mask <=")
        self.instruction("                mcast_child_mask[mcast_hold_in_port] |")
        self.instruction("                (NUM_PORTS'(1) << P_LOCAL);")
        self.instruction("        end else if (mcast_fire) begin")
        self.instruction("            mcast_hold_valid <= 1'b0;")
        self.instruction("            mcast_hold_child_mask <= '0;")
        self.instruction("        end")
        self.instruction("    end")
        self.instruction(")")
        self.instruction("")

    def generate_mode_switch(self):
        self.comment("==========================================================================")
        self.comment("Mode switch - fan-out FSM, control generator, ack tally")
        self.comment("(Task 6)")
        self.comment("==========================================================================")
        self.comment("A consumed mode switch (see the head decode) is processed")
        self.comment("exactly once per cell: the cell updates r_mode, returns a")
        self.comment("one-beat ack to the origin, and re-emits the switch on")
        self.comment("every existing neighbor port. Suppressed copies (cell")
        self.comment("already in the target mode) consume with no side effects.")
        self.comment("The fan-out is serialized through a holding register --")
        self.comment("one switch per cell at a time; a distinct switch arriving")
        self.comment("mid-fan waits in its input FIFO until the register frees")
        self.comment("(no deadlock: the fan drains into the fabric under the")
        self.comment("credit protocol).")
        self.comment("==========================================================================")
        self.instruction("")
        self.comment("Neighbor enumeration for this instance (constant")
        self.comment("functions of the POS/GRID parameters).")
        self.instruction("function automatic int n_neighbors();")
        self.instruction("    int n;")
        self.instruction("    n = 0;")
        self.instruction("    if (POS_X > 0)        n++;")
        self.instruction("    if (POS_X < GRID_X-1) n++;")
        self.instruction("    if (POS_Y > 0)        n++;")
        self.instruction("    if (POS_Y < GRID_Y-1) n++;")
        self.instruction("    if (POS_Z > 0)        n++;")
        self.instruction("    if (POS_Z < GRID_Z-1) n++;")
        self.instruction("    return n;")
        self.instruction("endfunction")
        self.instruction("")
        self.instruction("function automatic int neighbor_port(int i);")
        self.instruction("    int n;")
        self.instruction("    n = 0;")
        self.instruction("    if (POS_X > 0) begin")
        self.instruction("        if (n == i) return P_X_NEG;")
        self.instruction("        n++;")
        self.instruction("    end")
        self.instruction("    if (POS_X < GRID_X-1) begin")
        self.instruction("        if (n == i) return P_X_POS;")
        self.instruction("        n++;")
        self.instruction("    end")
        self.instruction("    if (POS_Y > 0) begin")
        self.instruction("        if (n == i) return P_Y_NEG;")
        self.instruction("        n++;")
        self.instruction("    end")
        self.instruction("    if (POS_Y < GRID_Y-1) begin")
        self.instruction("        if (n == i) return P_Y_POS;")
        self.instruction("        n++;")
        self.instruction("    end")
        self.instruction("    if (POS_Z > 0) begin")
        self.instruction("        if (n == i) return P_Z_NEG;")
        self.instruction("        n++;")
        self.instruction("    end")
        self.instruction("    if (POS_Z < GRID_Z-1) begin")
        self.instruction("        if (n == i) return P_Z_POS;")
        self.instruction("        n++;")
        self.instruction("    end")
        self.comment("    // Unreachable for i < n_neighbors().")
        self.instruction("    return P_LOCAL;")
        self.instruction("endfunction")
        self.instruction("")
        self.instruction("localparam int N_NEIGH = n_neighbors();")
        self.instruction("")
        self.comment("Fan-out holding register + sequence index.")
        self.instruction("logic               msw_hold_valid;")
        self.instruction("logic [3:0]         msw_hold_mode;")
        self.instruction("logic [COORD_W-1:0] msw_hold_src_x;")
        self.instruction("logic [COORD_W-1:0] msw_hold_src_y;")
        self.instruction("logic [COORD_W-1:0] msw_hold_src_z;")
        self.instruction("logic [15:0]        msw_hold_pid;")
        self.instruction("logic [3:0]         msw_fan_idx;")
        self.instruction("")
        self.comment("Control generator FIFO write side (the read side feeds")
        self.comment("the local-port intake mux, see the input buffers).")
        self.instruction("logic              gen_fifo_wr_valid;")
        self.instruction("logic              gen_fifo_wr_ready;")
        self.instruction("logic [FLIT_W-1:0] gen_fifo_wr_data;")
        self.instruction("")
        self.comment("Beat construction: fan index 0 acks the origin; index")
        self.comment("k >= 1 re-emits the switch toward neighbor_port(k-1) with")
        self.comment("the dst coordinate rewritten to the neighbor's own, so")
        self.comment("the pinned dst == self discriminator holds on arrival.")
        self.comment("Both beat kinds ride the control class (sr_ptr[0] = 1):")
        self.comment("they route DOR regardless of the current mode, which is")
        self.comment("what makes the switch machinery mode-independent.")
        self.instruction("logic [USER_WIDTH-1:0] gen_hdr;")
        self.instruction("logic [DATA_WIDTH-1:0] gen_tdata;")
        self.instruction("logic [COORD_W-1:0]    gen_dst_x;")
        self.instruction("logic [COORD_W-1:0]    gen_dst_y;")
        self.instruction("logic [COORD_W-1:0]    gen_dst_z;")
        self.instruction("int unsigned           gen_nport;")
        self.instruction("")
        self.instruction("always_comb begin")
        self.comment("    // fan index 0 has no neighbor: the ack branch ignores")
        self.comment("    // the destination computation.")
        self.instruction("    gen_nport = neighbor_port(int'(msw_fan_idx) - 1);")
        self.instruction("    gen_dst_x = COORD_W'(POS_X);")
        self.instruction("    gen_dst_y = COORD_W'(POS_Y);")
        self.instruction("    gen_dst_z = COORD_W'(POS_Z);")
        self.instruction("    if (gen_nport == P_X_NEG) begin")
        self.instruction("        gen_dst_x = COORD_W'(POS_X - 1);")
        self.instruction("    end else if (gen_nport == P_X_POS) begin")
        self.instruction("        gen_dst_x = COORD_W'(POS_X + 1);")
        self.instruction("    end else if (gen_nport == P_Y_NEG) begin")
        self.instruction("        gen_dst_y = COORD_W'(POS_Y - 1);")
        self.instruction("    end else if (gen_nport == P_Y_POS) begin")
        self.instruction("        gen_dst_y = COORD_W'(POS_Y + 1);")
        self.instruction("    end else if (gen_nport == P_Z_NEG) begin")
        self.instruction("        gen_dst_z = COORD_W'(POS_Z - 1);")
        self.instruction("    end else if (gen_nport == P_Z_POS) begin")
        self.instruction("        gen_dst_z = COORD_W'(POS_Z + 1);")
        self.instruction("    end")
        self.instruction("    gen_hdr   = '0;")
        self.instruction("    gen_tdata = '0;")
        self.instruction("    if (msw_fan_idx == 4'd0) begin")
        self.comment("        // Ack to the switch origin (the switch header's")
        self.comment("        // src coordinate); payload carries the ack magic.")
        self.instruction("        gen_hdr[HDR_DST_X_LO +: COORD_W] = msw_hold_src_x;")
        self.instruction("        gen_hdr[HDR_DST_Y_LO +: COORD_W] = msw_hold_src_y;")
        self.instruction("        gen_hdr[HDR_DST_Z_LO +: COORD_W] = msw_hold_src_z;")
        self.instruction("        gen_hdr[HDR_SRC_X_LO +: COORD_W] = COORD_W'(POS_X);")
        self.instruction("        gen_hdr[HDR_SRC_Y_LO +: COORD_W] = COORD_W'(POS_Y);")
        self.instruction("        gen_hdr[HDR_SRC_Z_LO +: COORD_W] = COORD_W'(POS_Z);")
        self.instruction("        gen_hdr[HDR_QOS_LO +: HDR_QOS_W] = 2'd1;")
        self.instruction("        gen_hdr[HDR_SR_PTR_LO]           = 1'b1;")
        self.instruction("        gen_hdr[HDR_PID_LO +: 16]        = msw_hold_pid;")
        self.instruction("        gen_tdata = {{(DATA_WIDTH-16){1'b0}}, ACK_MAGIC};")
        self.instruction("    end else begin")
        self.comment("        // Mode-switch copy to one neighbor: same payload")
        self.comment("        // shape as the original command, dst rewritten.")
        self.instruction("        gen_hdr[HDR_DST_X_LO +: COORD_W] = gen_dst_x;")
        self.instruction("        gen_hdr[HDR_DST_Y_LO +: COORD_W] = gen_dst_y;")
        self.instruction("        gen_hdr[HDR_DST_Z_LO +: COORD_W] = gen_dst_z;")
        self.instruction("        gen_hdr[HDR_SRC_X_LO +: COORD_W] = msw_hold_src_x;")
        self.instruction("        gen_hdr[HDR_SRC_Y_LO +: COORD_W] = msw_hold_src_y;")
        self.instruction("        gen_hdr[HDR_SRC_Z_LO +: COORD_W] = msw_hold_src_z;")
        self.instruction("        gen_hdr[HDR_QOS_LO +: HDR_QOS_W] = 2'd0;")
        self.instruction("        gen_hdr[HDR_MCAST_LO]            = 1'b1;")
        self.instruction("        gen_hdr[HDR_SR_PTR_LO]           = 1'b1;")
        self.instruction("        gen_hdr[HDR_PID_LO +: 16]        = msw_hold_pid;")
        self.instruction("        gen_tdata = {{(DATA_WIDTH-20){1'b0}},")
        self.instruction("                     msw_hold_mode, MSW_MAGIC};")
        self.instruction("    end")
        self.instruction("    gen_fifo_wr_data = {gen_hdr, 1'b1, gen_tdata};")
        self.instruction("end")
        self.instruction("")
        self.comment("Fan FSM: one beat per ready cycle -- ack first, then the")
        self.comment("neighbor copies; the holding register frees after the")
        self.comment("last copy pushes.")
        self.instruction("always_comb begin")
        self.instruction("    gen_fifo_wr_valid = msw_hold_valid &&")
        self.instruction("                        (msw_fan_idx <= 4'(N_NEIGH)) &&")
        self.instruction("                        gen_fifo_wr_ready;")
        self.instruction("end")
        self.instruction("")
        self.instruction("gaxi_fifo_sync #(")
        self.instruction("    .MEM_STYLE (FIFO_AUTO),")
        self.instruction("    .DATA_WIDTH(FLIT_W),")
        self.instruction("    .DEPTH     (GEN_FIFO_DEPTH)")
        self.instruction(") u_gen_fifo (")
        self.instruction("    .axi_aclk   (aclk),")
        self.instruction("    .axi_aresetn(aresetn),")
        self.instruction("    .wr_valid   (gen_fifo_wr_valid),")
        self.instruction("    .wr_ready   (gen_fifo_wr_ready),")
        self.instruction("    .wr_data    (gen_fifo_wr_data),")
        self.comment("    // The intake mux (input buffers) drains this FIFO")
        self.comment("    // between external packets.")
        self.instruction("    .rd_ready   (gen_take),")
        self.instruction("    .count      (),")
        self.instruction("    .rd_valid   (gen_fifo_rd_valid),")
        self.instruction("    .rd_data    (gen_fifo_rd_data)")
        self.instruction(");")
        self.instruction("")
        self.comment("Mode register: updates on every mode-switch consume")
        self.comment("(a suppressed consume writes back the same value).")
        self.instruction("`ALWAYS_FF_RST(aclk, aresetn,")
        self.instruction("    if (!aresetn) begin")
        self.instruction("        r_mode <= 4'd0;")
        self.instruction("    end else begin")
        self.instruction("        if (msw_consume_any) begin")
        self.instruction("            r_mode <= msw_mode[msw_winner];")
        self.instruction("        end")
        self.instruction("    end")
        self.instruction(")")
        self.instruction("")
        self.comment("Fan-out holding register: latches the origin + mode of a")
        self.comment("processing consume; the index walks ack + N_NEIGH copies.")
        self.comment("A processing consume is guaranteed an empty register (the")
        self.comment("consume gate), so the if/else priority cannot drop a")
        self.comment("pushed beat.")
        self.instruction("`ALWAYS_FF_RST(aclk, aresetn,")
        self.instruction("    if (!aresetn) begin")
        self.instruction("        msw_hold_valid <= 1'b0;")
        self.instruction("        msw_hold_mode  <= '0;")
        self.instruction("        msw_hold_src_x <= '0;")
        self.instruction("        msw_hold_src_y <= '0;")
        self.instruction("        msw_hold_src_z <= '0;")
        self.instruction("        msw_hold_pid   <= '0;")
        self.instruction("        msw_fan_idx    <= '0;")
        self.instruction("    end else begin")
        self.instruction("        if (msw_consume_any && msw_will_process) begin")
        self.instruction("            msw_hold_valid <= 1'b1;")
        self.instruction("            msw_hold_mode  <= msw_mode[msw_winner];")
        self.instruction("            msw_hold_src_x <=")
        self.instruction("                pres_tuser[msw_winner][HDR_SRC_X_LO +: COORD_W];")
        self.instruction("            msw_hold_src_y <=")
        self.instruction("                pres_tuser[msw_winner][HDR_SRC_Y_LO +: COORD_W];")
        self.instruction("            msw_hold_src_z <=")
        self.instruction("                pres_tuser[msw_winner][HDR_SRC_Z_LO +: COORD_W];")
        self.instruction("            msw_hold_pid   <=")
        self.instruction("                pres_tuser[msw_winner][HDR_PID_LO +: 16];")
        self.instruction("            msw_fan_idx    <= '0;")
        self.instruction("        end else if (gen_fifo_wr_valid) begin")
        self.instruction("            if (msw_fan_idx == 4'(N_NEIGH)) begin")
        self.instruction("                msw_hold_valid <= 1'b0;")
        self.instruction("                msw_fan_idx    <= '0;")
        self.instruction("            end else begin")
        self.instruction("                msw_fan_idx <= msw_fan_idx + 4'd1;")
        self.instruction("            end")
        self.instruction("        end")
