"""
Delta mesh cell generator using the unified verilog framework.

Task 4 scope: per-port per-VC input buffers (house gaxi_fifo_sync, one per
port per VC, DEPTH=4) between the port's s_axis acceptance and the
route/grant stage; credit flow control on the pinned credit sidebands (one
credit level per VC: m_credit advertises "my input buffer for this VC is
not full", a flit is presented on an output only while the corresponding
s_credit level is set); and packet-atomic grants operating on FIFO outputs
(grant held to TLAST, one-cycle bubble per packet boundary). VC selection:
the head flit's header vc bit picks the input VC FIFO; an idle port
presents VC0 ahead of VC1; both VCs route with the same power-on default
DOR. Flit acceptance into the input FIFO is unconditional on downstream
state -- credits govern the output side of each link, not local admission.

Task 5 scope: the combinational DOR decode is replaced by a per-cell
route_table RAM lookup keyed {qos, dst_z, dst_y, dst_x} (address sized for
the full key now so Task 7's QoS classes land without reshaping the
memory); the DOR function remains as the power-on image builder installed
by an initial block per instance POS. The local port gains the in-band
config plane (single-beat packet addressed to the cell itself, QoS class
0, sr_ptr[0]=write/read, {table_index, entry} payload) and malformed dst
coordinates drop at the head with an err_drop_cnt tally.
"""

import os

from rtl_generators.verilog.module import Module

from .config import DeltaMeshConfig
from .header import build_header_offsets
from .tables import (  # noqa: F401  (re-exported for fabric.py)
    NUM_PORTS,
    PORT_IDS,
    check_acyclic,
    default_dor_image,
)


class DeltaMeshCell(Module):
    """delta_mesh_cell emitter: input-buffered DOR router, credit flow control."""

    module_str = 'delta_mesh_cell'

    def __init__(self, config: DeltaMeshConfig):
        self.cfg = config

        Module.__init__(self, module_name=self.module_str)

        coord_w = max(1, (max(config.cells_x, config.cells_y, config.cells_z) - 1).bit_length())
        self.coord_w = coord_w
        self.hdr_offsets = build_header_offsets(coord_w)

        # Every emitted image must pass the offline VC0 acyclicity check
        # (spec sec. 13 formal assist) before any RTL is written.
        check_acyclic(default_dor_image(config), config)

        param_str = f'''
            parameter int DATA_WIDTH = {config.data_width},
            parameter int USER_WIDTH = {config.user_width},
            parameter int COORD_W = {coord_w},
            parameter int POS_X = 0,
            parameter int POS_Y = 0,
            parameter int POS_Z = 0,
            parameter int GRID_X = {config.cells_x},
            parameter int GRID_Y = {config.cells_y},
            parameter int GRID_Z = {config.cells_z},
            parameter int NUM_VC = 2,
            parameter string FIFO_IMPL = "{config.fifo_impl}",
            parameter int ENABLE_COUNTERS = {1 if config.add_counters else 0}
        '''
        self.params.add_param_string(param_str)

        port_str = '''
            input  logic aclk,
            input  logic aresetn,

            input  logic [DATA_WIDTH-1:0] s_axis_tdata  [7],
            input  logic                  s_axis_tvalid [7],
            output logic                  s_axis_tready [7],
            input  logic                  s_axis_tlast  [7],
            input  logic [USER_WIDTH-1:0] s_axis_tuser  [7],

            output logic [DATA_WIDTH-1:0] m_axis_tdata  [7],
            output logic                  m_axis_tvalid [7],
            input  logic                  m_axis_tready [7],
            output logic                  m_axis_tlast  [7],
            output logic [USER_WIDTH-1:0] m_axis_tuser  [7],

            input  logic [NUM_VC-1:0]     s_credit      [7],
            output logic [NUM_VC-1:0]     m_credit      [7],

            output logic [31:0]           o_err_drop_cnt
        '''
        self.ports.add_port_string(port_str)

