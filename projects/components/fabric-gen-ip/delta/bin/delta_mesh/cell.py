"""
Delta mesh cell generator using the unified verilog framework.

Task 4 scope: per-port per-VC input buffers (house gaxi_fifo_sync, one per
port per VC, DEPTH=4) between the port's s_axis acceptance and the
route/grant stage; credit flow control on the pinned credit sidebands (one
credit level per VC: m_credit advertises "my input buffer for this VC is
not full", a flit is presented on an output only while the corresponding
s_credit level is set); and packet-atomic grants operating on FIFO outputs
(grant held to TLAST, one-cycle bubble per packet boundary). VC selection:
the head flit's header vc bit picks the input VC FIFO; an idle port
presents VC0 ahead of VC1; both VCs route with the same power-on default
DOR. Flit acceptance into the input FIFO is unconditional on downstream
state -- credits govern the output side of each link, not local admission.

Task 5 scope: the combinational DOR decode is replaced by a per-cell
route_table RAM lookup keyed {qos, dst_z, dst_y, dst_x} (address sized for
the full key now so Task 7's QoS classes land without reshaping the
memory); the DOR function remains as the power-on image builder installed
by an initial block per instance POS. The local port gains the in-band
config plane (single-beat packet addressed to the cell itself, QoS class
0, sr_ptr[0]=write/read, {table_index, entry} payload) and malformed dst
coordinates drop at the head with an err_drop_cnt tally.

Task 6 scope: the standard fabric modes (spec sec. 5.4) land as a mode
mux in front of the route_table RAM -- r_mode[3:0] selects the custom
RAM image (0, power-on default) or one of the generated mode images
(1-8 at Task 6; mode 9 lands with Task 6b), so the RAM stays
user-intact and switching back to mode 0 restores the custom tables. A
broadcast mode-switch is a config-format
packet (dst == own coordinate, QoS class 0, mcast bit set, sr_ptr[0]
write, single beat, payload {mode_id[3:0], magic[15:0]}) recognized on
ANY input port: the consuming cell switches r_mode, returns a one-beat
ack to the switch origin (a control packet: qos 1, mcast 0, sr_ptr[0]
set, ack magic payload -- counted at the origin's o_mode_acks), and
re-emits the switch on every existing neighbor port so it floods the
fabric; a cell already in the target mode suppresses re-emission, which
terminates the flood. The origin's barrier completes when X*Y*Z acks
are in. Control traffic (sr_ptr[0] = 1) always routes DOR,
independent of r_mode and the RAM, so the switch/ack machinery works
under any current mode (a mode image may route data such that control
packets could not traverse it -- e.g. the pinned systolic-1D image).
The flooded copies carry each receiving cell's own coordinate as dst,
so the pinned dst == self discriminator holds at every recipient.
Data-plane contract: sr_ptr[0] = 0 on user data; the mode-switch magics
in the payload low bits are the control class markers.

Task 6b scope: the tetrad diagonal link + mode 9 (owner addition
2026-10-15). The port list gains P_DIA at index 6 and P_LOCAL MOVES to
index 7 (NUM_PORTS 8).

Task 6c scope: the inter-tetrad diagonal link + mode 10 (owner addition
2026-10-15). The port list gains P_DIA2 at index 7 and P_LOCAL MOVES to
index 8 (NUM_PORTS 9; every per-port structure -- input buffers, credit
sidebands, request/grant matrices, crossbar -- iterates NUM_PORTS, so
the extension is uniform). P_DIA and P_DIA2 are the two instances of the
single conceptual diagonal axis (spec sec. 2.2): P_DIA is the tetrad
scale, P_DIA2 the tile scale. The fabric wires cell (x,y,z)
m_axis[P_DIA2] to cell (x + (x&1 ? +1 : -1), y + (y&1 ? +1 : -1), z)
s_axis[P_DIA2] (one diagonal wire pair per unordered diagonal-tetrad
pair, both parities connect); on an odd X/Y edge the out-of-grid mate's
P_DIA2 ties off, which is safe because no in-grid dst can name it and
because DOR -- the power-on default and modes 1-8 -- never selects
P_DIA2, and mode 9 never selects P_DIA2 (generator-enforced guard,
tables.check_no_diag). Mode 10 (tile all-to-all K4 of tetrads) is the
one image allowed to route P_DIA2: the diagonal-tetrad corner mate rides
it in 1 hop, edge-adjacent tetrads keep the axis port (1 hop for the
shared boundary, else DOR within the tile), inter-tile dsts DOR. The
mode-switch control flood deliberately stays on the six axis ports
(P_DIA/P_DIA2 are mode-9/10 data-plane links; control traffic routes DOR
regardless).

Task 7 scope: QoS at the output arbiters. The head flit's header qos
field decodes the data class (controller-pinned: 1 = latency, 2 =
bulk; a data packet decoded at class 0 maps to the latency class --
class 0 is reserved to the control plane -- and the spec-table-
unassigned qos 3 decodes to the bulk class). The Task 4 per-port
per-VC input FIFOs remain the ONLY transport and per-VC credit
machinery is untouched; per-class QUEUING is realized as request
accounting at the arbiter: each input's head-of-line entry carries a
class, so an input requests its route as latency or bulk. Per output
the class filter is strict priority latency(1) > bulk(2) with two
antistarvation mechanisms, both on the AGING_LIMIT horizon
(parameter, default 64): (a) AGING -- a per-input counter runs while
the input's head is eligible but not granted; once it exceeds
AGING_LIMIT the head's effective class inverts priority and beats
non-aged higher-priority heads; it resets on grant. (b) BULK MINIMUM
RESERVATION -- a per-output saturating starve counter runs while bulk
is eligible but not granted; at the trigger point (BULK_MIN_CREDITS+2
cycles inside the AGING_LIMIT window, absorbing the pick phase plus
the grant registration so the grant lands within AGING_LIMIT eligible
cycles) the output forces bulk candidates, so a continuously eligible
bulk flow sees >= 1 grant per AGING_LIMIT cycles. The winner pick
itself is the house
arbiter_matrix (matrix fair arbiter, ACK mode): the registered grant
is held to the packet's TLAST handshake exactly like the pre-Task-7
grant register, the release cycle keeps its documented one-cycle
bubble (the retiring grant is acknowledged one cycle after TLAST, so
the next winner is picked from the requests visible during the bubble
-- never re-granted in the TLAST cycle), and the P_LOCAL config-
response stall blocks only fresh grant registration. Packet-atomic
grants and the credit-gated presentation (a flit is presented only
while the downstream credit level is set; a grant is held while
credit == 0) are preserved unchanged -- the QoS logic replaces the
arbitration POLICY, not the atomicity/credit machinery. The per-
output starved state is observable on the new o_bulk_starved[8:0]
pin (bit q = output q's bulk reservation is due). Routing stays
identical across classes at power-on (every qos table region holds
the same DOR image); per-class routing tables are a deferred
follow-on, as is spec QoS path diversity.
"""

