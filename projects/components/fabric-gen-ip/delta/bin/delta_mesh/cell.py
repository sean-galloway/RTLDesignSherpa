    def generate_input_buffers(self):
        self.comment("==========================================================================")
        self.comment("Input buffers - one house FIFO per port per VC")
        self.comment("==========================================================================")
        self.comment("A flit word is {TUSER, TLAST, TDATA}: the head-flit header")
        self.comment("rides TUSER on the first beat and the body beats carry 0,")
        self.comment("so the whole beat streams through the buffer unchanged.")
        self.comment("Intake steering: the head beat's header vc bit picks the VC")
        self.comment("FIFO; body beats follow the in_vc latch taken at the head's")
        self.comment("acceptance (in_pkt tracks beats-since-TLAST). Acceptance is")
        self.comment("unconditional on downstream state -- the port backpressures")
        self.comment("only when the selected VC FIFO is full.")
        self.comment("==========================================================================")
        self.instruction("")
        self.instruction("logic [FLIT_W-1:0]     w_fifo_wr_data  [NUM_PORTS][NUM_VC];")
        self.instruction("logic                  w_fifo_wr_valid [NUM_PORTS][NUM_VC];")
        self.instruction("logic                  w_fifo_wr_ready [NUM_PORTS][NUM_VC];")
        self.instruction("logic [FLIT_W-1:0]     w_fifo_rd_data  [NUM_PORTS][NUM_VC];")
        self.instruction("logic                  w_fifo_rd_valid [NUM_PORTS][NUM_VC];")
        self.instruction("logic                  w_fifo_rd_ready [NUM_PORTS][NUM_VC];")
        self.instruction("")
        self.instruction("logic [VC_W-1:0] wr_vc   [NUM_PORTS];")
        self.instruction("logic            in_pkt  [NUM_PORTS];")
        self.instruction("logic [VC_W-1:0] in_vc   [NUM_PORTS];")
        self.instruction("")
        self.comment("Intake steering and FIFO write side")
        self.instruction("always_comb begin")
        self.instruction("    for (int p = 0; p < NUM_PORTS; p++) begin")
        self.instruction("        wr_vc[p] = in_pkt[p] ? in_vc[p] :")
        self.instruction("                    VC_W'(s_axis_tuser[p][HDR_VC_LO +: HDR_VC_W]);")
        self.instruction("        s_axis_tready[p] = w_fifo_wr_ready[p][wr_vc[p]];")
        self.instruction("        for (int v = 0; v < NUM_VC; v++) begin")
        self.instruction("            w_fifo_wr_valid[p][v] = s_axis_tvalid[p] &&")
        self.instruction("                                      (wr_vc[p] == VC_W'(v));")
        self.instruction("            w_fifo_wr_data[p][v]  = {s_axis_tuser[p],")
        self.instruction("                                     s_axis_tlast[p],")
        self.instruction("                                     s_axis_tdata[p]};")
        self.instruction("        end")
        self.instruction("    end")
        self.instruction("end")
        self.instruction("")
        self.comment("Per-port per-VC input FIFOs (house gaxi_fifo_sync)")
        self.instruction("generate")
        self.instruction("    for (genvar p = 0; p < NUM_PORTS; p++) begin : gen_input_fifo")
        self.instruction("        for (genvar v = 0; v < NUM_VC; v++) begin : gen_vc")
        self.instruction("            gaxi_fifo_sync #(")
        self.instruction("                .MEM_STYLE (P_FIFO_MEM_STYLE),")
        self.instruction("                .DATA_WIDTH(FLIT_W),")
        self.instruction("                .DEPTH     (FIFO_DEPTH)")
        self.instruction("            ) u_input_fifo (")
        self.instruction("                .axi_aclk   (aclk),")
        self.instruction("                .axi_aresetn(aresetn),")
        self.instruction("                .wr_valid   (w_fifo_wr_valid[p][v]),")
        self.instruction("                .wr_ready   (w_fifo_wr_ready[p][v]),")
        self.instruction("                .wr_data    (w_fifo_wr_data[p][v]),")
        self.instruction("                .rd_ready   (w_fifo_rd_ready[p][v]),")
        self.instruction("                .count      (),")
        self.instruction("                .rd_valid   (w_fifo_rd_valid[p][v]),")
        self.instruction("                .rd_data    (w_fifo_rd_data[p][v])")
        self.instruction("            );")
        self.instruction("        end")
        self.instruction("    end")
        self.instruction("endgenerate")
        self.instruction("")
        self.comment("Credit advertisement: the credit count each link needs is")
        self.comment("the free-slot count of this port's VC FIFO -- DEPTH at")
        self.comment("reset, post-consume after every accepted flit. The pinned")
        self.comment("sideband carries one level bit per VC, so the count rides")
        self.comment("in saturated form: m_credit[p][vc] = the FIFO is not full.")
        self.comment("A sender holding this level can always place one more flit")
        self.comment("(the buffer itself absorbs up to DEPTH in-flight flits),")
        self.comment("so the saturated count loses burst budgeting only, never")
        self.comment("losslessness.")
        self.instruction("generate")
        self.instruction("    for (genvar p = 0; p < NUM_PORTS; p++) begin : gen_credit_adv")
        self.instruction("        for (genvar v = 0; v < NUM_VC; v++) begin : gen_vc_lvl")
        self.instruction("            assign m_credit[p][v] = w_fifo_wr_ready[p][v];")
        self.instruction("        end")
        self.instruction("    end")
        self.instruction("endgenerate")
        self.instruction("")
        self.comment("Presented flit per port: the head of the selected VC FIFO.")
        self.comment("A locked port presents its packet's VC; an idle port")
        self.comment("presents VC0 ahead of VC1 (VC0 is the escape resource and")
        self.comment("must never wait behind VC1).")
        self.instruction("logic [VC_W-1:0]       sel_vc      [NUM_PORTS];")
        self.instruction("logic                  pres_valid  [NUM_PORTS];")
        self.instruction("logic                  pres_last   [NUM_PORTS];")
        self.instruction("logic [USER_WIDTH-1:0] pres_tuser  [NUM_PORTS];")
        self.instruction("logic [DATA_WIDTH-1:0] pres_tdata  [NUM_PORTS];")
        self.instruction("")
        self.instruction("always_comb begin")
        self.instruction("    for (int p = 0; p < NUM_PORTS; p++) begin")
        self.instruction("        if (lock_active[p]) begin")
        self.instruction("            sel_vc[p] = lock_vc[p];")
        self.instruction("        end else begin")
        self.instruction("            sel_vc[p] = '0;")
        self.instruction("            for (int v = NUM_VC-1; v >= 0; v--) begin")
        self.instruction("                if (w_fifo_rd_valid[p][v]) begin")
        self.instruction("                    sel_vc[p] = VC_W'(v);")
        self.instruction("                end")
        self.instruction("            end")
        self.instruction("        end")
        self.instruction("    end")
        self.instruction("end")
        self.instruction("")
        self.instruction("always_comb begin")
        self.instruction("    for (int p = 0; p < NUM_PORTS; p++) begin")
        self.instruction("        pres_valid[p] = w_fifo_rd_valid[p][sel_vc[p]];")
        self.instruction("        pres_last[p]  = w_fifo_rd_data[p][sel_vc[p]][DATA_WIDTH];")
        self.instruction("        pres_tuser[p] =")
        self.instruction("            w_fifo_rd_data[p][sel_vc[p]][DATA_WIDTH+1 +: USER_WIDTH];")
        self.instruction("        pres_tdata[p] =")
        self.instruction("            w_fifo_rd_data[p][sel_vc[p]][DATA_WIDTH-1:0];")
        self.instruction("    end")
        self.instruction("end")
        self.instruction("")

    def generate_route_table(self):
        self.comment("==========================================================================")
        self.comment("Route table RAM + head-flit classification")
        self.comment("==========================================================================")
        self.comment("The presented head flit classifies before it routes:")
        self.comment("in-range dsts look the RAM up (combinational read) and the")
        self.comment("winning port mask bit becomes route_req; out-of-range dsts")
        self.comment("and empty masks take the drop path instead of a grant; a")
        self.comment("config-shaped local head (dst == POS, QoS class 0) is")
        self.comment("consumed by the config plane, never granted. Body beats")
        self.comment("(!lock_active low, drop_active set) drain with no side")
        self.comment("effects. Non-head beats of a granted packet never")
        self.comment("recompute -- they follow lock_active/lock_port to TLAST.")
        self.comment("==========================================================================")
        self.instruction("")
        self.comment("Per-cell table: combinational read for the route stage,")
        self.comment("single-cycle write port from the config plane below. The")
        self.comment("initial block installs the power-on image; the config")
        self.comment("write is the only always_ff writer (deliberate two-process")
        self.comment("table: image at time 0, runtime writes after).")
        self.instruction("logic [ENTRY_W-1:0] route_table [ROUTE_DEPTH];")
        self.instruction("")
        self.comment("Power-on image: DOR toward the coord-0 (rapids) boundary,")
        self.comment("evaluated per instance from the POS parameters so one")
        self.comment("checked-in module serves every grid position. A")
        self.comment("mechanical transcription of delta_mesh.tables.dor_port;")
        self.comment("the cocotb suites verify the equivalence behaviorally and")
        self.comment("tables.check_acyclic proves the VC0 subrelation")
        self.comment("connected + acyclic at generation time.")
        self.instruction("function automatic logic [ENTRY_W-1:0] dor_default_entry(")
        self.instruction("    input int addr")
        self.instruction(");")
        self.instruction("    int unsigned d_x, d_y, d_z;")
        self.instruction("    int unsigned port;")
        self.instruction("    begin")
        self.instruction("        d_x = addr[0 +: COORD_W];")
        self.instruction("        d_y = addr[COORD_W +: COORD_W];")
        self.instruction("        d_z = addr[2*COORD_W +: COORD_W];")
        self.instruction("        port = P_LOCAL;")
        self.instruction("        if (int'(d_x) < POS_X)       port = P_X_NEG;")
        self.instruction("        else if (int'(d_x) > POS_X)  port = P_X_POS;")
        self.instruction("        else if (int'(d_y) < POS_Y)  port = P_Y_NEG;")
        self.instruction("        else if (int'(d_y) > POS_Y)  port = P_Y_POS;")
        self.instruction("        else if (int'(d_z) < POS_Z)  port = P_Z_NEG;")
        self.instruction("        else if (int'(d_z) > POS_Z)  port = P_Z_POS;")
        self.instruction("        if ((int'(d_x) >= GRID_X) || (int'(d_y) >= GRID_Y) ||")
        self.instruction("            (int'(d_z) >= GRID_Z))")
        self.comment("        // Representable but out-of-grid dst: drop encoding.")
        self.instruction("            dor_default_entry = '0;")
        self.instruction("        else")
        self.comment("        // {port_mask[6:0] one-hot, vc = 0}")
        self.instruction("            dor_default_entry = {VC_W'(0), 7'(32'd1 << port)};")
        self.instruction("    end")
        self.instruction("endfunction")
        self.instruction("")
        self.instruction("initial begin")
        self.comment("    Every QoS region gets the same DOR default (the image")
        self.comment("    ignores the qos key bits); Task 7 overlays per-class")
        self.comment("    routes without reshaping the memory.")
        self.instruction("    for (int a = 0; a < ROUTE_DEPTH; a++) begin")
        self.instruction("        route_table[a] = dor_default_entry(a);")
        self.instruction("    end")
        self.instruction("end")
        self.instruction("")
        self.comment("Head decode of the presented flit (meaningful only on a")
        self.comment("head beat; bodies carry tuser == 0 and never consult it)")
        self.instruction("logic [COORD_W-1:0] head_dst_x [NUM_PORTS];")
        self.instruction("logic [COORD_W-1:0] head_dst_y [NUM_PORTS];")
        self.instruction("logic [COORD_W-1:0] head_dst_z [NUM_PORTS];")
        self.instruction("logic [HDR_QOS_W-1:0] head_qos   [NUM_PORTS];")
        self.instruction("logic               dst_in_range [NUM_PORTS];")
        self.instruction("logic               head_cfg     [NUM_PORTS];")
        self.instruction("logic [ENTRY_W-1:0] head_entry   [NUM_PORTS];")
        self.instruction("logic               head_no_route [NUM_PORTS];")
        self.instruction("logic [PORT_W-1:0]  route_req    [NUM_PORTS];")
        self.instruction("")
        self.instruction("always_comb begin")
        self.instruction("    for (int p = 0; p < NUM_PORTS; p++) begin")
        self.instruction("        head_dst_x[p] = pres_tuser[p][HDR_DST_X_LO +: COORD_W];")
        self.instruction("        head_dst_y[p] = pres_tuser[p][HDR_DST_Y_LO +: COORD_W];")
        self.instruction("        head_dst_z[p] = pres_tuser[p][HDR_DST_Z_LO +: COORD_W];")
        self.instruction("        head_qos[p]   = pres_tuser[p][HDR_QOS_LO +: HDR_QOS_W];")
        self.instruction("        dst_in_range[p] = (int'(head_dst_x[p]) < GRID_X) &&")
        self.instruction("                          (int'(head_dst_y[p]) < GRID_Y) &&")
        self.instruction("                          (int'(head_dst_z[p]) < GRID_Z);")
        self.comment("        Config shape: local port, dst == own coordinate,")
        self.comment("        QoS class 0 (plan-pinned config class).")
