        self.comment("arbitrates external beats against the control")
        self.comment("generator: a generator beat is injected only while the")
        self.comment("external master presents nothing, the intake packet")
        self.comment("boundary is closed (in_pkt low), AND the local VC0")
        self.comment("input FIFO can accept it -- the house FIFO commits a")
        self.comment("write only on wr_valid && wr_ready, while the gen FIFO")
