class DeltaMeshCell(Module):
    """delta_mesh_cell emitter: input-buffered DOR router, credit flow control."""

    module_str = 'delta_mesh_cell'

    def __init__(self, config: DeltaMeshConfig):
        self.cfg = config

        Module.__init__(self, module_name=self.module_str)

        coord_w = max(1, (max(config.cells_x, config.cells_y, config.cells_z) - 1).bit_length())
        self.coord_w = coord_w
        self.hdr_offsets = build_header_offsets(coord_w)

        # Every emitted image must pass the offline VC0 acyclicity check
        # (spec sec. 13 formal assist) before any RTL is written: the
        # power-on DOR image (Task 5 form: origin per image, DOR
        # elsewhere) and every standard-mode image (Task 6 form: every
        # cell routes per the mode function; modes 9/10 the K4 images of
        # Tasks 6b/6c). The controller-pinned guard also proves DOR --
        # the default image and modes 1-8 -- never selects either
        # diagonal port (only mode 9 may select P_DIA, only mode 10 may
        # select P_DIA2), which is what keeps the pre-6b suites
        # regression-free by construction and the odd-dimension tie-offs
        # safe.
        check_acyclic(default_dor_image(config), config)
        check_no_diag(default_dor_image(config), "power-on DOR image")
        for mode_id in range(1, 11):
            image = mode_image(config, mode_id)
            check_acyclic(image, config,
                          route_fn=(lambda dst, pos, m=mode_id:
                                    mode_port(m, dst, pos, config)))
            if mode_id == 9:
                check_no_diag(image, f"mode {mode_id} image",
                              allow=(P_DIA,))
            elif mode_id == 10:
                check_no_diag(image, f"mode {mode_id} image",
                              allow=(P_DIA2,))
            else:
                check_no_diag(image, f"mode {mode_id} image")

        param_str = f'''
            parameter int DATA_WIDTH = {config.data_width},
            parameter int USER_WIDTH = {config.user_width},
            parameter int COORD_W = {coord_w},
            parameter int POS_X = 0,
            parameter int POS_Y = 0,
            parameter int POS_Z = 0,
            parameter int GRID_X = {config.cells_x},
            parameter int GRID_Y = {config.cells_y},
            parameter int GRID_Z = {config.cells_z},
            parameter int NUM_VC = 2,
            parameter string FIFO_IMPL = "{config.fifo_impl}",
            parameter int ENABLE_COUNTERS = {1 if config.add_counters else 0},
            parameter int AGING_LIMIT = 64,
            parameter int BULK_MIN_CREDITS = 1,
            parameter bit TORUS_X = {1 if config.torus_x else 0},
            parameter bit TORUS_Y = {1 if config.torus_y else 0},
            parameter bit TORUS_Z = {1 if config.torus_z else 0},
            parameter bit SOURCE_ROUTE = {1 if config.source_route else 0},
            parameter bit SPECULATION = {1 if config.speculation else 0}
        '''
        self.params.add_param_string(param_str)

        port_str = '''
            input  logic aclk,
            input  logic aresetn,

            input  logic [DATA_WIDTH-1:0] s_axis_tdata  [9],
            input  logic                  s_axis_tvalid [9],
            output logic                  s_axis_tready [9],
            input  logic                  s_axis_tlast  [9],
            input  logic [USER_WIDTH-1:0] s_axis_tuser  [9],

            output logic [DATA_WIDTH-1:0] m_axis_tdata  [9],
            output logic                  m_axis_tvalid [9],
            input  logic                  m_axis_tready [9],
            output logic                  m_axis_tlast  [9],
            output logic [USER_WIDTH-1:0] m_axis_tuser  [9],

            input  logic [NUM_VC-1:0]     s_credit      [9],
            output logic [NUM_VC-1:0]     m_credit      [9],

            input  logic [8:0]            wrap_mask,

            output logic [31:0]           o_err_drop_cnt,
            output logic [31:0]           o_mode_acks,
            output logic [8:0]            o_bulk_starved,
            output logic [31:0]           o_spec_active
        '''
        self.ports.add_port_string(port_str)

