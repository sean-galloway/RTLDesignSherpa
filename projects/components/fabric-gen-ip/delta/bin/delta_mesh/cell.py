    def generate_arbitration(self):
        self.comment("==========================================================================")
        self.comment("Output arbitration - round-robin, packet atomic")
        self.comment("==========================================================================")
        self.comment("Per output: grant the round-robin winner among the requests and")
        self.comment("hold the grant until the TLAST handshake (packet atomicity -- no")
        self.comment("interleaving on an output). On the release cycle the grant is")
        self.comment("dropped, not re-granted (see next-grant computation below).")
        self.comment("==========================================================================")
        self.instruction("")
        self.instruction("logic [NUM_PORTS-1:0] grant_matrix [NUM_PORTS];  // [output][input]")
        self.instruction("logic [NUM_PORTS-1:0] grant_next [NUM_PORTS];")
        self.instruction("logic [PORT_W-1:0]    last_grant [NUM_PORTS];")
        self.instruction("logic [PORT_W-1:0]    last_grant_next [NUM_PORTS];")
        self.instruction("logic                 packet_active [NUM_PORTS];")
        self.instruction("logic                 packet_active_next [NUM_PORTS];")
        self.instruction("logic                 out_xfer_last [NUM_PORTS];")
        self.instruction("")
        self.comment("TLAST handshake on an output this cycle")
        self.instruction("always_comb begin")
        self.instruction("    for (int q = 0; q < NUM_PORTS; q++) begin")
        self.instruction("        out_xfer_last[q] = (|grant_matrix[q]) && m_axis_tvalid[q] &&")
        self.instruction("                           m_axis_tready[q] && m_axis_tlast[q];")
        self.instruction("    end")
        self.instruction("end")
        self.instruction("")
        self.comment("Round-robin pick: first requesting input at or after last+1")
        self.comment("(wrapping); winner returned through the output argument.")
        self.instruction("function automatic logic [NUM_PORTS-1:0] rr_pick(")
        self.instruction("    input  logic [NUM_PORTS-1:0] reqs,")
        self.instruction("    input  logic [PORT_W-1:0]    last,")
        self.instruction("    output logic [PORT_W-1:0]    winner")
        self.instruction(");")
        self.instruction("    logic [NUM_PORTS-1:0] grant;")
        self.instruction("    grant  = '0;")
        self.instruction("    winner = last;")
        self.instruction("    for (int i = 1; i <= NUM_PORTS; i++) begin")
        self.instruction("        if (reqs[(last + i) % NUM_PORTS] && (grant == '0)) begin")
        self.instruction("            grant[(last + i) % NUM_PORTS] = 1'b1;")
        self.instruction("            winner = PORT_W'((last + i) % NUM_PORTS);")
        self.instruction("        end")
        self.instruction("    end")
        self.instruction("    return grant;")
        self.instruction("endfunction")
        self.instruction("")
        self.comment("Next-grant computation (hold while the packet is in flight)")
        self.comment("Release cycle (TLAST handshake): the grant is dropped, NOT")
        self.comment("re-granted in the same cycle -- the releasing input may")
        self.comment("already present its next packet's head flit at the following")
        self.comment("edge, routed to a different output; a held or re-granted grant")
        self.comment("would steer that head onto this output (misroute + duplicate,")
        self.comment("exposed by the Task 3 fabric all-pairs back-to-back traffic).")
        self.comment("The one-cycle bubble per packet boundary is the price of")
        self.comment("keeping the steering unambiguous.")
        self.instruction("always_comb begin")
        self.instruction("    for (int q = 0; q < NUM_PORTS; q++) begin")
        self.comment("        A pending config response owns the idle local")
        self.comment("        output: no new data grant registers until the")
        self.comment("        response drains (requests are not dropped -- the")
        self.comment("        round-robin re-picks once the response leaves).")
        self.instruction("        if ((q == P_LOCAL) && cfg_resp_rd_valid &&")
        self.instruction("            !packet_active[q]) begin")
        self.instruction("            grant_next[q]      = '0;")
        self.instruction("            last_grant_next[q] = last_grant[q];")
        self.instruction("        end else if (packet_active[q]) begin")
        self.instruction("            if (out_xfer_last[q]) begin")
        self.instruction("                grant_next[q]      = '0;")
        self.instruction("                last_grant_next[q] = last_grant[q];")
        self.instruction("            end else begin")
        self.instruction("                grant_next[q]      = grant_matrix[q];")
        self.instruction("                last_grant_next[q] = last_grant[q];")
        self.instruction("            end")
        self.instruction("        end else begin")
        self.instruction("            grant_next[q] = rr_pick(request_matrix[q], last_grant[q],")
        self.instruction("                                      last_grant_next[q]);")
        self.instruction("        end")
        self.instruction("        packet_active_next[q] = |grant_next[q];")
        self.instruction("    end")
        self.instruction("end")
        self.instruction("")

    def generate_input_lock(self):
        self.comment("==========================================================================")
        self.comment("Input tracking - packet allocation per input")
        self.comment("==========================================================================")
        self.comment("Once a head beat is consumed into the crossbar, the input")
        self.comment("locks its granted output and VC so the body beats steer to")
        self.comment("the same port from the same FIFO; the lock releases on the")
        self.comment("packet's TLAST handshake. Single-beat packets never lock.")
        self.comment("The in_pkt/in_vc pair is the intake mirror of the same")
        self.comment("packet boundary: it steers body beats into the VC FIFO the")
        self.comment("head chose.")
        self.comment("==========================================================================")
        self.instruction("")
        self.instruction("logic              lock_active [NUM_PORTS];")
        self.instruction("logic              lock_active_next [NUM_PORTS];")
        self.instruction("logic [PORT_W-1:0] lock_port [NUM_PORTS];")
        self.instruction("logic [PORT_W-1:0] lock_port_next [NUM_PORTS];")
        self.instruction("logic [VC_W-1:0]   lock_vc [NUM_PORTS];")
        self.instruction("logic [VC_W-1:0]   lock_vc_next [NUM_PORTS];")
        self.instruction("logic              in_xfer [NUM_PORTS];")
        self.instruction("logic              in_xfer_last [NUM_PORTS];")
        self.instruction("logic [PORT_W-1:0] in_cov_port [NUM_PORTS];")
        self.instruction("")
        self.comment("Consumed flit per input: the presented flit of the selected")
        self.comment("VC FIFO leaves when its granted output accepts it")
        self.comment("(rd_valid gates inside the FIFO).")
        self.instruction("always_comb begin")
        self.instruction("    for (int p = 0; p < NUM_PORTS; p++) begin")
        self.instruction("        in_xfer[p]      = pres_valid[p] &&")
        self.instruction("                          w_fifo_rd_ready[p][sel_vc[p]];")
        self.instruction("        in_xfer_last[p] = in_xfer[p] && pres_last[p];")
        self.instruction("    end")
        self.instruction("end")
        self.instruction("")
        self.instruction("always_comb begin")
        self.instruction("    for (int p = 0; p < NUM_PORTS; p++) begin")
        self.instruction("        in_cov_port[p] = PORT_W'(P_LOCAL);")
        self.instruction("        for (int q = 0; q < NUM_PORTS; q++) begin")
        self.instruction("            if (grant_matrix[q][p]) begin")
        self.instruction("                in_cov_port[p] = PORT_W'(q);")
        self.instruction("            end")
        self.instruction("        end")
        self.instruction("    end")
        self.instruction("end")
        self.instruction("")
        self.instruction("always_comb begin")
        self.instruction("    for (int p = 0; p < NUM_PORTS; p++) begin")
        self.instruction("        lock_active_next[p] = lock_active[p];")
        self.instruction("        lock_port_next[p]   = lock_port[p];")
        self.instruction("        lock_vc_next[p]     = lock_vc[p];")
        self.instruction("        if (lock_active[p]) begin")
        self.instruction("            if (in_xfer_last[p]) begin")
        self.instruction("                lock_active_next[p] = 1'b0;")
        self.instruction("            end")
        self.instruction("        end else if (in_xfer[p] && !pres_last[p]) begin")
        self.instruction("            lock_active_next[p] = 1'b1;")
        self.instruction("            lock_port_next[p]   = in_cov_port[p];")
        self.instruction("            lock_vc_next[p]     = sel_vc[p];")
        self.instruction("        end")
        self.instruction("    end")
        self.instruction("end")
        self.instruction("")

    def generate_crossbar_mux(self):
        self.comment("==========================================================================")
        self.comment("Crossbar data multiplexing + credit-gated presentation")
        self.comment("==========================================================================")
        self.comment("Per output: forward the granted input's presented flit")
        self.comment("(payload streams pass transparently -- the head-flit header")
        self.comment("rides TUSER like flat mode's TDEST handling). A flit is")
        self.comment("presented only while the downstream credit level for its VC")
        self.comment("is set; on the handshake it leaves the input FIFO and the")
        self.comment("neighbor's free-slot count drops by one (its m_credit level")
        self.comment("follows one cycle later). While a presented flit waits on a")
        self.comment("low tready the credit level cannot change -- this link's")
        self.comment("handshakes are the only thing that consume this VC's slots,")
        self.comment("so the AXI payload-hold rule holds. The FIFO read enable")
        self.comment("is the same predicate as tvalid && tready.")
        self.comment("==========================================================================")
        self.instruction("")
        self.instruction("always_comb begin")
        self.instruction("    for (int q = 0; q < NUM_PORTS; q++) begin")
        self.instruction("        m_axis_tdata[q]  = '0;")
        self.instruction("        m_axis_tvalid[q] = 1'b0;")
        self.instruction("        m_axis_tlast[q]  = 1'b0;")
        self.instruction("        m_axis_tuser[q]  = '0;")
        self.comment("        Config responses own the local output while it")
        self.comment("        is idle (no data grant holds it); data grants")
        self.comment("        resume the cycle after the response drains.")
        self.instruction("        if ((q == P_LOCAL) && cfg_resp_present) begin")
        self.instruction("            m_axis_tdata[q]  =")
        self.instruction("                {{(DATA_WIDTH-RESP_W){1'b0}}, cfg_resp_rd_data};")
        self.instruction("            m_axis_tvalid[q] = 1'b1;")
        self.instruction("            m_axis_tlast[q]  = 1'b1;")
        self.instruction("        end else begin")
        self.instruction("        for (int p = 0; p < NUM_PORTS; p++) begin")
        self.instruction("            if (grant_matrix[q][p]) begin")
        self.instruction("                m_axis_tdata[q]  =")
        self.instruction("                    w_fifo_rd_data[p][sel_vc[p]][DATA_WIDTH-1:0];")
        self.instruction("                m_axis_tvalid[q] = pres_valid[p] &&")
        self.instruction("                    s_credit[q][sel_vc[p]];")
        self.instruction("                m_axis_tlast[q]  = pres_last[p];")
        self.instruction("                m_axis_tuser[q]  = pres_tuser[p];")
        self.instruction("            end")
        self.instruction("        end")
        self.instruction("        end")
        self.instruction("    end")
        self.instruction("end")
        self.instruction("")
        self.instruction("always_comb begin")
        self.instruction("    for (int p = 0; p < NUM_PORTS; p++) begin")
        self.instruction("        for (int v = 0; v < NUM_VC; v++) begin")
        self.instruction("            w_fifo_rd_ready[p][v] = 1'b0;")
        self.instruction("        end")
        self.instruction("    end")
        self.instruction("    for (int q = 0; q < NUM_PORTS; q++) begin")
        self.instruction("        for (int p = 0; p < NUM_PORTS; p++) begin")
        self.instruction("            if (grant_matrix[q][p]) begin")
        self.instruction("                w_fifo_rd_ready[p][sel_vc[p]] =")
        self.instruction("                    m_axis_tready[q] && s_credit[q][sel_vc[p]];")
        self.instruction("            end")
        self.instruction("        end")
        self.instruction("    end")
        self.comment("    Drop/config consumption wins over (the absent)")
        self.comment("    grant path: special consumers leave the FIFO with")
        self.comment("    no output side effects.")
        self.instruction("    for (int p = 0; p < NUM_PORTS; p++) begin")
        self.instruction("        if (special_consume[p]) begin")
        self.instruction("            w_fifo_rd_ready[p][sel_vc[p]] = 1'b1;")
        self.instruction("        end")
        self.instruction("    end")
        self.instruction("end")
        self.instruction("")

