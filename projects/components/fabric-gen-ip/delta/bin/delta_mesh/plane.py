def write_planes(output_dir: str, data_width: int = 64, user_width: int = 1,
                 cxs_max_credit: int = 32) -> list[str]:
    """Emit all four plane modules into output_dir; return their paths."""
    os.makedirs(output_dir, exist_ok=True)
    paths = []
    for cls in (DeltaMeshPlaneAxisTx, DeltaMeshPlaneAxisRx,
                DeltaMeshPlaneCxsTx, DeltaMeshPlaneCxsRx):
        if cls in (DeltaMeshPlaneCxsTx, DeltaMeshPlaneCxsRx):
            gen = cls(data_width, user_width, cxs_max_credit)
        else:
            gen = cls(data_width, user_width)
        gen.verilog(output_dir)
        paths.append(os.path.join(output_dir, f'{gen.module_name}.sv'))
    return paths
