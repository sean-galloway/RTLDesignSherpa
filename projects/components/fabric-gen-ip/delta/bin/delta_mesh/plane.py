"""
Delta mesh interface-plane generators.

Mirrors the rapids network-plane pattern
(rapids/rtl/plane/rapids_plane_{axis,cxs}_{tx,rx}.sv): the core-facing side
of every plane is the identical internal AXI-Stream (`fub_axis_*`); only the
outer side differs (native AXIS vs native CXS). The cell core is untouched;
the plane is the per-port shim that lets a delta mesh fabric speak either
protocol at its edge.

AXIS planes are simple pass-through wrappers (the delta_mesh_cell core is
already AXI-Stream). CXS planes translate between the internal AXIS record
and a credited CXS flit link using the house converters (axis_to_cxs /
cxs_to_axis) and link endpoints (cxs_master / cxs_slave).
"""

import os

from rtl_generators.verilog.module import Module


def _clog2(n: int) -> int:
    """SystemVerilog $clog2 semantics: $clog2(0)=0, $clog2(1)=0."""
    if n <= 1:
        return 0
    return (n - 1).bit_length()


def cxs_cntl_width(n: int, dw: int, align: int) -> int:
    """Python mirror of cxs_pkg::cntl_width (rtl/amba/includes/cxs_pkg.sv)."""
    if n <= 1:
        return 0
    start_ptr_w = _clog2(dw // 32) if align == 4 else _clog2(dw // 128)
    end_ptr_w = _clog2(dw // 32)
    return n * (3 + start_ptr_w + end_ptr_w)


def cxs_port_w(w: int) -> int:
    """Python mirror of cxs_pkg::port_w."""
    return w if w > 0 else 1


def cxs_widths(data_width: int, user_width: int, n: int = 2,
               align: int = 16) -> tuple:
    """(CNTL_W, CNTL_PW, CXS_UW) as integer literals for param defaults.

    The Module param parser splits on commas, so defaults must not contain
    function-call commas; cxs_pkg's own functions are reproduced above.
    """
    cntl_w = cxs_cntl_width(n, data_width, align)
    cntl_pw = cxs_port_w(cntl_w)
    cxs_uw = data_width // 8 + user_width
    return cntl_w, cntl_pw, cxs_uw


class DeltaMeshPlaneAxisTx(Module):
    """AXIS egress plane: internal AXIS -> outer AXIS (pass-through)."""

    module_str = 'delta_mesh_plane_axis_tx'

    def __init__(self, data_width: int = 64, user_width: int = 1):
        Module.__init__(self, module_name=self.module_str)

        param_str = f'''
            parameter int DATA_WIDTH = {data_width},
            parameter int USER_WIDTH = {user_width}
        '''
        self.params.add_param_string(param_str)

        port_str = '''
            input  logic aclk,
            input  logic aresetn,

            input  logic [DATA_WIDTH-1:0] fub_axis_tdata,
            input  logic                  fub_axis_tvalid,
            output logic                  fub_axis_tready,
            input  logic                  fub_axis_tlast,
            input  logic [USER_WIDTH-1:0] fub_axis_tuser,

            output logic [DATA_WIDTH-1:0] m_axis_tdata,
            output logic                  m_axis_tvalid,
            input  logic                  m_axis_tready,
            output logic                  m_axis_tlast,
            output logic [USER_WIDTH-1:0] m_axis_tuser
        '''
        self.ports.add_port_string(port_str)

    def generate_header_comment(self):
        self.comment("==============================================================================")
        self.comment(f"Module: {self.module_str}")
        self.comment("Project: Delta - AXI-Stream Crossbar Generator (mesh topology)")
        self.comment("==============================================================================")
        self.comment("Description: AXIS network plane, source egress (TX).")
        self.comment("")
        self.comment("The inner (core-facing) side and the outer (network) side")
        self.comment("are both AXI-Stream; this module is a structural pass-through")
        self.comment("so that the cell top can select AXIS or CXS by module name")
        self.comment("alone, mirroring the rapids plane pattern.")
        self.comment("")
        self.comment("Generated by: delta_generator.py --topology mesh")
        self.comment("==============================================================================")
        self.instruction("")

    def generate_body(self):
        self.instruction("assign m_axis_tdata  = fub_axis_tdata;")
        self.instruction("assign m_axis_tvalid = fub_axis_tvalid;")
        self.instruction("assign m_axis_tlast  = fub_axis_tlast;")
        self.instruction("assign m_axis_tuser  = fub_axis_tuser;")
        self.instruction("assign fub_axis_tready = m_axis_tready;")
        self.instruction("")

    def verilog(self, file_path):
        self.generate_header_comment()
        self.generate_body()
        self.start()
        self.end()
        self.start_instructions = [s.rstrip() for s in self.start_instructions]
        self.instructions = [s.rstrip() for s in self.instructions]
        self.end_instructions = [s.rstrip() for s in self.end_instructions]
        self.write(file_path, f'{self.module_name}.sv')


