`timescale 1ns / 1ps

`include "reset_defs.svh"

module delta_mesh_cell #(parameter int     DATA_WIDTH = 64,
parameter int     USER_WIDTH = 64,
parameter int     COORD_W = 2,
parameter int     POS_X = 0,
parameter int     POS_Y = 0,
parameter int     POS_Z = 0,
parameter int     NUM_VC = 2,
parameter string  FIFO_IMPL = "reg",
parameter int     ENABLE_COUNTERS = 1 )(
    input  logic                  aclk,
    input  logic                  aresetn,
    input  logic [DATA_WIDTH-1:0] s_axis_tdata  [7],
    input  logic                  s_axis_tvalid [7],
    output logic                  s_axis_tready [7],
    input  logic                  s_axis_tlast  [7],
    input  logic [USER_WIDTH-1:0] s_axis_tuser  [7],
    output logic [DATA_WIDTH-1:0] m_axis_tdata  [7],
    output logic                  m_axis_tvalid [7],
    input  logic                  m_axis_tready [7],
    output logic                  m_axis_tlast  [7],
    output logic [USER_WIDTH-1:0] m_axis_tuser  [7],
    input  logic [NUM_VC-1:0]     s_credit      [7],
    output logic [NUM_VC-1:0]     m_credit      [7]
);
// ==============================================================================
// Module: delta_mesh_cell
// Project: Delta - AXI-Stream Crossbar Generator (mesh topology)
// ==============================================================================
// Description: Mesh router cell for a 4x4x1 grid
//
// Delta: Where data flows split and merge like river deltas
//
// Generated by: delta_generator.py --topology mesh (framework version)
// Configuration:
//   - Topology: mesh (4x4x1)
//   - Data Width: 64 bits
//   - User Width: 64 bits (head-flit header in TUSER)
//   - Coordinate Width: 2 bits
//
// Features (Task 2 skeleton):
//   - Power-on default DOR: dst coord vs POS per dimension in X, Y, Z
//     order; negative port on <, positive port on >, next dimension
//     on equal; P_LOCAL when all equal
//   - Packet-atomic grants: output grant held until TLAST; non-head
//     beats follow the packet's allocated output
//   - Single VC (VC0); routing RAM tables land in Task 5
//   - Credit sideband ports tied off (credits always available);
//     the credit protocol lands in Task 4
//   - No input buffers yet: direct ready/valid steering
//
// ==============================================================================

// ==========================================================================
// Local parameters
// ==========================================================================
localparam int NUM_PORTS = 7;
localparam int PORT_W    = 3;

// Mesh port ids (pinned)
localparam int P_X_NEG = 0;
localparam int P_X_POS = 1;
localparam int P_Y_NEG = 2;
localparam int P_Y_POS = 3;
localparam int P_Z_NEG = 4;
localparam int P_Z_POS = 5;
localparam int P_LOCAL = 6;

// Head-flit header field offsets in TUSER, LSB-first
// (single source of truth: bin/delta_mesh/header.py)
localparam int HDR_DST_X_LO = 0;
localparam int HDR_DST_Y_LO = 2;
localparam int HDR_DST_Z_LO = 4;

// ==========================================================================
// Route computation - power-on default DOR
// ==========================================================================
// Head flit only: the destination coordinates in TUSER are compared
// against this cell's position, one dimension at a time in X, Y, Z
// order. A lower coordinate takes the negative-direction port, a
// higher coordinate the positive-direction port, an equal coordinate
// moves to the next dimension; all equal delivers to the attached
// host (P_LOCAL). Non-head beats do not recompute -- they follow the
// packet's allocated output (lock_active/lock_port below) to TLAST.
// ==========================================================================

// Per-dimension signed deltas: dst coordinate minus this
// cell's position (COORD_W+1 bits so the sign survives).
logic signed [COORD_W:0] delta_x [NUM_PORTS];
logic signed [COORD_W:0] delta_y [NUM_PORTS];
logic signed [COORD_W:0] delta_z [NUM_PORTS];
logic [PORT_W-1:0]       route_req [NUM_PORTS];

always_comb begin
    for (int p = 0; p < NUM_PORTS; p++) begin
        delta_x[p] = $signed({1'b0, s_axis_tuser[p][HDR_DST_X_LO +: COORD_W]}) -
                          $signed({1'b0, COORD_W'(POS_X)});
        delta_y[p] = $signed({1'b0, s_axis_tuser[p][HDR_DST_Y_LO +: COORD_W]}) -
                          $signed({1'b0, COORD_W'(POS_Y)});
        delta_z[p] = $signed({1'b0, s_axis_tuser[p][HDR_DST_Z_LO +: COORD_W]}) -
                          $signed({1'b0, COORD_W'(POS_Z)});
        route_req[p] = PORT_W'(P_LOCAL);
        if (delta_x[p] < 0)
            route_req[p] = PORT_W'(P_X_NEG);
        else if (delta_x[p] > 0)
            route_req[p] = PORT_W'(P_X_POS);
        else if (delta_y[p] < 0)
            route_req[p] = PORT_W'(P_Y_NEG);
        else if (delta_y[p] > 0)
            route_req[p] = PORT_W'(P_Y_POS);
        else if (delta_z[p] < 0)
            route_req[p] = PORT_W'(P_Z_NEG);
        else if (delta_z[p] > 0)
            route_req[p] = PORT_W'(P_Z_POS);
    end
end

// ==========================================================================
// Request matrix - which inputs want which outputs this cycle
// ==========================================================================
// An input with a packet in flight requests only its locked output;
// an idle input routes its head flit (route_req). Inputs present no
// request until granted, so a head beat is never consumed early.
// ==========================================================================

logic [NUM_PORTS-1:0] request_matrix [NUM_PORTS];  // [output][input]
logic [PORT_W-1:0]    req_port [NUM_PORTS];

always_comb begin
    for (int q = 0; q < NUM_PORTS; q++) begin
        request_matrix[q] = '0;
    end
    for (int p = 0; p < NUM_PORTS; p++) begin
        req_port[p] = lock_active[p] ? lock_port[p] : route_req[p];
        if (s_axis_tvalid[p]) begin
            request_matrix[req_port[p]][p] = 1'b1;
        end
    end
end

// ==========================================================================
// Input tracking - packet allocation per input
// ==========================================================================
// Once a head beat is accepted, the input locks its granted output
// so the body beats steer to the same port; the lock releases on the
// input's TLAST handshake. Single-beat packets never lock.
// ==========================================================================

logic              lock_active [NUM_PORTS];
logic              lock_active_next [NUM_PORTS];
logic [PORT_W-1:0] lock_port [NUM_PORTS];
logic [PORT_W-1:0] lock_port_next [NUM_PORTS];
logic              in_xfer [NUM_PORTS];
logic              in_xfer_last [NUM_PORTS];
logic [PORT_W-1:0] in_cov_port [NUM_PORTS];

// Steered backpressure: an input is ready exactly when its granted
// output is ready; ungranted inputs are not ready (the head beat
// must wait for its grant).
always_comb begin
    for (int p = 0; p < NUM_PORTS; p++) begin
        s_axis_tready[p] = 1'b0;
        in_cov_port[p]   = PORT_W'(P_LOCAL);
        for (int q = 0; q < NUM_PORTS; q++) begin
            if (grant_matrix[q][p]) begin
                s_axis_tready[p] = m_axis_tready[q];
                in_cov_port[p]   = PORT_W'(q);
            end
        end
        in_xfer[p]      = s_axis_tvalid[p] && s_axis_tready[p];
        in_xfer_last[p] = in_xfer[p] && s_axis_tlast[p];
    end
end

always_comb begin
    for (int p = 0; p < NUM_PORTS; p++) begin
        lock_active_next[p] = lock_active[p];
        lock_port_next[p]   = lock_port[p];
        if (lock_active[p]) begin
            if (in_xfer_last[p]) begin
                lock_active_next[p] = 1'b0;
            end
        end else if (in_xfer[p] && !s_axis_tlast[p]) begin
            lock_active_next[p] = 1'b1;
            lock_port_next[p]   = in_cov_port[p];
        end
    end
end

// ==========================================================================
// Output arbitration - round-robin, packet atomic
// ==========================================================================
// Per output: grant the round-robin winner among the requests and
// hold the grant until the TLAST handshake (packet atomicity -- no
// interleaving on an output). On the release cycle the grant is
// dropped, not re-granted (see next-grant computation below).
// ==========================================================================

logic [NUM_PORTS-1:0] grant_matrix [NUM_PORTS];  // [output][input]
logic [NUM_PORTS-1:0] grant_next [NUM_PORTS];
logic [PORT_W-1:0]    last_grant [NUM_PORTS];
logic [PORT_W-1:0]    last_grant_next [NUM_PORTS];
logic                 packet_active [NUM_PORTS];
logic                 packet_active_next [NUM_PORTS];
logic                 out_xfer_last [NUM_PORTS];

// TLAST handshake on an output this cycle
always_comb begin
    for (int q = 0; q < NUM_PORTS; q++) begin
        out_xfer_last[q] = (|grant_matrix[q]) && m_axis_tvalid[q] &&
                           m_axis_tready[q] && m_axis_tlast[q];
    end
end

// Round-robin pick: first requesting input at or after last+1
// (wrapping); winner returned through the output argument.
function automatic logic [NUM_PORTS-1:0] rr_pick(
    input  logic [NUM_PORTS-1:0] reqs,
    input  logic [PORT_W-1:0]    last,
    output logic [PORT_W-1:0]    winner
);
    logic [NUM_PORTS-1:0] grant;
    grant  = '0;
    winner = last;
    for (int i = 1; i <= NUM_PORTS; i++) begin
        if (reqs[(last + i) % NUM_PORTS] && (grant == '0)) begin
            grant[(last + i) % NUM_PORTS] = 1'b1;
            winner = PORT_W'((last + i) % NUM_PORTS);
        end
    end
    return grant;
endfunction

// Next-grant computation (hold while the packet is in flight)
// Release cycle (TLAST handshake): the grant is dropped, NOT
// re-granted in the same cycle -- the releasing input may
// already present its next packet's head flit at the following
// edge, routed to a different output; a held or re-granted grant
// would steer that head onto this output (misroute + duplicate,
// exposed by the Task 3 fabric all-pairs back-to-back traffic).
// The one-cycle bubble per packet boundary is the price of
// keeping the steering unambiguous.
always_comb begin
    for (int q = 0; q < NUM_PORTS; q++) begin
        if (packet_active[q]) begin
            if (out_xfer_last[q]) begin
                grant_next[q]      = '0;
                last_grant_next[q] = last_grant[q];
            end else begin
                grant_next[q]      = grant_matrix[q];
                last_grant_next[q] = last_grant[q];
            end
        end else begin
            grant_next[q] = rr_pick(request_matrix[q], last_grant[q],
                                      last_grant_next[q]);
        end
        packet_active_next[q] = |grant_next[q];
    end
end

// ==========================================================================
// Crossbar data multiplexing
// ==========================================================================
// Per output: forward the granted input's beat (payload streams pass
// transparently -- the head-flit header rides TUSER like flat mode's
// TDEST handling).
// ==========================================================================

always_comb begin
    for (int q = 0; q < NUM_PORTS; q++) begin
        m_axis_tdata[q]  = '0;
        m_axis_tvalid[q] = 1'b0;
        m_axis_tlast[q]  = 1'b0;
        m_axis_tuser[q]  = '0;
        for (int p = 0; p < NUM_PORTS; p++) begin
            if (grant_matrix[q][p]) begin
                m_axis_tdata[q]  = s_axis_tdata[p];
                m_axis_tvalid[q] = s_axis_tvalid[p];
                m_axis_tlast[q]  = s_axis_tlast[p];
                m_axis_tuser[q]  = s_axis_tuser[p];
            end
        end
    end
end

// ==========================================================================
// Registers (house ALWAYS_FF_RST: async assert, sync release)
// ==========================================================================
generate
    for (genvar q = 0; q < NUM_PORTS; q++) begin : gen_output_grant
        `ALWAYS_FF_RST(aclk, aresetn,
            if (!aresetn) begin
                grant_matrix[q]  <= '0;
                last_grant[q]    <= '0;
                packet_active[q] <= 1'b0;
            end else begin
                grant_matrix[q]  <= grant_next[q];
                last_grant[q]    <= last_grant_next[q];
                packet_active[q] <= packet_active_next[q];
            end
        )
    end

    for (genvar p = 0; p < NUM_PORTS; p++) begin : gen_input_lock
        `ALWAYS_FF_RST(aclk, aresetn,
            if (!aresetn) begin
                lock_active[p] <= 1'b0;
                lock_port[p]   <= '0;
            end else begin
                lock_active[p] <= lock_active_next[p];
                lock_port[p]   <= lock_port_next[p];
            end
        )
    end
endgenerate

// ==========================================================================
// Credit sidebands (Task 2 tie-off)
// ==========================================================================
// Credits are always available: m_credit is tied to 1 per VC and the
// s_credit inputs are ignored. The real credit protocol lands in
// Task 4; the ports exist now so later tasks do not change the shape.
// ==========================================================================
generate
    for (genvar p = 0; p < NUM_PORTS; p++) begin : gen_credit
        assign m_credit[p] = {NUM_VC{1'b1}};
    end
endgenerate

// s_credit is consumed by no logic this task; sink it for lint
/* verilator lint_off UNUSEDSIGNAL */
logic unused_s_credit;
always_comb begin
    unused_s_credit = 1'b0;
    for (int p = 0; p < NUM_PORTS; p++) begin
        unused_s_credit = unused_s_credit ^ (|s_credit[p]);
    end
end
/* verilator lint_on UNUSEDSIGNAL */

endmodule
