module delta_mesh_cell #(parameter int     DATA_WIDTH = 64,
parameter int     USER_WIDTH = 64,
parameter int     COORD_W = 2,
parameter int     POS_X = 0,
parameter int     POS_Y = 0,
parameter int     POS_Z = 0,
parameter int     GRID_X = 4,
parameter int     GRID_Y = 4,
parameter int     GRID_Z = 1,
parameter int     NUM_VC = 2,
parameter string  FIFO_IMPL = "reg",
parameter int     ENABLE_COUNTERS = 1,
parameter int     AGING_LIMIT = 64,
parameter int     BULK_MIN_CREDITS = 1 )(
    input  logic                  aclk,
    input  logic                  aresetn,
    input  logic [DATA_WIDTH-1:0] s_axis_tdata   [9],
    input  logic                  s_axis_tvalid  [9],
    output logic                  s_axis_tready  [9],
    input  logic                  s_axis_tlast   [9],
    input  logic [USER_WIDTH-1:0] s_axis_tuser   [9],
    output logic [DATA_WIDTH-1:0] m_axis_tdata   [9],
    output logic                  m_axis_tvalid  [9],
    input  logic                  m_axis_tready  [9],
    output logic                  m_axis_tlast   [9],
    output logic [USER_WIDTH-1:0] m_axis_tuser   [9],
    input  logic [NUM_VC-1:0]     s_credit       [9],
    output logic [NUM_VC-1:0]     m_credit       [9],
    output logic [31:0]           o_err_drop_cnt,
    output logic [31:0]           o_mode_acks,
    output logic [8:0]            o_bulk_starved
);
// ==============================================================================
// Module: delta_mesh_cell
// Project: Delta - AXI-Stream Crossbar Generator (mesh topology)
// ==============================================================================
// Description: Mesh router cell for a 4x4x1 grid
//
// Delta: Where data flows split and merge like river deltas
//
// Generated by: delta_generator.py --topology mesh (framework version)
// Configuration:
//   - Topology: mesh (4x4x1)
//   - Data Width: 64 bits
//   - User Width: 64 bits (head-flit header in TUSER)
//   - Coordinate Width: 2 bits
//
// Features (Task 4):
//   - Per-port per-VC input buffers: one house gaxi_fifo_sync per
//     port per VC (9 x NUM_VC, DEPTH=4) between s_axis acceptance
//     and the route/grant stage; a flit word is
//     {TUSER, TLAST, TDATA}. Acceptance is unconditional on
//     downstream state (credits govern the output side of each
//     link, not local admission); the port backpressures only
//     when the selected VC FIFO is full.
//   - Credit flow control per VC: the credit sideband carries
//     one level per VC -- m_credit[p][vc] = the VC FIFO at port
//     p is not full (the free-slot count, DEPTH at reset,
//     saturated to its level form). A flit is presented on
//     m_axis[q] only while s_credit[q][vc] is set and consumes
//     one slot per handshake; the neighbor returns credit by
//     draining its buffer (post-consume, one cycle later).
//   - VC selection: the head flit's header vc bit steers the
//     beat into the VC FIFO at intake; an idle port presents
//     VC0 ahead of VC1; both VCs route with the same DOR.
//   - Packet-atomic grants on FIFO outputs: the output grant is
//     held until TLAST (a packet never interleaves with
//     another on a link); one-cycle grant bubble per packet
//     boundary (release cycle drops the grant, see below).
//   - Power-on default DOR: dst coord vs POS per dimension in
//     X, Y, Z order; P_LOCAL when all equal (Task 5: installed
//     as the route_table RAM image, see below).
//   - Route table RAM (Task 5): per-cell table keyed
//     {qos, dst_z, dst_y, dst_x} -> {port_mask[8:0], vc};
//     the address carries the full key width now so Task 7's
//     QoS classes land without reshaping the memory. The
//     power-on image is installed by an initial block and
//     re-derives the DOR decision from this instance's POS
//     parameters (one checked-in module serves every grid
//     position). Out-of-range dst coordinates and empty
//     masks drop at the head flit with err_drop_cnt tally;
//     the vc field is written 0 and is not consulted by the
//     datapath this task (the output VC follows the packet's
//     intake VC; Task 7 activates the vc field).
//   - In-band config on the local port (Task 5): a single-
//     beat packet addressed to this cell itself (dst == POS),
//     QoS class 0, sr_ptr[0] = 1 write / 0 read, command in
//     beat-0 TDATA {table_index[15:0], entry[ENTRY_W-1:0]}.
//     Writes commit on the accepting clock edge (single-cycle
//     write; a master that awaits the ack never sees stale
//     routes); a multi-beat config-shaped packet is dropped
//     whole (head counted, op not executed). The response is
//     one beat on the local m_axis, same {table_index, entry}
//     shape (write: echo; read: table value; out-of-depth
//     index reads back 0), tlast = 1, tuser = 0. Config
//     responses wait for the idle local output and stall its
//     grant registration meanwhile.
//   - Standard fabric modes (Task 6; mode 9 Task 6b):
//     r_mode[3:0] selects the route source -- 0: the
//     custom RAM image (power-on default), 1-9: the
//     generated standard-mode images (spec sec. 5.4
//     catalog), a mux in front of the RAM lookup so the
//     RAM stays user-intact across switches. Mode 1 =
//     pure DOR; mode 2 = systolic-1D (+X when dst_x >
//     POS_X else P_LOCAL; wrap is Task 9); mode 5 =
//     broadcast placeholder (DOR; multicast replication
//     lands with Task 8); mode 6 = convergecast (every dst
//     routes toward root 0,0,0); mode 9 = tetrad
//     all-to-all K4 (diagonal mate via P_DIA, 1 hop;
//     edge mates via the axis port; inter-tetrad DOR);
//     modes 3/4/7/8 = minimal DOR images.
//   - Broadcast mode-switch (Task 6): a config-format
//     packet -- dst == own coordinate, QoS class 0, mcast
//     bit set, sr_ptr[0] = 1 (write), single beat, payload
//     beat-0 {mode_id[3:0] in the entry field, 16'hC0DE
//     magic in the index field} -- recognized on ANY input
//     port (the controller's 16'hM0DE spelling is not a
//     legal SystemVerilog hex digit; C0DE is the legal
//     stand-in). The consuming cell switches r_mode,
//     returns a one-beat ack to the origin (dst = the
//     switch header's src coordinate; qos 1, mcast 0,
//     sr_ptr[0] = 1 control class, 16'hACED payload
//     magic) and re-emits the switch on every existing
//     neighbor port; a cell already in the target mode
//     suppresses re-emission, which terminates the flood.
//     The origin counts received acks in
//     o_mode_acks[31:0]; the barrier for an N-cell fabric
//     completes at N acks. Acks and fan copies are
//     generated into the local VC0 input FIFO between
//     external packets (the external master is never
//     shadowed mid-handshake) and route DOR as control
//     traffic (sr_ptr[0] = 1 bypasses the mode mux and
//     the RAM), so the switch machinery works under any
//     current mode.
//   - QoS (Task 7): the head-flit header qos field
//     decodes the data class at the arbiter: class 1 =
//     latency, class 2 = bulk. A data packet decoded
//     at class 0 maps to the latency class -- class 0
//     is reserved to the control plane (a class-0
//     packet addressed to this cell itself IS config
//     and is consumed by the config plane, never
//     granted), so class-0 data can only arrive with
//     dst != self and rides as latency. The spec's 3-
//     class table leaves qos 3 unassigned; it decodes
//     to the bulk class. Per-class queuing is request
//     accounting, not new FIFOs: the Task 4 per-port
//     per-VC input FIFOs remain the only transport,
//     each input's head-of-line entry carries a class
//     (latched per packet for the body beats, whose
//     tuser is 0), and the VC assignment stays header-
//     driven and orthogonal to class. Per output the
//     class filter is strict priority latency > bulk
//     with two antistarvation mechanisms on the
//     AGING_LIMIT horizon (parameter, default 64):
//     AGING -- a per-input counter runs while the
//     input's head is eligible but not granted and
//     saturates at AGING_LIMIT+1; once it exceeds
//     AGING_LIMIT the head joins the aged candidate
//     set, which beats every non-aged head (priority
//     inversion); it resets on grant. BULK MINIMUM
//     RESERVATION -- a per-output saturating starve
//     counter runs while bulk is eligible but not
//     granted and resets on any bulk grant; at the
//     trigger point (BULK_MIN_CREDITS+2 cycles inside
//     the AGING_LIMIT window -- absorbing the worst-
//     case pick phase plus the grant registration --
//     so the grant itself lands within AGING_LIMIT
//     eligible cycles) the output forces bulk
//     candidates, giving a continuously eligible
//     bulk flow >= 1 grant per AGING_LIMIT cycles.
//     The reservation outranks
//     aging inversion; within a candidate set the
//     house arbiter_matrix (ACK mode) fair-picks.
//     The arbiter's registered grant is held to the
//     packet's TLAST handshake exactly like the pre-
//     Task-7 grant register; the release cycle keeps
//     its one-cycle bubble (the retiring grant is
//     acknowledged one cycle after TLAST, so the next
//     winner is picked from the requests visible in
//     the bubble cycle -- never re-granted in the
//     TLAST cycle), and a pending config response on
//     P_LOCAL blocks only fresh grant registration.
//     Packet atomicity and the credit-gated
//     presentation are untouched: QoS replaces the
//     arbitration policy, not the atomicity/credit
//     machinery. o_bulk_starved[8:0] exposes the per-
//     output reservation-due state (bit q = output q)
//     for DV; it is a status flag, not a cumulative
//     counter, so it is not gated by ENABLE_COUNTERS.
//     Routing stays identical across classes at power-
//     on (every qos table region holds the same DOR
//     image); per-class routing tables / spec QoS path
//     diversity are a deferred follow-on.
//
// ==============================================================================

// ==========================================================================
// Local parameters
// ==========================================================================
localparam int NUM_PORTS = 9;
localparam int PORT_W    = $clog2(NUM_PORTS);

// Mesh port ids (pinned; Task 6c: P_DIA at 6, P_DIA2
// at 7, P_LOCAL moved to 8)
localparam int P_X_NEG = 0;
localparam int P_X_POS = 1;
localparam int P_Y_NEG = 2;
localparam int P_Y_POS = 3;
localparam int P_Z_NEG = 4;
localparam int P_Z_POS = 5;
localparam int P_DIA = 6;
localparam int P_DIA2 = 7;
localparam int P_LOCAL = 8;

// Input buffer configuration (plan-pinned DEPTH=4)
localparam int FIFO_DEPTH = 4;
localparam int FLIT_W     = DATA_WIDTH + USER_WIDTH + 1;
localparam int VC_W       = (NUM_VC > 1) ? $clog2(NUM_VC) : 1;
// FIFO memory style from the FIFO_IMPL knob: 'reg' -> AUTO
// (register array, mux read); 'sram' -> BRAM (registered read)
localparam fifo_mem_t P_FIFO_MEM_STYLE =
    (FIFO_IMPL == "sram") ? FIFO_BRAM : FIFO_AUTO;

// Head-flit header field offsets in TUSER, LSB-first
// (single source of truth: bin/delta_mesh/header.py)
localparam int HDR_DST_X_LO = 0;
localparam int HDR_DST_Y_LO = 2;
localparam int HDR_DST_Z_LO = 4;
localparam int HDR_SRC_X_LO = 6;
localparam int HDR_SRC_Y_LO = 8;
localparam int HDR_SRC_Z_LO = 10;
localparam int HDR_VC_LO = 15;
localparam int HDR_VC_W  = 1;
localparam int HDR_QOS_LO = 12;
localparam int HDR_QOS_W  = 2;
localparam int HDR_SR_PTR_LO = 20;
localparam int HDR_MCAST_LO = 14;
localparam int HDR_PID_LO = 28;

// Route table organization (Task 5): key {qos, dst_z, dst_y,
// dst_x} -> entry {port_mask[8:0], vc}; an all-zero mask is
// the drop encoding. The mask widened from 8 to 9 bits when
// P_DIA2 landed (Task 6c). The dst space occupies the low
// 3*COORD_W address bits; QoS rides above it.
localparam int ROUTE_ADDR_W = 3*COORD_W + 2;
localparam int ROUTE_DEPTH  = 2**ROUTE_ADDR_W;
localparam int ENTRY_MASK_W = 9;
localparam int ENTRY_W      = ENTRY_MASK_W + VC_W;
localparam int RESP_W       = 16 + ENTRY_W;

// Standard-mode + control-plane constants (Task 6)
// 16'hC0DE = mode-switch magic (the pinned 'M0DE' is not a
// legal SV hex digit); 16'hACED = ack magic. The control
// generator FIFO holds at most one switch fan-out (1 ack +
// 6 neighbor copies on a fully populated cell).
localparam logic [15:0] MSW_MAGIC = 16'hC0DE;
localparam logic [15:0] ACK_MAGIC = 16'hACED;
localparam int GEN_FIFO_DEPTH = 8;

// QoS constants (Task 7): AGE_W holds the saturated
// AGING_LIMIT+1; STARVE_DUE is the bulk reservation
// trigger point, set BULK_MIN_CREDITS+2 cycles inside
// the AGING_LIMIT window so that, after the worst-case
// pick-phase alignment plus the 1-cycle grant
// registration, the bulk grant itself lands within
// AGING_LIMIT eligible cycles (BULK_MIN_CREDITS=1:
// any AGING_LIMIT consecutive eligible cycles hold at
// least one bulk grant; the counter saturates at the
// trigger, keeping the reservation due until served).
localparam int AGE_W = $clog2(AGING_LIMIT + 2);
localparam int STARVE_DUE =
    (AGING_LIMIT > (BULK_MIN_CREDITS + 2)) ?
        (AGING_LIMIT - BULK_MIN_CREDITS - 2) : 1;

// ==========================================================================
// Input buffers - one house FIFO per port per VC
// ==========================================================================
// A flit word is {TUSER, TLAST, TDATA}: the head-flit header
// rides TUSER on the first beat and the body beats carry 0,
// so the whole beat streams through the buffer unchanged.
// Intake steering: the head beat's header vc bit picks the VC
// FIFO; body beats follow the in_vc latch taken at the head's
// acceptance (in_pkt tracks beats-since-TLAST). Acceptance is
// unconditional on downstream state -- the port backpressures
// only when the selected VC FIFO is full.
// ==========================================================================

logic [FLIT_W-1:0]     w_fifo_wr_data  [NUM_PORTS][NUM_VC];
logic                  w_fifo_wr_valid [NUM_PORTS][NUM_VC];
logic                  w_fifo_wr_ready [NUM_PORTS][NUM_VC];
logic [FLIT_W-1:0]     w_fifo_rd_data  [NUM_PORTS][NUM_VC];
logic                  w_fifo_rd_valid [NUM_PORTS][NUM_VC];
logic                  w_fifo_rd_ready [NUM_PORTS][NUM_VC];

logic [VC_W-1:0] wr_vc   [NUM_PORTS];
logic            in_pkt  [NUM_PORTS];
logic [VC_W-1:0] in_vc   [NUM_PORTS];

// Control-generator read side (Task 6): acks and mode-
// switch fan copies queue in u_gen_fifo (see the mode-
// switch section) and enter the fabric through the local
// port's VC0 input FIFO, i.e. they are ordinary data
// packets from the route stage's point of view (the
// control sr_ptr[0] marker sends them down the DOR
// route).
logic                gen_take;
logic                gen_fifo_rd_valid;
logic [FLIT_W-1:0]   gen_fifo_rd_data;

// Intake steering and FIFO write side. The local port
// arbitrates external beats against the control
// generator: a generator beat is injected only while the
// external master presents nothing, the intake packet
// boundary is closed (in_pkt low), AND the local VC0
// input FIFO can accept it -- the house FIFO commits a
// write only on wr_valid && wr_ready, while the gen FIFO
// pops on rd_ready alone, so a gen_take without
// wr_ready would silently and permanently lose the beat
// (dropped ack/fan copy -> barrier hang, no error tally).
// No deadlock: the route stage drains the local FIFO
// independently of the gen FIFO. External packets are
// never interleaved mid-packet and no s_axis handshake
// is shadowed (gen_take implies s_axis_tvalid low).
always_comb begin
    for (int p = 0; p < NUM_PORTS; p++) begin
        wr_vc[p] = in_pkt[p] ? in_vc[p] :
                    VC_W'(s_axis_tuser[p][HDR_VC_LO +: HDR_VC_W]);
        s_axis_tready[p] = w_fifo_wr_ready[p][wr_vc[p]];
        for (int v = 0; v < NUM_VC; v++) begin
            w_fifo_wr_valid[p][v] = s_axis_tvalid[p] &&
                                      (wr_vc[p] == VC_W'(v));
            w_fifo_wr_data[p][v]  = {s_axis_tuser[p],
                                     s_axis_tlast[p],
                                     s_axis_tdata[p]};
        end
    end
//     // Local port: the control generator fills the
//     // bubbles between external packets (VC0), gated by
//     // the VC0 FIFO's wr_ready (full-FIFO beats wait in
//     // the gen FIFO, never drop).
    gen_take = gen_fifo_rd_valid &&
               w_fifo_wr_ready[P_LOCAL][0] &&
               !in_pkt[P_LOCAL] &&
               !s_axis_tvalid[P_LOCAL];
    s_axis_tready[P_LOCAL] =
        w_fifo_wr_ready[P_LOCAL][wr_vc[P_LOCAL]] && !gen_take;
    for (int v = 0; v < NUM_VC; v++) begin
        w_fifo_wr_valid[P_LOCAL][v] =
            (s_axis_tvalid[P_LOCAL] &&
             (wr_vc[P_LOCAL] == VC_W'(v))) ||
            (gen_take && (v == 0));
        w_fifo_wr_data[P_LOCAL][v]  = gen_take ?
            gen_fifo_rd_data :
            {s_axis_tuser[P_LOCAL], s_axis_tlast[P_LOCAL],
             s_axis_tdata[P_LOCAL]};
    end
end

// Per-port per-VC input FIFOs (house gaxi_fifo_sync)
generate
    for (genvar p = 0; p < NUM_PORTS; p++) begin : gen_input_fifo
        for (genvar v = 0; v < NUM_VC; v++) begin : gen_vc
            gaxi_fifo_sync #(
                .MEM_STYLE (P_FIFO_MEM_STYLE),
                .DATA_WIDTH(FLIT_W),
                .DEPTH     (FIFO_DEPTH)
            ) u_input_fifo (
                .axi_aclk   (aclk),
                .axi_aresetn(aresetn),
                .wr_valid   (w_fifo_wr_valid[p][v]),
                .wr_ready   (w_fifo_wr_ready[p][v]),
                .wr_data    (w_fifo_wr_data[p][v]),
                .rd_ready   (w_fifo_rd_ready[p][v]),
                .count      (),
                .rd_valid   (w_fifo_rd_valid[p][v]),
                .rd_data    (w_fifo_rd_data[p][v])
            );
        end
    end
endgenerate

// Credit advertisement: the credit count each link needs is
// the free-slot count of this port's VC FIFO -- DEPTH at
// reset, post-consume after every accepted flit. The pinned
// sideband carries one level bit per VC, so the count rides
// in saturated form: m_credit[p][vc] = the FIFO is not full.
// A sender holding this level can always place one more flit
// (the buffer itself absorbs up to DEPTH in-flight flits),
// so the saturated count loses burst budgeting only, never
// losslessness.
generate
    for (genvar p = 0; p < NUM_PORTS; p++) begin : gen_credit_adv
        for (genvar v = 0; v < NUM_VC; v++) begin : gen_vc_lvl
            assign m_credit[p][v] = w_fifo_wr_ready[p][v];
        end
    end
endgenerate

// Presented flit per port: the head of the selected VC FIFO.
// A locked port presents its packet's VC; an idle port
// presents VC0 ahead of VC1 (VC0 is the escape resource and
// must never wait behind VC1).
logic [VC_W-1:0]       sel_vc      [NUM_PORTS];
logic                  pres_valid  [NUM_PORTS];
logic                  pres_last   [NUM_PORTS];
logic [USER_WIDTH-1:0] pres_tuser  [NUM_PORTS];
logic [DATA_WIDTH-1:0] pres_tdata  [NUM_PORTS];

always_comb begin
    for (int p = 0; p < NUM_PORTS; p++) begin
        if (lock_active[p]) begin
            sel_vc[p] = lock_vc[p];
        end else begin
            sel_vc[p] = '0;
            for (int v = NUM_VC-1; v >= 0; v--) begin
                if (w_fifo_rd_valid[p][v]) begin
                    sel_vc[p] = VC_W'(v);
                end
            end
        end
    end
end

always_comb begin
    for (int p = 0; p < NUM_PORTS; p++) begin
        pres_valid[p] = w_fifo_rd_valid[p][sel_vc[p]];
        pres_last[p]  = w_fifo_rd_data[p][sel_vc[p]][DATA_WIDTH];
        pres_tuser[p] =
            w_fifo_rd_data[p][sel_vc[p]][DATA_WIDTH+1 +: USER_WIDTH];
        pres_tdata[p] =
            w_fifo_rd_data[p][sel_vc[p]][DATA_WIDTH-1:0];
    end
end

// ==========================================================================
// Route table RAM + head-flit classification
// ==========================================================================
// The presented head flit classifies before it routes:
// in-range dsts look the RAM up (combinational read) and the
// winning port mask bit becomes route_req; out-of-range dsts
// and empty masks take the drop path instead of a grant; a
// config-shaped local head (dst == POS, QoS class 0) is
// consumed by the config plane, never granted. Body beats
// (!lock_active low, drop_active set) drain with no side
// effects. Non-head beats of a granted packet never
// recompute -- they follow lock_active/lock_port to TLAST.
// ==========================================================================

// Per-cell table: combinational read for the route stage,
// single-cycle write port from the config plane below. The
// initial block installs the power-on image; the config
// write is the only always_ff writer (deliberate two-process
// table: image at time 0, runtime writes after).
logic [ENTRY_W-1:0] route_table [ROUTE_DEPTH];

// Power-on image: DOR toward the coord-0 (rapids) boundary,
// evaluated per instance from the POS parameters so one
// checked-in module serves every grid position. A
// mechanical transcription of delta_mesh.tables.dor_port;
// the cocotb suites verify the equivalence behaviorally and
// tables.check_acyclic proves the VC0 subrelation
// connected + acyclic at generation time.
function automatic logic [ENTRY_W-1:0] dor_default_entry(
    input int addr
);
    int unsigned d_x, d_y, d_z;
    int unsigned port;
    begin
        d_x = addr[0 +: COORD_W];
        d_y = addr[COORD_W +: COORD_W];
        d_z = addr[2*COORD_W +: COORD_W];
        port = P_LOCAL;
        if (int'(d_x) < POS_X)       port = P_X_NEG;
        else if (int'(d_x) > POS_X)  port = P_X_POS;
        else if (int'(d_y) < POS_Y)  port = P_Y_NEG;
        else if (int'(d_y) > POS_Y)  port = P_Y_POS;
        else if (int'(d_z) < POS_Z)  port = P_Z_NEG;
        else if (int'(d_z) > POS_Z)  port = P_Z_POS;
        if ((int'(d_x) >= GRID_X) || (int'(d_y) >= GRID_Y) ||
            (int'(d_z) >= GRID_Z))
//         // Representable but out-of-grid dst: drop encoding.
            dor_default_entry = '0;
        else
//         // {port_mask[8:0] one-hot, vc = 0}
            dor_default_entry = {VC_W'(0), 9'(32'd1 << port)};
    end
endfunction

// Inter-tetrad diagonal mate helper (Task 6c): the
// parity-directed diagonal-tetrad corner mate of a
// coordinate. Used by the mode-10 default entry below.
function automatic int dia2_mate(int c);
    dia2_mate = ((c & 1) != 0) ? (c + 1) : (c - 1);
endfunction

// Standard-mode image (Task 6; modes 9/10 Tasks 6b/6c): the
// mechanical twin of delta_mesh.tables.mode_port,
// evaluated per instance POS. Modes 1/3/4/5/7/8 are the
// minimal DOR image; mode 2 is the pinned systolic-1D
// image (+X when the dst is to the right, else local --
// the wrap ring lands with Task 9); mode 6 is
// convergecast (every dst routes toward the root
// 0,0,0); mode 9 is the tetrad all-to-all K4 image
// (diagonal mate via P_DIA, override below); mode 10
// is the tile K4-of-tetrads image (diagonal-tetrad
// corner mate via P_DIA2, override below). The offline
// tables.check_acyclic validates every mode image and
// tables.check_no_diag guards that only mode 9 selects
// P_DIA and only mode 10 selects P_DIA2, both at
// generation time.
function automatic logic [ENTRY_W-1:0] mode_default_entry(
    input int mode,
    input int addr
);
    int unsigned d_x, d_y, d_z;
    int unsigned port;
    begin
        d_x = addr[0 +: COORD_W];
        d_y = addr[COORD_W +: COORD_W];
        d_z = addr[2*COORD_W +: COORD_W];
        port = P_LOCAL;
        case (mode)
//         // Mode 2: systolic-1D pinned minimal image.
            4'd2: port = (int'(d_x) > POS_X) ? P_X_POS : P_LOCAL;
//         // Mode 6: convergecast toward the root.
            4'd6: begin
                if (POS_X > 0)      port = P_X_NEG;
                else if (POS_Y > 0) port = P_Y_NEG;
                else if (POS_Z > 0) port = P_Z_NEG;
            end
//         // Modes 1/3/4/5/7/8: minimal DOR image; modes 9/10's
//         // non-diagonal dsts also land here.
            default: begin
                if (int'(d_x) < POS_X)       port = P_X_NEG;
                else if (int'(d_x) > POS_X)  port = P_X_POS;
                else if (int'(d_y) < POS_Y)  port = P_Y_NEG;
                else if (int'(d_y) > POS_Y)  port = P_Y_POS;
                else if (int'(d_z) < POS_Z)  port = P_Z_NEG;
                else if (int'(d_z) > POS_Z)  port = P_Z_POS;
            end
        endcase
//         // Mode 9 (tetrad K4, Task 6b): the diagonal mate
//         // of this cell's aligned 2x2x1 block -- (x^1,
//         // y^1, z) -- rides P_DIA in 1 hop; every other
//         // dst keeps the port the case computed (edge
//         // mates are the axis answer; inter-tetrad dsts
//         // DOR). The XOR names the mate exactly: on an
//         // odd X/Y edge the out-of-grid mate can never
//         // be an in-grid dst, so a tied-off P_DIA is
//         // never selected. d_z == POS_Z keeps the
//         // diagonal planar; Z expansion stays axis-
//         // routed (spec sec. 2.2).
        if ((mode == 4'd9) && (int'(d_z) == POS_Z) &&
            ((int'(d_x) ^ POS_X) == 1) &&
            ((int'(d_y) ^ POS_Y) == 1)) begin
            port = P_DIA;
        end
//         // Mode 10 (tile K4 of tetrads, Task 6c): the
//         // diagonal-tetrad corner mate -- (x + (x&1 ? +1
//         // : -1), y + (y&1 ? +1 : -1), z) -- rides P_DIA2
//         // in 1 hop. The parity form is symmetric and
//         // names exactly one in-grid mate per cell; on an
//         // odd X/Y edge the out-of-grid mate ties off so
//         // no in-grid dst can select it. Edge-adjacent
//         // tetrads use the axis port (the DOR answer for a
//         // one-boundary mate or DOR within the tile);
//         // inter-tile dsts DOR.
        if ((mode == 4'd10) && (int'(d_z) == POS_Z) &&
            (int'(d_x) == dia2_mate(POS_X)) &&
            (int'(d_y) == dia2_mate(POS_Y))) begin
            port = P_DIA2;
        end
        if ((int'(d_x) >= GRID_X) || (int'(d_y) >= GRID_Y) ||
            (int'(d_z) >= GRID_Z))
//         // Representable but out-of-grid dst: drop encoding.
            mode_default_entry = '0;
        else
//         // {port_mask[8:0] one-hot, vc = 0}
            mode_default_entry = {VC_W'(0), 9'(32'd1 << port)};
    end
endfunction

initial begin
//     Every QoS region gets the same DOR default (the image
//     ignores the qos key bits); Task 7 overlays per-class
//     routes without reshaping the memory.
    for (int a = 0; a < ROUTE_DEPTH; a++) begin
        route_table[a] = dor_default_entry(a);
    end
end

// Head decode of the presented flit (meaningful only on a
// head beat; bodies carry tuser == 0 and never consult it)
// Mode register (Task 6): 0 = custom RAM tables (power-on
// default), 1-10 = the standard-mode image; written by the
// mode-switch fan-out section below.
logic [3:0]         r_mode;
logic [COORD_W-1:0] head_dst_x [NUM_PORTS];
logic [COORD_W-1:0] head_dst_y [NUM_PORTS];
logic [COORD_W-1:0] head_dst_z [NUM_PORTS];
logic [HDR_QOS_W-1:0] head_qos   [NUM_PORTS];
logic               dst_in_range [NUM_PORTS];
logic               head_self_cfg [NUM_PORTS];
logic               head_mcast   [NUM_PORTS];
logic               head_cfg     [NUM_PORTS];
logic [ENTRY_W-1:0] head_entry   [NUM_PORTS];
logic               head_no_route [NUM_PORTS];
logic [PORT_W-1:0]  route_req    [NUM_PORTS];

always_comb begin
    for (int p = 0; p < NUM_PORTS; p++) begin
        head_dst_x[p] = pres_tuser[p][HDR_DST_X_LO +: COORD_W];
        head_dst_y[p] = pres_tuser[p][HDR_DST_Y_LO +: COORD_W];
        head_dst_z[p] = pres_tuser[p][HDR_DST_Z_LO +: COORD_W];
        head_qos[p]   = pres_tuser[p][HDR_QOS_LO +: HDR_QOS_W];
        dst_in_range[p] = (int'(head_dst_x[p]) < GRID_X) &&
                          (int'(head_dst_y[p]) < GRID_Y) &&
                          (int'(head_dst_z[p]) < GRID_Z);
//         Config shape: dst == own coordinate, QoS class
//         0 (plan-pinned config class). head_cfg is the
//         Task 5 unicast config plane (local port, mcast
//         clear); the mcast-flagged form is the Task 6
//         mode-switch broadcast, decoded below.
        head_self_cfg[p] = dst_in_range[p] &&
                      (int'(head_dst_x[p]) == POS_X) &&
                      (int'(head_dst_y[p]) == POS_Y) &&
                      (int'(head_dst_z[p]) == POS_Z) &&
                      (head_qos[p] == 2'd0);
        head_mcast[p] = pres_tuser[p][HDR_MCAST_LO];
        head_cfg[p] = (p == P_LOCAL) && head_self_cfg[p] &&
                      !head_mcast[p];
//         Route source (Task 6): control heads (sr_ptr[0]
//         set -- mode-switch fan copies, mode acks) route
//         DOR, independent of r_mode and the RAM, so the
//         switch machinery works under any mode; data
//         heads route per r_mode (0 = custom RAM image,
//         1-8 = the standard-mode image).
        if (pres_tuser[p][HDR_SR_PTR_LO]) begin
            head_entry[p] = dor_default_entry(
                {head_qos[p], head_dst_z[p],
                 head_dst_y[p], head_dst_x[p]});
        end else if (r_mode == 4'd0) begin
            head_entry[p] = route_table[{head_qos[p], head_dst_z[p],
                                       head_dst_y[p], head_dst_x[p]}];
        end else begin
            head_entry[p] = mode_default_entry(
                int'(r_mode), {head_qos[p], head_dst_z[p],
                               head_dst_y[p], head_dst_x[p]});
        end
        head_no_route[p] =
            (head_entry[p][ENTRY_MASK_W-1:0] == '0);
//         Lowest set mask bit wins (multi-bit masks --
//         multicast -- arrive in Task 8).
        route_req[p] = PORT_W'(P_LOCAL);
        for (int b = ENTRY_MASK_W-1; b >= 0; b--) begin
            if (head_entry[p][b]) begin
                route_req[p] = PORT_W'(b);
            end
        end
    end
end

// Special consumers: drop heads (out-of-range dst or empty
// mask), malformed config (multi-beat config shape), and
// well-formed config commands. All are consumed straight
// from the input FIFO -- no output grant, no credit -- so
// the local input path serializes config against data
// exactly like a granted packet does.
//
// Drain VC integrity: drop_req fires only on the
// presented head, so the consumption below always
// addresses the presented VC's FIFO; and that first
// consume forms the per-input packet lock
// (in_xfer && !pres_last), which pins sel_vc to the
// drain VC for the rest of the packet. A mid-drain
// arrival on the other VC therefore waits untouched
// -- do not remove the lock's side effect on sel_vc
// without an explicit drop_vc-style guard.
logic drop_req        [NUM_PORTS];
logic bad_cfg_req     [NUM_PORTS];
logic cfg_req         [NUM_PORTS];
logic msw_shape     [NUM_PORTS];
logic msw_wellformed [NUM_PORTS];
logic [3:0]         msw_mode    [NUM_PORTS];
logic               msw_req_vec [NUM_PORTS];
logic               msw_consume [NUM_PORTS];
logic               msw_consume_any;
logic [PORT_W-1:0]  msw_winner;
logic               msw_will_process;
logic special_req     [NUM_PORTS];
logic special_consume [NUM_PORTS];
logic drop_active     [NUM_PORTS];
logic drop_active_next [NUM_PORTS];

// Mode-switch decode (Task 6): the mcast-flagged config
// shape on ANY port. A well-formed switch is single-beat
// with sr_ptr[0] = 1 (write), the MSW magic in TDATA[15:0]
// and the mode id in TDATA[19:16] (the config entry field's
// low nibble); mode ids 0-10 are valid (0 returns to the
// custom RAM tables). Only ONE port's switch is consumed per
// cycle (lowest port wins): the winner updates r_mode at the
// next edge, so a copy arriving simultaneously on another
// port re-evaluates against the new mode and is suppressed
// (r_mode == target) instead of double-acking. A cell whose
// r_mode already equals the target consumes duplicate copies
// silently -- that suppression is what terminates the flood.
always_comb begin
    for (int p = 0; p < NUM_PORTS; p++) begin
        msw_mode[p]       = pres_tdata[p][16 +: 4];
        msw_shape[p]      = head_self_cfg[p] && head_mcast[p];
        msw_wellformed[p] = msw_shape[p] && pres_last[p] &&
                            pres_tuser[p][HDR_SR_PTR_LO] &&
                            (pres_tdata[p][15:0] == MSW_MAGIC) &&
                            (msw_mode[p] <= 4'd10);
        msw_req_vec[p] = pres_valid[p] && !lock_active[p] &&
                         !drop_active[p] && msw_wellformed[p];
    end
    msw_winner = PORT_W'(P_LOCAL);
    for (int p = NUM_PORTS-1; p >= 0; p--) begin
        if (msw_req_vec[p]) begin
            msw_winner = PORT_W'(p);
        end
    end
    msw_will_process = (r_mode != msw_mode[msw_winner]);
    for (int p = 0; p < NUM_PORTS; p++) begin
        msw_consume[p] = msw_req_vec[p] &&
                         (PORT_W'(p) == msw_winner) &&
                         (!msw_will_process || !msw_hold_valid);
    end
    msw_consume_any = 1'b0;
    for (int p = 0; p < NUM_PORTS; p++) begin
        msw_consume_any = msw_consume_any || msw_consume[p];
    end
end

always_comb begin
    for (int p = 0; p < NUM_PORTS; p++) begin
        drop_req[p] = pres_valid[p] && !lock_active[p] &&
                      !drop_active[p] && !head_cfg[p] &&
                      !msw_wellformed[p] &&
                      (!dst_in_range[p] || head_no_route[p]);
//         Malformed config shapes drop whole (head counted,
//         op not executed) so body beats with tuser=0 can
//         never be misread as fresh headers: a multi-beat
//         unicast config (Task 5) and an mcast config-shape
//         packet that fails any mode-switch field (Task 6:
//         multi-beat, sr_ptr[0] != 1, bad magic, mode id
//         above 9).
        bad_cfg_req[p] = pres_valid[p] && !lock_active[p] &&
                         !drop_active[p] &&
                         ((head_cfg[p] && !pres_last[p]) ||
                          (msw_shape[p] && !msw_wellformed[p]));
//         A well-formed config command waits when the
//         response FIFO is full (local master protocol:
//         one outstanding config transaction).
        cfg_req[p]  = pres_valid[p] && !lock_active[p] &&
                      !drop_active[p] && head_cfg[p] &&
                      pres_last[p] && cfg_resp_wr_ready;
//         Mode-switch heads raise NO route request while
//         they wait for the one-hot winner (special_req)
//         but only the winner -- and suppressed copies --
//         actually pop the FIFO (special_consume): a
//         non-winner granted onto its route would emit the
//         switch as data in the same cycle the winner
//         logic consumes it (duplication), and suppressed
//         copies must still leave no grant trace.
        special_req[p]     = drop_req[p] || bad_cfg_req[p] ||
                             cfg_req[p] || msw_req_vec[p];
        special_consume[p] = drop_req[p] || bad_cfg_req[p] ||
                             cfg_req[p] || msw_consume[p] ||
                             (drop_active[p] && pres_valid[p]);
        drop_active_next[p] = drop_active[p];
        if (drop_req[p] || bad_cfg_req[p]) begin
            drop_active_next[p] = !pres_last[p];
        end else if (drop_active[p] && pres_valid[p] &&
                   pres_last[p]) begin
            drop_active_next[p] = 1'b0;
        end
    end
end

// Config plane: beat-0 TDATA carries the command
// {table_index[15:0], entry[ENTRY_W-1:0]}; sr_ptr[0] selects
// write (1) / read (0). The response beat carries the same
// {table_index, entry} shape (write: echo of the written
// entry; read: the table value, 0 for an out-of-depth
// index) with tlast = 1 and tuser = 0.
logic [15:0]        cfg_index;
logic [ENTRY_W-1:0] cfg_entry;
logic               cfg_write_op;
logic [RESP_W-1:0]  cfg_resp_wr_data;
logic [RESP_W-1:0]  cfg_resp_rd_data;
logic               cfg_resp_rd_valid;
logic               cfg_resp_rd_ready;
logic               cfg_resp_wr_ready;
logic               cfg_resp_present;

always_comb begin
    cfg_index    = pres_tdata[P_LOCAL][15:0];
    cfg_entry    = pres_tdata[P_LOCAL][16 +: ENTRY_W];
//     sr_ptr[0] lives in the header (TUSER), not the payload:
    cfg_write_op = pres_tuser[P_LOCAL][HDR_SR_PTR_LO];
    cfg_resp_wr_data = {cfg_write_op ?
//         // write: echo the entry that committed
                            cfg_entry :
//         // read: current table value (0 out of depth)
                            ((int'(cfg_index) < ROUTE_DEPTH)
                                ? route_table[cfg_index[ROUTE_ADDR_W-1:0]]
                                : ENTRY_W'(0)),
                        cfg_index};
end

// Response skid: config responses wait here for the idle
// local output; grant registration on P_LOCAL stalls
// while any response is pending (see arbitration).
gaxi_fifo_sync #(
    .MEM_STYLE (FIFO_AUTO),
    .DATA_WIDTH(RESP_W),
    .DEPTH     (FIFO_DEPTH)
) u_config_resp_fifo (
    .axi_aclk   (aclk),
    .axi_aresetn(aresetn),
    .wr_valid   (cfg_req[P_LOCAL]),
    .wr_ready   (cfg_resp_wr_ready),
    .wr_data    (cfg_resp_wr_data),
    .rd_ready   (cfg_resp_rd_ready),
    .count      (),
    .rd_valid   (cfg_resp_rd_valid),
    .rd_data    (cfg_resp_rd_data)
);

// A response presents only while no data grant holds the
// local output (packet_active[P_LOCAL] == 0); the read
// pointer holds the beat stable under tready backpressure.
assign cfg_resp_present = cfg_resp_rd_valid &&
                          !packet_active[P_LOCAL];
assign cfg_resp_rd_ready = cfg_resp_present &&
                           m_axis_tready[P_LOCAL];

// ==========================================================================
// Mode switch - fan-out FSM, control generator, ack tally
// (Task 6)
// ==========================================================================
// A consumed mode switch (see the head decode) is processed
// exactly once per cell: the cell updates r_mode, returns a
// one-beat ack to the origin, and re-emits the switch on
// every existing neighbor port. Suppressed copies (cell
// already in the target mode) consume with no side effects.
// The fan-out is serialized through a holding register --
// one switch per cell at a time; a distinct switch arriving
// mid-fan waits in its input FIFO until the register frees
// (no deadlock: the fan drains into the fabric under the
// credit protocol).
// ==========================================================================

// Neighbor enumeration for this instance (constant
// functions of the POS/GRID parameters).
function automatic int n_neighbors();
    int n;
    n = 0;
    if (POS_X > 0)        n++;
    if (POS_X < GRID_X-1) n++;
    if (POS_Y > 0)        n++;
    if (POS_Y < GRID_Y-1) n++;
    if (POS_Z > 0)        n++;
    if (POS_Z < GRID_Z-1) n++;
    return n;
endfunction

function automatic int neighbor_port(int i);
    int n;
    n = 0;
    if (POS_X > 0) begin
        if (n == i) return P_X_NEG;
        n++;
    end
    if (POS_X < GRID_X-1) begin
        if (n == i) return P_X_POS;
        n++;
    end
    if (POS_Y > 0) begin
        if (n == i) return P_Y_NEG;
        n++;
    end
    if (POS_Y < GRID_Y-1) begin
        if (n == i) return P_Y_POS;
        n++;
    end
    if (POS_Z > 0) begin
        if (n == i) return P_Z_NEG;
        n++;
    end
    if (POS_Z < GRID_Z-1) begin
        if (n == i) return P_Z_POS;
        n++;
    end
//     // Unreachable for i < n_neighbors().
    return P_LOCAL;
endfunction

localparam int N_NEIGH = n_neighbors();

// Fan-out holding register + sequence index.
logic               msw_hold_valid;
logic [3:0]         msw_hold_mode;
logic [COORD_W-1:0] msw_hold_src_x;
logic [COORD_W-1:0] msw_hold_src_y;
logic [COORD_W-1:0] msw_hold_src_z;
logic [15:0]        msw_hold_pid;
logic [3:0]         msw_fan_idx;

// Control generator FIFO write side (the read side feeds
// the local-port intake mux, see the input buffers).
logic              gen_fifo_wr_valid;
logic              gen_fifo_wr_ready;
logic [FLIT_W-1:0] gen_fifo_wr_data;

// Beat construction: fan index 0 acks the origin; index
// k >= 1 re-emits the switch toward neighbor_port(k-1) with
// the dst coordinate rewritten to the neighbor's own, so
// the pinned dst == self discriminator holds on arrival.
// Both beat kinds ride the control class (sr_ptr[0] = 1):
// they route DOR regardless of the current mode, which is
// what makes the switch machinery mode-independent.
logic [USER_WIDTH-1:0] gen_hdr;
logic [DATA_WIDTH-1:0] gen_tdata;
logic [COORD_W-1:0]    gen_dst_x;
logic [COORD_W-1:0]    gen_dst_y;
logic [COORD_W-1:0]    gen_dst_z;
int unsigned           gen_nport;

always_comb begin
//     // fan index 0 has no neighbor: the ack branch ignores
//     // the destination computation.
    gen_nport = neighbor_port(int'(msw_fan_idx) - 1);
    gen_dst_x = COORD_W'(POS_X);
    gen_dst_y = COORD_W'(POS_Y);
    gen_dst_z = COORD_W'(POS_Z);
    if (gen_nport == P_X_NEG) begin
        gen_dst_x = COORD_W'(POS_X - 1);
    end else if (gen_nport == P_X_POS) begin
        gen_dst_x = COORD_W'(POS_X + 1);
    end else if (gen_nport == P_Y_NEG) begin
        gen_dst_y = COORD_W'(POS_Y - 1);
    end else if (gen_nport == P_Y_POS) begin
        gen_dst_y = COORD_W'(POS_Y + 1);
    end else if (gen_nport == P_Z_NEG) begin
        gen_dst_z = COORD_W'(POS_Z - 1);
    end else if (gen_nport == P_Z_POS) begin
        gen_dst_z = COORD_W'(POS_Z + 1);
    end
    gen_hdr   = '0;
    gen_tdata = '0;
    if (msw_fan_idx == 4'd0) begin
//         // Ack to the switch origin (the switch header's
//         // src coordinate); payload carries the ack magic.
        gen_hdr[HDR_DST_X_LO +: COORD_W] = msw_hold_src_x;
        gen_hdr[HDR_DST_Y_LO +: COORD_W] = msw_hold_src_y;
        gen_hdr[HDR_DST_Z_LO +: COORD_W] = msw_hold_src_z;
        gen_hdr[HDR_SRC_X_LO +: COORD_W] = COORD_W'(POS_X);
        gen_hdr[HDR_SRC_Y_LO +: COORD_W] = COORD_W'(POS_Y);
        gen_hdr[HDR_SRC_Z_LO +: COORD_W] = COORD_W'(POS_Z);
        gen_hdr[HDR_QOS_LO +: HDR_QOS_W] = 2'd1;
        gen_hdr[HDR_SR_PTR_LO]           = 1'b1;
        gen_hdr[HDR_PID_LO +: 16]        = msw_hold_pid;
        gen_tdata = {{(DATA_WIDTH-16){1'b0}}, ACK_MAGIC};
    end else begin
//         // Mode-switch copy to one neighbor: same payload
//         // shape as the original command, dst rewritten.
        gen_hdr[HDR_DST_X_LO +: COORD_W] = gen_dst_x;
        gen_hdr[HDR_DST_Y_LO +: COORD_W] = gen_dst_y;
        gen_hdr[HDR_DST_Z_LO +: COORD_W] = gen_dst_z;
        gen_hdr[HDR_SRC_X_LO +: COORD_W] = msw_hold_src_x;
        gen_hdr[HDR_SRC_Y_LO +: COORD_W] = msw_hold_src_y;
        gen_hdr[HDR_SRC_Z_LO +: COORD_W] = msw_hold_src_z;
        gen_hdr[HDR_QOS_LO +: HDR_QOS_W] = 2'd0;
        gen_hdr[HDR_MCAST_LO]            = 1'b1;
        gen_hdr[HDR_SR_PTR_LO]           = 1'b1;
        gen_hdr[HDR_PID_LO +: 16]        = msw_hold_pid;
        gen_tdata = {{(DATA_WIDTH-20){1'b0}},
                     msw_hold_mode, MSW_MAGIC};
    end
    gen_fifo_wr_data = {gen_hdr, 1'b1, gen_tdata};
end

// Fan FSM: one beat per ready cycle -- ack first, then the
// neighbor copies; the holding register frees after the
// last copy pushes.
always_comb begin
    gen_fifo_wr_valid = msw_hold_valid &&
                        (msw_fan_idx <= 4'(N_NEIGH)) &&
                        gen_fifo_wr_ready;
end

gaxi_fifo_sync #(
    .MEM_STYLE (FIFO_AUTO),
    .DATA_WIDTH(FLIT_W),
    .DEPTH     (GEN_FIFO_DEPTH)
) u_gen_fifo (
    .axi_aclk   (aclk),
    .axi_aresetn(aresetn),
    .wr_valid   (gen_fifo_wr_valid),
    .wr_ready   (gen_fifo_wr_ready),
    .wr_data    (gen_fifo_wr_data),
//     // The intake mux (input buffers) drains this FIFO
//     // between external packets.
    .rd_ready   (gen_take),
    .count      (),
    .rd_valid   (gen_fifo_rd_valid),
    .rd_data    (gen_fifo_rd_data)
);

// Mode register: updates on every mode-switch consume
// (a suppressed consume writes back the same value).
`ALWAYS_FF_RST(aclk, aresetn,
    if (!aresetn) begin
        r_mode <= 4'd0;
    end else begin
        if (msw_consume_any) begin
            r_mode <= msw_mode[msw_winner];
        end
    end
)

// Fan-out holding register: latches the origin + mode of a
// processing consume; the index walks ack + N_NEIGH copies.
// A processing consume is guaranteed an empty register (the
// consume gate), so the if/else priority cannot drop a
// pushed beat.
`ALWAYS_FF_RST(aclk, aresetn,
    if (!aresetn) begin
        msw_hold_valid <= 1'b0;
        msw_hold_mode  <= '0;
        msw_hold_src_x <= '0;
        msw_hold_src_y <= '0;
        msw_hold_src_z <= '0;
        msw_hold_pid   <= '0;
        msw_fan_idx    <= '0;
    end else begin
        if (msw_consume_any && msw_will_process) begin
            msw_hold_valid <= 1'b1;
            msw_hold_mode  <= msw_mode[msw_winner];
            msw_hold_src_x <=
                pres_tuser[msw_winner][HDR_SRC_X_LO +: COORD_W];
            msw_hold_src_y <=
                pres_tuser[msw_winner][HDR_SRC_Y_LO +: COORD_W];
            msw_hold_src_z <=
                pres_tuser[msw_winner][HDR_SRC_Z_LO +: COORD_W];
            msw_hold_pid   <=
                pres_tuser[msw_winner][HDR_PID_LO +: 16];
            msw_fan_idx    <= '0;
        end else if (gen_fifo_wr_valid) begin
            if (msw_fan_idx == 4'(N_NEIGH)) begin
                msw_hold_valid <= 1'b0;
                msw_fan_idx    <= '0;
            end else begin
                msw_fan_idx <= msw_fan_idx + 4'd1;
            end
        end
    end
)

// Ack tally: a one-beat control packet (qos 1, mcast 0,
// sr_ptr[0] set) carrying the ack magic in the payload low
// bits, leaving on the local output. Counted at every cell;
// only the origin's value is the barrier. Saturating;
// frozen at ENABLE_COUNTERS == 0 (o_err_drop_cnt policy).
logic ack_fire;

always_comb begin
    ack_fire = m_axis_tvalid[P_LOCAL] &&
               m_axis_tready[P_LOCAL] &&
               m_axis_tlast[P_LOCAL] &&
               (m_axis_tuser[P_LOCAL][HDR_QOS_LO +: HDR_QOS_W]
                    == 2'd1) &&
               !m_axis_tuser[P_LOCAL][HDR_MCAST_LO] &&
               m_axis_tuser[P_LOCAL][HDR_SR_PTR_LO] &&
               (m_axis_tdata[P_LOCAL][15:0] == ACK_MAGIC);
end

`ALWAYS_FF_RST(aclk, aresetn,
    if (!aresetn) begin
        o_mode_acks <= '0;
    end else if (ENABLE_COUNTERS != 0) begin
        if (ack_fire && (o_mode_acks != 32'hFFFF_FFFF)) begin
            o_mode_acks <= o_mode_acks + 32'd1;
        end
    end
)

// ==========================================================================
// Request matrix - which inputs want which outputs this cycle
// ==========================================================================
// An input with a packet in flight requests only its locked
// output; an idle input routes its presented head flit
// (route_req from the table). Drop/config heads and
// draining bodies request nothing -- they consume without a
// grant -- so a head beat is never consumed early and a
// malformed flit never reaches an output.
// ==========================================================================

logic [NUM_PORTS-1:0] request_matrix [NUM_PORTS];  // [output][input]
logic [PORT_W-1:0]    req_port [NUM_PORTS];

always_comb begin
    for (int q = 0; q < NUM_PORTS; q++) begin
        request_matrix[q] = '0;
    end
    for (int p = 0; p < NUM_PORTS; p++) begin
        req_port[p] = lock_active[p] ? lock_port[p] : route_req[p];
        if (pres_valid[p] && !special_req[p] &&
            !drop_active[p]) begin
            request_matrix[req_port[p]][p] = 1'b1;
        end
    end
end

// ==========================================================================
// Input tracking - packet allocation per input
// ==========================================================================
// Once a head beat is consumed into the crossbar, the input
// locks its granted output and VC so the body beats steer to
// the same port from the same FIFO; the lock releases on the
// packet's TLAST handshake. Single-beat packets never lock.
// The in_pkt/in_vc pair is the intake mirror of the same
// packet boundary: it steers body beats into the VC FIFO the
// head chose.
// ==========================================================================

logic              lock_active [NUM_PORTS];
logic              lock_active_next [NUM_PORTS];
logic [PORT_W-1:0] lock_port [NUM_PORTS];
logic [PORT_W-1:0] lock_port_next [NUM_PORTS];
logic [VC_W-1:0]   lock_vc [NUM_PORTS];
logic [VC_W-1:0]   lock_vc_next [NUM_PORTS];
logic              in_xfer [NUM_PORTS];
logic              in_xfer_last [NUM_PORTS];
logic [PORT_W-1:0] in_cov_port [NUM_PORTS];

// Consumed flit per input: the presented flit of the selected
// VC FIFO leaves when its granted output accepts it
// (rd_valid gates inside the FIFO).
always_comb begin
    for (int p = 0; p < NUM_PORTS; p++) begin
        in_xfer[p]      = pres_valid[p] &&
                          w_fifo_rd_ready[p][sel_vc[p]];
        in_xfer_last[p] = in_xfer[p] && pres_last[p];
    end
end

always_comb begin
    for (int p = 0; p < NUM_PORTS; p++) begin
        in_cov_port[p] = PORT_W'(P_LOCAL);
        for (int q = 0; q < NUM_PORTS; q++) begin
            if (grant_matrix[q][p]) begin
                in_cov_port[p] = PORT_W'(q);
            end
        end
    end
end

always_comb begin
    for (int p = 0; p < NUM_PORTS; p++) begin
        lock_active_next[p] = lock_active[p];
        lock_port_next[p]   = lock_port[p];
        lock_vc_next[p]     = lock_vc[p];
        if (lock_active[p]) begin
            if (in_xfer_last[p]) begin
                lock_active_next[p] = 1'b0;
            end
        end else if (in_xfer[p] && !pres_last[p]) begin
            lock_active_next[p] = 1'b1;
            lock_port_next[p]   = in_cov_port[p];
            lock_vc_next[p]     = sel_vc[p];
        end
    end
end

// ==========================================================================
// Output arbitration - QoS class filter + house arbiter_matrix
// (Task 7), packet atomic
// ==========================================================================
// Per output: a class filter narrows the request matrix to
// one candidate set -- the bulk reservation (if due), else
// the aged set (aging inversion), else latency, else bulk
// -- and the house arbiter_matrix (matrix fair arbiter,
// WAIT_GNT_ACK = 1) fair-picks within it. The arbiter's
// registered grant IS the output grant: it is held until
// the packet's TLAST handshake (packet atomicity -- no
// interleaving on an output, and the credit-gated
// presentation keeps a stalled flit presented while its
// credit level is low). The release cycle keeps its
// documented one-cycle bubble: the retiring grant is
// acknowledged one cycle AFTER the TLAST handshake, so
// the same-cycle handoff computes the next winner from
// the requests visible during the bubble cycle -- the
// releasing input's freshly routed next head among them
// -- and the grant is never re-registered in the TLAST
// cycle itself (that would steer the next head before
// its route is known: misroute + duplicate, exposed by
// the Task 3 fabric all-pairs back-to-back traffic). A
// pending config response on P_LOCAL blocks only fresh
// grant registration while the local output is idle.
// ==========================================================================

// Class accounting. cur_class is the QoS class of the
// entry an input currently presents to the arbiters: a
// locked input's in-flight packet keeps the class its
// head decoded (in_class, latched when the packet lock
// forms -- body beats carry tuser == 0 and would
// otherwise misdecode); an unlocked input decodes its
// presented head. Class 0 data rides as latency (class
// 0 is the control plane; its only granted traffic is
// the qos-1 acks); qos 3 is unassigned by the spec's
// 3-class table and rides as bulk.
logic [1:0]         cur_class  [NUM_PORTS];
logic [1:0]         in_class   [NUM_PORTS];
logic               in_aged    [NUM_PORTS];
logic [AGE_W-1:0]   in_age_cnt [NUM_PORTS];
logic               in_granted [NUM_PORTS];
logic               req_active [NUM_PORTS];

// Per-output candidate sets ([output][input]) and the
// filtered request into each arbiter.
logic [NUM_PORTS-1:0] cls_lat_req  [NUM_PORTS];
logic [NUM_PORTS-1:0] cls_bulk_req [NUM_PORTS];
logic [NUM_PORTS-1:0] cls_aged_req [NUM_PORTS];
logic [NUM_PORTS-1:0] arb_req      [NUM_PORTS];
logic               bulk_due     [NUM_PORTS];
logic [AGE_W-1:0]   starve_cnt   [NUM_PORTS];

// Arbiter handshake per output.
logic [NUM_PORTS-1:0] arb_grant  [NUM_PORTS];
logic               arb_valid  [NUM_PORTS];
logic               winner_bulk [NUM_PORTS];
logic               bubble     [NUM_PORTS];
logic [NUM_PORTS-1:0] gnt_ack    [NUM_PORTS];
logic               block_arb  [NUM_PORTS];

// The visible grant: the arbiter's held grant, masked
// to nothing during the release bubble. Everything
// downstream of arbitration (crossbar steering, input
// locks, drop paths, formal assists) reads this; it is
// registered state (arbiter output + bubble flop), so
// it is stable across the cycle exactly like the pre-
// Task-7 grant register.
logic [NUM_PORTS-1:0] grant_matrix [NUM_PORTS];  // [output][input]
logic                 packet_active [NUM_PORTS];
logic                 out_xfer_last [NUM_PORTS];

// TLAST handshake on an output this cycle
always_comb begin
    for (int q = 0; q < NUM_PORTS; q++) begin
        out_xfer_last[q] = (|grant_matrix[q]) && m_axis_tvalid[q] &&
                           m_axis_tready[q] && m_axis_tlast[q];
    end
end

// Class decode of the presented entry per input.
always_comb begin
    for (int p = 0; p < NUM_PORTS; p++) begin
        if (lock_active[p]) begin
            cur_class[p] = in_class[p];
        end else if (pres_tuser[p][HDR_QOS_LO +: HDR_QOS_W] >= 2'd2) begin
            cur_class[p] = 2'd2;
        end else begin
//             // qos 0 data and qos 1: latency class
            cur_class[p] = 2'd1;
        end
    end
end

// Eligibility and grant coverage per input (aging
// inputs): an input ages only while its head is
// eligible -- presented, routable, neither a special
// consumer nor mid-drop -- and holds no grant.
always_comb begin
    for (int p = 0; p < NUM_PORTS; p++) begin
        req_active[p] = pres_valid[p] && !special_req[p] &&
                      !drop_active[p];
        in_granted[p] = 1'b0;
        for (int q = 0; q < NUM_PORTS; q++) begin
            in_granted[p] = in_granted[p] || grant_matrix[q][p];
        end
        in_aged[p] = in_age_cnt[p] > AGE_W'(AGING_LIMIT);
    end
end

// Per-output class filter: strict priority latency >
// bulk, with the bulk reservation outranking aging
// inversion and aging outranking plain latency. An
// aged head beats every non-aged head regardless of
// class; within the winning candidate set the
// arbiter's matrix fair-picks.
always_comb begin
    for (int q = 0; q < NUM_PORTS; q++) begin
        for (int p = 0; p < NUM_PORTS; p++) begin
            cls_lat_req[q][p]  = request_matrix[q][p] &&
                                 (cur_class[p] == 2'd1) && !in_aged[p];
            cls_bulk_req[q][p] = request_matrix[q][p] &&
                                 (cur_class[p] == 2'd2);
            cls_aged_req[q][p] = request_matrix[q][p] && in_aged[p];
        end
        bulk_due[q] = starve_cnt[q] >= AGE_W'(STARVE_DUE);
        if (bulk_due[q] && (cls_bulk_req[q] != '0)) begin
            arb_req[q] = cls_bulk_req[q];
        end else if (cls_aged_req[q] != '0) begin
            arb_req[q] = cls_aged_req[q];
        end else if (cls_lat_req[q] != '0) begin
            arb_req[q] = cls_lat_req[q];
        end else begin
            arb_req[q] = cls_bulk_req[q];
        end
    end
end

// The house matrix arbiter per output, ACK mode: the
// grant registers from the filtered candidates and is
// held until grant_ack retires it (foreign-ack immune),
// giving same-cycle handoff to the winner computed
// from the post-ack matrix. block_arb freezes fresh
// grant registration without disturbing a held grant.
generate
    for (genvar q = 0; q < NUM_PORTS; q++) begin : gen_arbiter
        arbiter_matrix #(
            .CLIENTS     (NUM_PORTS),
            .WAIT_GNT_ACK(1)
        ) u_arbiter (
            .clk       (aclk),
            .rst_n     (aresetn),
            .block_arb (block_arb[q]),
            .request   (arb_req[q]),
            .grant_ack (gnt_ack[q]),
            .grant_valid(arb_valid[q]),
            .grant     (arb_grant[q]),
            .grant_id  (),
            .last_grant()
        );
    end
endgenerate

// Grant visibility, release bubble, arbiter control.
// The retiring grant is acknowledged during the bubble
// cycle (one cycle after its TLAST handshake), which is
// what schedules the same-cycle handoff onto the
// bubble cycle's requests -- the releasing input's
// freshly routed next head is evaluated against the
// updated matrix, and the new grant registers one
// cycle after the bubble exactly like the pre-Task-7
// re-pick. The winner's class is decoded from the
// entry it presents (latched in_class while its
// packet is in flight) for the starve-counter reset.
always_comb begin
    for (int q = 0; q < NUM_PORTS; q++) begin
        grant_matrix[q]  = arb_valid[q] && !bubble[q] ?
                           arb_grant[q] : '0;
        gnt_ack[q]       = bubble[q] ? arb_grant[q] : '0;
        packet_active[q] = |grant_matrix[q];
//         A pending config response owns the idle local
//         output: block fresh grant registration until
//         it drains (a held grant is undisturbed).
        block_arb[q]     = (q == P_LOCAL) && cfg_resp_rd_valid &&
                           !packet_active[q];
        winner_bulk[q]   = 1'b0;
        for (int p = 0; p < NUM_PORTS; p++) begin
            winner_bulk[q] = winner_bulk[q] ||
                (grant_matrix[q][p] && (cur_class[p] == 2'd2));
        end
    end
end

// Per-output bulk starve counter: runs while bulk is
// eligible but not granted, saturates at the due
// horizon, and resets on any bulk grant (a held bulk
// grant keeps it at zero through the packet's
// flight). The due flag is the observability pin.
always_comb begin
    for (int q = 0; q < NUM_PORTS; q++) begin
        o_bulk_starved[q] = bulk_due[q];
    end
end

// ==========================================================================
// Crossbar data multiplexing + credit-gated presentation
// ==========================================================================
// Per output: forward the granted input's presented flit
// (payload streams pass transparently -- the head-flit header
// rides TUSER like flat mode's TDEST handling). A flit is
// presented only while the downstream credit level for its VC
// is set; on the handshake it leaves the input FIFO and the
// neighbor's free-slot count drops by one (its m_credit level
// follows one cycle later). While a presented flit waits on a
// low tready the credit level cannot change -- this link's
// handshakes are the only thing that consume this VC's slots,
// so the AXI payload-hold rule holds. The FIFO read enable
// is the same predicate as tvalid && tready.
// ==========================================================================

always_comb begin
    for (int q = 0; q < NUM_PORTS; q++) begin
        m_axis_tdata[q]  = '0;
        m_axis_tvalid[q] = 1'b0;
        m_axis_tlast[q]  = 1'b0;
        m_axis_tuser[q]  = '0;
//         Config responses own the local output while it
//         is idle (no data grant holds it); data grants
//         resume the cycle after the response drains.
        if ((q == P_LOCAL) && cfg_resp_present) begin
            m_axis_tdata[q]  =
                {{(DATA_WIDTH-RESP_W){1'b0}}, cfg_resp_rd_data};
            m_axis_tvalid[q] = 1'b1;
            m_axis_tlast[q]  = 1'b1;
        end else begin
        for (int p = 0; p < NUM_PORTS; p++) begin
            if (grant_matrix[q][p]) begin
                m_axis_tdata[q]  =
                    w_fifo_rd_data[p][sel_vc[p]][DATA_WIDTH-1:0];
                m_axis_tvalid[q] = pres_valid[p] &&
                    s_credit[q][sel_vc[p]];
                m_axis_tlast[q]  = pres_last[p];
                m_axis_tuser[q]  = pres_tuser[p];
            end
        end
        end
    end
end

always_comb begin
    for (int p = 0; p < NUM_PORTS; p++) begin
        for (int v = 0; v < NUM_VC; v++) begin
            w_fifo_rd_ready[p][v] = 1'b0;
        end
    end
    for (int q = 0; q < NUM_PORTS; q++) begin
        for (int p = 0; p < NUM_PORTS; p++) begin
            if (grant_matrix[q][p]) begin
                w_fifo_rd_ready[p][sel_vc[p]] =
                    m_axis_tready[q] && s_credit[q][sel_vc[p]];
            end
        end
    end
//     Drop/config consumption wins over (the absent)
//     grant path: special consumers leave the FIFO with
//     no output side effects.
    for (int p = 0; p < NUM_PORTS; p++) begin
        if (special_consume[p]) begin
            w_fifo_rd_ready[p][sel_vc[p]] = 1'b1;
        end
    end
end

// ==========================================================================
// Registers (house ALWAYS_FF_RST: async assert, sync release)
// ==========================================================================
// Per-output release bubble: set on the TLAST handshake
// cycle, clear otherwise. While set, the arbiter's still-
// held retiring grant is masked off the visible grant and
// serves as the grant_ack that schedules the same-cycle
// handoff onto the bubble cycle's requests.
generate
    for (genvar q = 0; q < NUM_PORTS; q++) begin : gen_release_bubble
        `ALWAYS_FF_RST(aclk, aresetn,
            if (!aresetn) begin
                bubble[q] <= 1'b0;
            end else begin
                bubble[q] <= out_xfer_last[q];
            end
        )
    end

// Per-input aging counter (Task 7): counts cycles the
// input's head is eligible but holds no grant, saturates
// at AGING_LIMIT+1 (the in_aged decode), and resets the
// cycle the input wins a grant.
    for (genvar p = 0; p < NUM_PORTS; p++) begin : gen_aging
        `ALWAYS_FF_RST(aclk, aresetn,
            if (!aresetn) begin
                in_age_cnt[p] <= '0;
            end else begin
                if (in_granted[p]) begin
                    in_age_cnt[p] <= '0;
                end else if (req_active[p]) begin
                    in_age_cnt[p] <=
                        (in_age_cnt[p] > AGE_W'(AGING_LIMIT)) ?
                            in_age_cnt[p] : in_age_cnt[p] + 1'b1;
                end else begin
                    in_age_cnt[p] <= '0;
                end
            end
        )
    end

// Per-input class latch: the packet lock takes the class
// of the head it is formed on, so the body beats (tuser
// == 0) keep the packet's class for the filter and the
// starve-counter reset.
    for (genvar p = 0; p < NUM_PORTS; p++) begin : gen_class_track
        `ALWAYS_FF_RST(aclk, aresetn,
            if (!aresetn) begin
                in_class[p] <= 2'd1;
            end else begin
                if (in_xfer[p] && !pres_last[p]) begin
                    in_class[p] <= cur_class[p];
                end
            end
        )
    end

// Per-output bulk starve counter (Task 7): runs while
// bulk is eligible but holds no grant (a held bulk grant
// keeps it at zero through the packet's flight),
// saturates at STARVE_DUE, and resets on any bulk grant
// or when no bulk is eligible.
    for (genvar q = 0; q < NUM_PORTS; q++) begin : gen_starve
        `ALWAYS_FF_RST(aclk, aresetn,
            if (!aresetn) begin
                starve_cnt[q] <= '0;
            end else begin
                if (winner_bulk[q]) begin
                    starve_cnt[q] <= '0;
                end else if (cls_bulk_req[q] != '0) begin
                    starve_cnt[q] <=
                        (starve_cnt[q] >= AGE_W'(STARVE_DUE)) ?
                            starve_cnt[q] : starve_cnt[q] + 1'b1;
                end else begin
                    starve_cnt[q] <= '0;
                end
            end
        )
    end

    for (genvar p = 0; p < NUM_PORTS; p++) begin : gen_input_lock
        `ALWAYS_FF_RST(aclk, aresetn,
            if (!aresetn) begin
                lock_active[p] <= 1'b0;
                lock_port[p]   <= '0;
                lock_vc[p]     <= '0;
                in_pkt[p]      <= 1'b0;
                in_vc[p]       <= '0;
            end else begin
                lock_active[p] <= lock_active_next[p];
                lock_port[p]   <= lock_port_next[p];
                lock_vc[p]     <= lock_vc_next[p];
                if (s_axis_tvalid[p] && s_axis_tready[p]) begin
                    in_pkt[p] <= !s_axis_tlast[p];
                    if (!in_pkt[p]) begin
                        in_vc[p] <= wr_vc[p];
                    end
                end
            end
        )
    end
endgenerate

// Drop-draining state per input: a dropped head latches
// drop_active so the packet's body beats drain silently
// (consumed, no counter, no grant) up to and including
// their TLAST beat.
generate
    for (genvar p = 0; p < NUM_PORTS; p++) begin : gen_drop_track
        `ALWAYS_FF_RST(aclk, aresetn,
            if (!aresetn) begin
                drop_active[p] <= 1'b0;
            end else begin
                drop_active[p] <= drop_active_next[p];
            end
        )
    end
endgenerate

// Dropped-head tally (per cycle, across all inputs):
logic [3:0] drop_fire_cnt;

always_comb begin
    drop_fire_cnt = 4'd0;
    for (int p = 0; p < NUM_PORTS; p++) begin
        drop_fire_cnt = drop_fire_cnt +
            4'(drop_req[p] || bad_cfg_req[p]);
    end
end

// Route table write port: a well-formed config write
// commits on the accepting clock edge (single-cycle
// write -- no batching barrier); the response beat leaves
// after the commit, so a master that awaits the ack never
// steers against a stale entry. The table is not reset --
// the power-on image (initial block) remains the config
// plane's baseline across aresetn.
`ALWAYS_FF_RST(aclk, aresetn,
    if (!aresetn) begin
    end else begin
        if (cfg_req[P_LOCAL] && cfg_write_op &&
            (int'(cfg_index) < ROUTE_DEPTH)) begin
            route_table[cfg_index[ROUTE_ADDR_W-1:0]] <= cfg_entry;
        end
    end
)

// err_drop_cnt: heads dropped this cycle (out-of-range
// dst, empty-mask in-range dst, malformed config).
// Saturating 32-bit; frozen when ENABLE_COUNTERS == 0.
`ALWAYS_FF_RST(aclk, aresetn,
    if (!aresetn) begin
        o_err_drop_cnt <= '0;
    end else if (ENABLE_COUNTERS != 0) begin
        if (drop_fire_cnt != 4'd0 &&
            (o_err_drop_cnt <= (32'hFFFF_FFFF - 32'(drop_fire_cnt)))) begin
            o_err_drop_cnt <= o_err_drop_cnt + 32'(drop_fire_cnt);
        end
    end
)

// ==========================================================================
// Formal assists (flat-mode discipline)
// ==========================================================================
// One-hot output grant; a granted head always carries an
// in-range, non-empty-mask dst (out-of-range heads take
// the drop path instead); a grant is never released before
// its packet's TLAST handshake (packet atomicity).
// ==========================================================================
`ifdef FORMAL
generate
    for (genvar q = 0; q < NUM_PORTS; q++) begin : gen_onehot_assert
        assert property (@(posedge aclk) disable iff (!aresetn)
            $onehot0(grant_matrix[q])
        ) else $error("Grant matrix not one-hot for output %0d", q);
    end
endgenerate

generate
    for (genvar p = 0; p < NUM_PORTS; p++) begin : gen_dst_range_assert
        for (genvar q = 0; q < NUM_PORTS; q++) begin : gen_out
            assert property (@(posedge aclk) disable iff (!aresetn)
                (grant_matrix[q][p] && !lock_active[p])
                    |-> (dst_in_range[p] && !head_no_route[p])
            ) else $error(
                "Granted head with unroutable dst: in %0d out %0d",
                p, q);
        end
    end
endgenerate

generate
    for (genvar q = 0; q < NUM_PORTS; q++) begin : gen_hold_assert
//         The visible grant is the arbiter's held grant;
//         it may change only through the bubble cycle that
//         follows this packet's TLAST handshake (the
//         same-cycle handoff), so outside out_xfer_last
//         it must be stable next cycle. bubble[q] next
//         cycle implies out_xfer_last[q] this cycle,
//         which the antecedent excludes.
        assert property (@(posedge aclk) disable iff (!aresetn)
            (packet_active[q] && !out_xfer_last[q])
                |=> (grant_matrix[q] == $past(grant_matrix[q]))
        ) else $error(
            "Grant released before TLAST on output %0d", q);
    end
endgenerate

// Mode ids 11-15 have no image; the decode gates them, and
// the register must never hold one.
assert property (@(posedge aclk) disable iff (!aresetn)
    (r_mode <= 4'd10)
) else $error("r_mode out of range: %0d", r_mode);
`endif

endmodule
