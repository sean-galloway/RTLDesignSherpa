// Boundary predicate and boundary-index map, matching
// bin/delta_mesh/fabric.py (single source of truth). The
// index enumerates boundary cells in x-major, then y, then
// z order -- ascending linear index (z*Y + y)*X + x over
// boundary cells only. Constant functions: elaboration-
// time evaluated per generate-loop iteration.
function automatic logic is_boundary(int x, int y, int z);
    return (x == 0) || (x == X_DIM-1) ||
           (y == 0) || (y == Y_DIM-1) ||
           (z == 0) || (z == Z_DIM-1);
endfunction

function automatic int linear_idx(int x, int y, int z);
    return (z*Y_DIM + y)*X_DIM + x;
endfunction

function automatic int boundary_index(int x, int y, int z);
    int idx = 0;
    for (int zz = 0; zz < Z_DIM; zz++) begin
        for (int yy = 0; yy < Y_DIM; yy++) begin
            for (int xx = 0; xx < X_DIM; xx++) begin
                if (linear_idx(xx, yy, zz) < linear_idx(x, y, z))
                    if (is_boundary(xx, yy, zz))
                        idx++;
            end
        end
    end
    return idx;
endfunction

