// Tie-off policy (no torus this task -- wrap links land in
// Task 9; --torus-* is rejected at generation time):
//   - An absent boundary-neighbor port ties its s-side to
//     '0 (tvalid low) and s_credit to all-ones, and its
//     m-side tready to 1'b0: never ready, so a misroute
//     toward a nonexistent neighbor stalls visibly instead
//     of dropping flits. In-range DOR never selects one.
//   - An interior cell's local port (possible only when
//     X, Y, Z all >= 3) is tied off the same way.
//
// Tetrad diagonal links (Task 6b, owner addition
// 2026-10-15): every 2x2x1 tetrad is fully connected K4
// -- the 4 perimeter edges over +/-X/+/-Y plus BOTH
// diagonals. Each cell has exactly one diagonal mate,
