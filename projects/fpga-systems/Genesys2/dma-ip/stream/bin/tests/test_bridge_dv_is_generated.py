# Subsystem: fpga-systems/Genesys2/dma-ip/stream

"""`regen_bridges.sh` regenerates the bridge RTL AND its DV. Nothing under
`rtl/bridges/dv/` is hand-maintained.

This area once owned its bridge tests by hand, after `--generate-tests` kept
reverting fixes made to them. Hand ownership did not hold either: by
2026-10-15 the kept copies had drifted from their own TOML (a master the
config gained was missing from the monitor test's CFG_PREFIXES) and from the
generator (no TEST_LEVEL grid, no compliance checks, no fabric-ID widths). The
things the hand copies carried are generator features now: the sys.path TB
import, the PeakRDL `-Wno-MULTIDRIVEN`, level scaling, and the AXIL
narrow-to-wide alignment test. A fix to these files is a fix to the
generator, then a regeneration.

That limitation, hand-kept DV outside the bridge component, is fixed under
bridge GitHub #119 L8.

The parse check stays: an uncollectable test does not fail, it vanishes from
the report, which reads exactly like a suite that passed.
"""

import ast
import os

import pytest

_AREA = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                     os.pardir, os.pardir))
_REGEN = os.path.join(_AREA, 'bin', 'regen_bridges.sh')
_DV = os.path.join(_AREA, 'rtl', 'bridges', 'dv')
_STAMP = 'Generated by bridge test generator'


def _dv_files():
    out = []
    for sub in ('tests', 'tbclasses'):
        d = os.path.join(_DV, sub)
        if not os.path.isdir(d):
            continue
        out += [os.path.join(d, f) for f in sorted(os.listdir(d))
                if f.endswith('.py') and f != '__init__.py']
    return out


def test_regen_generates_dv():
    body = '\n'.join(ln for ln in open(_REGEN, encoding='utf-8').read().splitlines()
                     if not ln.lstrip().startswith('#'))
    for flag in ('--generate-tests', '--output-tb', '--output-test'):
        assert flag in body, f"regen_bridges.sh no longer passes {flag}"


@pytest.mark.parametrize('path', _dv_files(), ids=lambda p: os.path.basename(p))
def test_dv_file_is_generated(path):
    head = open(path, encoding='utf-8').read(4096)
    assert _STAMP in head, (
        f"{os.path.basename(path)} has no '{_STAMP}' stamp. Nothing in "
        f"rtl/bridges/dv/ is hand-maintained: emit it from the bridge "
        f"generator and regenerate.")


@pytest.mark.parametrize('path', _dv_files(), ids=lambda p: os.path.basename(p))
def test_dv_file_parses(path):
    src = open(path, encoding='utf-8').read()
    try:
        ast.parse(src, filename=path)
    except SyntaxError as exc:
        pytest.fail(f"{os.path.basename(path)} does not parse: "
                    f"line {exc.lineno}: {exc.text!r}")


def test_there_are_dv_files_to_check():
    """A guard over an empty list passes by saying nothing."""
    assert _dv_files(), f"no DV files found under {_DV} -- the guard is vacuous"
