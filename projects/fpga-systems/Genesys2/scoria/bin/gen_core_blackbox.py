#!/usr/bin/env python3
"""Emit a Verilator blackbox stub for a generated LiteDRAM core.

The core is Xilinx-primitive soup -- OSERDESE2, ODELAYE2, IDELAYCTRL, OBUFDS --
so Verilator cannot elaborate it and `--lint-only` on the pin-level top reports
50+ MODMISSING errors that say nothing about the design. pumice's LiteDRAM flow
handles this by linting a HARNESS that excludes the core, but a board-proof top
contains nothing BUT the core, so there is no harness to substitute.

Without a stub the only options are to skip lint entirely, or to hand-write 53
ports that go stale the moment the core is regenerated with a different config.
This derives the stub FROM the core, so the interface lint checks is by
construction the interface the core actually has.

What it is for: catching a mis-wired port on the top -- wrong width, wrong
direction, a name that silently became an implicit net. What it is NOT for:
anything about the core's internals. Vivado remains the authority there.
"""
from __future__ import annotations
import argparse, re, sys

def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument('core', help='generated core .v')
    ap.add_argument('-m', '--module', required=True)
    ap.add_argument('-o', '--output', required=True)
    a = ap.parse_args()

    s = open(a.core).read()
    m = re.search(r'module\s+' + re.escape(a.module) + r'\s*\((.*?)\);', s, re.S)
    if not m:
        sys.exit(f"module {a.module} not found in {a.core}")

    ports = []
    for raw in m.group(1).split(','):
        p = raw.strip()
        if not p:
            continue
        # "output reg [7:0] name" / "input wire name" -> keep dir+range, drop
        # the net type: a stub drives its outputs, so reg vs wire is ours.
        pm = re.match(r'(input|output|inout)\s+(?:wire|reg)?\s*(\[[^\]]+\]\s*)?(\w+)$', p)
        if not pm:
            sys.exit(f"cannot parse port: {p!r}")
        ports.append((pm.group(1), (pm.group(2) or '').strip(), pm.group(3)))

    L = [
        "// SPDX-License-Identifier: MIT",
        "// SPDX-FileCopyrightText: 2024-2026 sean galloway",
        "//",
        f"// Module: {a.module} (Verilator blackbox stub)",
        "// GENERATED by bin/gen_core_blackbox.py from the core itself. Do not hand-edit.",
        "//",
        "// Lets --lint-only elaborate the pin-level top so a mis-wired port is caught",
        "// before Vivado. Says NOTHING about the core's behaviour: outputs are tied to",
        "// zero, so this must never reach a simulation that expects the core to work.",
        "`timescale 1ns / 1ps",
        "",
        "`ifdef VERILATOR",
        f"module {a.module} (",
    ]
    decl = [f"    {d:<6} {r:<10} {n}".rstrip() for d, r, n in ports]
    L.append(',\n'.join(decl))
    L.append(");")
    L.append("")
    outs = [(r, n) for d, r, n in ports if d == 'output']
    if outs:
        L.append("    // Tied low. A stub that left these floating would turn a wiring")
        L.append("    // check into a sea of UNDRIVEN warnings and hide the real one.")
        for r, n in outs:
            L.append(f"    assign {n} = '0;")
    L.append("")
    L.append(f"endmodule : {a.module}")
    L.append("`endif")
    open(a.output, 'w').write('\n'.join(L) + '\n')
    print(f"wrote {a.output}: {len(ports)} ports ({len(outs)} outputs tied low)")
    return 0

if __name__ == '__main__':
    raise SystemExit(main())
