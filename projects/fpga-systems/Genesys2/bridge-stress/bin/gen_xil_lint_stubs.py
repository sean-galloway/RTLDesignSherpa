"""Write Verilator lint stubs for build-xil's AMD/Xilinx IP.

The ports are read from the synthesis stubs Vivado writes for each IP
(<ip>_stub.v, beside the IP after a build-xil synthesis), so a stub cannot
disagree with the IP the board build instantiates. (An IP's instantiation
template or RTL header is NOT authoritative: MIG's, when this build used it,
listed calibration-tap ports its configuration did not have.) Lint only:
Vivado gets the real IP from fpga/tcl/bs_xil_ip.tcl and never sees this file.

    python3 bin/gen_xil_lint_stubs.py [<project>.gen/sources_1/ip]

(default: build-xil's project) writes rtl/lint/bs_xil_ip_stubs.sv, tracked
so lint needs no Vivado. Rerun it after bs_xil_ip.tcl or the bridge_bs_xil
ports change and build-xil has synthesized.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

AREA = Path(__file__).resolve().parent.parent
OUT = AREA / 'rtl/lint/bs_xil_ip_stubs.sv'
GEN = AREA / 'build-xil/fpga/build/vivado_project/bs_xil.gen/sources_1/ip'
IPS = ('bs_atg', 'bs_cdma', 'bs_bram_ctrl', 'bs_bram', 'bs_pc_ddr', 'bs_pc_bram')
DECL = re.compile(r'^\s*(input|output|inout)\s*(\[[^\]]*\])?\s*([\w,\s]+?)\s*(?:/\*.*?\*/)?\s*;', re.M)


def ports(stub: str, where: str) -> list[tuple[str, str, str]]:
    out = []
    stub = re.sub(r'\(\*.*?\*\)', ' ', stub, flags=re.S)      # attributes
    for d, w, names in DECL.findall(stub):
        out += [(d, (w or '').replace(' ', ''), n.strip()) for n in names.split(',') if n.strip()]
    if not out:
        sys.exit(f'gen_xil_lint_stubs: no ports found in {where}')
    return out


def stub(name: str, plist: list[tuple[str, str, str]]) -> str:
    body = ',\n'.join(f'    {d:<6} wire {w:<9} {n}' for d, w, n in plist)
    return f'(* blackbox *)\nmodule {name} (\n{body}\n);\nendmodule : {name}\n'


def main() -> int:
    gen = Path(sys.argv[1]) if len(sys.argv) > 1 else GEN
    mods = []
    for ip in IPS:
        f = gen / ip / f'{ip}_stub.v'
        if not f.is_file():
            sys.exit(f'gen_xil_lint_stubs: {f} missing (synthesize build-xil first)')
        mods.append(stub(ip, ports(f.read_text(), f.name)))
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        '// SPDX-License-Identifier: MIT\n'
        '// SPDX-FileCopyrightText: 2026 sean galloway\n'
        '//\n'
        '// Generated by: projects/fpga-systems/Genesys2/bridge-stress/bin/gen_xil_lint_stubs.py\n'
        '// From:         the Vivado 2025.1 synthesis stubs of fpga/tcl/bs_xil_ip.tcl\n'
        '// DO NOT EDIT -- regenerate.\n'
        '//\n'
        "// Lint stubs for build-xil's AMD/Xilinx IP (ports only). Vivado builds the\n"
        '// real IP and never reads this file.\n'
        '//==============================================================================\n'
        '/* verilator lint_off DECLFILENAME */\n'
        '/* verilator lint_off UNUSEDSIGNAL */\n'
        '/* verilator lint_off UNDRIVEN */\n\n'
        + '\n'.join(mods)
        + '\n/* verilator lint_on UNDRIVEN */\n/* verilator lint_on UNUSEDSIGNAL */\n'
          '/* verilator lint_on DECLFILENAME */\n')
    print(f'[gen_xil_lint_stubs] {OUT} ({len(mods)} modules)')
    return 0


if __name__ == '__main__':
    sys.exit(main())
