#!/usr/bin/env python3
"""Emit the Genesys 2 DDR3 pin constraints from litex-boards' platform file.

GENERATED, not transcribed. The ddram group is 70 pins across 15 subsignals
with three different IO standards -- reset_n is LVCMOS15 while everything
around it is SSTL15 -- and a hand-copied pin table is a class of bug that costs
a board bring-up and looks like a PHY problem while you hunt it.

Source of truth: litex_boards/platforms/digilent_genesys2.py, the same file
LiteDRAM itself reads when it builds for this board. Point --platform at it.

    ./gen_genesys2_ddr3_xdc.py --platform <path> -o <build>/fpga/constraints/ddr3_pins.xdc

The pin NAMES emitted match the generated core's ports (ddram_a, ddram_dq, ...)
so the same file constrains both builds: LiteDRAM's core and the scoria harness
that replaces it. That is the point of the A/B -- identical pins, identical
board, one thing different.
"""
from __future__ import annotations
import argparse, re, sys

BANNER = """# Genesys 2 DDR3 pin constraints -- GENERATED by bin/gen_genesys2_ddr3_xdc.py
# from litex_boards/platforms/digilent_genesys2.py. Do not hand-edit: regenerate.
#
# 2 x MT41J256M16 (x16) side by side -> 32-bit DQ, 4 byte groups, 8 banks.
"""

def parse(path: str) -> tuple[dict, dict]:
    s = open(path).read()
    m = re.search(r'\("ddram", 0,\n(.*?)\n\s{4}\),\n', s, re.S)
    if not m:
        sys.exit(f"no ddram group found in {path}")
    blk = m.group(1)
    pins, std = {}, {}
    # Split on Subsignal boundaries first. A single-line regex over the whole
    # block silently drops continuation lines, and 'a' and 'dq' are BOTH
    # multi-line here -- that failure yields a 8-pin address bus and an XDC
    # that constrains a quarter of the data bus without complaining.
    for part in re.split(r'\n\s*(?=Subsignal\()', blk):
        nm = re.search(r'Subsignal\("(\w+)"', part)
        if not nm:
            continue
        pb = re.search(r'Pins\((.*?)\)\s*,?\s*(?:IOStandard|Misc|\Z)', part, re.S)
        io = re.search(r'IOStandard\("([^"]+)"\)', part)
        pins[nm.group(1)] = ' '.join(re.findall(r'"([^"]*)"', pb.group(1))).split() if pb else []
        std[nm.group(1)] = io.group(1) if io else None
    return pins, std

# Widths the generated LiteDRAM core declares. Checked, not assumed: a silent
# width mismatch here is an XDC that constrains pins the design does not drive.
EXPECT = {'a': 15, 'ba': 3, 'dq': 32, 'dm': 4, 'dqs_p': 4, 'dqs_n': 4,
          'ras_n': 1, 'cas_n': 1, 'we_n': 1, 'cs_n': 1,
          'clk_p': 1, 'clk_n': 1, 'cke': 1, 'odt': 1, 'reset_n': 1}

def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument('--platform', required=True)
    ap.add_argument('-o', '--output', required=True)
    ap.add_argument('--prefix', default='ddram')
    a = ap.parse_args()

    pins, std = parse(a.platform)
    bad = [(k, len(pins.get(k, [])), v) for k, v in EXPECT.items() if len(pins.get(k, [])) != v]
    if bad:
        for k, got, want in bad:
            print(f"  width mismatch: {k} got {got}, expected {want}", file=sys.stderr)
        return 1

    out = [BANNER]
    for name in EXPECT:
        p, io = pins[name], std[name]
        out.append(f"\n# {a.prefix}_{name}  ({len(p)} pin{'s' if len(p) > 1 else ''}, {io})")
        for i, pin in enumerate(p):
            port = f"{a.prefix}_{name}[{i}]" if len(p) > 1 else f"{a.prefix}_{name}"
            out.append(f"set_property -dict {{PACKAGE_PIN {pin}  IOSTANDARD {io}}} [get_ports {{{port}}}]")
    # Board-wide requirements for SSTL15 banks on this part.
    out.append("\n# VCCAUX_IO=HIGH and SLEW=FAST come from the platform's Misc() on the")
    out.append("# ddram group; they are bank-wide requirements for 1.5 V SSTL, not per-pin taste.")
    out.append(f"set_property SLEW FAST [get_ports -filter {{NAME =~ \"{a.prefix}_*\"}}]")
    open(a.output, 'w').write('\n'.join(out) + '\n')
    total = sum(len(pins[k]) for k in EXPECT)
    print(f"wrote {a.output}: {total} pins across {len(EXPECT)} subsignals")
    return 0

if __name__ == '__main__':
    raise SystemExit(main())
