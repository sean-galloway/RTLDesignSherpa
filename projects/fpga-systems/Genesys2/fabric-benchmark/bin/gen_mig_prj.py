"""Write the MIG 7-series project file for the Genesys 2 DDR3 (fb_mig).

The pins are not typed in here: they are read from the Genesys 2 DDR3 pin file
that the LiteDRAM board proof uses (its memtest passes on this board), which is
itself generated from litex_boards' digilent_genesys2 platform. One pinout,
proven on silicon, for every controller on this board.

Design point (PRD.md section 3, K3):
  - 2 x MT41J256M16 (x16) -> 32-bit DDR3, 1 GB, 8 banks, 15 row / 10 col bits
  - DDR3-800: tCK 2500 ps, 4:1 PHY -> ui_clk = 100 MHz, the fabric clock, so
    the DDR slave port needs no clock crossing
  - system clock: the board's 200 MHz LVDS oscillator (AD12/AD11, bank 33),
    also used as the IDELAYCTRL reference
  - internal VREF on banks 32-34 (the board has no external VREF)
  - AXI4 slave, 128-bit data, ID width = the fabric's slave-side ID (10), so
    MIG sits directly on the fabric's S0 port

Output (generated, never hand-edited):
  rtl/generated/fb_mig_prj/fb_mig.prj   (vendor_ip.tcl copies it into the IP)
"""
from __future__ import annotations

import re
import sys
import tomllib
from pathlib import Path

AREA = Path(__file__).resolve().parent.parent
REPO = AREA.parents[3]
PINS = REPO / "projects/fpga-systems/Genesys2/mem-ctrl-ip/scoria/build-litedram/fpga/constraints/ddr3_pins.xdc"
CONFIG = AREA / "rtl/bridges/configs/bridge_fb_data.toml"
OUT = AREA / "rtl/generated/fb_mig_prj/fb_mig.prj"

# LiteDRAM port name -> MIG pin name (MIG indexes the single-bit buses too).
RENAME = {"ddram_a": "ddr3_addr", "ddram_ba": "ddr3_ba", "ddram_dq": "ddr3_dq",
          "ddram_dm": "ddr3_dm", "ddram_dqs_p": "ddr3_dqs_p", "ddram_dqs_n": "ddr3_dqs_n",
          "ddram_ras_n": "ddr3_ras_n", "ddram_cas_n": "ddr3_cas_n", "ddram_we_n": "ddr3_we_n",
          "ddram_cs_n": "ddr3_cs_n[0]", "ddram_clk_p": "ddr3_ck_p[0]", "ddram_clk_n": "ddr3_ck_n[0]",
          "ddram_cke": "ddr3_cke[0]", "ddram_odt": "ddr3_odt[0]", "ddram_reset_n": "ddr3_reset_n"}
# MIG wants the DCI-terminated standards on the strobes as well as the data.
IOSTD = {"ddr3_dqs_p": "DIFF_SSTL15_T_DCI", "ddr3_dqs_n": "DIFF_SSTL15_T_DCI"}
EXPECT = {"ddr3_addr": 15, "ddr3_ba": 3, "ddr3_dq": 32, "ddr3_dm": 4, "ddr3_dqs_p": 4, "ddr3_dqs_n": 4}
PIN = re.compile(r"PACKAGE_PIN\s+(\S+)\s+IOSTANDARD\s+(\S+)\}\s*\[get_ports\s*\{(\w+)(?:\[(\d+)\])?\}\]")


def pins() -> list[tuple[str, str, str]]:
    out, counts = [], {}
    for line in PINS.read_text().splitlines():
        m = PIN.search(line)
        if not m:
            continue
        pad, iostd, port, idx = m.groups()
        name = RENAME[port]
        base = name.split("[")[0]
        if idx is not None:
            name = f"{name}[{idx}]"
        counts[base] = counts.get(base, 0) + 1
        out.append((name, pad, IOSTD.get(base, iostd)))
    for base, n in EXPECT.items():
        if counts.get(base) != n:
            sys.exit(f"gen_mig_prj: {base} has {counts.get(base)} pins in {PINS}, expected {n}")
    if len(out) != 71:
        sys.exit(f"gen_mig_prj: {len(out)} DDR3 pins in {PINS}, expected 71")
    return out


def slave_id_width() -> int:
    slaves = tomllib.loads(CONFIG.read_text())["bridge"]["slaves"]
    return next(s["id_width"] for s in slaves if s["name"] == "ddr")


