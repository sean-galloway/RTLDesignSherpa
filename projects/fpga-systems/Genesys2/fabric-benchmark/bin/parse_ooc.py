"""Tabulate the out-of-context fabric builds: size and timing per leg.

Reads reports/ooc/<leg>/<period>ns/summary.txt (written by
fpga/tcl/ooc_fabric.tcl) and writes reports/ooc/README.md: one row per leg and
clock period, with the post-route WNS. The Fmax estimate, 1000 / (period - WNS)
MHz, is given only on each leg's tightest-period row: at a loose period Vivado
stops optimizing once timing is met, so the slack there says little about how
fast the leg can go.

A row exists only for a build that finished; a missing leg is reported as
missing, never as zero.
"""
from __future__ import annotations

import sys
from pathlib import Path

AREA = Path(__file__).resolve().parent.parent
OOC = AREA / "reports/ooc"
LEGS = (("bridge", "A: bridge crossbar"),
        ("bridge_plain", "A2: bridge crossbar, preset = \"xbar\""),
        ("xbar", "B1: Xilinx AXI Crossbar"),
        ("sc", "B2: Xilinx SmartConnect"),
        ("forencich", "C1: Forencich verilog-axi axi_crossbar"),
        ("pulp", "C2: PULP axi_xbar"),
        ("litex", "C3: LiteX AXI crossbar"))
COLS = ("lut", "lutram", "srl", "ff", "bram_tile", "carry4", "muxf")


def read(path: Path) -> dict[str, str]:
    out = {}
    for line in path.read_text().splitlines():
        key, _, val = line.partition(" ")
        out[key] = val.strip()
    return out


def main() -> int:
    rows, missing, tightest = [], [], {}
    for leg, label in LEGS:
        found = sorted((OOC / leg).glob("*ns/summary.txt"))
        if not found:
            missing.append(label)
        for f in found:
            d = read(f)
            period, wns = float(d["period_ns"]), float(d["wns_ns"])
            fmax = 1000.0 / (period - wns)
            rows.append((label, period, d, wns, fmax))
            tightest[label] = min(period, tightest.get(label, period))
    lines = ["# Out-of-context fabric builds (Genesys 2, xc7k325tffg900-2)", "",
             "Each leg's `fb_data_fabric` alone, synthesized, placed and routed out of",
             "context by `fpga/tcl/ooc_fabric.tcl` (Vivado 2025.1). Same port set, address",
             "map and connectivity in every leg (`bin/gen_fabric_legs.py`). Only",
             "register-to-register paths are timed. Fmax est. = 1000 / (period - WNS),",
             "on each leg's tightest-period run only (a loose target is not pushed).",
             "Generated by `bin/parse_ooc.py`; do not edit.", "",
             "| Leg | Period (ns) | WNS (ns) | Fmax est. (MHz) | Worst-path levels | "
             + " | ".join(c.upper() for c in COLS) + " |",
             "| --- | ---: | ---: | ---: | ---: | " + " | ".join("---:" for _ in COLS) + " |"]
    for label, period, d, wns, fmax in rows:
        est = f"{fmax:.0f}" if period == tightest[label] else "-"
        lines.append(f"| {label} | {period:.1f} | {wns:+.3f} | {est} | {d['worst_levels']} | "
                     + " | ".join(d.get(c, "-") for c in COLS) + " |")
    lines += ["", ": Table 1: Size and timing per leg, post-route", ""]
    if missing:
        lines += ["Not built yet: " + ", ".join(missing) + ".", ""]
    lines += ["Worst setup path per build:", ""]
    for label, period, d, wns, fmax in rows:
        lines.append(f"- **{label} @ {period:.1f} ns:** `{d['worst_start']}` -> `{d['worst_end']}`")
    (OOC / "README.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    sys.exit(main())
