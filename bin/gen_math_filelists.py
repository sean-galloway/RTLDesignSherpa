#!/usr/bin/env python3
"""Generate per-module filelists for rtl/math (MATH-003).

Each math module gets rtl/math/filelists/<module>.f carrying its compile
closure by CONVENTION, never hand-curated:

  +incdir / reset_defs.svh header (the reset macros)
  -f $REPO_ROOT/rtl/{math,common,cdc}/filelists/<dep>.f   for each instantiated
                                                          module that has a .f
  $REPO_ROOT/rtl/math/<module>.sv                          the module itself

Instantiation closure is computed from the source (same regex family as
bin/build_review_bundle.py's deps_of). Deps are included as `-f` references to
the dep's own filelist -- never a hand-listed source -- so a change inside a
dependency propagates everywhere (the counter_bingray lesson).

Idempotent: regenerates from the tree every run. Only writes modules whose
.f does not already exist UNLESS --all is given (existing hand-maintained
family lists like math_all.f are never touched).

Usage: python3 bin/gen_math_filelists.py [--all] [--dry-run]
"""
import os
import re
import sys
import glob

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

INST_RE = re.compile(r"^\s{0,16}([a-z_][a-z0-9_]{2,})\s*(?:#\s*\(|\w[\w\[\]:]*\s*\()", re.M)
KW = {'module', 'if', 'else', 'for', 'case', 'begin', 'end', 'always', 'always_ff',
      'always_comb', 'always_latch', 'assign', 'logic', 'wire', 'generate', 'endgenerate',
      'endmodule', 'initial', 'function', 'task', 'posedge', 'negedge', 'input', 'output',
      'inout', 'parameter', 'localparam', 'typedef', 'enum', 'struct', 'endcase', 'while',
      'return', 'signed', 'unsigned', 'int', 'bit', 'reg', 'integer', 'genvar', 'endfunction'}

HEADER = """# Filelist for {mod} module (generated by bin/gen_math_filelists.py)
# Location: rtl/math/filelists/{mod}.f

# Include directories
+incdir+$REPO_ROOT/rtl/amba/includes

# Header files with macros (MUST be compiled first)
$REPO_ROOT/rtl/amba/includes/reset_defs.svh
"""


def build_index():
    idx = {}
    for area in ("math", "common", "cdc", "amba"):
        for p in glob.glob(f"{REPO}/rtl/{area}/**/*.sv", recursive=True):
            idx.setdefault(os.path.basename(p)[:-3], (area, p))
    return idx


def f_exists(area, mod):
    return os.path.exists(f"{REPO}/rtl/{area}/filelists/{mod}.f")


def deps_of(path, idx):
    text = open(path, encoding="utf-8", errors="replace").read()
    out = []
    for m in INST_RE.findall(text):
        if m in KW or m not in idx:
            continue
        out.append(m)
    return out


def closure(mod, idx, generated):
    """Full instantiation closure as (area, module) in dependency-first order."""
    seen, order = set(), []

    def visit(m):
        if m in seen or m not in idx:
            return
        seen.add(m)
        area, path = idx[m]
        for d in deps_of(path, idx):
            visit(d)
        order.append((area, m))

    visit(mod)
    return order


def main():
    dry = "--dry-run" in sys.argv
    all_ = "--all" in sys.argv
    idx = build_index()
    made = skipped = 0
    for area, path in sorted(idx.values(), key=lambda t: t[1]):
        if area != "math":
            continue
        mod = os.path.basename(path)[:-3]
        target = f"{REPO}/rtl/math/filelists/{mod}.f"
        if os.path.exists(target) and not all_:
            skipped += 1
            continue
        clo = closure(mod, idx, set())
        lines = [HEADER.format(mod=mod)]
        for darea, dmod in clo[:-1]:  # all but the module itself
            lines.append(f"-f $REPO_ROOT/rtl/{darea}/filelists/{dmod}.f")
        lines.append(f"$REPO_ROOT/rtl/math/{mod}.sv")
        content = "\n".join(lines) + "\n"
        if dry:
            print(f"would write {mod}.f ({len(clo)-1} deps)")
        else:
            open(target, "w").write(content)
        made += 1
    print(f"{'would write' if dry else 'wrote'} {made}, kept {skipped} existing")


if __name__ == "__main__":
    main()
