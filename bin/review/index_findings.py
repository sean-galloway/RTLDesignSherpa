#!/usr/bin/env python3
"""Turn Kimi critiques into a trackable findings index.

The critiques are prose blocks. That is fine for reading and useless for
working: there is no way to see how many findings are open, which files they
touch, or whether a round has been integrated. This flattens every finding into
one row so the work can be planned and its progress seen.

Findings look like:

    [CONFIRMED] one-line title, sometimes wrapped
      File:     path[, path]
      Says:     what the doc claims
      Actually: what the RTL does
      Impact:   why it matters

Usage: index_findings.py <review_root> [out.md]
       review_root holds round_N/ directories of <unit>.md critiques.
"""
import collections
import glob
import os
import re
import sys

# Two critique layouts are in the corpus and both must be parsed. Counting only
# one silently undercounts the backlog, which is the single worst failure mode
# for a tracker: it reads as progress.
#
#   A   [CONFIRMED] title
#         File:     path
#   B   ### F1 - title
#       **[CONFIRMED]**
#       - File: `path`
#
# In layout A a "### N." heading is a GROUP above one or more findings, not a
# finding itself - so headings are never counted, only severity markers are.
SEV = re.compile(r"^\[([A-Z]+)\]\s*(.*)$")
SEV_B = re.compile(r"^\*\*\[([A-Z]+)\]\*\*\s*$")
HEAD_B = re.compile(r"^#{2,4}\s+F?\d+[.—-]*\s*(.*)$")
FIELD = re.compile(r"^\s{2,}(File|Says|Actually|Impact):\s*(.*)$")
FIELD_B = re.compile(r"^\s*[-*]\s+(?:\*\*)?(File|Says|Actually|Impact)(?:\*\*)?:\s*(.*)$")


def _files(text):
    out = []
    for p in re.split(r"[,\s]+", text):
        p = p.strip("`,() ")
        if p:
            out.append(p)
    return out


def parse(path):
    """Yield findings from one critique file, in either layout."""
    unit = os.path.splitext(os.path.basename(path))[0]
    cur = None
    pending_title = None      # layout B: heading arrives before the severity
    for raw in open(path):
        line = raw.rstrip("\n")

        hb = HEAD_B.match(line)
        if hb:
            pending_title = hb.group(1).strip()
            # not a finding on its own - layout A uses these as group headings
            continue

        mb = SEV_B.match(line)
        if mb:
            if cur:
                yield cur
            cur = {"unit": unit, "severity": mb.group(1),
                   "title": pending_title or "(untitled)", "files": [],
                   "field": "done"}
            pending_title = None
            continue

        fb = FIELD_B.match(line)
        if fb and cur:
            cur["field"] = fb.group(1)
            if fb.group(1) == "File":
                cur["files"] += [p for p in _files(fb.group(2))
                                 if "/" in p or p.endswith((".md", ".sv"))]
            continue

        m = SEV.match(line)
        if m:
            if cur:
                yield cur
            cur = {"unit": unit, "severity": m.group(1),
                   "title": m.group(2).strip(), "files": [], "field": "title"}
            continue
        if not cur:
            continue
        f = FIELD.match(line)
        if f:
            cur["field"] = f.group(1)
            if f.group(1) == "File":
                cur["files"] += [p.strip().rstrip(",")
                                 for p in f.group(2).split(",") if p.strip()]
            continue
        # continuation of whatever field we are in
        if cur["field"] == "title" and line.strip() and not line.startswith("```"):
            cur["title"] += " " + line.strip()
        elif cur["field"] == "File" and line.strip() and line.startswith(" " * 6):
            cur["files"] += [p.strip().rstrip(",")
                             for p in line.split(",") if p.strip()]
    if cur:
        yield cur


def main():
    root = sys.argv[1]
    out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(root, "FINDINGS.md")

    rounds = collections.OrderedDict()
    for rd in sorted(glob.glob(os.path.join(root, "round_*"))):
        if not os.path.isdir(rd):
            continue
        items = []
        for c in sorted(glob.glob(os.path.join(rd, "*.md"))):
            if os.path.basename(c) == "FINDINGS.md":
                continue
            items += list(parse(c))
        if items:
            rounds[os.path.basename(rd)] = items

    lines = ["# Kimi findings index", "",
             "Generated by `bin/review/index_findings.py` - do not hand-edit the",
             "tables; re-run it instead. Track integration in the Status column of",
             "a task page, not here.", ""]

    total = sum(len(v) for v in rounds.values())
    lines += ["## Summary", "",
              "| Round | Units | Findings | CONFIRMED | SUSPECTED |",
              "|---|---|---|---|---|"]
    for r, items in rounds.items():
        sev = collections.Counter(i["severity"] for i in items)
        units = len({i["unit"] for i in items})
        lines.append(f"| {r} | {units} | {len(items)} | "
                     f"{sev.get('CONFIRMED', 0)} | {sev.get('SUSPECTED', 0)} |")
    lines += ["", f"**{total} findings total.**", ""]

    # Which files are implicated most - this is the real work-planning view.
    hot = collections.Counter()
    for items in rounds.values():
        for i in items:
            for f in i["files"]:
                if "/" in f:
                    hot[f.split(" ")[0]] += 1
    lines += ["## Most-implicated files", "",
              "| Findings | File |", "|---|---|"]
    for f, n in hot.most_common(25):
        lines.append(f"| {n} | `{f}` |")
    lines.append("")

    for r, items in rounds.items():
        lines += [f"## {r}", ""]
        by_unit = collections.defaultdict(list)
        for i in items:
            by_unit[i["unit"]].append(i)
        for unit in sorted(by_unit):
            lines += [f"### {unit}", ""]
            for i in by_unit[unit]:
                title = re.sub(r"\s+", " ", i["title"]).strip()
                files = ", ".join(f"`{f}`" for f in i["files"][:3]) or "-"
                lines.append(f"- [ ] **{i['severity']}** {title}")
                lines.append(f"  - {files}")
            lines.append("")

    open(out, "w").write("\n".join(lines) + "\n")
    print(f"{total} findings across {len(rounds)} rounds -> {out}")
    for r, items in rounds.items():
        print(f"  {r}: {len(items)}")


if __name__ == "__main__":
    sys.exit(main())
