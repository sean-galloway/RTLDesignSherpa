#!/usr/bin/env python3
"""Regenerate REVIEWER_BRIEF.md's book table from a built bundle.

The brief tells the reviewer how many docs and modules each book holds. That
table is ground truth handed to the reviewer, and it rots exactly the way the
documentation it reviews rots: a module split changes the tree and leaves the
table behind. A stale row primes the reviewer to hunt modules that were never
missing -- at the start of the common round it still claimed 57 docs / 56
modules against a tree with 50 / 49 (the math and cdc splits).

So: never hand-edit the table. Rebuild the bundle, then run this.

    python3 bin/review/update_brief_table.py ~/rtl-doc-review/books
    python3 bin/review/update_brief_table.py ~/rtl-doc-review/books --check

`--check` is non-destructive and exits 1 when the brief disagrees with the
bundle; `run_batch.py qc` runs it before dispatching, because a wrong table is
discovered otherwise only in the findings it invents.

Counts come from what the bundler actually wrote: `N documentation files` in
DOCS.md and `N documented modules` in RTL.sv (which excludes the dependency
closure and any GOLDEN section). A multi-part book sums its parts -- the
reviewer holding one part holds a SUBSET, which the caption says so a count
gap does not read as a missing module.

`_meta` units are deliberately absent. They are per-area, hand-triggered
(make_meta_unit.py) and carry an inventory rather than source; they are not
books and a row for one would misstate what the reviewer holds.
"""
import argparse
import glob
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
BRIEF = os.path.join(HERE, "REVIEWER_BRIEF.md")
BEGIN = "<!-- BOOK TABLE: generated by bin/review/update_brief_table.py -- do not hand-edit -->"
END = "<!-- END BOOK TABLE -->"


def unit_stats(d):
    """(docs, documented modules, bytes) for one unit directory."""
    docs_p, rtl_p = os.path.join(d, "DOCS.md"), os.path.join(d, "RTL.sv")
    head = open(docs_p, encoding="utf-8", errors="replace").read(400)
    m = re.search(r"(\d+)\s+documentation files", head)
    docs = int(m.group(1)) if m else 0
    mods = 0
    if os.path.exists(rtl_p):
        rhead = open(rtl_p, encoding="utf-8", errors="replace").read(400)
        m = re.search(r"(\d+)\s+documented modules", rhead)
        mods = int(m.group(1)) if m else 0
    size = os.path.getsize(docs_p) + (os.path.getsize(rtl_p) if os.path.exists(rtl_p) else 0)
    return docs, mods, size


def title_of(d):
    first = open(os.path.join(d, "DOCS.md"), encoding="utf-8", errors="replace").readline()
    return first[2:].strip() if first.startswith("# ") else os.path.basename(d)


def collect(books):
    """One row per book: (key, title, docs, modules, size, parts)."""
    rows = []
    for entry in sorted(os.listdir(books)):
        d = os.path.join(books, entry)
        if not os.path.isdir(d) or entry.endswith("_meta"):
            continue
        parts = sorted(glob.glob(os.path.join(d, "parts", "part_*")))
        units = parts or ([d] if os.path.exists(os.path.join(d, "DOCS.md")) else [])
        if not units:
            continue
        docs = mods = size = 0
        for u in units:
            a, b, c = unit_stats(u)
            docs, mods, size = docs + a, mods + b, size + c
        rows.append((entry, title_of(units[0]), docs, mods, size, len(units)))
    rows.sort(key=lambda r: r[4])
    return rows


def render(rows):
    out = [BEGIN,
           "",
           "| book | title | docs | documented modules | approx tokens | parts |",
           "|------|-------|------|--------------------|---------------|-------|"]
    for key, title, docs, mods, size, parts in rows:
        # Tokens, not bytes: ~4 chars/token, the same figure the bundler prints.
        # Measured AFTER golden augmentation, so it is what the reviewer holds.
        out.append(f"| `{key}` | {title} | {docs} | {mods} | ~{size // 4000}k | {parts} |")
    out += ["",
            "Counts are per whole book, regenerated from the built bundle "
            "(`documented modules` is the figure in each `RTL.sv` header, which "
            "excludes the dependency closure and any GOLDEN section). A book with "
            "more than one part is already split for you: **you are reviewing ONE "
            "part**, so its scope is a subset of the row above. Do not infer a "
            "missing module from these numbers.",
            "",
            END]
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("books", help="the bundle books dir, e.g. ~/rtl-doc-review/books")
    ap.add_argument("--check", action="store_true",
                    help="report drift and exit 1; write nothing")
    a = ap.parse_args()

    books = os.path.expanduser(a.books)
    if not os.path.isdir(books):
        sys.exit(f"not a books directory: {books}")
    rows = collect(books)
    if not rows:
        sys.exit(f"no book units under {books} -- point at <OUT>/books, not <OUT>")

    brief = open(BRIEF, encoding="utf-8").read()
    table = render(rows)
    if BEGIN in brief and END in brief:
        current = brief[brief.index(BEGIN):brief.index(END) + len(END)]
    else:
        sys.exit(f"markers not found in {os.path.relpath(BRIEF)} -- "
                 f"insert {BEGIN} / {END} around the book table first")

    if current.strip() == table.strip():
        print(f"book table current: {len(rows)} books, "
              f"{sum(r[2] for r in rows)} docs, {sum(r[3] for r in rows)} modules")
        return 0

    print("book table is STALE against the bundle:")
    old = {ln.split("|")[1].strip(): ln for ln in current.splitlines() if ln.startswith("| `")}
    new = {ln.split("|")[1].strip(): ln for ln in table.splitlines() if ln.startswith("| `")}
    for k in sorted(set(old) | set(new)):
        if old.get(k) != new.get(k):
            print(f"  - {old.get(k, '(absent)')}")
            print(f"  + {new.get(k, '(absent)')}")
    if a.check:
        print("\nrun without --check to regenerate")
        return 1
    open(BRIEF, "w", encoding="utf-8").write(brief.replace(current, table))
    print(f"\nrewrote the table in {os.path.relpath(BRIEF)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
