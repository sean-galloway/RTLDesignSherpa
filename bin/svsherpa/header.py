"""File headers and documentation banners.

The Parameters and Ports sections are generated from the module's real
parameter and port lists rather than written by hand, which removes the most
common form of stale comment: a header that describes ports the module no
longer has.

Everything else -- description, timing, behaviour, notes -- is authored, since
no generator can infer intent.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Sequence

RULE_WIDTH = 80
BANNER = "=" * (RULE_WIDTH - 3)
THIN = "-" * (RULE_WIDTH - 3)


@dataclass
class ModuleDoc:
    """Authored documentation for a module.

    Every field is optional; only the sections that carry content are emitted,
    so a small utility module gets a small header.
    """

    description: str = ""
    features: Sequence[str] = field(default_factory=tuple)
    param_notes: dict = field(default_factory=dict)
    port_notes: dict = field(default_factory=dict)
    timing: Sequence[str] = field(default_factory=tuple)
    behavior: str = ""
    wavedrom: str = ""
    usage: str = ""
    notes: Sequence[str] = field(default_factory=tuple)
    related: Sequence[str] = field(default_factory=tuple)
    test: str = ""
    references: Sequence[str] = field(default_factory=tuple)


def spdx_header(
    module_name: str,
    purpose: str,
    *,
    subsystem: str = "common",
    author: str = "sean galloway",
    created: str = "",
    docs: str = "",
) -> list[str]:
    """The SPDX / provenance block that opens every file in the repo."""
    doc_path = docs or f"docs/markdown/rtl-{subsystem}/index.md"
    lines = [
        "// SPDX-License-Identifier: MIT",
        "// SPDX-FileCopyrightText: 2024-2025 sean galloway",
        "//",
        "// RTL Design Sherpa - Industry-Standard RTL Design and Verification",
        "// https://github.com/sean-galloway/RTLDesignSherpa",
        "//",
        f"// Module: {module_name}",
        f"// Purpose: {purpose}",
        "//",
        f"// Documentation: {doc_path}",
        f"// Subsystem: {subsystem}",
        "//",
        f"// Author: {author}",
    ]
    if created:
        lines.append(f"// Created: {created}")
    lines.append("//")
    lines.append("// Generated by svsherpa -- edit the generator, not this file.")
    return lines


def _section(title: str) -> list[str]:
    return [f"//{THIN}", f"// {title}", f"//{THIN}"]


def _wrap_lines(text: str, indent: str = "//   ") -> list[str]:
    return [f"{indent}{line}".rstrip() for line in text.strip().splitlines()]


def doc_banner(module_name: str, doc: ModuleDoc, params, ports) -> list[str]:
    """The full ``//===`` documentation banner for a module."""
    out = [f"//{BANNER}", f"// Module: {module_name}", f"//{BANNER}"]

    if doc.description:
        out.append("// Description:")
        out.extend(_wrap_lines(doc.description))
        out.append("//")

    if doc.features:
        out.append("// Features:")
        out.extend(f"//   - {item}" for item in doc.features)
        out.append("//")

    if params:
        out.extend(_section("Parameters:"))
        for param in params:
            out.append(f"//   {param.name}:")
            note = doc.param_notes.get(param.name, "")
            if note:
                out.extend(_wrap_lines(note, "//     "))
            out.append(f"//     Type: {param.ptype}")
            default = param.default_text()
            if default:
                out.append(f"//     Default: {default}")
            out.append("//")

    if ports:
        out.extend(_section("Ports:"))
        for direction, label in (("input", "Inputs:"), ("output", "Outputs:"),
                                 ("inout", "Bidirectional:")):
            group = [p for p in ports if getattr(p, "direction", "") == direction]
            if not group:
                continue
            out.append(f"//   {label}")
            pad = max(len(_port_label(p)) for p in group)
            for port in group:
                note = doc.port_notes.get(port.name, "")
                out.append(f"//     {_port_label(port) + ':':<{pad + 1}} {note}".rstrip())
        out.append("//")

    if doc.timing:
        out.extend(_section("Timing:"))
        out.extend(f"//   {item}" for item in doc.timing)
        out.append("//")

    if doc.behavior:
        out.extend(_section("Behavior:"))
        out.extend(_wrap_lines(doc.behavior))
        out.append("//")

    if doc.wavedrom:
        out.extend(_section("Timing Diagram:"))
        out.extend(_wrap_lines(doc.wavedrom))
        out.append("//")

    if doc.usage:
        out.extend(_section("Usage Example:"))
        out.extend(_wrap_lines(doc.usage))
        out.append("//")

    if doc.notes:
        out.extend(_section("Notes:"))
        out.extend(f"//   - {item}" for item in doc.notes)
        out.append("//")

    if doc.related:
        out.extend(_section("Related Modules:"))
        out.extend(f"//   - {item}" for item in doc.related)
        out.append("//")

    if doc.test:
        out.extend(_section("Test:"))
        out.extend(_wrap_lines(doc.test))
        out.append("//")

    if doc.references:
        out.extend(_section("References:"))
        out.extend(f"//   - {item}" for item in doc.references)
        out.append("//")

    out.append(f"//{BANNER}")
    return out


def _port_label(port) -> str:
    """``name[WIDTH-1:0]`` for a vector, plain ``name`` for a scalar."""
    packed = getattr(port, "packed", ())
    if len(packed) == 1 and packed[0].try_eval({}) == 1:
        return port.name
    spans = "".join(f"[{(d - 1).render()}:0]" for d in packed
                    if d.try_eval({}) != 1)
    return f"{port.name}{spans}"
