"""STREAM TASK-083: a .rdl edit must not leave its generated artifacts stale.

Editing a .rdl without running bin/peakrdl_generate.py leaves the tree
regen-dirty and NOTHING catches it: the regblock RTL, the regmaps and the docs
simply disagree with the .rdl, and every test still passes because they all
read the stale generated copies. That happened during the TASK-085 work -- a
317-line divergence rode along until an explicit regen-and-diff surfaced it.

This regenerates each manifest entry into a TEMPORARY directory and diffs the
result against what is committed. It never writes into the tree.

Two things the manifest has to carry, because neither is derivable:

  * the exact invocation. A generated artifact does NOT record the command
    that made it -- stream's two regmaps carry byte-identical banners
    ("Generated by: peakrdl_generate.py --regmap") despite coming from
    different invocations. One run emits one regmap, so a block needing two
    regmaps needs two entries.

  * which .rdl files affect it. stream_regs.rdl `include`s stream_mon_regs.rdl,
    so editing the include changes stream's output while the parent file is
    never staged. Gating on "the staged .rdl" alone would sail straight past
    it; entries therefore declare every source that feeds them.

Usage:
    check_rdl_regen.py                 # check every manifest entry
    check_rdl_regen.py --staged        # only entries whose sources are staged
    check_rdl_regen.py --list          # show the manifest and exit
"""
import argparse
import filecmp
import importlib.util
import subprocess
import sys
import tempfile
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
GENERATOR = REPO_ROOT / "bin" / "peakrdl_generate.py"

# Each entry: one invocation of peakrdl_generate.py and the tracked files it
# must reproduce byte-for-byte. `sources` is every .rdl that feeds the entry.
#
# Adding a block: run its real invocation into a scratch dir, confirm the
# output matches what is committed, then record it here. Do NOT guess the
# flags -- a wrong entry reports permanent staleness and blocks every commit.
STREAM = "projects/components/dmas/stream"
STREAM_SOURCES = [
    f"{STREAM}/rtl/macro/stream_regs.rdl",
    f"{STREAM}/rtl/macro/stream_mon_regs.rdl",   # `include`d by stream_regs.rdl
]

PUMICE = "projects/components/memory-controllers/pumice-ddr2-lpddr2"
PUMICE_SOURCES = [f"{PUMICE}/rtl/macro/pumice_csr.rdl"]

MANIFEST = [
    {
        "name": "stream_regs (regblock + docs + regmap)",
        "rdl": f"{STREAM}/rtl/macro/stream_regs.rdl",
        "sources": STREAM_SOURCES,
        "flags": ["--no-html"],
        "regmap_output": None,
        "compare": [
            (f"{STREAM}/regs/generated/rtl/stream_regs.sv", "rtl/stream_regs.sv"),
            (f"{STREAM}/regs/generated/rtl/stream_regs_pkg.sv", "rtl/stream_regs_pkg.sv"),
            (f"{STREAM}/regs/generated/stream_regs_regmap.py", "stream_regs_regmap.py"),
            (f"{STREAM}/regs/generated/docs/stream_regs.md", "docs/stream_regs.md"),
        ],
    },
    {
        "name": "stream_regs (DV-facing regmap copy)",
        "rdl": f"{STREAM}/rtl/macro/stream_regs.rdl",
        "sources": STREAM_SOURCES,
        "flags": ["--no-html"],
        # A second invocation: --regmap-output renames the emitted regmap, and
        # the docstring inside it derives from that filename, so this file is
        # NOT a copy of the one above and cannot be produced by the same run.
        "regmap_output": "stream_regmap.py",
        "compare": [
            (f"{STREAM}/rtl/stream_regmap.py", "stream_regmap.py"),
        ],
    },
    {
        "name": "pumice_csr (regblock + docs + regmap)",
        "rdl": f"{PUMICE}/rtl/macro/pumice_csr.rdl",
        "sources": PUMICE_SOURCES,
        "flags": ["--no-html"],
        "regmap_output": None,
        "compare": [
            (f"{PUMICE}/regs/generated/rtl/pumice_csr.sv", "rtl/pumice_csr.sv"),
            (f"{PUMICE}/regs/generated/rtl/pumice_csr_pkg.sv", "rtl/pumice_csr_pkg.sv"),
            (f"{PUMICE}/regs/generated/pumice_csr_regmap.py", "pumice_csr_regmap.py"),
            (f"{PUMICE}/regs/generated/docs/pumice_csr.md", "docs/pumice_csr.md"),
        ],
    },
    {
        "name": "pumice_csr (DV-facing regmap copy)",
        "rdl": f"{PUMICE}/rtl/macro/pumice_csr.rdl",
        "sources": PUMICE_SOURCES,
        "flags": ["--no-html"],
        # Second invocation, same reason as stream's: --regmap-output renames
        # the emitted regmap rather than adding one, so a single run cannot
        # produce both this and the regs/generated copy above. This is the file
        # the component TBs load (pumice_top_csr_tb.py, pumice_top_tb.py), and
        # it is what went a month stale after 16eda8ed7 added
        # SCHED_WR_WM.wr_batch_max -- see PUMICE-047.
        "regmap_output": "pumice_regmap.py",
        "compare": [
            (f"{PUMICE}/dv/tbclasses/pumice_regmap.py", "pumice_regmap.py"),
        ],
    },
]


def staged_files():
    out = subprocess.run(
        ["git", "diff", "--cached", "--name-only", "--diff-filter=ACM"],
        cwd=REPO_ROOT, capture_output=True, text=True, check=False)
    return {l.strip() for l in out.stdout.splitlines() if l.strip()}


def check_entry(entry, tmp_root):
    """Regenerate one entry into tmp and diff. Returns list of problems."""
    problems = []
    out_dir = Path(tmp_root) / "out"
    out_dir.mkdir(parents=True, exist_ok=True)

    cmd = [sys.executable, str(GENERATOR), str(REPO_ROOT / entry["rdl"]),
           "-o", str(out_dir), *entry["flags"]]
    if entry["regmap_output"]:
        cmd += ["--regmap-output", str(out_dir / entry["regmap_output"])]

    res = subprocess.run(cmd, cwd=REPO_ROOT, capture_output=True, text=True, check=False)
    if res.returncode != 0:
        tail = (res.stdout + res.stderr).strip().splitlines()[-6:]
        return [f"generator FAILED (rc={res.returncode}):\n      " + "\n      ".join(tail)]

    for spec in entry["compare"]:
        tracked_rel, gen_rel = spec[0], spec[1]
        mode = spec[2] if len(spec) > 2 else "bytes"
        tracked = REPO_ROOT / tracked_rel
        generated = out_dir / gen_rel
        if not generated.exists():
            problems.append(f"generator did not emit {gen_rel} (expected for {tracked_rel})")
            continue
        if not tracked.exists():
            problems.append(f"{tracked_rel} is MISSING but the generator emits it")
            continue
        if mode == "semantic":
            bad = _regmap_differs(tracked, generated)
            if bad:
                problems.append(f"{tracked_rel} register map is STALE: {bad}")
        elif not filecmp.cmp(tracked, generated, shallow=False):
            problems.append(f"{tracked_rel} is STALE (does not match a fresh regen)")
    return problems


def _load_regmap(path):
    """Load a *_regmap.py and return its register dict, or None."""
    spec = importlib.util.spec_from_file_location("rm_" + path.stem, path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    for name in dir(mod):
        obj = getattr(mod, name)
        if isinstance(obj, dict) and obj and all(
                isinstance(v, dict) for v in list(obj.values())[:3]):
            return obj
    return None


def _regmap_differs(tracked, generated):
    """Compare two regmaps by REGISTER CONTENT, ignoring header/docstring prose.

    Some regmaps carry a deliberately hand-written header -- rapids_regmap.py
    explains that its two engine instances share the layout and are loaded at
    different start_addresses, which a generated docstring cannot say. That is
    an improvement, not drift, but it makes the file differ byte-for-byte from
    a fresh regen forever. Comparing the register dictionary keeps the gate
    honest about what actually matters: the registers.

    Returns a human-readable description of the difference, or "" if equal.
    """
    a, b = _load_regmap(tracked), _load_regmap(generated)
    if a is None or b is None:
        return "could not load a register dict from one of the files"
    only_tracked = sorted(set(a) - set(b))
    only_fresh = sorted(set(b) - set(a))
    changed = sorted(k for k in set(a) & set(b) if a[k] != b[k])
    bits = []
    if only_tracked:
        bits.append(f"HAND-ADDED (not emitted by a regen): {only_tracked[:6]}")
    if only_fresh:
        bits.append(f"MISSING (emitted but not committed): {only_fresh[:6]}")
    if changed:
        bits.append(f"content differs: {changed[:6]}")
    return "; ".join(bits)


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--staged", action="store_true",
                    help="only check entries whose .rdl sources are staged")
    ap.add_argument("--list", action="store_true", help="print the manifest and exit")
    args = ap.parse_args()

    if args.list:
        for e in MANIFEST:
            print(f"{e['name']}")
            print(f"  rdl     : {e['rdl']}")
            print(f"  sources : {', '.join(e['sources'])}")
            print(f"  emits   : {', '.join(t for t, _ in e['compare'])}")
        return 0

    entries = MANIFEST
    if args.staged:
        st = staged_files()
        entries = [e for e in MANIFEST if st & set(e["sources"])]
        if not entries:
            return 0

    failed = 0
    for e in entries:
        problems = check_entry(e, tempfile.mkdtemp(prefix="rdlregen_"))
        if problems:
            failed += 1
            print(f"\n[rdl-regen] {e['name']}: OUT OF SYNC with {e['rdl']}", file=sys.stderr)
            for p in problems:
                print(f"    - {p}", file=sys.stderr)

    if failed:
        print("\n  Regenerate with bin/peakrdl_generate.py (never raw peakrdl -- it", file=sys.stderr)
        print("  skips the docs and the regmap), then stage the result:", file=sys.stderr)
        for e in entries:
            cmd = f"    python3 bin/peakrdl_generate.py {e['rdl']} -o <dir> {' '.join(e['flags'])}"
            if e["regmap_output"]:
                cmd += f" \\\n        --regmap-output {e['compare'][0][0]}"
            print(cmd, file=sys.stderr)
        return 1

    return 0


if __name__ == "__main__":
    sys.exit(main())
